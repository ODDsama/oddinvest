// NoBrokerLabel — як показується надходження без брокера: «—» і в нозі
// маршруту, і в плановому потоці (route.go), щоб одне місце не мало двох
// позначень.
const NoBrokerLabel = "—"

// readyFlow — одне майбутнє надходження до конкретного брокера.
//
// PRINCIPAL І KIND. Маршрут (route.go) веде прохід
// уперед по капіталу, а там різниця принципова — купон це НОВІ гроші, а
// погашення лише перекладає власне тіло з паперу в готівку. Без цієї пари
// прохід рахував би повернення номіналу приростом капіталу й через це
// занижував би розрив до цілі саме того виду, який щойно погасився.
//
// Обидва поля тут, а не в окремій структурі поруч, бо джерело в них одне й
// те саме — розклад, — і другий збирач розкладу розійшовся б із першим.
type readyFlow struct {
	Date   domain.Date
	Amount int64 // мінорні, у валюті виплати
	Label  string
	// Principal — скільки з Amount є поверненням ВЛАСНОГО тіла (погашення
	// ОВДП, тіло вкладу). Решта — дохід. Kind — вид, з якого це тіло
	// повертається, у термінах ребалансу ("bonds" | "deposits").
	Principal int64
	Kind      string
	// Basis — на чому це надходження стоїть. Порожньо = ЗОБОВʼЯЗАННЯ, і
	// саме таким futureIncome лишає кожен свій рядок: інших основ вона не
	// знає й знати не мусить. Непорожнє ставить лише routeIncome нижче.
	Basis string
	// Ref — ключ, яким цю виплату позначають отриманою: ISIN паперу або
	// синтетичний "deposit:<id>" вкладу. ОКРЕМО від Label, бо в вкладу вони
	// різні — на екрані «вклад ПУМБ», у payment_status «deposit:7», — а
	// кнопка «Прийшло» мусить надіслати саме другий.
	//
	// Порожньо в оцінок: дивіденд фонду позначати нема чого, його справжній
	// запис — операція фонду, а не рядок статусу.
	Ref string
	// Why — чому в нозі стоїть менше, ніж фонд нарахував. Порожньо в усіх
	// інших надходжень: там сума і є сумою.
	//
	// Готовою прозою з бекенда, а не парою чисел на складання в браузері, —
	// з того самого доводу, що RestWhy й ReserveSkipWhy: сума, яка
	// «зменшилась сама», читається як поломка, а рахувати її вдруге в JS
	// заборонено (CLAUDE.md §5).
	Why string
	// Uses — дозвіл САМОГО ДЖЕРЕЛА цих грошей (plan_flows.uses, міграція
	// 0041) у канонічному вигляді, який читає domain.PlanUseAllowed.
	// Порожньо означає «будь-куди», як і в сховищі.
	//
	// Ставить його лише planAhead: у виплат портфеля дозволу немає й бути не
	// може — купон нічим не позначений, і завести йому порожній рядок
	// «про запас» означало б збрехати, що позначка там буває.
	//
	// Тут, а не в окремій структурі поруч, з того самого доводу, що
	// Principal і Kind: джерело в них одне — рядок плану, — і другий збирач
	// розійшовся б із першим. coalesceSameDay цього поля не зводить і не
	// мусить: вона працює лише над виплатами портфеля, де воно завжди
	// порожнє.
	Uses string
}

// reinvestFlowWhy — підпис до ноги фонду, який докуповує сертифікати сам.
// Порожньо, коли нічого не докупив: тоді сума й так уся. Суми — прозою у
// валюті звітності (mt), як і решта підписів ноги: числа ноги перекладає
// презентер, а рядок він не бачить.
func reinvestFlowWhy(mt moneyText, s domain.FundReinvestSplit, cur string) string {
	if s.Units <= 0 || s.Spent <= 0 {
		return ""
	}
	return fmt.Sprintf("фонд утримав виплату %s і докупив %d %s на %s — на рахунок іде лише решта",
		mt.cur(float64(s.Gross)/100, cur), s.Units,
		Plural(int(s.Units), "сертифікат", "сертифікати", "сертифікатів"),
		mt.cur(float64(s.Spent)/100, cur))
}

// Основи надходження. Порожній рядок у readyFlow.Basis означає basisOwed —
// назовні воно завжди назване словом, бо колонка «основа» з порожньою
// коміркою читалась би як «невідомо», а не як «портфель це винен».
const (
	basisOwed     = "owed"     // портфель винен сам собі: купон, погашення, відсотки
	basisEstimate = "estimate" // оцінка: дивіденд фонду, порахований зі ставки
	BasisPlan     = "plan"     // намір: дохід із plan_flows
	basisMixed    = "mixed"    // у горщику зійшлись різні
)

// flowBasis — основа надходження словом. Порожнє поле означає
// зобовʼязання, і назовні воно мусить бути названим (див. коментар вище).
func flowBasis(f readyFlow) string {
	if f.Basis == "" {
		return basisOwed
	}
	return f.Basis
}

// readyEvent — те саме назовні: з чого саме склалася сума.
type readyEvent struct {
	Date   string    `json:"date"`
	Label  string    `json:"label"`
	Amount MoneyJSON `json:"amount"`
}

// incomeAhead — майбутні надходження в розрізі (брокер × валюта).
type incomeAhead map[brokerCur][]readyFlow

// brokerCur — ключ надходження: (брокер × валюта). Жив у store поруч із
// гаманцем; рахунків більше немає, а маршрут і далі складає надходження
// одного брокера й однієї валюти в один горщик.
type brokerCur struct {
	Broker   string
	Currency string
}

// futureIncome — що ще прийде і до якого брокера.
//
// Купон іде до брокера, де куплено папір, відсотки вкладу — до його банку.
// Порожня назва стає «—»: гроші без привʼязки — це теж місце, і мовчки
// зливати їх із чиїмись не можна.
//
// Виплати рахує domain.FuturePayments — та сама функція, якою збирається
// календар і зведення. Розділені по брокерах лоти дають розділені потоки:
// сума по всіх брокерах дорівнює загальному розкладу, бо HolderQty
// лінійна за лотами (на це є тест).
//
// arrived фільтрує те, що вже позначене «отримано»: така виплата сталась,
// і маршрут не має вести її вдруге як майбутню.
func futureIncome(src *sources, today domain.Date) (incomeAhead, error) {
	arrived := domain.Arrived(src.statuses, today)
	out := incomeAhead{}
	add := func(broker, currency string, f readyFlow) {
		broker = cmp.Or(broker, NoBrokerLabel)
		k := brokerCur{Broker: broker, Currency: currency}
		out[k] = append(out[k], f)
	}

	byChannel := map[string][]domain.Lot{}
	for _, l := range src.lots {
		byChannel[l.Channel] = append(byChannel[l.Channel], l)
	}
	for channel, lots := range byChannel {
		cfs, err := domain.FuturePayments(src.pays, lots, src.sales, today)
		if err != nil {
			return nil, err
		}
		for _, cf := range cfs {
			if arrived(cf.ISIN, cf.Date) {
				continue
			}
			f := readyFlow{Date: cf.Date, Amount: cf.Amount.Amount(),
				Label: cf.ISIN, Kind: "bonds", Ref: cf.ISIN}
			if cf.Type == domain.PayRedemption {
				f.Principal = cf.Amount.Amount()
			}
			add(channel, cf.Amount.Currency().Code, f)
		}
	}

	for _, dep := range src.termDeposits {
		// Вклад подушки чи цілі при погашенні повертається туди ж (F7b,
		// state_sources.go), а не до брокера: маршрут інакше планував би
		// купівлі за гроші подушки.
		if dep.Earmarked() {
			continue
		}
		// Назву банку в підписі видно саме тут, і це навмисне розходження зі
		// state.payLabel, де стоїть просто «вклад»: там перелік вкладів у
		// функцію не передається, а тут він і є входом.
		label := "вклад"
		if dep.Bank != "" {
			label += " " + dep.Bank
		}
		for _, cf := range domain.DepositSchedule(dep, today) {
			if arrived(cf.ISIN, cf.Date) {
				continue
			}
			f := readyFlow{Date: cf.Date, Amount: cf.Amount.Amount(),
				Label: label, Kind: "deposits", Ref: cf.ISIN}
			if cf.Type == domain.PayRedemption {
				f.Principal = cf.Amount.Amount()
			}
			add(dep.Bank, cf.Amount.Currency().Code, f)
		}
	}

	for k := range out {
		sortFlows(out[k])
		out[k] = coalesceSameDay(out[k])
	}
	return out, nil
}

// sortFlows — сталий порядок усередині зрізу: дата, потім підпис.
//
// Повним ключем, а не самою датою: сортування нестабільне, і дві виплати
// одного дня ставали б у порядку, у якому їх поклав збирач. Спільна
// функція, бо зрізи сортуються в трьох місцях, і четверта копія цього
// порівняння розійшлася б із рештою тихо.
//
// СТАБІЛЬНИМ, і це не зайва обережність. Виплати портфеля від залишкової
// нестабільності рятувало зведення (coalesceSameDay); плановим ногам такого
// зведення немає, а два потоки з однією назвою й одним днем мають РІЗНІ
// дозволи (Uses). Мовчки звести їх означало б віддати обом найсуворіший із
// двох, а лишити нестабільними — давати різний маршрут на тих самих даних.
func sortFlows(flows []readyFlow) {
	sort.SliceStable(flows, func(i, j int) bool {
		if flows[i].Date != flows[j].Date {
			return flows[i].Date < flows[j].Date
		}
		return flows[i].Label < flows[j].Label
	})
}

// routeIncome — те саме, що futureIncome, плюс половина, якої та свідомо
// не бачить: оцінені дивіденди фондів.
//
// # ЧОМУ ТУТ ЇМ МІСЦЕ, А В ДАТІ «КОЛИ ВИСТАЧИТЬ» — НІ
//
// Відмова в шапці цього файла стосується ОДНОГО ЧИСЛА. Дата — саме одне
// число, і оцінка, підмішана в нього, стає невидимою: «набереться 16
// вересня» не має де сказати, що воно набереться, лише якщо фонд заплатить
// стільки, скільки платив торік.
//
// Маршрут — таблиця названих рядків, і в кожного рядка своя основа, яку
// видно (Basis). Зобовʼязання й оцінка не зводяться в ньому в одне число
// ніде: горщик, у якому вони зійшлись, чесно каже basisMixed. Це той самий
// стандарт, за яким оцінка вже живе в календарі виплат — «стоїть
// підписаною й читається як оцінка».
//
// futureIncome при цьому не змінюється НІЯК, і на це є регресійний тест:
// саме її незмінність і тримає ту відмову.
//
// # ЧОГО НЕМАЄ Й ТУТ
//
// Виплат НПФ: гроші звідти не приходять до пенсійного віку, а обрій
// маршруту — рік. Ця межа лишається.
//
// А от планового доходу тут більше НЕ бракує, і відмова, що стояла на
// цьому місці, знялась не поступкою, а знахідкою. Вона казала: план
// нетиться з витратами, тож завести його сюди без другого означення
// «скільки план дає чистими» не виходить. Друге означення й не знадобилось
// — перше вже було: MonthPlan.PlanUAH (state_month.go) і є тим числом,
// дохід плюс позапланове мінус витрати, з уже застосованою часткою в
// портфель. Від нього ж рахується стеля подушки, тож маршрут і стеля
// говорять про одні й ті самі гроші. Збирає ті події planAhead нижче.
//
// І віддає їх УЖЕ РОЗНЕСЕНИМИ ПО ПОТОКАХ, а не однією нотою на місяць. Це
// не друге означення того самого числа: ділиться рівно MonthPlan.PlanUAH, у
// частках того самого внеску, з якого воно складене, тож сума ніг місяця і
// є місяць. Довід, чому це стало можливим, — у шапці planAhead.
func routeIncome(src *sources, today domain.Date, months int) (incomeAhead, error) {
	out, err := futureIncome(src, today)
	if err != nil {
		return nil, err
	}
	if len(src.fundOps) == 0 {
		return out, nil
	}
	// Зведення позицій те саме, що будує документ: друге означення «скільки
	// сертифікатів у мене зараз» розійшлося б із першим на першій же
	// позначці ціни.
	hold := domain.NewHoldings(src.lots, src.sales, src.bonds,
		src.fundOps, src.fundPrices, src.payoutDays(), today, domain.Arrived(src.statuses, today))
	mt := moneyTextOfSrc(src)

	for i := range hold.Funds {
		fp := &hold.Funds[i].FundPosition
		// Накопичувальний не платить нічого: увесь його дохід сидить у ціні
		// сертифіката. Та сама перевірка, що в buildSchedule, і з тієї самої
		// причини — проставлений комусь payout_day інакше вигадав би
		// щомісячні дивіденди фонду, який їх не платить.
		if src.fundRefs[fp.Fund].Kind == store.FundAccumulating {
			continue
		}
		measured, _ := domain.DividendYieldNet(src.fundOps, fp, today)
		ref := src.fundRefs[fp.Fund]
		y := fundPayoutRatePct(ref, measured) // виплати — після податку
		broker := fundBroker(src.fundOps, fp.Fund)
		// ТУТ — ЛИШЕ ГОТІВКОВА ЧАСТИНА, на відміну від календаря, який
		// показує всю нараховану ренту (довід — у buildSchedule). Маршрут
		// відповідає на питання «що впаде на рахунок і куди воно піде», а
		// сертифікатами, які фонд докупив сам, у НПФ не внесеш.
		//
		// Ціна помилки була не косметична: на живих даних застосунок
		// показував 68,60 ₴ там, де приходить близько 1,85 ₴, і щомісяця
		// радив віднести в пенсійний гроші, яких не існуватиме.
		for _, f := range domain.FundDividendFlows(fp, y, months, today,
			ref.Kind == store.FundReinvesting) {
			if f.Amount.Amount() <= 0 {
				// Місяць, у якому решти не лишилось (рента поділилась на
				// сертифікати без остачі). Нога на 0 ₴ подією не є, а горщик
				// і стелю подушки прокрутила б.
				continue
			}
			k := brokerCur{Broker: broker, Currency: f.Amount.Currency().Code}
			out[k] = append(out[k], readyFlow{
				Date: f.Date, Amount: f.Amount.Amount(),
				Label: fp.Fund, Kind: "funds", Basis: basisEstimate,
				Why: reinvestFlowWhy(mt, f.Split, fp.Currency),
			})
		}
	}
	// Пересортувати треба ті пари, куди дивіденди справді лягли: futureIncome
	// віддає кожен зріз відсортованим, а append це порушив. Зведення одного
	// дня повторно безпечне — воно ідемпотентне за побудовою.
	for k := range out {
		sortFlows(out[k])
		out[k] = coalesceSameDay(out[k])
	}
	return out, nil
}

// splitByWeights — розкласти totalMinor на len(w) часток у пропорціях w.
//
// НАЙБІЛЬШИМИ ОСТАЧАМИ, а не «решту останньому». Останній тут не
// випадковий — це та сама зарплата щомісяця, — і три копійки, віддані їй
// дванадцять разів поспіль, стають систематичним зсувом на одному й тому
// самому названому рядку. Найбільша остача віддає копійку тому, кому вона
// справді ближча, а рівність вирішує порядок у зрізі; той уже впорядкований
// (день, назва, id), тож два запуски дають одне й те саме.
//
// ГАРАНТІЯ, НА ЯКІЙ СТОЇТЬ УСЕ РЕШТА: сума часток дорівнює totalMinor точно.
// Саме тому ногу з нульовою часткою можна викинути й не боятись, що місяць
// після цього не зійдеться з PlanUAH: її копійку вже забрав хтось інший.
//
// Недодатні ваги не беруть нічого й остачі не мають: потік, який у підсумок
// не додав, не має права з нього брати.
func splitByWeights(totalMinor int64, w []float64) []int64 {
	out := make([]int64, len(w))
	if len(w) == 0 || totalMinor <= 0 {
		return out
	}
	sum := 0.0
	for _, v := range w {
		if v > 0 {
			sum += v
		}
	}
	if sum <= 0 {
		return out
	}
	type remainder struct {
		i int
		f float64
	}
	rems := make([]remainder, 0, len(w))
	left := totalMinor
	for i, v := range w {
		if v <= 0 {
			continue
		}
		exact := float64(totalMinor) * v / sum
		whole := int64(exact)
		out[i] = whole
		left -= whole
		rems = append(rems, remainder{i: i, f: exact - float64(whole)})
	}
	// Стабільним: дві однакові остачі інакше мінялися б місцями від запуску
	// до запуску, а копійка — це видиме число на екрані, не похибка.
	sort.SliceStable(rems, func(a, b int) bool { return rems[a].f > rems[b].f })
	for k := 0; left > 0 && len(rems) > 0; k++ {
		out[rems[k%len(rems)].i]++
		left--
	}
	return out
}

// planPart — один потік, який цього місяця платить, і його вага в поділі.
//
// skip — ноги в цього потоку не буде (день минув або відмічено), але ВАГА
// його лишається в знаменнику: частка потоку в місяці не залежить від того,
// чи він уже прийшов. Викинути його з поділу означало б віддати його
// гроші сусідам — і нога сусіда показала б більше, ніж переказує банк.
type planPart struct {
	date   domain.Date
	name   string
	uses   string
	weight float64
	id     int64
	skip   bool
}

// planParts — потоки місяця, які маршрут має право показати, у сталому
// порядку.
//
// ДВА РІЗНІ ПИТАННЯ, І В КОЖНОГО СВІЙ ФОКУС. «Чи платить цей потік цього
// місяця» — валовий (копія зі стовідсотковою часткою), бо потік, який у
// портфель не дає нічого, однаково платить, і саме так це питання ставлять
// buildMonthPlan і чеклист надходжень. «Скільки він додає в підсумок» —
// чистий, із відміткою: це той самий доданок, із якого підсумок і складений.
func planParts(src *sources, marks PlanMarks, today domain.Date,
	m int, key string) []planPart {

	var out []planPart
	for _, f := range src.planFlows {
		if f.Kind != "income" {
			continue
		}
		gross := f
		gross.InvestBP = 10000
		if planFlowAtMonth(gross, today, m, nil) == 0 {
			continue
		}
		date := domain.Date(receiptDueDate(key, f.FromDate.Day()))
		if date == "" {
			continue
		}
		// День уже минув: гроші або прийшли (і лежать у балансі), або не
		// прийшли — і ні того, ні того маршрут вести не має. Відмічене
		// цього місяця так само вже в балансі, і показати його ще раз
		// означало б повести ті самі гроші двічі. Лише поточний місяць: у
		// майбутніх відміток немає за побудовою.
		//
		// Обидва випадки — skip, а не continue: вага такого потоку лишається
		// в поділі (довід — при planPart).
		_, marked := marks.at(f.ID, today, m)
		skip := date < today || (marked && m == 0)
		w := PlanFlowUAH(planFlowAtMonth(f, today, m, marks), f.Currency, src.rates)
		if w <= 0 {
			continue
		}
		out = append(out, planPart{
			date: date, name: f.Name, uses: f.Uses, weight: w, id: f.ID, skip: skip,
		})
	}
	sort.SliceStable(out, func(i, j int) bool {
		switch {
		case out[i].date != out[j].date:
			return out[i].date < out[j].date
		case out[i].name != out[j].name:
			return out[i].name < out[j].name
		default:
			return out[i].id < out[j].id
		}
	})
	return out
}

// planAhead — плановий дохід як події маршруту, ПО НОЗІ НА ПОТІК.
//
// # ЧОМУ ВЖЕ НЕ ОДНА НОГА НА МІСЯЦЬ
//
// Тут стояла відмова, і знялась вона не поступкою. Вона казала: чесного
// числа «скільки цей потік дає на свою дату» не існує, бо план — нетто, і
// рознести витрати місяця по датах доходу можна лише вигаданим правилом
// (порівну? пропорційно? з першої зарплати?). Ціна тієї відмови була видна
// на живих даних: чотири надходження — 1-го, 7-го, 15-го й 21-го — ставали
// одним рядком 21-го числа. Три з них на екрані не існували, а четверте
// показувалось учетверо більшим за себе.
//
// Вихід у тому, що ділити треба не дохід із витратами окремо, а ВЖЕ ГОТОВЕ
// НЕТТО. MonthPlan.PlanUAH — те саме число, від якого рахується стеля
// подушки й ділиться місяць між видами, — розкладається між потоками
// пропорційно їхньому ЧИСТОМУ внеску, тобто рівно тому доданку, з якого
// воно й складене (buildMonthPlan). Вигаданого правила не лишається: частка
// потоку в результаті дорівнює його частці в підсумку.
//
// # ЩО ЦЕ ЗБЕРІГАЄ
//
// Сума ніг місяця дорівнює PlanUAH ДО КОПІЙКИ (splitByWeights вище), тож
// третій читач того самого числа не розходиться з першими двома. У
// поточному місяці — за вирахуванням ніг, яких уже немає (нижче).
//
// Стеля подушки лишається досяжною, і це доводиться, а не сподівається:
// PlanReserveUAH віднімає витрати ПОВНІСТЮ (state_month.go), а нога — лише
// пропорційно своїй частці, тож сума дозволених ніг завжди не менша за
// стелю. Рівний поділ цієї властивості не має — саме тому він тут і не
// годиться, хоч виглядав би простішим.
//
// # ДАТА — ДЕНЬ САМОГО ПОТОКУ
//
// Тим самим receiptDueDate, що малює чеклист надходжень («зарплата 17-го
// приходить 17-го»), тож два екрани називають один день. День найпізнішого
// доходу місяця, що стояв тут раніше, був потрібен, доки нога зводила
// місяць цілком, і зник разом із нею.
//
// # ПОТОЧНИЙ МІСЯЦЬ — ТЕ САМЕ ПРАВИЛО, ЛИШЕ БЕЗ НІГ У ТОГО, ЩО ВЖЕ ПРИЙШЛО
//
// Поділ той самий: чистий дохід місяця між УСІМА його потоками за вагою,
// разом із тими, чий день минув чи які відмічені. Ніг вони не дістають,
// але своєї частки нікому не віддають (planPart.skip). Тож нога потоку —
// його власна сума в будь-який день місяця: аванс на 4 500 ₴ показує
// 4 500 ₴ і 1-го, і 29-го.
//
// Тут стояло інше правило, і знялось воно не поступкою. Воно віддавало
// ногам, що лишились, НЕДОНЕСЕНЕ місяця (LeftUAH = план мінус уже
// закинуте), і брехало в обидва боки: 2 201 ₴, закинуті 1-го з інших
// грошей, урізали аванс і зарплату до 3 400 ₴ кожну, а коли з чотирьох
// виплат лишалась одна, вона несла весь залишок — більше за себе саму.
// Рівно та неправда про виписку, проти якої написаний InflowUAH (route.go).
// Захищати ним було нічого: стеля подушки поточного місяця береться з
// документа готовою, уже за вирахуванням відкладеного, і enterMonth цей
// місяць пропускає (newRouteCarry) — сума ніг їй не потрібна. «Скільки план
// ще просить» лишається питанням картки плану (LeftUAH, «Розкласти»), і на
// нього нога не відповідає.
//
// # ЧОГО ТУТ НЕМАЄ
//
// Позапланове (ExtraUAH) дати не має — за ним немає потоку — і в ноги НЕ
// розмазується: ділиться PlanUAH без нього. У поточному місяці це гроші,
// що вже прийшли відміткою «інше», і підняти ними ноги майбутніх днів
// означало б повести їх удруге; у майбутніх місяцях відміток не буває, і
// віднімати нема чого.
//
// Місяць, у якому дохід є ЛИШЕ позаплановий, ніг не дає взагалі: вигадати
// йому дату означало б завести друге правило заради одного випадку.
//
// # БРОКЕРА НЕМАЄ, І ЦЕ НЕ ПРОГАЛИНА
//
// Планових грошей на брокерському рахунку ще немає — вони на картці. Тому
// «—», те саме місце без привʼязки, що й у NoBrokerLabel. Наслідок треба
// назвати вголос: зарплата НЕ доскладеться до купона в mono, щоб разом
// набрати на цілий квиток. Це чесніше за протилежне — сказати, що гроші
// вже лежать там, де їх нема.
//
// Ref порожній: планове надходження відмічають у чеклисті плану
// (plan/receipts), а не статусом виплати, і кнопка «Прийшло» на такій нозі
// вела б не туди. Kind і Principal нульові: жоден вид не худне. Uses
// натомість тепер НЕ порожній — нога знає свій дозвіл, бо потік у неї один,
// і саме на цьому стоїть передача дозволу в розкладку (route.go).
func planAhead(src *sources, plans map[string]*state.MonthPlan,
	today domain.Date, months int) []readyFlow {

	if len(src.planFlows) == 0 {
		return nil
	}
	marks := NewPlanMarks(src.planReceipts)
	var out []readyFlow
	for m := 0; m <= months; m++ {
		key := MonthKeyAt(today, m)
		mp := plans[key]
		if mp == nil {
			continue
		}
		total := mp.PlanUAH.Major() - mp.ExtraUAH.Major()
		if total <= 0 {
			continue
		}
		parts := planParts(src, marks, today, m, key)
		if len(parts) == 0 {
			continue
		}
		weights := make([]float64, len(parts))
		for i := range parts {
			weights[i] = parts[i].weight
		}
		for i, cut := range splitByWeights(int64(math.Round(total*100)), weights) {
			if cut <= 0 || parts[i].skip {
				continue
			}
			out = append(out, readyFlow{
				Date: parts[i].date, Amount: cut,
				Label: parts[i].name, Basis: BasisPlan, Uses: parts[i].uses,
			})
		}
	}
	return out
}

// fundBroker — рахунок, на який фонд платить.
//
// Мажоритарний: брокер, у якого цього фонду куплено найбільше. Точної
// відповіді тут немає в принципі — операція фонду несе брокера, а виплата
// ні, — і ділити оцінений дивіденд пропорційно між двома рахунками означало
// б розбити його на суми, менші за будь-який квиток, тобто зробити маршрут
// гіршим заради видимості точності. Нічия й порожнеча дають «—», той самий
// місце без привʼязки (NoBrokerLabel).
func fundBroker(ops []domain.FundOp, fund string) string {
	byBroker := map[string]int64{}
	for _, op := range ops {
		if op.Kind != domain.FundBuy || op.Fund != fund {
			continue
		}
		b := cmp.Or(op.Broker, NoBrokerLabel)
		byBroker[b] += op.Amount
	}
	best, bestAmt, tie := NoBrokerLabel, int64(0), false
	// Обхід за відсортованими ключами: мапа в Go обходиться в довільному
	// порядку, і два запуски на тих самих даних інакше давали б різних
	// брокерів, а разом із ними — різні горщики.
	names := slices.Sorted(maps.Keys(byBroker))
	for _, b := range names {
		switch v := byBroker[b]; {
		case v > bestAmt:
			best, bestAmt, tie = b, v, false
		case v == bestAmt && bestAmt > 0:
			tie = true
		}
	}
	if tie {
		return NoBrokerLabel
	}
	return best
}

// coalesceSameDay зводить виплати одного паперу одного дня в одну подію.
//
// Купон і погашення приходять окремими рядками розкладу — типи різні, і в
// календарі це правильно. Але на рахунок вони лягають одним приходом того
// самого дня, і в складі суми «UA4000235865 817,50 ₴ + UA4000235865
// 10 000,00 ₴» назва повторюється двічі там, де сталася одна подія.
// Знайдено на живих даних НБУ, а не тестом.
//
// Зведення нічого не міняє в даті: доданки того самого дня в будь-якому
// разі накопичуються разом.
func coalesceSameDay(flows []readyFlow) []readyFlow {
	out := flows[:0:0]
	for _, f := range flows {
		if n := len(out); n > 0 && out[n-1].Date == f.Date && out[n-1].Label == f.Label {
			out[n-1].Amount += f.Amount
			// Тіло складається разом із сумою: зведений рядок і далі каже,
			// скільки в ньому доходу, а скільки повернення власного. Купон і
			// погашення одного паперу одного дня — саме той випадок, заради
			// якого це зведення й існує.
			out[n-1].Principal += f.Principal
			continue
		}
		out = append(out, f)
	}
	return out
}
