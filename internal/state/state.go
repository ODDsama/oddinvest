// MarketYieldRow — один строк однієї валюти на первинному ринку.
//
// Дата тут обов'язкова разом із рівнем: аукціони бувають раз на тиждень,
// а на валютні строки — раз на місяць і рідше, тож «3.2%» без дати не
// каже, це позавчора чи півроку тому. ISIN поруч — щоб було видно, який
// саме папір тоді розміщували.
type MarketYieldRow struct {
	Currency string  `json:"currency"`
	Bucket   string  `json:"bucket"` // строк, як його назвав НБУ: "1y", "1.5y"…
	Pct      float64 `json:"pct"`    // дохідність розміщення, до податку
	Date     string  `json:"date"`   // день аукціону, ISO
	ISIN     string  `json:"isin"`
	// VsPortfolioPP — на скільки п.п. рівень розміщення вищий за дохідність
	// портфеля В ЦІЙ САМІЙ ВАЛЮТІ (відʼємне — нижчий). Порожньо, якщо
	// паперів цієї валюти в портфелі немає: порівнювати нема з чим.
	//
	// Порівнюється саме з НОМІНАЛЬНОЮ дохідністю (portfolio_yield), не з
	// реальною. Аукціонний рівень — до податку й до знецінення, тож
	// поставити проти нього portfolio_yield_real означало б відняти в
	// однієї сторони те, чого не віднімали в другої, і різниця системно
	// завищувалась би на всю інфляцію. Те саме правило вже сформульоване
	// для читача у web/js/info.js під ключем "market"; тут воно вдруге,
	// але машиночитно — щоб наступний споживач (сповіщення в HA) не
	// виводив його втретє й не помилився на цьому самому місці.
	//
	// Це РІЗНИЦЯ ДВОХ УЖЕ ОПУБЛІКОВАНИХ ДОХІДНОСТЕЙ, а не рівень: ціною
	// паперу її не сплутати навіть випадково. Чому ціни з аукціону не
	// виводимо взагалі — у README, розділ «Чого тут свідомо немає».
	VsPortfolioPP float64 `json:"vs_portfolio_pp,omitempty"`
}

// RealizedRow — результат по одній валюті за фактом і причина, з якої
// річна ставка поруч може мовчати.
//
// MinDays лежить тут разом із MoneyDays навмисно, хоч і є константою
// коду. Без нього жоден споживач не може сказати «лишилось стільки-то»,
// не вписавши поріг у себе — а споживачів уже двоє (веб і Home
// Assistant), тож число розійшлося б утретє й учетверте. Правило
// «арифметика в одному місці» тут дешевше за поле.
// TotalReturn — зведений результат портфеля в гривневому еквіваленті.
//
// XIRRPct — ВКАЗІВНИК, а не float64 з omitempty, і це не педантизм:
// портфель законно може дати рівно 0.00% річних, і нулем не відрізнити
// «не заробив нічого» від «порогу не набрано». Решта полів заповнена
// завжди, коли обʼєкт узагалі є: результат у гривнях чесний з першого дня,
// бо не ануалізований, — і саме він пояснює, чого бракує річному числу.
type TotalReturn struct {
	XIRRPct   *float64 `json:"xirr_pct,omitempty"`
	GainUAH   float64  `json:"gain_uah"`
	GainPct   float64  `json:"gain_pct"`
	MoneyDays float64  `json:"money_days"`
	MinDays   int      `json:"min_days"`
	// FXMaxLagDays — на скільки днів найстаріший ужитий курс відстав від
	// події. Нуль = усі курси знайшлись на свою дату. Мовчати про це не
	// можна: помісячна історія означає, що подія може відставати на
	// тиждень-другий, і чесна відповідь — назвати число, а не вдавати
	// точність.
	FXMaxLagDays int `json:"fx_max_lag_days,omitempty"`
}

