package state

import "math"

// round2 — суми в документі мажорні з двома знаками (див. пакетний
// коментар). Тут своя копія, бо будівник стану живе в іншому пакеті.
func round2(v float64) float64 { return math.Round(v*100) / 100 }

// Capital — ЄДИНЕ місце, де вирішується, що таке «капітал» і що таке
// «частка валюти».
//
// Доти це вирішувалось у чотирьох місцях незалежно, і всі чотири давали
// різні числа:
//
//	Build            — папери + рахунок + фонди + вклади
//	ребаланс         — папери + рахунок
//	старт проєкції   — папери + рахунок + фонди
//	фронтенд         — сума полів документа
//
// Наслідок було видно на одному екрані: плитка «Частка USD» показувала
// 57.6%, а картка ребалансу під нею — 0% для тієї самої валюти. Обидва
// числа були «правильні» кожне у своїй арифметиці, і саме тому дізнатись,
// яке з них брехливе, не було де.
//
// НПФ (0028) додався сюди першим, а не останнім, і це не порядок правок, а
// умова: пенсійні гроші входять у капітал, тож щойно вони зʼявляються,
// КОЖНА частка, порахована без них, стає заниженою. Асистент реінвесту
// бере def і kindDef саме звідси — тобто без цього рядка він рахував би
// пораду від хибного знаменника й лишався б при цьому правдоподібним.
//
// Тому тип, а не хелпер: хелпер із п'ятьма параметрами так само дозволяє
// передати різне з різних місць, а структура збирається один раз і далі
// лише читається.
type Capital struct {
	// BondsUAH — номінал ОВДП, грн-екв., усі валюти разом.
	BondsUAH Money
	// AccountUAH — гроші на рахунках брокерів, грн-екв.
	AccountUAH Money
	// FundsUAH — ринкова вартість сертифікатів, грн-екв.
	FundsUAH Money
	// DepositsUAH — тіло діючих вкладів, грн-екв.
	DepositsUAH Money
	// ReserveUAH — резерв («матрац»), грн-екв.
	ReserveUAH Money
	// GoalsUAH — цілі накопичення, грн-екв.
	//
	// У капіталі з того самого доводу, що й резерв: капітал — це «скільки в
	// мене є», а не «скільки я можу вкласти». На друге відповідає купівельна
	// спроможність, і там цілі віднімаються нарівні з подушкою (аргумент —
	// у міграції 0039).
	GoalsUAH Money
	// NPFUAH — пенсійні активи, грн-екв.
	//
	// У капіталі, попри те, що витратити їх не можна до 50 років: капітал —
	// це «скільки в мене є», а не «скільки я можу зняти». Друге питання
	// ставить ліквідність, і саме там НПФ стоїть у locked_uah окремим
	// рядком, щоб «замкнено до 2027-03» не читалось як правда про гроші, що
	// звільняються у 2051-му.
	NPFUAH Money

	// *ByCur — грн-еквівалент того, що є СПРАВЖНЬОЮ експозицією в валюту.
	//
	// Готівки брокера тут немає навмисно: вона от-от стане чимось іншим,
	// тож стоїть лише в знаменнику («вільний кеш розводить частки»).
	// Резерв, навпаки, грішми й лишиться — $5000 у матраці це валютна
	// експозиція нарівні з доларовим папером.
	// НПФ тут є, на відміну від фондів: одиниці пенсійних активів — це
	// справжня експозиція в гривню, і найдовша з усіх. Сертифікатів немає з
	// тієї ж причини, що й доти (їхня валютна природа складніша за код
	// валюти операції), а замок на експозицію не впливає: гроші, які не
	// можна забрати, все одно знецінюються разом із гривнею.
	//
	// Цілі накопичення — так само справжня експозиція, і рахуються вони за
	// валютою САМИХ ГРОШЕЙ, а не за валютою цілі. Це різні речі: «збираю на
	// авто $20 000, лежить у гривні» дає гривневу експозицію, а курс при
	// цьому працює ПРОТИ цілі — саме те, що Goal.FXMixed і називає.
	BondsByCur    map[string]Money
	DepositsByCur map[string]Money
	ReserveByCur  map[string]Money
	GoalsByCur    map[string]Money
	NPFByCur      map[string]Money
}

// TotalUAH — увесь капітал, грн-екв.
func (c Capital) TotalUAH() float64 {
	return c.BondsUAH.Major() + c.AccountUAH.Major() + c.FundsUAH.Major() + c.DepositsUAH.Major() +
		c.ReserveUAH.Major() + c.GoalsUAH.Major() + c.NPFUAH.Major()
}

// ExposureUAH — скільки капіталу стоїть у цій валюті, грн-екв.
func (c Capital) ExposureUAH(cur string) float64 {
	return c.BondsByCur[cur].Major() + c.DepositsByCur[cur].Major() + c.ReserveByCur[cur].Major() +
		c.GoalsByCur[cur].Major() + c.NPFByCur[cur].Major()
}

// SharePct — частка валюти в капіталі, %.
func (c Capital) SharePct(cur string) float64 {
	total := c.TotalUAH()
	if total <= 0 {
		return 0
	}
	return c.ExposureUAH(cur) * 100 / total
}
