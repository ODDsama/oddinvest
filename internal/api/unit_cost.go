// Ціна ОДНОГО кроку покупки — в одному місці на весь застосунок.
//
// Крок різний за природою: папір купують штуками, сертифікат теж
// штуками, але за ринковою ціною, вклад поповнюють сумою відкриття.
// Спільне в них те, що це найменша неподільна покупка, і саме нею
// міряється «на скільки вистачить грошей».
//
// Чому не два обчислення. Помічник реінвесту показує ціну в пораді,
// кошик рахує з неї «що станеться, якщо куплю». Якби кожен рахував сам,
// той самий папір мав би на екрані дві ціни, і жодна не була б очевидно
// правильною — цей застосунок уже проходив таке з частками капіталу
// (див. state.Capital) і з арифметикою помічника (handlers_reinvest.go).
//
// # ЦІНА ПАПЕРУ ТЕПЕР БУВАЄ РИНКОВОЮ
//
// Доти тут стояло «ціни в довіднику НБУ немає, тож за номіналом — чесне
// наближення». Джерело знайшлось (internal/finomo), і наближення
// виявилось дорогим: папір коштує 1 100 ₴ там, де номінал плюс НКД давав
// 1 011 ₴. Помилка йшла ОДРАЗУ В ДВА місця — у розмір квитка й у
// дохідність, бо YTM рахується саме від ціни входу.
//
// Тому правило тут одне на пару (папір, дата): є свіжа ринкова ціна —
// беремо її; немає — старе наближення, слово в слово. І в обох випадках
// функція каже, ЩО САМЕ віддала: мовчазна підміна одного числа іншим на
// тому самому екрані — головний ризик цієї роботи, і сигнатура мусить
// змушувати кожного читача донести підставу до людини.

package api

import (
	"math"

	money "github.com/Rhymond/go-money"

	"github.com/ODDsama/oddinvest/internal/domain"
	"github.com/ODDsama/oddinvest/internal/store"
)

// Підстава ціни кроку — з чого вона взята.
const (
	CostBasisMarket  = "market"
	CostBasisNominal = "nominal"
)

// quoteFreshDays — скільки днів ринкова ціна лишається ціною.
//
// Продавці котирують у торгові дні. П'ятнична ціна, прочитана в
// понеділок, — це три дні, і вона досі останнє, що сказав ринок; п'ять
// покривають довгі вихідні зі святом. Далі ми не знаємо, і «не знаємо»
// мусить падати на чесний номінал плюс НКД, а не на тижневе число,
// вдягнене в сьогоднішню дату.
//
// Той самий поріг діє й на ціну, вписану руками. Вона старіє так само —
// а помітити це важче, бо оновити її нікому, крім людини: рядок mono
// виглядає рівно так, як здобутий обходом.
const quoteFreshDays = 5

// quoteSaneBand — у скільки разів ціна може відхилятись від номіналу,
// перш ніж ми відмовимось у неї вірити.
//
// Другий шар сторожа масштабу (перший — у jobs, звірка номіналу з
// довідником). Єдиний спосіб отримати 101365 замість 1013.65 — помилка
// масштабу, і вона не виглядає помилкою: папір просто стає в сто разів
// дорожчим і тихо зникає з усіх порад, бо на нього «не вистачає».
const quoteSaneBand = 0.5

// bondUnitCost — скільки сьогодні коштує один папір, і на якій підставі.
//
// q — найдешевша ціна серед ТВОЇХ брокерів (freshestQuote нижче), або
// nil. Ринкова ціна БРУДНА, тобто вже містить накопичений купон, тож
// EstimateAccrued до неї НЕ ДОДАЄТЬСЯ: перевірено XIRR'ом на п'яти
// паперах — дохідність, порахована від неї як є, збігається з
// опублікованою до третього знака (16.600 % проти 16.60 %), а з доданим
// НКД дала б 15.975 %. Помилка була б тиха, однобічна і в −0,6 в.п.
//
// on — дата, НА ЯКУ питаємо. Саме проти неї, а не проти «сьогодні»,
// міряється свіжість, і це не педантизм: план купівель питає ціну на
// півроку вперед (state_plan_buys.go), і сьогоднішня котировка для тієї
// дати не є ціною. Правило дати робить це само, без особливого випадку в
// місці виклику.
func bondUnitCost(b domain.Bond, pays []domain.Payment, on domain.Date,
	q *store.Quote) (*money.Money, string) {

	if m, ok := marketCost(b, on, q); ok {
		return m, CostBasisMarket
	}
	cost := b.Nominal
	acc, err := domain.EstimateAccrued(pays, b.ISIN, on)
	if err != nil || acc == nil {
		return cost, CostBasisNominal
	}
	sum, err := cost.Add(acc)
	if err != nil {
		return cost, CostBasisNominal
	}
	return sum, CostBasisNominal
}

// marketCost — чи годиться ця котировка за ціну кроку на дату on.
//
// Усі відмови мовчазні навмисно: жодна з них не є подією, про яку варто
// сказати, — усі означають одне й те саме «ринкової ціни на цю дату не
// знаємо», а сказати це вміє сама підстава, яку віддає bondUnitCost.
func marketCost(b domain.Bond, on domain.Date, q *store.Quote) (*money.Money, bool) {
	if q == nil || q.PriceMinor <= 0 {
		return nil, false
	}
	code := b.Nominal.Currency().Code
	if q.Currency != code {
		return nil, false
	}
	// Дата має бути валідною з обох боків: DaysBetween мовчки читає
	// зіпсовану як нульовий час, і котировка з кривою датою інакше
	// виглядала б свіжою рівно тоді, коли їй вірити не можна.
	if !q.Date.Valid() || !on.Valid() {
		return nil, false
	}
	// Від'ємне теж відкидаємо: ціна «з майбутнього» означає не свіжість, а
	// зіпсований ряд. А велике додатне — ту саму котировку, прикладену до
	// дати, для якої вона нічого не значить (план купівель на півроку).
	if days := domain.DaysBetween(q.Date, on); days < 0 || days > quoteFreshDays {
		return nil, false
	}
	if nom := b.Nominal.Amount(); nom > 0 {
		ratio := float64(q.PriceMinor) / float64(nom)
		if math.Abs(ratio-1) > quoteSaneBand {
			return nil, false
		}
	}
	return money.New(q.PriceMinor, code), true
}

// fundUnitCost — один сертифікат за останньою відомою ціною. Нуль
// означає «ціни немає», і купувати за неї не можна нічого.
func fundUnitCost(lastPrice float64, currency string) *money.Money {
	if currency == "" {
		currency = money.UAH
	}
	minor := int64(math.Round(lastPrice * 100))
	if minor < 0 {
		minor = 0
	}
	return money.New(minor, currency)
}
