// Вибір ціни: яка з відомих котировок стає ціною кроку.
//
// # ЧОМУ ВІДБІР ІДЕ ПО СВОЇХ БРОКЕРАХ, А НЕ ПО РИНКУ
//
// Джерело возить ціни шести продавців, і найдешевша з них — цікавий
// факт, але не відповідь на питання «почім це мені». Рахунку в Kinto
// може не бути зовсім, і порада «купи за 1 013 ₴» означала б тоді
// «спершу відкрий рахунок», а квиток розкладки був би менший за той, що
// заплатиш насправді.
//
// Тому в кошик відбору потрапляють лише ті джерела, які зіставлені з
// рядками довідника брокерів (`brokers.quote_source`, 0059). Незіставлений
// брокер — mono, у якого цін не публікує ніхто, — у відборі не бере
// участі, доки ціну не вписали руками.
//
// # І ЧОМУ ОДНА ЦІНА НА ПАПІР, А НЕ ПО ОДНІЙ НА БРОКЕРА
//
// Спокуса очевидна: показати кожного продавця своїм рядком. Але рядок
// розкладки веде арифметику — кількість штук, суму, YTM, — і два рядки
// одного ISIN із різними цінами означали б, що allocAddLine
// (handlers_allocate.go) мусить вирішувати, який із них зливати. Такого
// правила немає, і вигадувати його заради показу не можна: різниця між
// брокерами показується ПОРУЧ із рядком, окремим підписом.
//
// # ЦЕ РОБИТЬ ВИБІР ПОРТФЕЛЬНИМ, А ТАБЛИЦЯ ЛИШАЄТЬСЯ ДОВІДКОВОЮ
//
// Ціна паперу в брокера одна на всіх — тому в ovdp_quotes немає
// portfolio_id (довід — у шапці 0059). А от ЯКУ з цих цін застосунок
// візьме, вирішує зіставлення, і воно вже належить портфелю: у дружини
// інші брокери. Факт спільний, вибір із фактів — свій, і тягнути
// portfolio_id у таблицю через це не треба.

package api

import (
	"context"
	"strings"
	"time"

	"github.com/ODDsama/oddinvest/internal/domain"
	"github.com/ODDsama/oddinvest/internal/store"
)

// quotePick — обрана ціна паперу разом із тим, що про неї треба сказати.
//
// Alt — наступна за ціною серед СВОЇХ, або порожньо. Потрібна рівно для
// одного речення на екрані («в Inzhur 1 013,65, у Приват24 1 018,62»),
// заради якого вся робота й робилась: без порівняння «найдешевше» — це
// твердження, яке нема з чим звірити.
type quotePick struct {
	Best  *store.Quote
	Alt   *store.Quote
	Label string // українська назва обраного продавця, якщо відома
}

// quoteBook — обрані ціни по паперах плюс усе, що знадобиться екрану.
type quoteBook struct {
	byISIN map[string]quotePick
	// all — увесь зріз, у порядку «папір, далі дешевші першими». Сторінка
	// позицій показує його цілком, включно з продавцями, у яких рахунку
	// немає: як орієнтир «де взагалі дешевше» це чесно, доки поруч
	// написано, що рахунку там немає.
	all []store.Quote
	// mine — ключ джерела -> назва МОГО брокера. Порожня мапа означає, що
	// не зіставлено жодного, і тоді ринкової ціни немає ні в кого: це не
	// поломка, а стан «зіставлення ще не зробили».
	mine      map[string]string
	fetchedAt string
	// sweptFresh — обхід НЕДАВНО покрив увесь довідник, тож «ціни немає»
	// означає «ніхто зі своїх не продає», а не «ми не питали». Лише за
	// цієї умови можна ховати папери без ціни; довід — при hideUnpriced.
	sweptFresh bool
}

// hideUnpriced — чи можна зараз ховати папери без ціни свого брокера.
//
// # ЧОМУ ЦЕ НЕ ПРОСТО «НЕМАЄ ЦІНИ — НЕМАЄ ПОРАДИ»
//
// Власник попросив не показувати те, чого не купиш: «важливіше щоб він був
// у доступності». Ціна від ТВОГО брокера і є доказом доступності — але
// ЛИШЕ тоді, коли її відсутність щось означає. Доки обхід питав шістдесят
// паперів зі ста вісімдесяти шести, відсутність ціни означала переважно
// «ми не питали», і фільтр сховав би півтори сотні паперів за неправдивою
// підставою.
//
// Тому право ховати вмикається знаком повного обходу (QuotesSweptAtKey) і
// гасне разом із ним: знака немає або він протух — список лишається таким,
// як був, а екран каже, що ціни давно не оновлювали. Тобто застосунок
// мовчить про доступність рівно доти, доки не має права про неї говорити.
func (b quoteBook) hideUnpriced() bool { return b.sweptFresh }

func (b quoteBook) pick(isin string) *store.Quote {
	if p, ok := b.byISIN[strings.ToUpper(isin)]; ok {
		return p.Best
	}
	return nil
}

// quotesFor — зріз цін для названих паперів разом із відбором по своїх.
//
// Порожній перелік паперів означає «всі» — так читає сторінка позицій.
// on — дата, НА ЯКУ обираємо: свіжість міряється проти неї (див. pickQuotes).
func (s *Server) quotesFor(ctx context.Context, isins []string, on domain.Date) (quoteBook, error) {
	book := quoteBook{byISIN: map[string]quotePick{}, mine: map[string]string{}}
	brokers, err := s.st.ListBrokers(ctx)
	if err != nil {
		return book, err
	}
	for _, b := range brokers {
		if src := strings.TrimSpace(b.QuoteSource); src != "" {
			book.mine[src] = b.Name
		}
	}
	all, err := s.st.LatestQuotes(ctx, isins)
	if err != nil {
		return book, err
	}
	book.all = all
	if book.fetchedAt, err = s.st.QuotesFetchedAt(ctx); err != nil {
		return book, err
	}
	book.byISIN = pickQuotes(all, book.mine, on)
	swept, err := s.st.GetAppState(ctx, store.QuotesSweptAtKey)
	if err != nil {
		return book, err
	}
	book.sweptFresh = sweepFresh(swept, on)
	return book, nil
}

// sweepFresh — чи не застарів знак повного обходу.
//
// Той самий поріг, що й у самої ціни (quoteFreshDays): обхід, старший за
// нього, не може підтверджувати доступність, бо й ціни з нього вже не
// ціни. Порожній або нерозбірливий знак читається як «обходу не було» —
// найобережніше з можливих значень, бо від нього залежить, чи ховати.
func sweepFresh(at string, on domain.Date) bool {
	t, err := time.Parse(time.RFC3339, strings.TrimSpace(at))
	if err != nil {
		return false
	}
	days := domain.DaysBetween(domain.NewDate(t), on)
	return days >= 0 && days <= quoteFreshDays
}

// pickQuotes — найдешевша СВІЖА ціна кожного паперу серед своїх, і
// наступна за нею.
//
// СВІЖІСТЬ ПЕРЕВІРЯЄТЬСЯ ТУТ, А НЕ ПОТІМ, і це головна річ у цій функції.
// Доти відбір ішов самою лише ціною, а вік перевірявся аж у bondUnitCost —
// тобто протухла, але дешевша котировка вигравала відбір, провалювала
// перевірку й забирала з собою свіжу дорожчу, лишаючи рядок за номіналом.
// На живих даних: UA4000236228 мав учорашню ціну Privat24 (1 097,09) і
// ціну Inzhur місячної давнини (1 087,18) — рядок показував 1 084,56 за
// номіналом і дохідність 17,9 % замість справжніх 15,0 %.
//
// Alt теж мусить бути свіжим: рядок «у Privat24 дорожче» з тримісячною
// ціною порівнював би сьогоднішнє з позаминулим і виглядав би при цьому
// як звичайне порівняння.
//
// Чиста функція над готовим зрізом — саме тому її можна перевірити тестом,
// не піднімаючи ні сервера, ні бази.
func pickQuotes(all []store.Quote, mine map[string]string, on domain.Date) map[string]quotePick {
	out := map[string]quotePick{}
	// LatestQuotes уже віддає «папір, далі дешевший першим», тож перші дві
	// придатні котировки в кожному папері — це найкраща й наступна за нею.
	// Другого сортування тут немає навмисно: порядок — властивість запиту,
	// і друга його копія розійшлася б із першою тихо.
	for i := range all {
		q := all[i]
		if _, ok := mine[q.Source]; !ok {
			continue
		}
		if !quoteFresh(&all[i], on) {
			continue
		}
		p := out[q.ISIN]
		switch {
		case p.Best == nil:
			p.Best, p.Label = &all[i], mine[q.Source]
		case p.Alt == nil:
			p.Alt = &all[i]
		default:
			continue
		}
		out[q.ISIN] = p
	}
	return out
}
