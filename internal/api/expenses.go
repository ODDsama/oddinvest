// Місячні витрати в гривні — переклад того, що ввів користувач.
//
// ЧОМУ ОКРЕМА ФУНКЦІЯ, А НЕ ПОЛЕ, ЯКЕ ЧИТАЮТЬ ЗІ СХОВИЩА. Витрати
// мисляться тією валютою, у якій живуть: «півтори тисячі доларів на
// місяць» — це одиниця рахунку, а не оцінка в чужих грошах (міграція
// 0038). Але вісім місць застосунку — ціль резерву, голова подушки,
// драбина, просадка, точка незалежності, віхи прогресу — читають
// SettingsDoc.MonthlyExpensesUAH і всі вісім вважають число ГРИВНЯМИ.
//
// Провести курс через пакет state, щоб він переводив сам, не можна: у
// нього немає ні курсів, ні «сьогодні», і саме цей поділ описаний у шапці
// state_reserve_ladder.go — будівник зводить, state тлумачить. Тому
// переклад живе тут, робиться РАЗ і кладеться в те саме поле.
//
// ЧОМУ СЬОГОДНІШНІЙ КУРС, А НЕ КУРС НА ДАТУ. Питання, на яке відповідають
// витрати, — «скільки коштує місяць життя ЗАРАЗ». Історії в них немає:
// це не потік подій, а одне число політики, і fx_asof.go (курс на дату
// події) тут не при чому.
package api

import (
	money "github.com/Rhymond/go-money"

	"github.com/ODDsama/oddinvest/internal/fx"
	"github.com/ODDsama/oddinvest/internal/state"
)

// resolveExpensesUAH заповнює MonthlyExpensesUAH із валютної пари.
//
// Порожній MonthlyExpenses лишає гривневе поле незайманим, і це не
// байдужість, а сам механізм сумісності: у базі, старшій за 0038, воно
// прочитане зі спадкового ключа monthly_expenses_uah, і затерти його
// нулем означало б вимкнути резерв тому, хто про це не просив.
//
// Помилка переведення веде туди ж, куди й порожнє значення. Причина в неї
// одна — невідомий код валюти, — а від нього стереже перелік у реєстрі;
// падати ж на розборі того, що вже лежить у базі, довелось би на кожній
// сторінці (той самий довід, що при applySetting).
func resolveExpensesUAH(set *state.SettingsDoc, rates fx.Rates) {
	if set == nil || set.MonthlyExpenses == nil {
		return
	}
	cur := orUAH(set.MonthlyExpensesCurrency)
	m := money.New(int64(*set.MonthlyExpenses*100+0.5), cur)
	u, err := fx.ToUAH(m, rates)
	if err != nil {
		return
	}
	uah := float64(u.Amount()) / 100
	set.MonthlyExpensesUAH = &uah
}
