// Маршрут грошей — куди піде те, що ще тільки прийде.
//
// Сторінка відповідає на питання, яке доти ставилось головою й лише заднім
// числом: «прийшов купон — куди його». Застосунок знав відповідь ще до
// того, як гроші прийшли (розклад виплат + політика + рейтинг), і мовчав
// рівно тому, що ніхто не спитав.
//
// ЖОДНОГО ЧИСЛА ТУТ НЕ РАХУЄТЬСЯ. Усе приходить із GET /api/route — навіть
// суми в колонці «Куди піде» беруться готовими рядками розкладки, а не
// складаються тут. Перша нога маршруту при цьому байт у байт дорівнює
// POST /api/allocate на ту саму суму, і це закріплено тестом на бекенді.
//
// КОЛОНКА «КУДИ ПІДЕ» — НЕ ДРУГА КОПІЯ ТАБЛИЦІ КРОКІВ (linesHTML в
// allocate.js). Та відповідає на «що саме купити»: кількість, ціна кроку,
// реальна дохідність, кнопка в план. Ця — на «куди пішли гроші цієї
// події»: назва й сума, стовпчиком усередині комірки. Повна таблиця
// всередині комірки таблиці нечитабельна, а урізати linesHTML до двох
// колонок означало б зробити з неї щось третє. Там, де питання таки те
// саме — у модалці «Прийшло», — кроки показує саме linesHTML: кнопка
// відкриває звичайну розкладку, а не свою копію.
//
// КНОПКА «ПРИЙШЛО» Є РІВНО ОДИН ДЕНЬ. Учорашню виплату domain.Arrived уже
// вважає отриманою й показує в балансі; завтрашніх грошей на рахунку ще
// немає. День самої виплати — єдиний, коли обидва твердження хибні, і саме
// тоді ухвалюється рішення. Оцінка кнопки не має взагалі: дивіденд фонду
// позначати нема чого, його справжній запис приходить випискою.
//
// ЧОМУ ЦЕ ОКРЕМА СТОРІНКА, А НЕ КОЛОНКА В «КАЛЕНДАРІ ВИПЛАТ». Зернистість
// рядка різна: у календарі рядок — одна виплата, тут — один ГОРЩИК, що
// може зібратись із трьох виплат і двох місяців. Час різний: календар має
// архів і відмітки «отримано», маршрут дивиться лише вперед. Джерело
// різне. Звести їх в одну таблицю означало б поставити в один список два
// різні знаменники — рівно та помилка, проти якої написана шапка
// buildSchedule.
//
// ЩО СТОЇТЬ ПІД ТАБЛИЦЕЮ І ЧОМУ ЦЕ НЕ ДРІБНИЦЯ. Порядок і ціна тут
// СЬОГОДНІШНІ: майбутнього НКД, майбутніх аукціонних рівнів і майбутнього
// довідника НБУ ми не знаємо. Сказати це зобов'язана саме сторінка —
// таблиця з датами 2027 року інакше читалась би як прогноз цін, яким вона
// не є й бути не може.

import { esc, uah0 as fmtUAH, dayMonth } from "../format.js";
import { opsGrid } from "../grid.js";
import { kindPill, empty } from "../components.js";
import { infoBtn } from "../info.js";
import { routeFor } from "../routes.js";
import { openAllocate, buyBody } from "./allocate.js";

// Основа надходження — підписом, і ТІЛЬКИ коли вона не «портфель це винен».
//
// Позначати кожен рядок означало б написати «зобовʼязання» двадцять разів
// поспіль і сховати за цим три рядки, які справді інші. Тому підпис несе
// виняток, а правило названо прозою під таблицею — інакше відсутність
// позначки читалась би як «невідомо».
//
// «Різні основи» замість колишнього «оцінка + зобовʼязання»: відколи в
// маршруті є й плановий дохід, у горщику можуть зійтися будь-які дві з
// трьох, і стара пара називала б одну з комбінацій неправдиво. Яка саме
// пара зійшлась, видно з ніг, що в цей горщик привели.
const BASIS = {
  estimate: "оцінка",
  plan: "план",
  mixed: "різні основи",
};

// Куди підуть гроші однієї ноги — стовпчиком, а не вкладеною таблицею.
//
// Подушка першим рядком, і це не оформлення: вона й у розкладці забирає
// своє першою, тож інший порядок тут суперечив би самому обчисленню.
function destHTML(leg) {
  const rows = [];
  if (leg.reserve && leg.reserve.amount_uah > 0) {
    rows.push(`<div class="fine">${kindPill("reserve")}
      <b>${fmtUAH(leg.reserve.amount_uah)}</b></div>`);
  }
  // Цілі — ДРУГИМИ, одразу за подушкою й перед паперами: так само, як у
  // самому обчисленні. Інший порядок тут суперечив би розкладці.
  for (const g of leg.goals || []) {
    rows.push(`<div class="fine">${kindPill("goal")} ${esc(g.name)}
      — <b>${fmtUAH(g.amount_uah)}</b></div>`);
  }
  for (const l of leg.lines || []) {
    rows.push(`<div class="fine">${kindPill(l.kind)} ${esc(l.label)}
      — <b>${fmtUAH(l.total_uah)}</b></div>`);
  }
  // Чому подушки в цьому рядку немає, хоч стеля місяця ще не добрана.
  // Причина одна — політика «Подушку наповнювати», — і без неї зникла
  // вирізка читалась би як поломка. Стоїть ПІСЛЯ призначень: спершу куди
  // гроші пішли, потім куди не пішли й чому.
  if (leg.reserve_skip_why) {
    rows.push(`<div class="fine-xs t-warn">${esc(leg.reserve_skip_why)}</div>`);
  }
  if (leg.goals_skip_why) {
    rows.push(`<div class="fine-xs t-warn">${esc(leg.goals_skip_why)}</div>`);
  }
  if (!rows.length) {
    // Порожня комірка читалась би як «загубилось». Причина в маршруті
    // завжди є: її називає сама розкладка (note або rest_why).
    return `<span class="muted fine-xs">${esc(leg.note || leg.rest_why
      || "нічого цілого не склалось — гроші чекають наступного надходження")}</span>`;
  }
  return rows.join("");
}

function legsHTML(doc) {
  return opsGrid({
    cols: [
      {
        key: "when", label: "Коли",
        cell: (leg) => `${esc(dayMonth(leg.date))}
          <div class="fine-xs muted">${esc(leg.label)}${leg.broker
  ? " · " + esc(leg.broker) : ""}</div>`,
      },
      {
        key: "inflow", label: "Надійде", num: true,
        // Саме надійде, а не весь горщик: сказати «надійде 3 123 ₴», коли
        // банк переказує 1 312 ₴, а решта чекала з минулого разу, було б
        // неправдою про виписку. Обидва числа стоять поруч і підписані.
        cell: (leg) => fmtUAH(leg.inflow_uah)
          + (BASIS[leg.basis]
            ? `<div class="fine-xs t-warn">${esc(BASIS[leg.basis])}</div>` : "")
          + (leg.principal_uah > 0
            ? `<div class="fine-xs muted">з них тіло ${fmtUAH(leg.principal_uah)}</div>` : "")
          // Чому число менше за нараховане. Приходить готовим рядком: різниця
          // між рентою й решткою рахується на бекенді, як і все інше тут.
          + (leg.inflow_why
            ? `<div class="fine-xs muted">${esc(leg.inflow_why)}</div>` : "")
          + (leg.carry_in_uah > 0
            ? `<div class="fine-xs muted">+ ${fmtUAH(leg.carry_in_uah)} з попереднього</div>`
            : ""),
      },
      { key: "pot", label: "Разом", num: true, cell: (leg) => fmtUAH(leg.amount_uah) },
      { key: "dest", label: "Куди піде", cell: destHTML },
      {
        key: "rest", label: "Лишиться", num: true,
        cell: (leg) => (leg.rest_uah > 0
          ? fmtUAH(leg.rest_uah)
            + `<div class="fine-xs muted">чекає наступного надходження</div>`
          : `<span class="muted">—</span>`),
      },
      {
        key: "act", label: "", cls: "row-actions nowrap",
        // Кнопка є РІВНО в ноги, датованої сьогодні, і рівно доки виплата не
        // позначена. Це не сором'язливість, а межа domain.Arrived: учорашню
        // виплату застосунок уже вважає отриманою й показує в балансі, а
        // завтрашніх грошей на рахунку ще немає — розкладати нічого. Один
        // день, коли обидва твердження хибні, і є моментом рішення.
        //
        // Оцінка кнопки не має: дивіденд фонду позначати нема чого, його
        // справжній запис приходить випискою (тому ref порожній).
        cell: (leg) => {
          if (leg.date === doc.from && leg.ref) {
            return `<button class="sm" data-arrived="${esc(String(leg.id))}">Прийшло</button>`;
          }
          // Планова нога ref не має й мати не може: її відмічають у
          // чеклисті плану (plan/receipts), а не статусом виплати. Кнопка
          // «Прийшло» тут писала б не в ту таблицю, тож замість неї —
          // дорога туди, де відмітка справді живе.
          if (leg.basis === "plan" && leg.date === doc.from) {
            return `<a class="lnk fine-xs" href="${routeFor("plan/inflow")}"
              >відмітити в плані</a>`;
          }
          if ((leg.planned || []).length) {
            return `<span class="muted fine-xs">у плані:
              ${esc(leg.planned.join(", "))}</span>`;
          }
          return leg.pinnable
            ? `<button class="sm quiet" data-pin="${esc(String(leg.id))}">Закріпити</button>`
            : "";
        },
      },
    ],
    rows: (doc.legs || []).map((leg, i) => ({ ...leg, id: i })),
    caption: "Маршрут грошей: коли надійде, скільки, куди піде і що лишиться",
  });
}

/** Маршрут грошей: кожне майбутнє надходження й те, куди воно веде. */
export async function renderRoute(ctx, main) {
  let doc;
  try {
    doc = await ctx.api("GET", "route");
  } catch (err) {
    // Своя помилка лишається своєю: вище вже намальований вердикт плану, і
    // стерти його заради однієї таблиці означало б погасити сторінку цілком.
    // Той самий прийом, що в renderCalendar.
    main.insertAdjacentHTML("beforeend", `<div class="card"><h2>Маршрут грошей</h2>
      <div class="muted">Маршрут не завантажився: ${esc(err.message || err)}</div></div>`);
    return;
  }

  const body = (doc.legs || []).length
    ? legsHTML(doc) + `
      <div class="sub-xs">Рядок без позначки — <b>зобовʼязання</b>: портфель винен це
        сам собі, і сума відома з графіка. «Оцінка» — дивіденд фонду, порахований з
        його ставки, а не з обіцянки на конкретну дату. «План» — те, що має надійти за
        планом доходу: одна нога на місяць, чистими (дохід і позапланове мінус витрати),
        датована днем найпізнішого доходу того місяця, бо раніше сума ще неповна.
        Рахунку в неї немає — планові гроші ще не в брокера, — тож із купонами в один
        квиток вони не складаються. Коли в горщику зійшлись різні основи, так і написано.
        Дата «коли вистачить» у «Що купити» ні оцінок, ні плану не бачить навмисно —
        там одне число, і припущення в ньому стало б невидимим.</div>
      <div class="sub-xs">Порядок і ціна кроку тут <b>сьогоднішні</b>: майбутнього НКД,
        майбутніх розміщень Мінфіну й майбутнього довідника НБУ ми не знаємо, а число,
        яке виглядає виведеним і насправді вигадане, гірше за його відсутність.
        Це твердження про сьогоднішні розриви твоєї політики, прикладене вперед —
        не прогноз цін.</div>
      <div class="sub-xs">Виплати по датах, без призначень —
        <a class="lnk" href="${routeFor("plan/payouts")}">Календар виплат</a>.</div>`
    : empty("Маршрут порожній", doc.note
      || "До горизонту портфель нічого не винен сам собі.");

  const card = `<div class="card">
    <h2 class="card-head"><span>Маршрут грошей ${infoBtn("route")}</span>
      <span class="muted fine-xs">${esc(doc.from)} — ${esc(doc.to)}</span></h2>
    <div class="note">Кожне надходження — те, що портфель уже винен сам собі, і те,
      що має принести план доходу, — і те, куди воно піде за <b>твоєю</b> політикою:
      стеля подушки, з яких грошей вона ріже, цільові частки за видом, твій порядок у
      «Що купити». Дрібні надходження чекають одне одного, доки не набереться на цілий
      квиток — рахунки при цьому роздільні.</div>
    ${body}</div>`;
  main.insertAdjacentHTML("beforeend", card);

  // «Прийшло» — дві дії одним рухом, і порядок між ними значущий.
  //
  // Спершу відмітка: доки її немає, domain.Arrived не кладе ці гроші на
  // рахунок, а розкладка рахується від документа, який їх не бачить. Потім
  // модалка — уже на свіжому стані, з рядком про те, куди вів маршрут.
  //
  // Розкладка тут НЕ береться готовою з ноги, хоч вона в нозі й лежить:
  // маршрут будувався до відмітки, і між двома числами могла минути доба.
  // Нога передається як `routed` — щоб було видно, куди вело, — а рішення
  // ухвалюється за щойно порахованим. Показати старе замість нового
  // означало б запропонувати записати вчорашню відповідь.
  main.querySelectorAll("[data-arrived]").forEach((b) =>
    b.addEventListener("click", async () => {
      const leg = (doc.legs || [])[Number(b.dataset.arrived)];
      if (!leg) return;
      b.disabled = true;
      try {
        await ctx.api("POST", "payments/status",
          { isin: leg.ref, pay_date: leg.date, status: "received" });
      } catch (err) {
        b.disabled = false;
        ctx.toast(String(err.message || err), false);
        return;
      }
      await openAllocate(ctx, {
        amount: leg.amount.amount, currency: leg.amount.currency,
        title: leg.label, routed: leg,
        // Кнопка є лише в ноги з ref, а ref мають самі виплати портфеля:
        // планове надходження відмічають у чеклисті плану. Тіло — звідси ж,
        // у нативній валюті, бо в гривні воно віддало б подушці курс.
        source: "portfolio",
        principal: leg.principal ? leg.principal.amount : 0,
      });
      ctx.reload();
    }));

  // «Закріпити» — кладе кроки ноги в план купівель із ЇЇ датою.
  //
  // Тіло рядка збирає buyBody з розкладки, а не цей файл: поля, яких вид
  // не має, бекенд відхиляє, і мовчки підкладати нулі означало б обходити
  // перевірку. Відмова (без ставки замок у прогнозі лише заморозив би
  // гроші) показується дослівно — ковтати 400 тут найгірше, бо рядок
  // просто не зʼявиться, а сторінка вдаватиме, що все записалось.
  main.querySelectorAll("[data-pin]").forEach((b) =>
    b.addEventListener("click", async () => {
      const leg = (doc.legs || [])[Number(b.dataset.pin)];
      if (!leg) return;
      b.disabled = true;
      const requests = (leg.lines || []).filter((l) => l.addable).map((l) => ({
        path: "plan/buys",
        body: {
          ...buyBody(l),
          buy_date: leg.date,
          broker: leg.broker === "—" ? "" : leg.broker,
          note: `маршрут: ${leg.label} · ${leg.date}`,
        },
      }));
      if (!requests.length) return;
      try {
        for (const rq of requests) await ctx.api("POST", rq.path, rq.body);
        ctx.toast("Закріплено в плані купівель");
        ctx.reload();
      } catch (err) {
        b.disabled = false;
        ctx.toast(String(err.message || err), false);
      }
    }));
}
