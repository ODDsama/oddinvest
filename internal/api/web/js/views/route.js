// Маршрут грошей — куди піде те, що ще тільки прийде.
//
// Сторінка відповідає на питання, яке доти ставилось головою й лише заднім
// числом: «прийшов купон — куди його». Застосунок знав відповідь ще до
// того, як гроші прийшли (розклад виплат + політика + рейтинг), і мовчав
// рівно тому, що ніхто не спитав.
//
// ЖОДНОГО ЧИСЛА ТУТ НЕ РАХУЄТЬСЯ. Усе приходить із GET /api/route — навіть
// суми в колонці «Куди піде» беруться готовими рядками розкладки, а не
// складаються тут. Перша нога маршруту при цьому байт у байт дорівнює
// POST /api/allocate на ту саму суму, і це закріплено тестом на бекенді.
//
// КОЛОНКА «КУДИ ПІДЕ» — НЕ ДРУГА КОПІЯ ТАБЛИЦІ КРОКІВ (linesHTML в
// allocate.js). Та відповідає на «що саме купити»: кількість, ціна кроку,
// реальна дохідність, кнопка в план. Ця — на «куди пішли гроші цієї
// події»: назва й сума, стовпчиком усередині комірки. Повна таблиця
// всередині комірки таблиці нечитабельна, а урізати linesHTML до двох
// колонок означало б зробити з неї щось третє. Там, де питання таки те
// саме — у модалці «Прийшло», — кроки показує саме linesHTML: кнопка
// відкриває звичайну розкладку, а не свою копію.
//
// КНОПКА «ПРИЙШЛО» Є РІВНО ОДИН ДЕНЬ. Учорашню виплату domain.Arrived уже
// вважає отриманою й показує в балансі; завтрашніх грошей на рахунку ще
// немає. День самої виплати — єдиний, коли обидва твердження хибні, і саме
// тоді ухвалюється рішення. Оцінка кнопки не має взагалі: дивіденд фонду
// позначати нема чого, його справжній запис приходить випискою.
//
// ЧОМУ ЦЕ ОКРЕМА СТОРІНКА, А НЕ КОЛОНКА В «КАЛЕНДАРІ ВИПЛАТ». Зернистість
// рядка різна: у календарі рядок — одна виплата, тут — один ГОРЩИК, що
// може зібратись із трьох виплат і двох місяців. Час різний: календар має
// архів і відмітки «отримано», маршрут дивиться лише вперед. Джерело
// різне. Звести їх в одну таблицю означало б поставити в один список два
// різні знаменники — рівно та помилка, проти якої написана шапка
// buildSchedule.
//
// ЩО СТОЇТЬ ПІД ТАБЛИЦЕЮ І ЧОМУ ЦЕ НЕ ДРІБНИЦЯ. Порядок і ціна тут
// СЬОГОДНІШНІ: майбутнього НКД, майбутніх аукціонних рівнів і майбутнього
// довідника НБУ ми не знаємо. Сказати це зобов'язана саме сторінка —
// таблиця з датами 2027 року інакше читалась би як прогноз цін, яким вона
// не є й бути не може.

