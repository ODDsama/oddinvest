// Папери, які людина обрала сама, по ногах: ключ — дата|рахунок|валюта
// (той самий routeKey, за яким бекенд упізнає ногу), значення — ISIN.
//
// У ПАМʼЯТІ СТОРІНКИ, а не в базі, і це не тимчасове рішення. Маршрут —
// вигляд, а не стан (шапка annotatePlanned на бекенді): вибір живе, доки
// людина дивиться й вирішує, і щойно ногу закріплено, його тримає план
// купівель — рядком із тим самим ISIN. Третє місце для «майбутнього паперу»
// розійшлося б із планом при першій же правці плану. Модуль переживає
// ctx.reload() так само, як список reinvest у now-view.js; перезавантаження
// вкладки його стирає — і це правильно: незакріплений вибір, який пережив
// би день, читався б як рішення, якого ніхто не записував.
const picks = new Map();

function legKey(leg) {
  return `${leg.date}|${leg.broker}|${leg.currency}`;
}

// Шлях запиту з вибором. Кожна нога — свій параметр pick: бекенд читає їх
// усі й перераховує ноги В ПРОХОДІ, бо інший папір — інший залишок, і він
// їде далі в наступні ноги того самого рахунку.
function routePath() {
  if (!picks.size) return "route";
  const q = [...picks].map(([k, isin]) =>
    "pick=" + encodeURIComponent(k + "|" + isin));
  return "route?" + q.join("&");
}

// Чи є в нозі рядок ОВДП, який можна замінити. Вибір є РІВНО там, де є
// «Закріпити»: на нозі через пів року він був би вибором сьогоднішньої ціни
// на липень — саме те, від чого відмовляється pinnable.
function pickable(leg) {
  return leg.pinnable && (leg.lines || []).some((l) => l.kind === "bond");
}

// Основа надходження — підписом, і ТІЛЬКИ коли вона не «портфель це винен».
//
// Позначати кожен рядок означало б написати «зобовʼязання» двадцять разів
// поспіль і сховати за цим три рядки, які справді інші. Тому підпис несе
// виняток, а правило названо прозою під таблицею — інакше відсутність
// позначки читалась би як «невідомо».
//
// «Різні основи» замість колишнього «оцінка + зобовʼязання»: відколи в
// маршруті є й плановий дохід, у горщику можуть зійтися будь-які дві з
// трьох, і стара пара називала б одну з комбінацій неправдиво. Яка саме
// пара зійшлась, видно з ніг, що в цей горщик привели.
const BASIS = {
  estimate: "оцінка",
  plan: "план",
  mixed: "різні основи",
};

// Куди підуть гроші однієї ноги — стовпчиком, а не вкладеною таблицею.
//
// Подушка першим рядком, і це не оформлення: вона й у розкладці забирає
// своє першою, тож інший порядок тут суперечив би самому обчисленню.
function destHTML(leg) {
  const rows = [];
  if (leg.reserve && leg.reserve.amount_uah > 0) {
    rows.push(`<div class="fine">${kindPill("reserve")}
      <b>${fmtUAH(leg.reserve.amount_uah)}</b></div>`);
  }
  // Борг — ДРУГИМ, між подушкою й цілями: рівно там, де він стоїть у
  // розкладці. Довго цього рядка не було взагалі, хоч вирізка рахувалась і
  // приїжджала в нозі: гроші йшли в борг, а колонка показувала подушку,
  // цілі, папери й «Лишиться» менше за суму — без пояснення.
  if (leg.debt && leg.debt.amount_uah > 0) {
    rows.push(`<div class="fine">${kindPill("debt")}
      <b>${fmtUAH(leg.debt.amount_uah)}</b>${leg.debt.why
  ? `<div class="fine-xs muted">${esc(leg.debt.why)}</div>` : ""}</div>`);
  }
  // Цілі — ТРЕТІМИ, за подушкою й боргом, перед паперами: так само, як у
  // самому обчисленні. Інший порядок тут суперечив би розкладці.
  for (const g of leg.goals || []) {
    rows.push(`<div class="fine">${kindPill("goal")} ${esc(g.name)}
      — <b>${fmtUAH(g.amount_uah)}</b></div>`);
  }
  for (const l of leg.lines || []) {
    // Обраний папір підписаний: без позначки вибір і порада виглядали б
    // однаково, і людина не знала б, що тут є що скидати.
    rows.push(`<div class="fine">${kindPill(l.kind)} ${esc(l.label)}
      — <b>${fmtUAH(l.total_uah)}</b>${l.picked
  ? ` <span class="fine-xs muted">твій вибір</span>` : ""}</div>`);
  }
  // Скільки СПРАВЖНІХ призначень набралось — рахується тут, до причин: далі
  // rows росте й від них теж, а питання «чи взяв хтось хоч щось» стосується
  // лише грошей.
  const took = rows.length;
  // Чому подушки в цьому рядку немає, хоч стеля місяця ще не добрана.
  // Причина одна — політика «Подушку наповнювати», — і без неї зникла
  // вирізка читалась би як поломка. Стоїть ПІСЛЯ призначень: спершу куди
  // гроші пішли, потім куди не пішли й чому.
  if (leg.reserve_skip_why) {
    rows.push(`<div class="fine-xs t-warn">${esc(leg.reserve_skip_why)}</div>`);
  }
  if (leg.debt_skip_why) {
    rows.push(`<div class="fine-xs t-warn">${esc(leg.debt_skip_why)}</div>`);
  }
  if (leg.goals_skip_why) {
    rows.push(`<div class="fine-xs t-warn">${esc(leg.goals_skip_why)}</div>`);
  }
  // Причина порожнечі потрібна й тоді, коли комірка НЕ порожня.
  //
  // «Цілі тут свого не беруть» пояснює цілі — і тільки їх, — а чому не
  // сталося решти, каже розкладка (note або rest_why). Доки внесок у
  // пенсійний брав будь-яку копійку, таких ніг не бувало взагалі: рядок
  // був завжди. Відколи в нього є поріг (allocMinCutUAH), нога без жодного
  // призначення, але з живою причиною про ЩОСЬ ІНШЕ, стала звичайною — і
  // без цього рядка вона мовчала б саме про те, чого людина шукає.
  if (!took) {
    rows.push(`<span class="muted fine-xs">${esc(leg.note || leg.rest_why
      || "нічого цілого не склалось — гроші чекають наступного надходження")}</span>`);
  }
  return rows.join("");
}

function legsHTML(doc) {
  return opsGrid({
    cols: [
      {
        key: "when", label: "Коли",
        cell: (leg) => `${esc(dayMonth(leg.date))}
          <div class="fine-xs muted">${esc(leg.label)}${leg.broker
  ? " · " + esc(leg.broker) : ""}</div>`,
      },
      {
        key: "inflow", label: "Надійде", num: true,
        // Саме надійде, а не весь горщик: сказати «надійде 3 123 ₴», коли
        // банк переказує 1 312 ₴, а решта чекала з минулого разу, було б
        // неправдою про виписку. Обидва числа стоять поруч і підписані.
        cell: (leg) => fmtUAH(leg.inflow_uah)
          + (BASIS[leg.basis]
            ? `<div class="fine-xs t-warn">${esc(BASIS[leg.basis])}</div>` : "")
          + (leg.principal_uah > 0
            ? `<div class="fine-xs muted">з них тіло ${fmtUAH(leg.principal_uah)}</div>` : "")
          // Чому число менше за нараховане. Приходить готовим рядком: різниця
          // між рентою й решткою рахується на бекенді, як і все інше тут.
          + (leg.inflow_why
            ? `<div class="fine-xs muted">${esc(leg.inflow_why)}</div>` : "")
          + (leg.carry_in_uah > 0
            ? `<div class="fine-xs muted">+ ${fmtUAH(leg.carry_in_uah)} з попереднього</div>`
            : ""),
      },
      { key: "pot", label: "Разом", num: true, cell: (leg) => fmtUAH(leg.amount_uah) },
      { key: "dest", label: "Куди піде", cell: destHTML },
      {
        key: "rest", label: "Лишиться", num: true,
        cell: (leg) => (leg.rest_uah > 0
          ? fmtUAH(leg.rest_uah)
            + `<div class="fine-xs muted">чекає наступного надходження</div>`
          : `<span class="muted">—</span>`),
      },
      {
        key: "act", label: "", cls: "row-actions nowrap",
        // Кнопка є РІВНО в ноги, датованої сьогодні, і рівно доки виплата не
        // позначена. Це не сором'язливість, а межа domain.Arrived: учорашню
        // виплату застосунок уже вважає отриманою й показує в балансі, а
        // завтрашніх грошей на рахунку ще немає — розкладати нічого. Один
        // день, коли обидва твердження хибні, і є моментом рішення.
        //
        // Оцінка кнопки не має: дивіденд фонду позначати нема чого, його
        // справжній запис приходить випискою (тому ref порожній).
        cell: (leg) => {
          if (leg.date === doc.from && leg.ref) {
            return `<button class="sm" data-arrived="${esc(String(leg.id))}">Прийшло</button>`;
          }
          // Планова нога ref не має й мати не може: її відмічають у
          // чеклисті плану (plan/receipts), а не статусом виплати. Кнопка
          // «Прийшло» тут писала б не в ту таблицю, тож замість неї —
          // дорога туди, де відмітка справді живе.
          if (leg.basis === "plan" && leg.date === doc.from) {
            return `<a class="lnk fine-xs" href="${routeFor("plan/inflow")}"
              >відмітити в плані</a>`;
          }
          if ((leg.planned || []).length) {
            return `<span class="muted fine-xs">у плані:
              ${esc(leg.planned.join(", "))}</span>`;
          }
          // «Інший папір» стоїть поруч із «Закріпити» й лише разом із ним:
          // вибір має сенс рівно там, де його можна записати (див. pickable).
          return (leg.pinnable
            ? `<button class="sm quiet" data-pin="${esc(String(leg.id))}">Закріпити</button>`
            : "")
            + (pickable(leg)
              ? ` <button class="sm quiet" data-pick="${esc(String(leg.id))}">Інший папір</button>`
              : "");
        },
      },
    ],
    rows: (doc.legs || []).map((leg, i) => ({ ...leg, id: i })),
    caption: "Маршрут грошей: коли надійде, скільки, куди піде і що лишиться",
  });
}

/** Борг на горизонті — місяцями. Не ноги: обовʼязкові платежі вибором не є
 *  і від планових ніг уже відняті (довід — у шапці route.go, «Борг»). Тут
 *  видно інше: скільки щомісяця йде в борг повз портфель, скільки маршрут
 *  віддає достроково, коли борг під ставкою закінчується і де платежів
 *  стає менше — тобто з якого місяця план місяця зростає сам. */
function monthsHTML(doc) {
  const rows = doc.months || [];
  if (!rows.length) return "";
  const any = rows.some((r) => r.debt_due_uah > 0 || r.card_inst_uah > 0
    || r.prepay_uah > 0 || r.debt_left_uah > 0);
  if (!any) return "";
  const grid = opsGrid({
    cols: [
      {
        key: "month", label: "Місяць",
        cell: (r) => esc(monthShort(r.month + "-01"))
          + (r.drop_uah > 0
            ? `<div class="fine-xs t-ok">платежів менше на ${fmtUAH(r.drop_uah)}</div>` : ""),
      },
      {
        key: "due", label: "Обовʼязкове", num: true,
        cell: (r) => (r.debt_due_uah + (r.card_inst_uah || 0) > 0
          ? fmtUAH(r.debt_due_uah + (r.card_inst_uah || 0))
            + (r.card_inst_uah > 0
              ? `<div class="fine-xs muted">з картки ${fmtUAH(r.card_inst_uah)}</div>` : "")
          : `<span class="muted">—</span>`),
      },
      {
        key: "prepay", label: "Достроково за маршрутом", num: true, prio: 2,
        cell: (r) => (r.prepay_uah > 0 ? fmtUAH(r.prepay_uah) : `<span class="muted">—</span>`),
      },
      {
        key: "left", label: "Під ставкою на кінець", num: true,
        cell: (r) => (r.debt_left_uah > 0 ? fmtUAH(r.debt_left_uah)
          : `<span class="t-ok">0</span>`),
      },
      { key: "plan", label: "План місяця", num: true, prio: 3, cell: (r) => fmtUAH(r.plan_uah) },
    ],
    rows,
    caption: "Борг на горизонті: обовʼязкове, дострокове за маршрутом, залишок під ставкою, план місяця",
  });
  return `<div class="card"><h2 class="h-row">Борг на горизонті ${infoBtn("route")}</h2>
    <div class="note">Обовʼязкові платежі в ногах не стоять: вони відняті від планових
      грошей ще до того, як ті стали ногами, а карткові розстрочки платяться з картки.
      Тут видно, скільки йде повз портфель щомісяця, скільки маршрут віддає достроково
      і коли борг під ставкою закінчується — з того місяця план місяця росте сам.</div>
    ${grid}</div>`;
}

/** Маршрут грошей: кожне майбутнє надходження й те, куди воно веде. */
export async function renderRoute(ctx, main) {
  let doc;
  try {
    doc = await ctx.api("GET", routePath());
  } catch (err) {
    // Вибір, який бекенд відкинув (папір погашений або без графіка), не
    // має права погасити всю таблицю: відмова показується дослівно, вибір
    // скидається, і маршрут малюється без нього. Скидаються всі, а не
    // винний: відповідь не каже, котрий саме, а вгадувати тут гірше, ніж
    // попросити обрати ще раз.
    if (picks.size) {
      picks.clear();
      ctx.toast(String(err.message || err), false);
      return renderRoute(ctx, main);
    }
    // Своя помилка лишається своєю: вище вже намальований вердикт плану, і
    // стерти його заради однієї таблиці означало б погасити сторінку цілком.
    // Той самий прийом, що в renderCalendar.
    main.insertAdjacentHTML("beforeend", `<div class="card"><h2>Маршрут грошей</h2>
      <div class="muted">Маршрут не завантажився: ${esc(err.message || err)}</div></div>`);
    return;
  }
  // Вибір на ногу, якої більше немає або яка вже в плані, — застарілий:
  // перша зникла з розкладу, другу тримає plan_buys. Обидва зникають
  // мовчки, інакше параметр їхав би в кожному запиті, не міняючи нічого.
  const live = new Set((doc.legs || [])
    .filter((leg) => !(leg.planned || []).length).map(legKey));
  for (const k of [...picks.keys()]) if (!live.has(k)) picks.delete(k);

  const body = (doc.legs || []).length
    ? legsHTML(doc) + `
      <div class="sub-xs">Рядок без позначки — <b>зобовʼязання</b>: портфель винен це
        сам собі, і сума відома з графіка. «Оцінка» — дивіденд фонду, порахований з
        його ставки, а не з обіцянки на конкретну дату. «План» — те, що має надійти за
        планом доходу: по нозі на кожен потік, у його день, чистими — частка потоку в
        доході місяця мінус витрати й обовʼязкові платежі, пропорційно. У поточному
        місяці ноги є лише в потоків, які ще не прийшли, і сума в нозі — їхня власна:
        те, що вже закинуто цього місяця, переказ банку не зменшує, а лише «лишилось
        закинути» на картці плану. Рахунку в ноги немає — планові гроші ще не в
        брокера, — тож із купонами в один квиток вони не складаються. Коли в горщику
        зійшлись різні основи, так і написано.
        Дата «коли вистачить» у «Що купити» ні оцінок, ні плану не бачить навмисно —
        там одне число, і припущення в ньому стало б невидимим.</div>
      <div class="sub-xs">Порядок і ціна кроку тут <b>сьогоднішні</b>: майбутнього НКД,
        майбутніх розміщень Мінфіну й майбутнього довідника НБУ ми не знаємо, а число,
        яке виглядає виведеним і насправді вигадане, гірше за його відсутність.
        Це твердження про сьогоднішні розриви твоєї політики, прикладене вперед —
        не прогноз цін.</div>
      <div class="sub-xs">Папір ОВДП у нозі можна обрати самому («Інший папір»): частка виду
        піде в нього й <b>тільки</b> в нього, а якщо на цілий квиток не вистачить — гроші
        чекатимуть, як і завжди. Вибір живе до закріплення: далі його тримає план купівель.</div>
      <div class="sub-xs">Виплати по датах, без призначень —
        <a class="lnk" href="${routeFor("plan/payouts")}">Календар виплат</a>.</div>`
    : empty("Маршрут порожній", doc.note
      || "До горизонту портфель нічого не винен сам собі.");

  const card = `<div class="card">
    <h2 class="card-head"><span>Маршрут грошей ${infoBtn("route")}</span>
      <span class="muted fine-xs">${esc(doc.from)} — ${esc(doc.to)}</span></h2>
    <div class="note">Кожне надходження — те, що портфель уже винен сам собі, і те,
      що має принести план доходу, — і те, куди воно піде за <b>твоєю</b> політикою:
      стеля подушки, з яких грошей вона ріже, цільові частки за видом, твій порядок у
      «Що купити». Дрібні надходження чекають одне одного, доки не набереться на цілий
      квиток — рахунки при цьому роздільні.</div>
    ${body}</div>${monthsHTML(doc)}`;
  main.insertAdjacentHTML("beforeend", card);

  // «Прийшло» — дві дії одним рухом, і порядок між ними значущий.
  //
  // Спершу відмітка: доки її немає, domain.Arrived не кладе ці гроші на
  // рахунок, а розкладка рахується від документа, який їх не бачить. Потім
  // модалка — уже на свіжому стані, з рядком про те, куди вів маршрут.
  //
  // Розкладка тут НЕ береться готовою з ноги, хоч вона в нозі й лежить:
  // маршрут будувався до відмітки, і між двома числами могла минути доба.
  // Нога передається як `routed` — щоб було видно, куди вело, — а рішення
  // ухвалюється за щойно порахованим. Показати старе замість нового
  // означало б запропонувати записати вчорашню відповідь.
  main.querySelectorAll("[data-arrived]").forEach((b) =>
    b.addEventListener("click", async () => {
      const leg = (doc.legs || [])[Number(b.dataset.arrived)];
      if (!leg) return;
      b.disabled = true;
      try {
        await ctx.api("POST", "payments/status",
          { isin: leg.ref, pay_date: leg.date, status: "received" });
      } catch (err) {
        b.disabled = false;
        ctx.toast(String(err.message || err), false);
        return;
      }
      await openAllocate(ctx, {
        amount: leg.amount.amount, currency: leg.amount.currency,
        title: leg.label, routed: leg,
        // Кнопка є лише в ноги з ref, а ref мають самі виплати портфеля:
        // планове надходження відмічають у чеклисті плану. Тіло — звідси ж,
        // у нативній валюті, бо в гривні воно віддало б подушці курс.
        source: "portfolio",
        principal: leg.principal ? leg.principal.amount : 0,
        // Вибір їде в розкладку разом із ногою: інакше на одному екрані
        // «Маршрут вів: UA…2» стояло б поруч із розкладкою на UA…1.
        pick: picks.get(legKey(leg)) || "",
      });
      ctx.reload();
    }));

  // «Інший папір» — обрати ISIN для цієї ноги й перерахувати її.
  //
  // Модалка НІЧОГО НЕ ПИШЕ: build захоплює введене й повертає null, тобто
  // тихо закриває діалог — той самий прийом, що `again` у openAllocate.
  // openEdit розрахований на запис, а тут запису немає й бути не може —
  // вибір іде параметром у наступний GET, і рахує ногу бекенд.
  //
  // Порожнє поле — скинути вибір: окремої кнопки «повернути пораду» не
  // треба, коли те саме поле показує поточний вибір і приймає порожнечу.
  main.querySelectorAll("[data-pick]").forEach((b) =>
    b.addEventListener("click", async () => {
      const leg = (doc.legs || [])[Number(b.dataset.pick)];
      if (!leg) return;
      const key = legKey(leg);
      let chosen = null;
      await openEdit(ctx, {
        title: `Папір для: ${esc(leg.label)} · ${esc(dayMonth(leg.date))}`,
        fields: refSuggest({ name: "isin", ref: "bond", value: picks.get(key) || "" })
          + `<div class="sub-xs">Частка ОВДП цієї ноги піде в обраний папір і тільки в
            нього; якщо на цілий квиток не вистачить — гроші чекатимуть. Порожнє поле —
            повернути папір із рейтингу.</div>`,
        wire: (f) => wireSuggest(ctx, f),
        submit: "Перерахувати",
      }, (f) => {
        chosen = f.elements.isin.value.trim().toUpperCase();
        return null;
      });
      if (chosen === null) return;
      if (chosen) picks.set(key, chosen);
      else picks.delete(key);
      ctx.reload();
    }));

  // «Закріпити» — кладе кроки ноги в план купівель із ЇЇ датою.
  //
  // Тіло рядка збирає buyBody з розкладки, а не цей файл: поля, яких вид
  // не має, бекенд відхиляє, і мовчки підкладати нулі означало б обходити
  // перевірку. Відмова (без ставки замок у прогнозі лише заморозив би
  // гроші) показується дослівно — ковтати 400 тут найгірше, бо рядок
  // просто не зʼявиться, а сторінка вдаватиме, що все записалось.
  main.querySelectorAll("[data-pin]").forEach((b) =>
    b.addEventListener("click", async () => {
      const leg = (doc.legs || [])[Number(b.dataset.pin)];
      if (!leg) return;
      b.disabled = true;
      const requests = (leg.lines || []).filter((l) => l.addable).map((l) => ({
        path: "plan/buys",
        body: {
          ...buyBody(l),
          buy_date: leg.date,
          broker: leg.broker === "—" ? "" : leg.broker,
          note: `маршрут: ${leg.label} · ${leg.date}`,
        },
      }));
      if (!requests.length) return;
      try {
        for (const rq of requests) await ctx.api("POST", rq.path, rq.body);
        // Далі вибір тримає план купівель — рядок із тим самим ISIN уже
        // записаний (buyBody бере l.ref), і другий екземпляр тут зайвий.
        picks.delete(legKey(leg));
        ctx.toast("Закріплено в плані купівель");
        ctx.reload();
      } catch (err) {
        b.disabled = false;
        ctx.toast(String(err.message || err), false);
      }
    }));
}
