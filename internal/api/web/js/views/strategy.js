const fillLevel = (a) => (["redeem", "plan"].includes(a.fill) ? a.fill : "");

// Розкладка валютної частини між доларом і євро. Пари дають РІВНО 100, і
// це не оформлення, а інваріант: із нього випливає, що розкладка не міняє
// величини валютної частки, а на цьому тримаються обидва сторожі валютних
// часток у server_test.go. Сторож читає ці пари з тексту файлу, тож
// літерал мусить лишатись плоским — з тієї самої причини, що й накладки.
//
// Вигаданих пропорцій немає жодної: усе, половина або нічого.
const FX_SPLIT = { usd: [100, 0], both: [50, 50], eur: [0, 100] };

// Скільки в.п. КАПІТАЛУ лишити меншій валюті на відповідь «щоб не все в
// одній». Пʼять названо в самому питанні вголос: обіцяти «невелику
// частку» й не сказати яку означало б сховати єдине, що ця відповідь
// робить.
const FX_DIVERSIFY_PP = 5;

// Рівень розкладки. Мовчання означає те саме, що у валютного й резервного
// питань: набір лишається при своїх числах. Це НЕ природа замка, де
// мовчання мусить означати «ні», — тримати євро нікому не заборонено й
// назад не замкнено, тож базове число набору є чесним станом.
const fxLevel = (a) => (a.fxmix in FX_SPLIT ? a.fxmix : "");

// Рівень «щоб не все в одній». Рівень один — "yes": «ні» і «не відповів»
// дають однакові числа. Словами вони різні, і підпис під питанням їх
// розрізняє, але переліку СТАНІВ це не стосується.
const divLevel = (a) => (a.fxdiv === "yes" ? "yes" : "");

// Осі накладок. Перелік ЖИВИЙ і читається обома — і `valuesAt`, і сторожем
// комбінацій у тесті: два списки тих самих імен розійшлись би тихо, а
// розійшовшись, лишили б цілу вісь неперевіреною.
//
// Порядок застосування зафіксований і значення не має: ключі осей не
// перетинаються (замок чіпає НПФ і ОВДП, валюта — usd/eur). Зафіксований
// саме тому, що колись перетнутись можуть, і мовчазна залежність від
// порядку в мапі — не той спосіб про це дізнатись.
const AXES = [
  ["lock", { some: "lockSome", most: "lockMost" }],
  ["spend", { uah: "spendUah", mixed: "spendMixed", fx: "spendFx" }],
  ["reserve", { no: "reserveNone", short: "reserveShort", ladder: "reserveLadder" }],
  ["fill", { redeem: "fillRedeem", plan: "fillPlan" }],
];

// Осі-ПЕРЕТВОРЕННЯ, і вони свідомо НЕ в AXES.
//
// Накладка — це готові числа поверх наявних ключів; вона нічого не рахує й
// не знає, що стоїть під нею. Розкладка рахує: її числа виводяться з
// валютної частки, яку щойно поставила накладка `spend`. Записати її
// накладкою означало б виписати по три обʼєкти на кожен із восьми наборів
// НА КОЖНУ комбінацію з валютним питанням — двадцять чотири блоки, які
// довелось би тримати узгодженими руками.
//
// Це ПЕРШИЙ випадок, коли дві осі чіпають спільні ключі (`usd`/`eur`) —
// рівно те, про що застерігає абзац над AXES. Тому порядок тут не
// «зафіксований про всяк випадок», а значущий: спершу накладки, потім
// перетворення. Навпаки не можна — перетворення ділило б те, чого ще немає.
//
// `div: "no"` у перелік не входить навмисно: він дає ті самі числа, що й
// відсутність відповіді, і подвоїв би перебір станів, не додавши жодного.
const TRANSFORMS = [["fx", Object.keys(FX_SPLIT)], ["div", ["yes"]]];

// Число так, як його читають налаштування: рядком, без хвостових нулів.
// Половинки законні — 25% навпіл це 12.5, поле «Цільова частка» приймає
// десяткові (`pct` у fields.js — inputmode "decimal"), а налаштування
// зберігаються рядком ДОСЛІВНО, тож "12.5" повертається з бекенда таким
// самим і збіг набору не розсипається.
const fxNum = (n) => String(Math.round(n * 100) / 100);

// Розкладка валютної частки між доларом і євро.
//
// ГОЛОВНЕ ПРАВИЛО, і воно єдине, заради якого варто читати цю функцію:
// ВЕЛИЧИНА ВАЛЮТНОЇ ЧАСТКИ НЕ ЗМІНЮЄТЬСЯ. `usd + eur` на виході дорівнює
// `usd + eur` на вході. Скільки валюти — це відповідь попереднього питання
// й накладки набору; тут вирішується лише, ЯКОЇ саме. Дві відповіді на
// одну частку капіталу дали б два числа, які нічого одне про одного не
// знають.
//
// Без жодної відповіді повертає той самий обʼєкт НЕТОРКАНИМ. Це не
// оптимізація: числа наборів мусять лишитись до символу, інакше inEffect
// перестане впізнавати набір, застосований до появи цих питань.
function splitFX(vals, fx, div) {
  if (!fx && !div) return vals;
  const num = (k) => Number(String(vals[k] || "").trim()) || 0;
  let usd = num("usd_target_share_pct");
  let eur = num("eur_target_share_pct");
  const total = usd + eur;
  if (FX_SPLIT[fx]) {
    const [u, e] = FX_SPLIT[fx];
    usd = total * u / 100;
    eur = total * e / 100;
  }
  // Стеля total/2 не дає «невеликій частці» перевернути більшість: при
  // валютній частці 5% пʼять в.п. — це вся вона, і меншою валюта від того
  // не стає. Рівні сторони не чіпаємо взагалі: меншої серед них немає.
  if (div === "yes" && total > 0) {
    const floor = Math.min(FX_DIVERSIFY_PP, total / 2);
    if (usd < floor && usd < eur) {
      usd = floor;
      eur = total - floor;
    } else if (eur < floor && eur < usd) {
      eur = floor;
      usd = total - floor;
    }
  }
  // Явний нуль, а не порожньо, і це свідоме рішення. Порожнє значення
  // СТИРАЄ ціль, тобто каже «про євро я нічого не казав»; людина ж сказала
  // «тільки в доларі». Нуль повторює сказане числом, і це видно там, де
  // числа й дивляться: у формі «Політика → Валютні цілі» стоїть 0 замість
  // порожнього поля, а плитка «Частка EUR» у «Ризику» отримує підпис
  // «ціль 0%».
  //
  // ЧОГО НУЛЬ НЕ РОБИТЬ, і сказати це треба тут, бо здається протилежне:
  // рядка EUR у валютному ребалансі він не створює. buildRebalance пропускає
  // валюту при `*tp <= 0` (state_rebalance.go), тож наявне євро НЕ буде
  // показане перебором — воно просто лишиться поза валютними рядками, так
  // само як і при порожній цілі. Різниця між нулем і порожнім тут лише в
  // тому, що сказане людиною записане, а не стерте.
  return { ...vals, usd_target_share_pct: fxNum(usd), eur_target_share_pct: fxNum(eur) };
}

// Числа набору на конкретній комбінації відповідей.
//
// Спершу накладки, потім перетворення — порядок значущий, див. TRANSFORMS.
//
// `k in out` — не охайність: накладка з чужим ключем має дати НЕ новий ключ
// у PUT, а нічого. Ціна тихої помилки тут різна на два порядки — зайвий
// ключ поїхав би в запит і затер сусіднє налаштування, пропущений лише
// лишив би базове число. Гучною цю помилку робить тест, а не браузер.
export function valuesAt(preset, levels) {
  // Рядком приймаємо теж: доти аргументом був самий рівень замка, і
  // мовчазна зміна сигнатури зробила б із «no» істинний об'єкт без жодного
  // збігу — тобто набір, що не збігається сам із собою.
  const at = typeof levels === "string" ? { lock: levels } : (levels || {});
  let out = null;
  for (const [axis, byLevel] of AXES) {
    const field = byLevel[at[axis]];
    const over = field && preset[field];
    if (!over) continue;
    if (!out) out = { ...preset.values };
    for (const k of Object.keys(over)) if (k in out) out[k] = over[k];
  }
  return splitFX(out || preset.values, at.fx, at.div);
}

// Усі комбінації рівнів — для перебору «який набір стоїть». Порожній рівень
// на осі означає «накладки немає», і він мусить бути в переліку: набір без
// відповіді про валюту — теж законний стан чисел.
export function allLevels() {
  let out = [{}];
  for (const [axis, byLevel] of AXES) {
    const next = [];
    for (const base of out) {
      next.push(base);
      for (const lv of Object.keys(byLevel)) next.push({ ...base, [axis]: lv });
    }
    out = next;
  }
  // Перетворення перебираються тим самим правилом і з тієї ж причини:
  // рукописний перелік станів пережив би появу нової осі мовчки, знаходячи
  // частину станів і називаючи решту «нічого не збіглось».
  for (const [axis, levels] of TRANSFORMS) {
    const next = [];
    for (const base of out) {
      next.push(base);
      for (const lv of levels) next.push({ ...base, [axis]: lv });
    }
    out = next;
  }
  return out;
}

