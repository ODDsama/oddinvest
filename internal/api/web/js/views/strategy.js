// про відповідь. Доти виміряне на цій сторінці лише стояло поруч: факт під
// питанням казав «а що в мене вже є» і на вердикт набору не впливав ніяк.
// «Тільки банк» діставав однаковий підпис і на порожньому портфелі, і при
