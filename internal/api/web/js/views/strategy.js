// Конфігуратор політики портфеля.
//
// МЕЖА, ЯКУ ТУТ НЕ ПЕРЕХОДИМО. У коді записано «Це інструмент, не порада»
// (handlers_reinvest.go), те саме — в довідці. Тож жоден рядок звідси не
// каже «вам варто тримати 60% ОВДП». Пресет — це ІМЕНОВАНИЙ НАБІР
// налаштувань із чесним підписом, що він оптимізує і чим за це платить;
// питання нижче не питають «чого ви хочете», вони питають про ОБМЕЖЕННЯ,
// які користувач знає про себе сам (коли можуть знадобитись гроші, в чому
// він витрачає). Підбір відповідає лише на «який набір НЕ суперечить
// названим вами обмеженням», і логіка збігу показана поруч із кожним
// рядком, а не захована в число.
//
// Через це тут немає слова «рекомендований» і немає сортування «найкращий
// зверху»: пресети стоять у сталому порядку, а збіг показано підписом.
// Застосувати можна будь-який, навіть той, що суперечить усім відповідям —
// обмеження міг змінитись, і застосунок про це не знає.
//
// Пресети — константи ФРОНТЕНДУ, які заповнюють ті самі поля, що й форми
// «Політики». Окремої сутності «стратегія» в бекенді немає навмисно: інакше
// зʼявився б другий, паралельний спосіб задати ті самі числа, і питання
// «яке з них справжнє» не мало б відповіді. З тієї ж причини немає й
// збереженого «поточного набору»: який набір стоїть, ВИВОДИТЬСЯ звіркою
// чисел, а поле вміло б казати «стоїть Драбина» про налаштування, у яких
// від неї лишилась половина.
//
// ЩО ЗМІНИЛОСЬ У ЦЬОМУ ПРАВИЛІ. Доти тут стояло «відповіді ні на що не
// впливають самі по собі». Тепер впливають ПʼЯТЬ — про замок, про подушку
// й три про валюту, — і чинне формулювання таке: ВІДПОВІДІ НЕ РАДЯТЬ, АЛЕ
// НАБІР ПОВАЖАЄ НАЗВАНЕ ОБМЕЖЕННЯ.
//
// Різниця між цими двома не косметична. «Порадити» означало б підняти
// частку, бо застосунок вважає інструмент вигідним. Тут навпаки: ціль НПФ
// порожня в УСІХ восьми наборах, доки про замок не сказано, — бо замок до
// 50 років це не незручність, а неможливість, і припускати її за людину
// не можна. Названа готовність знімає заборону, а не додає пораду.
//
// Валютна відповідь входить у те саме правило з іншого боку, і сплутати їх
// не можна. Замок питає про НЕМОЖЛИВІСТЬ, тож мовчання там означає «ні».
// Валюта питає про те, В ЧОМУ ЛЮДИНА ЖИВЕ, — обмеження не менш справжнє,
// але зворотне: тримати долар не заборонено нічим, назад не замкнено, і
// базове число набору лишається чесним станом, а не припущенням про
// людину. Тому мовчання тут не «ні», а «набір при своїй ціні».
//
// Чому цю відповідь узагалі підключили до чисел: вона питала рівно про те,
// що набір і задає числом, а число стояло незмінним. Тепер ланцюг
// замкнутий — відповідь про валюту задає валютну ціль, а з неї виводиться
// частка вкладів (див. довгий абзац про чергу до $1000-го паперу нижче).
//
// ВАЛЮТНИХ ПИТАНЬ ТЕПЕР ТРИ, І ВОНИ ПРО РІЗНЕ. Перше («у чому плануєте
// витрачати») задає ВЕЛИЧИНУ валютної частки. Друге («валютну частину
// тримати в чому») ділить її між доларом і євро. Третє («невелику частку
// іншої валюти») лишає меншій валюті пʼять в.п., якщо перші два лишили їй
// нуль.
//
// Розділити довелось саме так, бо це різні обмеження: скільки валюти
// потрібно людині — питання про її витрати, а яка саме валюта — питання
// про те, куди ці витрати підуть. Одне питання на обидва дало б перелік із
// девʼяти варіантів, половина яких не трапляється ніколи.
//
// І головне: другі два НЕ ЧІПАЮТЬ ВЕЛИЧИНИ. Сума usd+eur після розкладки
// дорівнює сумі до неї — інакше в застосунку зʼявилось би два числа про
// одну частку капіталу, які нічого одне про одного не знають. Саме на
// цьому інваріанті тримаються обидва сторожі валютних часток у
// server_test.go, і саме тому розкладка не є накладкою (див. TRANSFORMS).
//
