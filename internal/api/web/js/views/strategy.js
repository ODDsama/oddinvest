// Джерело — ctx.summary: той самий документ, який app.js уже дочекався перед
// рендером БУДЬ-ЯКОЇ сторінки, тобто безкоштовно.
//
// І водночас необовʼязкове. «Політика» стоїть у SUMMARY_FREE, тобто мусить
// малюватись і тоді, коли зведення не порахувалось, — а це найскладніший
// шлях у бекенді. Через це кожне звертання йде через `(ctx.summary || {})`, і
// відсутність факту означає відсутність РЯДКА, а не порожню сторінку.
// «Читає, якщо є» і «без цього порожня» — різні речі.
//
// Факт стоїть ПІД варіантами, а не над ними: він не підказує відповідь, він
// відповідає на інше питання — «а що в мене вже є».
//
// Тон розділений жорстко. Нейтральний рядок — просто виміряне. `t-ok` —
// твоя умова ВИКОНАНА. `t-warn` — твоя відповідь розходиться з фактом, і
// тоді обовʼязково сказано, ЧИМ позначка гасне: правило застосунку, від
// нагадування про внесок у НПФ до застарілого довідника.
const line = (txt, cls) => `<div class="sub-xs${cls ? ` ${cls}` : ""}">${txt}</div>`;

// Скільки різних паперів ведеться. Повертає null, коли порахувати нема з
// чого, і це важливіше за саме число.
//
// Переліку ОВДП у зведенні немає взагалі — там funds[], npf[], ladder_uah[],
// concentration[], а лотів немає. Порахувати самі фонди й НПФ і назвати це
// кількістю паперів було б тихо хибним числом, а таке гірше за жодне.
// Другий запит по /api/positions теж не варіант: він зробив би цю сторінку
// залежною від ще одного ендпойнта, а вона з двох, які мусять малюватись,
// коли решта API мовчить.
//
// Лишається concentration: там рівно по рядку на папір — але ЛИШЕ коли
// заданий ліміт на один папір, бо без ліміту вимір не рахується. Наявність
// ліміту видно безкоштовно, вона лежить у current.
function bondCount(s, current) {
  if (!(current.limit_isin_pct || "")) return null;
  const rows = (s.concentration || []).filter((c) => c.dimension === "isin");
  if (!rows.length) return null;
  // Фонди й НПФ ходять у цьому вимірі під префіксами — решта це ОВДП.
  return rows.filter((c) => !String(c.key).startsWith("fund:")
    && !String(c.key).startsWith("npf:")).length;
}

function factHTML(id, s, answers, current) {
  const a = answers[id];
  const out = [];

  if (id === "when") {
    const l = s.liquidity;
    if (!l) return "";
    out.push(line(`Зараз доступно <b>${fmtUAH(l.now_uah)}</b>, за 30 днів — ${
      fmtUAH(l.in_30_uah)}, за 90 — ${fmtUAH(l.in_90_uah)} (накопичувально, якщо нічого не купувати).`));
    if (l.locked_uah > 0) {
      const npf = l.locked_npf_uah > 0
        ? ` З них ${fmtUAH(l.locked_npf_uah)} у НПФ — до ${esc(npfAccess(s) || "пенсії")}.` : "";
      out.push(line(`Замкнено ${fmtUAH(l.locked_uah)}${
        l.unlock_date ? `, найближче розблокування ${esc(l.unlock_date)}` : ""}.${npf}`));
      // Два ВИМІРЯНІ числа поруч, без вигаданого порогу «багато»: замкнено
      // більше, ніж стане доступно за квартал, — це і є розходження з
      // «гроші можуть знадобитись будь-коли».
      if (a === "any" && l.locked_uah > (l.in_90_uah || 0)) {
        out.push(line(`⚠ ти відповів, що гроші можуть знадобитись будь-коли, а замкнено більше,
          ніж стане доступно за 90 днів. Порогу тут немає — це просто два виміряні числа поруч.
          Позначка зникне, коли доступного за квартал стане більше за замкнене: або мине найближче
          розблокування, або доросте решта портфеля.`, "t-warn"));
      }
    }
    return out.join("");
  }

  if (id === "spend") {
    const usd = s.usd_share_pct || 0, eur = s.eur_share_pct || 0;
    return line(usd || eur
      ? `Зараз у валюті: USD <b>${pct(usd)}</b>, EUR <b>${pct(eur)}</b> капіталу.`
      : "Валютної частини в капіталі зараз немає — усе в гривні.");
  }

  // Три валютні питання поспіль, і факт під кожним відповідає на СВОЄ.
  // Під «у чому витрачаєте» стоїть величина валютної частини; тут — її
  // розклад, поточні цілі й те, чим відповідь розходиться з портфелем.
  if (id === "fxmix") {
    const usd = s.usd_share_pct || 0, eur = s.eur_share_pct || 0;
    const tgt = (k, w) => (String(current[k] || "").trim() === ""
      ? `${w} не задана` : `${w} ${pct(Number(current[k]))}`);
    out.push(line(`Зараз у валюті: USD <b>${pct(usd)}</b>, EUR <b>${pct(eur)}</b> капіталу; цілі — ${
      tgt("usd_target_share_pct", "USD")}, ${tgt("eur_target_share_pct", "EUR")}.`));
    // Розходження відповіді з фактом, і сказати про нього треба разом із
    // тим, чого застосунок НЕ пропонує. Ціль у нуль — це опис («ці гроші
    // поза цілями»), а не вимога продати: продавати він не радить ніде.
    const clash = [["usd", "eur", eur, "євро"], ["eur", "usd", usd, "долар"]]
      .find(([ans, , have]) => a === ans && have > 0);
    if (clash) {
      const [, , have, what] = clash;
      out.push(line(`⚠ відповідь лишає ${esc(what)} без цілі, а в портфелі його ${pct(have)}
        капіталу. Ціль стане нулем — це буде видно у «Політиці» й на плитці частки в «Ризику», — і
        «Що купити» перестане цю валюту добирати. Окремого рядка про неї у валютному ребалансі при
        цьому не буде взагалі: нульова ціль рядка не створює, тож перебором ці гроші НЕ покажуть —
        вони просто лишаться поза валютними цілями. Продавати застосунок не радить ніде.
        Позначку прибирає зміна відповіді.`, "t-warn"));
    }
    return out.join("");
  }

  if (id === "fxdiv") {
    if (answers.fxmix === "both") {
      return line(`При відповіді «і в доларі, і в євро» це питання не змінює нічого: валютна
        частина вже поділена навпіл, і меншої серед двох рівних немає.`);
    }
    return line(`Меншій валюті дістануться ${FX_DIVERSIFY_PP} в.п. капіталу, забрані в більшої;
      величина валютної частини не зміниться. Більше половини валютної частини менша валюта не
      дістане ніколи — на частці 10% це вийде 5 і 5. Якщо валютної частини набір не ставить
      зовсім, ділити нема чого: відповідь не зробить нічого.`);
  }

  if (id === "cushion") {
    const r = s.reserve;
    if (!r && !(s.reserve_uah > 0)) {
      out.push(line("Резерву в застосунку немає, цілі для нього теж."));
    } else if (!r || !(r.target_uah > 0)) {
      out.push(line(`Резерв у застосунку: <b>${fmtUAH((r && r.uah) || s.reserve_uah)}</b>.
        Скільки це місяців — невідомо: місячні витрати не задані.`));
    } else if (r.gap_uah > 0) {
      out.push(line(`Резерв у застосунку: <b>${fmtUAH(r.uah)}</b> — це ${(r.months || 0).toFixed(1)} з ${
        r.target_months} ${plural(r.target_months, "місяця", "місяців", "місяців")} витрат, бракує ${
        fmtUAH(r.gap_uah)}.`));
    } else {
      out.push(line(`Резерв у застосунку: <b>${fmtUAH(r.uah)}</b> — ${(r.months || 0).toFixed(1)} з ${
        r.target_months} ${plural(r.target_months, "місяця", "місяців", "місяців")} витрат, ціль зібрана.`));
    }
    // Умова ВИКОНАНА — це не суперечність, і плутати їх не можна.
    if (a === "no" && r && r.target_uah > 0 && !(r.gap_uah > 0)) {
      out.push(line("✓ запас справді тут: ціль резерву зібрана, розриву немає.", "t-ok"));
    }
    if (a === "no" && !(r && r.target_uah > 0) && !(s.reserve_uah > 0)) {
      out.push(line(`⚠ ти відповів, що запас має бути тут, а ні цілі резерву, ні самого резерву в
        застосунку немає. Позначка зникне, щойно зʼявиться ціль — її ставлять набори «Ліквідний»,
        «Спершу подушка» і «Тільки банк», або руками в «Політика → Резерв» — чи перший запис у
        «Записати → Резерв».`, "t-warn"));
    }
    return out.join("");
  }

  if (id === "effort") {
    const bonds = bondCount(s, current);
    const funds = (s.funds || []).length, npf = (s.npf || []).length;
    if (bonds !== null) {
      return line(`Зараз ведеш <b>${bonds}</b> ${plural(bonds, "різний папір", "різні папери", "різних паперів")
      } ОВДП, ${funds} ${plural(funds, "фонд", "фонди", "фондів")} і ${npf} ${
        plural(npf, "рахунок", "рахунки", "рахунків")} НПФ.`);
    }
    // Мовчання про річ, яку явно можна порахувати, читається як поламане, а
    // не як принципове — тому кажемо, чому числа немає й де воно є.
    return line(`Фондів <b>${funds}</b>, рахунків НПФ <b>${npf}</b>. Скільки різних ОВДП — тут не
      видно: у зведенні їхньої кількості немає, а по перелік позицій ця сторінка не ходить
      навмисно, бо мусить малюватись і тоді, коли решта API мовчить. Порахувати — в «Активи →
      Позиції»; заразом задай «Макс. в одному папері», і число зʼявиться тут.`);
  }

  if (id === "lock50") {
    const rows = s.npf || [];
    const uah = s.npf_uah || 0;
    out.push(line(rows.length
      ? `У НПФ уже <b>${fmtUAH(uah)}</b> на ${rows.length} ${
        plural(rows.length, "рахунку", "рахунках", "рахунках")} — доступ із ${esc(npfAccess(s) || "?")}.`
      : "Рахунків НПФ у застосунку немає."));
    if (a === "no" && (rows.length || uah > 0)) {
      out.push(line(`⚠ ти відповів, що доступ має лишатись, а гроші в НПФ уже замкнені. Відповідь
        тут головніша за факт: усі набори лишають ціль НПФ порожньою, тобто НОВИХ грошей туди не
        поведуть. Позначку прибирає лише зміна відповіді — вийняти з НПФ раніше 50 років не можна,
        і застосунок такого не пропонує. Якщо рахунок дістався не з твого рішення, «Ні» лишається
        правдою про нові гроші, і позначку можна просто не чіпати.`, "t-warn"));
    }
    if ((a === "some" || a === "most") && rows.length) {
      out.push(line("✓ рахунок НПФ уже є — набори враховують названий рівень, ціль НПФ у них не порожня.", "t-ok"));
    }
    if ((a === "some" || a === "most") && !rows.length) {
      out.push(line(`Рахунків НПФ поки немає, тож ціль НПФ у наборі буде числом наперед: «Ризик →
        Структура» показуватиме дефіцит, доки не зʼявиться перший внесок. Завести рахунок — у
        «Налаштування → Довідники».`));
    }
    return out.join("");
  }

  if (id === "exit") {
    const funds = s.funds || [];
    const term = funds.filter((f) => f.close_date);
    if (!funds.length) return line("Строкових фондів у портфелі немає.");
    if (!term.length) {
      return line("Фонди в портфелі є, але жоден не має дати закриття — це питання їх не стосується.");
    }
    return line(`Строкові фонди в портфелі: ${term.map((f) => `«${esc(f.fund)}» — закриття <b>${
      esc(f.close_date)}</b>${f.buy_until ? `, купувати можна до ${esc(f.buy_until)}` : ""}`).join("; ")}.`);
  }

  return "";
}

// Найближча дата доступу до НПФ. Саме найближча: рахунків може бути кілька,
// і обіцяти пізнішу було б применшенням, а ранішу — вигадкою.
function npfAccess(s) {
  const dates = (s.npf || []).map((n) => n.access_date).filter(Boolean).sort();
  return dates[0] || "";
}

const LOCK_WORD = { some: "невелику частину", most: "значну частину" };

// Який набір стоїть ЗАРАЗ. ВИВОДИТЬСЯ порівнянням, а не читається зі
// збереженого поля — з тієї ж причини, з якої в бекенді немає сутності
// «стратегія»: поле було б другим джерелом правди про ті самі пʼятнадцять
// чисел, і воно ще й уміло б брехати — підправив число руками, а поле каже
// «стоїть Драбина». Тут збіг зникає сам.
//
// Шукаємо по ВСІХ комбінаціях накладок, а не лише по названих відповідях:
// людина могла застосувати набір, а потім зняти відповідь, і сказати їй
// тоді «жоден набір не збігся» було б формально правдою і повною дурницею.
//
// Комбінацій тепер більше, ніж рівнів замка, бо осей стало дві, — і перебір
// іде спільним allLevels(), а не власним списком: рукописна трійка "no",
// "some", "most" пережила б появу валютної осі мовчки, знаходячи рівно
// третину станів і називаючи решту «нічого не збіглось».
function inEffect(current) {
  const out = [];
  const combos = allLevels();
  for (const p of PRESETS) {
    for (const levels of combos) {
      const eff = valuesAt(p, levels);
      if (Object.entries(eff).every(([k, v]) => (current[k] || "") === v)) {
        // Комбінації одного набору різні за побудовою, тож перший збіг і є той.
        out.push({ preset: p, levels });
        break;
      }
    }
  }
  return out;
}

const banner = (cls, icon, title, sub) => `<div class="banner ${cls}">
  <div class="b-ic" aria-hidden="true">${icon}</div><div class="b-tx">
  <div class="b-t">${title}</div><div class="b-s">${sub}</div></div></div>`;

// Банер угорі картки: що стоїть зараз і чи не відпало те, заради чого його
// брали. Іде ПЕРШИМ — питання «а що в мене стоїть» ставлять до того, як
// гортати вісім карток.
function stateBannerHTML(s, answers, current) {
  const matches = inEffect(current);
  if (!matches.length) {
    return banner("neutral", "◦", "Жоден набір не збігається з тим, що стоїть",
      `Числа підправлені руками — це нормальний стан: набір і був стартовою точкою, а не режимом.
       Нижче видно, на скільки налаштувань відрізняється кожен із восьми.`);
  }
  // Називаємо лише вісь ЗАМКА, хоч осей у комбінації дві. Це не пропуск:
  // рівень замка змінює склад набору (частка НПФ проти ОВДП), тобто його
  // характер, а валютна відповідь змінює лише валютну ціль — число, яке
  // видно окремим рядком у тій самій картці. Дописати сюди ще й її
  // означало б зробити підпис довшим за твердження, яке він несе.
  const named = matches.map(({ preset, levels }) =>
    `«${esc(preset.name)}»${levels.lock && levels.lock !== "no"
      ? ` на рівні «${LOCK_WORD[levels.lock]}»` : ""}`).join(" і ");
  const out = [];

  // Окрема гілка: числа стоять із НПФ, а про замок не відповідали. Це і є
  // «сказати словами замість тихого нуля» — інакше кнопка нижче показала б
  // різницю, ніби ціль НПФ треба прибрати, і причина була б невідома.
  const silentLock = !answers.lock50 && matches.some((m) => m.levels.lock && m.levels.lock !== "no");
  if (silentLock) {
    out.push(banner("wait", "○", `Зараз стоїть ${named} — але питання про замок без відповіді`,
      `Числа, які стоять, — це саме цей набір із ціллю НПФ. Доки готовність замкнути частину
       грошей до 50 років не названа, набори ставлять ціль НПФ у нуль: припускати такий замок за
       тебе застосунок не буде. Тому кнопка нижче покаже різницю, ніби НПФ треба прибрати.
       Відповіси на питання — різниця зникне.`));
  } else {
    out.push(banner("ok", "✓", `Зараз стоїть ${named}`,
      `Усі пʼятнадцять налаштувань збігаються з цим набором. Це не збережений вибір: застосунок
       щоразу звіряє числа з наборами й називає той, що збігся, — щойно ти підправиш будь-яке
       число руками, збіг зникне сам.`));
  }

  // «Набір відпрацював». Перевірка через target_uah обовʼязкова: обидва поля
  // omitempty, тож «розриву немає» і «цілі немає» приїжджають однаково —
  // порожнечею, і без неї повідомлення спрацювало б там, де цілі не ставили.
  const r = s.reserve;
  const done = matches.find((m) => m.preset.expires === "reserveFull");
  if (done && r && r.target_uah > 0 && !(r.gap_uah > 0)) {
    out.push(banner("wait", "◦", `«${esc(done.preset.name)}» своє відпрацював`,
      `Резерв зібрано: ${fmtUAH(r.uah)} при цілі ${fmtUAH(r.target_uah)}, розриву немає. Саме
       поповнення вже мовчить — стеля «з вільних у резерв» перестає щось радити тієї миті, коли
       розрив стає нулем, і вимикати її окремо не треба. А от решта чотирнадцяти чисел лишились
       такими, якими їх ставили ПІД ЗБІР. Це нічого не ламає — просто набір обирали під задачу,
       якої вже немає. Що з цим робити і чи робити взагалі — вирішуєш ти; нижче видно, на скільки
       налаштувань відрізняється кожен інший.`));
  }

  // «Фонд зі строком» відпрацював — це ЗАЧИНЕНЕ ВІКНО КУПІВЛІ.
  //
  // Три стани, і плутати їх не можна:
  //   (а) тримаєш строковий фонд, вікно відкрите — казати нема чого;
  //   (б) тримаєш, вікно зачинилось — ціль фондів більше нічим не добрати,
  //       і оце й є відпрацювання;
  //   (в) НЕ тримаєш жодного строкового фонду — набір ще НЕ ПОЧАВСЯ.
  //       Назвати це «відпрацював» означало б оголосити завершеним те, чого
  //       не було, тобто повторити помилку, від якої в reserveFull вище
  //       стоїть перевірка target_uah.
  //
  // УСІ, а не «хоч один»: два строкові фонди, з яких один ще продають, — це
  // набір, що працює, і ціль наповнити ще є чим. Фонд без buy_until
  // зачиненим не рахується: невідоме вікно і зачинене вікно — різні речі.
  const { term, shut, gone } = termFundState(s);
  const doneTerm = matches.find((m) => m.preset.expires === "buyWindowClosed");
  if (doneTerm && term.length && shut.length === term.length) {
    const named = term.map((f) => `«${esc(f.fund)}»`).join(" і ");
    const fundsPct = esc(valuesAt(doneTerm.preset, doneTerm.levels).target_funds_pct);
    const tail = `Ціль фондів у ${fundsPct}% наповнювати вже нема чим: у наборі був рівно один спосіб.
      Решта чотирнадцяти чисел лишились такими, якими їх ставили ПІД КУПІВЛЮ. Що з цим робити і чи
      робити взагалі — вирішуєш ти; нижче видно, на скільки налаштувань відрізняється кожен інший.`;
    out.push(banner("wait", "◦", `«${esc(doneTerm.preset.name)}» своє відпрацював`,
      gone.length === term.length
        // Про це мовчати не можна: дата закриття не обробляється в
        // застосунку НІДЕ — ні в календарі, ні в проєкції. Отже він не
        // знає, чи гроші повернулись, і рядок фонду стоятиме незмінним.
        ? `Вікно купівлі зачинилось, а тепер минула й дата закриття: ${named} мав закритись
           ${esc(gone[0].close_date)}. Що сталося насправді, застосунок не знає — дату закриття
           він не обробляє ніде, — тож рядок фонду стоятиме незмінним, доки погашення не зайде
           випискою. ${tail}`
        : `Вікно купівлі зачинилось: ${named} приймав гроші до ${esc(shut[0].buy_until)}, і від
           тієї дати «Що купити» його не пропонує — порада купити те, чого не продають, гірша за
           мовчання. Сам фонд нікуди не подівся й працює до закриття ${esc(term[0].close_date)};
           змінилось лише те, що ДОКЛАДАТИ в нього не можна. ${tail}`));
  }
  return out.join("");
}

export function strategyCardHTML(ctx, current) {
  const answers = readAnswers();
  const answered = QUESTIONS.filter((q) => answers[q.id]).length;
  const s = (ctx && ctx.summary) || {};

  const quiz = QUESTIONS.map((q) => `<div class="mb">
    <div class="mb-xs">${esc(q.q)}</div>
    <div class="row-h">
      ${q.opts.map(([v, t]) => `<button type="button" class="sm${
        answers[q.id] === v ? "" : " quiet"}" data-answer="${q.id}:${v}">${esc(t)}</button>`).join("")}
    </div>${factHTML(q.id, s, answers, current)}</div>`).join("");

  const cards = PRESETS.map((p) => {
    const { ok, clash } = matchOf(p, answers);
    // Чинні числа набору — ОДИН виклик на картку. Різниця нижче й рядок
    // готовності читають той самий обʼєкт: рівень замка вирішує, чи є в
    // наборі ціль НПФ узагалі, тобто й чи є про неї що сказати.
    const eff = effectiveValues(p, answers);
    // Різниця з тим, що стоїть зараз. Порожнє поточне значення — це
    // «не задано», і показуємо це словом, а не порожнім місцем.
    const diff = Object.entries(eff).filter(([k, v]) => (current[k] || "") !== v);
    const verdict = !answered
      ? `<span class="muted">обмеження ще не названі</span>`
      : clash.length
        ? `<span class="t-warn">суперечить ${clash.length} з названих обмежень</span>`
        : ok.length
          ? `<span class="t-ok">не суперечить жодному з ${ok.length} названих</span>`
          : `<span class="muted">до названих обмежень байдужий</span>`;
    // ДРУГИЙ вердикт, а не доданок до першого. Названі обмеження й виміряні
    // факти мають різних авторів, і злити їх в одне число означало б
    // сказати «суперечить трьом», не розрізняючи, де людина відповіла, а де
    // застосунок порахував. Порожній він у більшості наборів — так і має
    // бути: суперечність із портфелем це рідкість, а не підпис під кожним.
    const measured = measuredOf(p, eff, s);
    const seen = measured.length
      ? `<span class="t-warn">суперечить ${measured.length} ${
        plural(measured.length, "виміряному факту", "виміряним фактам", "виміряним фактам")}</span>`
      : "";
    const why = [...clash.map((c) => `<div class="sub-xs t-warn">✕ ${esc(c.q)} → «${esc(c.a)}»</div>`),
      ...ok.map((c) => `<div class="sub-xs">✓ ${esc(c.q)} → «${esc(c.a)}»</div>`)].join("");
    const seenWhy = measured.map((m) => `<div class="sub-xs t-warn">✕ ${m.what}</div>
      <div class="sub-xs">${m.why}</div>`).join("");
    return `<div class="rule-top">
      <div class="kv wrap">
        <b>${esc(p.name)}</b>${verdict}${seen}
      </div>
      <div class="sub">Дає: ${esc(p.gives)}</div>
      <div class="sub">Платить: ${esc(p.costs)}</div>
      ${why}
      ${seenWhy}
      ${needsHTML(eff, s, current)}
      <div class="mt-sm">
        ${diff.length
          ? `<button class="sm" data-preset="${p.key}">Показати, що зміниться (${diff.length})</button>`
          : `<span class="t-ok">✓ зараз стоїть саме цей набір</span>`}
      </div>
      <div data-preview="${p.key}"></div>
    </div>`;
  }).join("");

  return `<div class="card">
    <h2 class="h-row">Готові набори налаштувань ${infoBtn("strategy")}</h2>
    ${stateBannerHTML(s, answers, current)}
    <div class="muted mb">Це не поради, а іменовані комбінації тих самих
      цілей, лімітів і правил, що у формах «Політики» — з підписом, що кожна дає і чим за це
      платить. Питання нижче нічого не радять: вони позначають, який набір не суперечить названим
      вами обмеженням, і показують поруч виміряне — що у вас уже є. Там, де набір
      суперечить не відповіді, а самому портфелю, це сказано окремим рядком, а перед
      записом видно, що його цілі означають у гривнях. Частина питань при цьому впливає на числа.
      Замок: доки не сказано, чи готові ви замкнути частину грошей до 50 років, ціль НПФ у всіх
      наборах порожня — замок туди не припускають за вас. Валюта: три питання поспіль задають
      величину валютної частки та її розклад між доларом і євро. Застосувати можна будь-який
      набір, і будь-яке число потім змінити руками.</div>
    ${quiz}
    ${cards}
  </div>`;
}

// --- превʼю: що ці цілі означають при твоєму капіталі ---
//
// За зразком fetchWhatIf (views/buy-plan.js) і з тієї самої причини: жодне
// число тут не рахується. Ціль у гривнях, дефіцит, здійсненність і
// щільність приходять із бекенда, який рахує їх ТИМ САМИМ buildRebalance,
// що малює «Ризик» і ранжує «Що купити».
//
// Запит іде на клік, а не на кожен рендер: карток вісім, і превʼю під
// кожною означало б вісім найдорожчих шляхів бекенда на відкриття
// сторінки. Питання «що це означатиме в гривнях» ставлять до ОДНОГО набору
// — того, який зважились застосувати.
async function fetchPolicyPreview(ctx, settings) {
  const resp = await ctx.store.raw("policy/preview", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ settings }),
  });
  if (!resp.ok) throw new Error(`${resp.status}: ${(await resp.text()).slice(0, 200)}`);
  return resp.json();
}

// Назва цілі одним рядком: вид інструмента або валюта. KIND_GROUP — той
// самий довідник, що в «Структурі за видом»; власний перелік тих самих
// п'яти назв розійшовся б тихо (див. constants.js).
const targetName = (r) => (r.dimension === "kind"
  ? (KIND_GROUP[r.key] || r.key) : (r.key || r.currency));

// Вимір щільності словами. Ключі ті самі, що в ConcentrationRow.Dimension.
const DIM_WORD = {
  isin: "в одному папері", broker: "в одній установі", year: "погашень в один рік",
};

// Таблиця цілей у гривнях плюс те, що з них не виходить.
//
// Рядки — ЛИШЕ з непорожньою ціллю. Рядок без цілі приходить у відповіді
// довідковим (гроші у виді, якому набір частки не ставить), і в таблиці
// ПРО ЦІЛІ він читався б як ціль у нуль — тобто як твердження, якого набір
// не робив. Те, що набір справді лишає поза цілями, каже measuredOf.
function moneyHTML(res) {
  const rows = (res.rebalance || []).filter((r) => r.target_pct > 0
    && (r.dimension === "kind" || r.dimension === "currency"));
  if (!rows.length) {
    return `<div class="sub-xs mt-sm muted">Перерахувати цілі в гривні поки нема з чого: або
      капітал нульовий, або набір не ставить жодної частки.</div>`;
  }
  // Три стани, а не два. «Бракує» і «зібрано» очевидні; третій — перебір,
  // і мовчати про нього не можна: 143% при цілі 20% це не «ціль досягнута»,
  // а перекіс, який цим набором не виправиться. Поріг 105 замість 100 —
  // щоб округлення не читалось як перекіс.
  const gap = (r) => {
    if (r.deficit_uah > 0) return `<b>${fmtUAH(r.deficit_uah)}</b>`;
    if (r.fill_pct > 105) return `<span class="t-warn">перебір, зібрано ${pct(r.fill_pct, 0)}</span>`;
    return `<span class="t-ok">зібрано</span>`;
  };
  const grid = opsGrid({
    cols: [
      { key: "what", label: "Ціль",
        cell: (r) => `${esc(targetName(r))} ${r.target_pct}%` },
      { key: "target", label: "Це в гривнях", num: true, cell: (r) => fmtUAH(r.target_uah) },
      { key: "now", label: "Зараз", num: true, cls: "muted", cell: (r) => fmtUAH(r.current_uah) },
      { key: "gap", label: "Бракує", num: true, cell: gap },
    ],
    rows,
    caption: "Цілі набору в гривнях: ціль, її сума, поточна сума, розрив",
    cls: "mt-sm",
  });
  // Недосяжна ціль — не помилка набору, а розмір портфеля. Числа всі
  // порахував бекенд, включно з тим, при якому капіталі вона вписалась би.
  const hard = rows.filter((r) => r.feasible === false && r.bond_cost_uah > 0)
    .map((r) => `<div class="sub-xs t-warn">⚠ ${esc(targetName(r))} ${r.target_pct}%: найдешевша
      одиниця входу коштує ${fmtUAH(r.bond_cost_uah)} — це більше за всю цільову суму
      ${fmtUAH(r.target_uah)}. Стільки вписалося б у цю ціль при капіталі
      ${fmtUAH(r.min_portfolio_uah)}.</div>`).join("");
  // Щільність рахується вже за НОВИМИ лімітами набору — у цьому весь сенс
  // показати її до запису.
  const over = (res.concentration || []).filter((c) => c.over_uah > 0);
  const dense = over.map((c) => `<div class="sub-xs t-warn">⚠ Ліміт ${c.limit_pct}% ${
    esc(DIM_WORD[c.dimension] || c.dimension)} уже порушений: ${esc(c.label || c.key)} —
    ${pct(c.share_pct)}, це ${fmtUAH(c.over_uah)} понад стелю.</div>`).join("");
  // Один раз, а не під кожним рядком: це те саме твердження про них усі.
  //
  // І воно не про те, що ліміт треба підняти. Ліміт для того й існує, щоб
  // казати «розкладай ширше»; підняти його під факт означало б заглушити
  // справжнє попередження — саме тому набір нічого тут не переписує.
  const denseTail = over.length
    ? `<div class="sub-xs">Це не помилка набору: ліміт для того й існує, щоб казати «розкладай
       ширше». Але доки перевищення є, «Що купити» опускатиме ці рядки нижче — тобто набір
       почне з зауваження з першого ж дня. Виправляє це або новий папір (чи брокер, чи рік
       погашення), або інший ліміт у «Політика → Концентрація».</div>`
    : "";
  return grid + hard + dense + denseTail;
}

export function wireStrategy(ctx, main, current) {
  // Відповіді читаються ОДИН раз на рендер, і саме тому таблиця різниці не
  // може розійтися із записом: перегляд і PUT беруть числа з одного виклику
  // effectiveValues. Застаріти цей знімок не встигає — зміна відповіді
  // перемальовує сторінку через ctx.reload нижче.
  const answers = readAnswers();
  main.querySelectorAll("[data-answer]").forEach((b) =>
    b.addEventListener("click", () => {
      const [id, v] = b.dataset.answer.split(":");
      const a = readAnswers();
      // Повторний клік по обраному знімає відповідь: обмеження може
      // виявитись неактуальним, і мовчазної «жодної відповіді» бути не
      // повинно — лише явна.
      if (a[id] === v) delete a[id]; else a[id] = v;
      writeAnswers(a);
      ctx.reload();
    }));

  main.querySelectorAll("[data-preset]").forEach((b) =>
    b.addEventListener("click", () => {
      const p = PRESETS.find((x) => x.key === b.dataset.preset);
      const box = main.querySelector(`[data-preview="${p.key}"]`);
      if (!p || !box) return;
      // Два кроки навмисно, як в імпорті виписки: спершу показати, що
      // саме буде переписано, і лише потім писати. Набір чіпає пʼятнадцять
      // налаштувань одразу, і «застосував і не помітив, що затер валютну
      // ціль» — помилка, яка знаходиться не одразу.
      //
      // «Прибрати» в третьому стовпчику — не окраса: порожнє значення
      // справді СТИРАЄ налаштування, і саме тому перехід між наборами не
      // лишає позаду чужого числа.
      //
      // Числа беруться з effectiveValues на ТОМУ САМОМУ знімку відповідей,
      // що й diff у картці вище й тіло PUT нижче. Три виклики, одне
      // джерело — інакше перегляд збрехав би про запис.
      const eff = effectiveValues(p, answers);
      const diff = Object.entries(eff).filter(([k, v]) => (current[k] || "") !== v);
      const warn = measuredOf(p, eff, (ctx.summary || {}));
      // ДВІ таблиці, і питання в них різні. Перша — що зміниться в
      // НАЛАШТУВАННЯХ; вона й була тут завжди. Друга — що ці налаштування
      // означають у ГРОШАХ, і саме її бракувало: пʼятнадцять чисел
      // записувались, жодного разу не глянувши на портфель, а дізнатись
      // ціну можна було лише після запису.
      //
      // Друга приходить пізніше за першу й не затримує її: розрив у
      // налаштуваннях видно одразу, а гривні домальовуються, коли бекенд
      // відповість. Помилка запиту не ховає нічого й нічого не блокує —
      // превʼю відповідає на ДРУГЕ питання, а не дозволяє записати.
      box.innerHTML = opsGrid({
        cols: [
          { key: "setting", label: "Налаштування",
            cell: ([k]) => esc(FIELD_LABEL[k] || k) },
          { key: "now", label: "Зараз", num: true, cls: "muted",
            cell: ([k]) => (current[k] ? esc(shown(k, current[k])) : "не задано") },
          { key: "next", label: "Стане", num: true,
            cell: ([k, v]) => `<b>${v ? esc(shown(k, v)) : "прибрати"}</b>` },
        ],
        rows: diff,
        caption: `Що змінить набір «${esc(p.name)}»: налаштування, поточне значення, нове`,
        cls: "mt-sm",
      })
        + `<div data-money><div class="sub-xs mt-sm muted">Рахуємо, що ці цілі означають при
           твоєму капіталі…</div></div>`
        // Виміряна суперечність ПОВТОРЮЄТЬСЯ тут коротким рядком, і це не
        // недогляд. Повний доказ стоїть у картці вище; тут — нагадування
        // рівно в ту мить, коли палець уже на кнопці. Кнопка при цьому
        // лишається робочою: застосувати можна будь-який набір (див. шапку).
        + warn.map((m) => `<div class="sub-xs t-warn mt-sm">⚠ ${m.what}</div>`).join("")
        + `<button class="sm mt-sm" data-apply="${p.key}">Застосувати «${esc(p.name)}»</button>`;
      const money = box.querySelector("[data-money]");
      fetchPolicyPreview(ctx, eff).then((res) => {
        money.innerHTML = moneyHTML(res);
      }).catch((err) => {
        money.innerHTML = `<div class="sub-xs t-warn mt-sm">Порахувати, що це означає в гривнях,
          не вдалось: ${esc(String(err.message || err))}. Різниця в налаштуваннях вище від цього
          не залежить.</div>`;
      });
      box.querySelector("[data-apply]").addEventListener("click", async (e) => {
        e.target.disabled = true;
        await apply(ctx, { method: "PUT", path: "settings", body: eff },
          `Застосовано «${p.name}»`);
      });
    }));
}
