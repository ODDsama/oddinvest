// --- виміряне поруч із питаннями ---
//
// Джерело — ctx.summary: той самий документ, який app.js уже дочекався перед
// рендером БУДЬ-ЯКОЇ сторінки, тобто безкоштовно.
//
// І водночас необовʼязкове. «Політика» стоїть у SUMMARY_FREE, тобто мусить
// малюватись і тоді, коли зведення не порахувалось, — а це найскладніший
// шлях у бекенді. Через це кожне звертання йде через `(ctx.summary || {})`, і
// відсутність факту означає відсутність РЯДКА, а не порожню сторінку.
// «Читає, якщо є» і «без цього порожня» — різні речі.
//
// Факт стоїть ПІД варіантами, а не над ними: він не підказує відповідь, він
// відповідає на інше питання — «а що в мене вже є».
//
// Тон розділений жорстко. Нейтральний рядок — просто виміряне. `t-ok` —
// твоя умова ВИКОНАНА. `t-warn` — твоя відповідь розходиться з фактом, і
// тоді обовʼязково сказано, ЧИМ позначка гасне: правило застосунку, від
// нагадування про внесок у НПФ до застарілого довідника.
const line = (txt, cls) => `<div class="sub-xs${cls ? ` ${cls}` : ""}">${txt}</div>`;

// Скільки різних паперів ведеться. Повертає null, коли порахувати нема з
// чого, і це важливіше за саме число.
//
// Переліку ОВДП у зведенні немає взагалі — там funds[], npf[], ladder_uah[],
// concentration[], а лотів немає. Порахувати самі фонди й НПФ і назвати це
// кількістю паперів було б тихо хибним числом, а таке гірше за жодне.
// Другий запит по /api/positions теж не варіант: він зробив би цю сторінку
// залежною від ще одного ендпойнта, а вона з двох, які мусять малюватись,
// коли решта API мовчить.
//
// Лишається concentration: там рівно по рядку на папір — але ЛИШЕ коли
// заданий ліміт на один папір, бо без ліміту вимір не рахується. Наявність
// ліміту видно безкоштовно, вона лежить у current.
function bondCount(s, current) {
  if (!(current.limit_isin_pct || "")) return null;
  const rows = (s.concentration || []).filter((c) => c.dimension === "isin");
  if (!rows.length) return null;
  // Фонди й НПФ ходять у цьому вимірі під префіксами — решта це ОВДП.
  return rows.filter((c) => !String(c.key).startsWith("fund:")
    && !String(c.key).startsWith("npf:")).length;
}

