// Збіг набору з названими обмеженнями. Повертає РОЗКЛАД, а не оцінку:
// саме він і показується поруч, бо число без пояснення — це та сама
// порада, лише в іншій обгортці.
function matchOf(preset, answers) {
  const ok = [], clash = [];
  for (const q of QUESTIONS) {
    const a = answers[q.id];
    const allowed = preset.fits[q.id];
    if (!a || !allowed) continue; // не відповіли або набору байдуже
    const label = (q.opts.find(([v]) => v === a) || [, a])[1];
    (allowed.includes(a) ? ok : clash).push({ q: q.q, a: label });
  }
  return { ok, clash };
}

// Стан СТРОКОВИХ фондів у портфелі. Три різні речі, і плутати їх не можна:
// `term` — строкові фонди, які тримаються; `shut` — ті, чиє вікно купівлі
// вже зачинилось; `gone` — ті, чия дата закриття вже минула.
//
// Винесено сюди, бо споживачів стало двоє: банер про ЧИННИЙ набір і
// виміряна суперечність картки. Дві копії цієї трійки розійшлись би тихо, а
// різниця між «не тримаю жодного» і «тримаю, але вікно зачинене» тут
// вирішує, чи набір відпрацював, чи ще не почався.
//
// Фонд без `buy_until` зачиненим не рахується: невідоме вікно і зачинене
// вікно — різні речі.
function termFundState(s) {
  const iso = today();
  const term = (s.funds || []).filter((f) => f.close_date && f.market_value > 0);
  return {
    term,
    shut: term.filter((f) => f.buy_until && f.buy_until < iso),
    gone: term.filter((f) => f.close_date < iso),
  };
}

// --- набір проти того, що вже куплено ---
//
// ДРУГА ПОЛОВИНА ПРАВИЛА З ШАПКИ. `matchOf` вище міряє набір проти НАЗВАНИХ
// обмежень, це — проти ВИМІРЯНИХ, і різниця в тому, хто автор факту: там
// людина відповіла, тут застосунок порахував.
//
// Своєї арифметики немає жодної: беруться числа, які бекенд уже порахував,
// і порівнюються з тим, що набір ставить. Гривні самих цілей рахує превʼю
// (POST /api/policy/preview) — правило 5 CLAUDE.md.
//
// ЩО СЮДИ НЕ ВХОДИТЬ І ЧОМУ — важливіше за те, що входить, бо правило
// добору одне: рядок, який спрацьовує під УСІМА вісьмома наборами, навчає
// не читати цей блок, і замовкають разом із ним ті кілька, що варті уваги.
//
// ВКЛАДИ БЕЗ ЦІЛІ. Порожні в семи наборах із восьми, тож рядок стояв би сім
// разів — і був би ще й хибним: вклад тут ЧЕРГА до валютного паперу, а не
// вид під частку, і його частку рахує бекенд вирізкою з цілі ОВДП.
//
// НПФ БЕЗ ЦІЛІ. Порожній в усіх восьми, доки не названа готовність
// замкнути гроші. Сказане про це вже стоїть один раз і в правильному
// місці — під питанням про замок, у factHTML.
//
// ЦІЛЬ ФОНДІВ БЕЗ ЖОДНОГО ФОНДУ. Теж усі вісім, і це не суперечність, а
// «набір ще не почався»: фонд заводиться реальною операцією через виписку.
// Та сама межа, що в needsHTML нижче.
//
// ЦІЛЬ, НЕДОСЯЖНА ПРИ ПОТОЧНОМУ КАПІТАЛІ. Це вже не порівняння, а
// арифметика, і живе вона в превʼю разом із min_portfolio_uah — там, де її
// рахує той, хто має право.
function measuredOf(preset, eff, s) {
  // Фактів немає, доки зведення не порахувалось: «Політика» малюється й без
  // нього. Той самий guard, що в needsHTML: сказати «в портфелі нічого
  // немає» тоді, коли ми просто не дивились, — гірше за мовчання.
  if (!s.generated_at) return [];
  const out = [];
  const zero = (k) => {
    const v = String(eff[k] || "").trim();
    return v === "" || Number(v) === 0;
  };

  // Набір відмовляється від ВИДУ, у якому вже лежать гроші. Спрацьовує на
  // одному наборі з восьми — «Тільки банк», — і саме тому спрацьовує голосно.
  //
  // Вклади й НПФ у цьому переліку відсутні з причин, названих вище.
  for (const [key, target] of [["bonds", "target_bonds_pct"], ["funds", "target_funds_pct"]]) {
    if (!zero(target)) continue;
    const row = (s.rebalance || []).find((r) => r.dimension === "kind" && r.key === key);
    if (!row || !(row.current_uah > 0)) continue;
    out.push({
      what: `${KIND_GROUP[key]}: ціль стане нульовою, а в портфелі ${fmtUAH(row.current_uah)}`,
      why: `Проданим ніщо не стане — застосунок не радить продавати ніде, — але ці гроші лишаться
        ПОЗА цілями: «Ризик → Структура» покаже їх перебором на всю суму, а «Що купити» перестане
        їх добирати. Позначка зникне, якщо ціль повернути.`,
    });
  }

  // Набору нема з чого початись: усі строкові фонди в портфелі вже не
  // приймають грошей. Умова та сама, що в банері про чинний набір, і саме
  // тому тут `expires`, а не ім'я набору: правило належить набору, а не
  // рядку в переліку.
  //
  // «Жодного строкового фонду немає» сюди НЕ входить: про фонди, яких у
  // портфелі немає, застосунок не знає нічого — ні дати закриття, ні вікна.
  // Це «набір ще не почався», і назвати його суперечністю означало б
  // оголосити зачиненим те, чого ми не бачили.
  const { term, shut } = termFundState(s);
  if (preset.expires === "buyWindowClosed" && term.length && shut.length === term.length) {
    out.push({
      what: "Строкові фонди в портфелі більше не приймають грошей",
      why: `${term.map((f) => `«${esc(f.fund)}»`).join(" і ")} приймав гроші до
        ${esc(shut[0].buy_until)}, і від тієї дати «Що купити» його не пропонує — порада купити те,
        чого не продають, гірша за мовчання. Ціль фондів у ${esc(String(eff.target_funds_pct))}%
        наповнювати нема чим: у наборі був рівно один спосіб. Позначка зникне з фондом, вікно
        купівлі якого ще відкрите.`,
    });
  }
  return out;
}

// --- «що цей набір потребує» ---
//
// ПЕРШЕ в застосунку попередження з боку ТОГО, ХТО ЗАДАЄ ЧИСЛО. Усі наявні
// (needsSetting у components.js і чотири його виклики) кажуть протилежне:
// «ця картка порожня, бо бракує налаштування». Жодне не казало «ти задав X,
// а Y порожнє, тож X ні на що не впливає».
//
// Саме тут ця тиша найдорожча. Набір ставить пʼятнадцять чисел одним
// натиском, і три з них можуть бути мертві з першої секунди: ціль резерву
// без місячних витрат не рахується в гривні, ціль вкладів без пари
// «ставка + мінімум» не має чим наповнюватись, а обіцяні в підписі 18% ПДФО
// не зʼявляться ніде без утриманого за рік ПДФО. Дізнатись про це можна
// було лише не знайшовши число там, де його чекав.
//
// ВИВОДИТЬСЯ з чинних чисел, а не оголошується полем `needs:` поруч.
// Оголошений список довелося б тримати трирівневим — накладки вже роблять
// перелік чинних чисел залежним від відповіді про замок, — тобто дублювати
// valuesAt() руками, і сторож мусив би стерегти ще й його. Виведений
// розійтися з числами не може за побудовою.
//
// ЧОГО СЮДИ НЕ ВХОДИТЬ І ЧОМУ.
//
// Ціль накопичення (goal_amount_uah / goal_date). Жоден набір її не пише, і
// жодне число набору без неї не ламається: частки, ліміти, резерв і порядок
// «Що купити» рахуються самі. Навіть режим «під план» не про ціль — у
// planScore входять валютний і видовий дефіцити, а дедлайн не входить
// узагалі. Половина застосунку без цілі справді темна, але це інша розмова,
// у неї свої порожні стани, і однаковий рядок під усіма вісьмома навчив би
// не читати цей блок.
//
// «Немає жодного фонду» під ціллю фондів. Межа проходить не там, де
// здається: у резерву, вкладів і НПФ бракує ЧИСЛА У ФОРМІ, за один клік, а
// фонд заводиться лише реальною операцією через виписку. Це «набір ще не
// почався», а не «бракує налаштування», і змішувати їх в одному блоці
// означало б розмити його зміст. Рахунок НПФ лишається саме тому, що він
// заводиться В САМОМУ застосунку — «Налаштування → Довідники».
const isSet = (current, k) => String(current[k] || "").trim() !== "";

// Дзеркало depositMinMinorByCur разом із його асиметрією: порожній USD/EUR
// дає 100, порожній UAH — нічого, а сміття прирівнюється до вимкненого.
// Дефолт у гривні означав би вигадати умову конкретного банку — мінімальна
// сума вкладу це тариф, а не властивість валюти.
//
// ПО ОДНІЙ ВАЛЮТІ, а не «хоч одна готова», і це стало важливим разом із
// розкладкою. Доти валютна ціль була фактично одна, і різниці не було;
// відколи набір ставить дві, задана ставка долара глушила б попередження
// про євро — тобто ціль, до якої дороги немає, лишалась би без жодного
// слова. Загальна відповідь лишається поруч: вона потрібна «Тільки банку»,
// де валютної цілі немає взагалі.
function depositReadyFor(current, cur) {
  const num = (k) => {
    const raw = String(current[k] || "").trim();
    if (raw === "") return null;
    const f = Number(raw);
    return Number.isFinite(f) ? f : 0;
  };
  const rate = num(`deposit_rate_${cur}_pct`);
  const min = num(`deposit_min_${cur}`);
  const minOn = min === null ? cur !== "uah" : min > 0;
  return rate > 0 && minOn;
}

const depositReady = (current) => ["usd", "eur", "uah"].some((c) => depositReadyFor(current, c));

