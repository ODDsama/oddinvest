// Банер дії показуємо ЗАВЖДИ — він ніколи не порожній і завжди каже,
// що робити: почати, купити або накопичувати далі.
// Банера дії тут більше немає, і це не спрощення, а розширення. Він
// відповідав на питання розділу ОДНІЄЮ порадою за раз і мав дві кнопки без
// жодного слухача (data-go), тобто єдина CTA головної сторінки нічого не
// робила. Його три гілки — «почни», «можеш купити», «ще збираєш» — стали
// трьома задачами в views/tasks.js, де вони стоять поруч із рештою того,
// що теж потребує рішення.

// Картки «Найближчі виплати» тут більше немає: вона жила на колишній «Що
// робити», а на «Сьогодні» те саме питання закриває «Що заходить
// найближчим часом» — ноги маршруту вже складені за датою, брокером і
// валютою, тож купон і погашення одного дня й там стоять одним числом.

// Що купити: папери, відранжовані БЕКЕНДОМ. Показуємо кілька позицій ЗАВЖДИ —
// попередній варіант зникав саме тоді, коли ти плануєш наступний крок, а ще
// був таблицею-звалищем на весь довідник, тож тут свідомо лише верхівка.
//
// ПОРЯДКУ ТУТ НЕМАЄ ВЗАГАЛІ, і це виправлення, а не спрощення.
//
// Доти модуль мав власний компаратор byReal — «замкнене нижче, далі за
// реальною дохідністю» — і сортував ним уже впорядковану відповідь. З'явився
// він проти справжньої вади: фронтенд скасовував серверне пониження НПФ, і той
// із 31.7% ставав над вкладом із 6.8%. Але лікував наслідок. Сервер сортує
// ЧОТИРМА правилами-префіксами (замкнене вниз, по кишені вгору, понад ліміт
// вниз, несвіже вниз) і аж ТОДІ режимом, який вибрав користувач; byReal знав
// лише про перше з них і мовчки викидав решту.
//
// Ціна була конкретна: налаштування «Порядок у "Що купити"» (reinvest_rank,
// internal/settings) на цьому списку не працювало ЖОДНОГО разу — чотири
// режими давали один і той самий екран. Гірше: черга задач бере перший рядок
// із серверного порядку, тож «Що робити» радила одне («найкраще зараз — Новий
// вклад»), а список під тією ж стелею — інше.
//
// Тому порядок один і живе там, де для нього є дані. Дедуплікація нижче
// («перший на kind|currency») на це й розрахована: перший — значить кращий за
// тими правилами, які назвав сам користувач.

// Назва рядка поради. Валюту несе сума поруч, строк переїхав у розкриття,
// а вид інструмента каже пігулка — тож слова «вклад» і «сертифікат» у
// назві стали б повтором того, що вже видно.
function suggestName(r) {
  // Ставка лишається при вкладі: це умова договору, а не дохідність, і
  // саме вона відрізняє два вклади в одній валюті один від одного.
  if (r.kind === "deposit") return `${esc(r.label)} <span class="muted">${pct(r.rate_pct)}</span>`;
  // Замок у самій назві: без нього рядок читається як звичайна
  // альтернатива вкладу, а він нею не є ні на день.
  if (r.locked) return `${esc(r.label)} <span class="t-warn">🔒 до ${esc(r.locked_until || "?")}</span>`;
  return esc(r.label || r.isin);
}

// Поповнення резерву — ОКРЕМИЙ блок, а не рядок у ранжованому списку, і це
// не питання верстки.
//
// У списку є рівно одне головне число — реальна дохідність, і саме вона
// вирішує порядок. У резерву її немає: це гроші, і в сьогоднішніх гривнях
// вони дають мінус знецінення. Щоб поставити резерв у той самий стовпчик,
// довелося б або вписати вигадане число, або завести для нього особливий
// випадок у сортуванні — обидва шляхи прямо заборонені коментарем до
// Locked у engine/reinvest.go, а там ішлося про інструмент, у якого
// дохідність хоча б справжня.
//
// СПОЖИВАЧ ЛИШИВСЯ ОДИН — крок «Що далі» на сторінці резерву
// (instrument-view.js). Зі сторінки «Що купити» цей банер прибраний: черга
// задач уже несе рядок reserve-fill із тим самим заголовком і тією ж сумою
// (state_tasks.go), тож на сусідніх сторінках стояло одне речення двічі. Два
// однакові речення — не наголос, а розсинхрон, що чекає нагоди: проза тут і
// проза там уже встигли розійтись (тут є «ти вже поклав N ₴», там немає).
//
// Числа приходять ГОТОВИМИ зі стану (reserve.fill_*). Порахувати частку
// тут було б на два рядки коротше й завело б другу копію арифметики
// резерву — рівно ту помилку, через яку колись плитка й картка показували
// різні числа.
export function reserveFillHTML(ctx) {
  const r = (ctx.summary || {}).reserve;
  if (!r || !(r.fill_now_uah > 0)) return "";
  // Що саме обмежило суму — стеля чи сам розрив. Мовчати про це не можна:
  // сума без причини читається як вимога, а не як стеля, яку людина сама
  // собі поставила.
  const capped = r.fill_month_uah >= (r.gap_uah || 0);
  // Уже відкладене цього місяця називаємо ЛИШЕ коли воно є: без нього сума
  // тут дорівнює місячній частці, і рядок «з них уже покладено 0» був би
  // шумом. А коли є — саме воно й пояснює, чому порада менша за частку.
  const done = r.fill_moved_uah > 0
    ? ` З місячної частки ${fmtUAH(r.fill_month_uah)} ти вже поклав ${
      fmtUAH(r.fill_moved_uah)} — лишилось стільки.` : "";
  const why = capped
    ? `Це все, чого бракує до цілі — ${fmtUAH(r.target_uah)}, тобто ${r.target_months} ${
      plural(r.target_months, "місяць", "місяці", "місяців")} витрат.${done}`
    // База — гроші МІСЯЦЯ, а не готівка на рахунках: подушку наповнюють із
    // нових грошей, і на малому рахунку стеля від готівки давала поради на
    // кшталт «відклади 2,48 ₴» при розриві в 359 500 ₴.
    : `${pct(r.fill_share_pct, 0)} від того, що заводить план цього місяця
       (${fmtUAH(r.fill_from_uah)}) — стеля, яку ти сам поставив. До цілі ще ${
  fmtUAH(r.gap_uah)}, решта грошей лишається на папери.${done}`;
  return `<div class="banner wait"><div class="b-ic">○</div><div class="b-tx">
    <div class="b-t">Спершу поповнити резерв — ${fmtUAH(r.fill_now_uah)}</div>
    <div class="b-s">${why} Сума в гривневому еквіваленті: у чому саме відкладати — вирішуєш ти.
      <a class="lnk" href="${routeFor("portfolio/reserve/record")}">Записати рух</a>.</div>
  </div></div>`;
}

/** Ранжовані поради. opts.kinds звужує до одного виду, opts.title міняє
 *  заголовок картки.
 *
 *  Звуження — для воронки інструмента, і саме звуження, а не окрема
 *  реалізація: рядок там мусить виглядати й рахуватись так само, як у
 *  спільному списку, інакше та сама пропозиція показувала б два різні
 *  числа на двох сторінках. Порівняння ВИДІВ між собою при цьому нікуди не
 *  дівається — воно живе в «Що купити» цілим, і воронка на нього
 *  посилається, а не підміняє його своїм зрізом. */
export function reinvestHTML(ctx, opts = {}) {
  const { kinds = null, title = "Що взяти" } = opts;
  // По одній найкращій пропозиції на ТИП × ВАЛЮТУ. Раніше ключем була
  // сама валюта — чотири майже однакові папери не давали вибору, і
  // порівняти гривню з доларом було сенсом блоку. Тепер інструментів три,
  // і ключ лише за валютою ховав би два з них: усі гривневі пропозиції
  // згорталися б в одну, і фонд із облігацією просто зникали б за
  // вкладом. Порівнювати треба і валюти, і природу інструмента.
  const byKey = new Map();
  for (const r of reinvest || []) {
    if (kinds && !kinds.includes(r.kind || "bond")) continue;
    const k = `${r.kind || "bond"}|${r.currency}`;
    if (!byKey.has(k)) byKey.set(k, r);
  }
  const rows = [...byKey.values()];
  // ПОРОЖНІЙ СПИСОК — ТЕЖ ВІДПОВІДЬ, і мовчати про нього більше не можна.
  //
  // Доти порожнеча означала «довідник ще не завантажили», і німа картка
  // була чесною. Відколи папір без свіжої ціни від СВОГО брокера
  // ховається (engine/reinvest.go), порожнеча має другу причину — «ціни
  // застаріли, і застосунок не має права стверджувати, що щось доступне».
  // Різниця між ними — це різниця між «зачекай» і «натисни кнопку», і
  // залишати людину гадати, яка з них зараз, було б найгіршим виглядом
  // тиші: екран виглядав би зламаним.
  //
  // Розрізняє їх наявність цін узагалі: є хоч одна — отже, довідник на
  // місці, і порожнеча саме про доступність.
  if (!rows.length) {
    if (!(kinds && !kinds.includes("bond")) && (quotesDoc().rows || []).length) {
      return `<div class="card"><h2 class="card-head"><span>${esc(title)}</span></h2>
        ${quotesBarHTML()}
        <div class="sub">Жоден із твоїх брокерів зараз не продає нічого з довідника —
          принаймні за тими цінами, які ми бачили востаннє. Онови ціни: якщо папір
          зняли з продажу, він і не має тут стояти, а якщо ціни просто застаріли,
          список повернеться.</div></div>`;
    }
    return "";
  }
  // Рядок пропозиції. Головне число — НОМІНАЛЬНЕ (те, що в договорі),
  // реальне під ним дрібним, увесь ланцюжок — на клік (yield.js). Порядок
  // при цьому лишився за реальним: показ і порядок — різні питання, і в
  // підвалі картки це сказано вголос.
  //
  // Решта (підстава, розклад по брокерах, причина) — у розкритті: доти
  // вона стояла в рядку дрібним текстом, і шість пропозицій по чотири
  // рядки читались як суцільна стіна, у якій не видно головного.
  const item = (r) => {
    const key = `${r.kind || "bond"}|${r.currency}`;
    const open = isOpen(OPEN_SCOPE, key);
    const kind = ["fund", "deposit", "npf"].includes(r.kind) ? r.kind : "bond";
    const cost = r.cost_per_bond ? fmtCur(Number(r.cost_per_bond.amount), r.currency) : "";
    // «Вистачає / бракує» і «коли набереться» більше не рахуються: вони
    // міряли ціну проти залишку на рахунку брокера, а рахунків застосунок
    // не веде (ревізія 2026-10-03). Чи пора купувати, каже задача «Дохід
    // чекає» в черзі — вона міряє той самий папір доходом, що прийшов.
    // Останнє розміщення — окремим рядком, а не в загальній стрічці: це
    // єдине тут число із ЗОВНІШНЬОГО світу, скільки платить ринок за той
    // самий папір. Прозою бекенд його не дублює — у причині лишається
    // тільки попередження, коли розміщення застаріле.
    const auc = r.last_auction
      ? `<div>на аукціоні ${esc(dayMonth(r.last_auction))} давали ${pct(r.last_auction_pct)}</div>`
      : "";
    // ЗВІДКИ ЦІНА — окремим рядком, і саме тут, поруч із аукціонним рівнем.
    //
    // Дохідність у цьому рядку рахується ВІД ЦІНИ ВХОДУ, тож підстава ціни
    // і є підставою самого числа, за яким стоїть увесь порядок списку.
    // Ринкова ціна й «номінал + НКД» відрізняються на пару відсотків, а
    // YTM через це — на пару відсоткових пунктів; без підпису перехід між
    // ними читався б як рух ринку. Тому рядок стоїть В ОБОХ випадках.
    const price = r.kind !== "bond" || !r.cost_basis ? ""
      : r.cost_basis !== "market"
        ? `<div>ціна за номіналом + накопичений купон — ринкової немає</div>`
        : `<div>ціна ${esc(r.cost_where_label || r.cost_where)}${
          r.cost_as_of ? ", " + esc(dayMonth(r.cost_as_of)) : ""}${
          r.cost_alt && r.cost_alt_where
            ? ` · у ${esc(r.cost_alt_where)} ${fmtCur(Number(r.cost_alt.amount), r.currency)}`
            : ""}</div>`;
    // Номінальної тут БІЛЬШЕ НЕМА: вона переїхала в головне число рядка
    // (yield.js), і повторювати її в стрічці означало б сказати те саме
    // двічі. Основа лишилась — вона відповідає на інше питання.
    const details = [
      r.kind === "bond" ? "до погашення" : r.yield_basis,
      r.maturity ? `до ${monthYearGen(r.maturity)}` : "",
      r.reason,
    ].filter(Boolean).map(esc).join(" · ");
    return `<div class="sg" data-sg="${key}">
      <button class="caret${open ? " open" : ""}" data-sgexp="${key}" aria-expanded="${open}"
        title="Показати, звідки взялася ця дохідність">▸</button>
      ${kindPill(kind)}
      <span class="sg-n"><b>${suggestName(r)}</b> <span class="muted">${cost}</span></span>
      <span class="sg-y">${yieldCell(r.rate_parts, {
        real: r.real_pct, nominal: r.nominal_pct != null ? r.nominal_pct : r.ytm_pct })}</span>
      ${boughtBtn(kind, r)}
    </div>
    <div class="sg-d sub-xs" data-sgdetail="${key}"${open ? "" : " hidden"}>${details}${price}${auc}</div>`;
  };

  // Перемикач лінійки — той самий `.seg`, що й вікна валютного шоку.
  // Типово реальна: тільки вона розсуджує гривню з доларом. Номінальна
  // відповідає на інше питання — «де більше гривень», — і людина має
  // право поставити список саме так.
  //
  // Лише в гривні: у валюті звітності ≠ гривні номінальної лінійки немає
  // (15% ОВДП — не 15% у доларах), бекенд віддає одну, і перемикати нема
  // що; order=nominal він у такому документі й так ігнорує.
  const inBook = currency() === BOOK;
  const seg = inBook ? `<span class="seg">
    <button data-sgorder="real" aria-pressed="${order === "real"}"
      title="Порядок за реальною дохідністю проти долара — після податку й знецінення гривні">реальна</button>
    <button data-sgorder="nominal" aria-pressed="${order === "nominal"}"
      title="Порядок за номінальною — валюти при цьому незіставні">номінальна</button>
  </span>` : "";
  const legend = inBook
    ? `Головне число — <b>номінальне</b>: те, що в договорі чи в довіднику.
      Під ним реальне, і саме за ним упорядкований список — тільки воно розсуджує
      гривню з доларом.`
    : `Головне число — дохідність <b>у валюті звітності</b>: гривневі ставки вже
      після податку й знецінення, валютні — як є; саме за ним упорядкований список.`;
  return `<div class="card"><h2 class="card-head">
    <span>${esc(title)} ${infoBtn("reinvest")}</span>
    ${seg}</h2>
    ${rows.map(item).join("")}
    <div class="sub">${legend} Клік по числу показує весь ланцюжок: податок, знецінення,
      інфляція. Каретка розкриває решту рядка. «Купив» записує покупку з уже
      заповненими полями.</div></div>`;
}

// «Купив» — покупка за порадою записується з того самого рядка.
//
// Доти дорога від поради до записаної покупки йшла через план купівель:
// «+» → «3 · План і наслідки» → ✓ → ціна вручну — сім кліків і жодного
// поля, якого застосунок сам не знав. Власник купує сам і лише записує
// (ревізія 2026-10-03), тож план прибрано, а запис став одним кроком.
//
// Папір — модалкою з тими самими полями лота (bonds.js, lotFields): ISIN,
// ціна кроку з поради (брудна — та сама, від якої рахована дохідність) і
// брокер, у якого ця ціна, уже підставлені. Кількість — одиниця: скільки
// купив насправді, знає лише людина. Решта видів у модалку не лягає, і
// кожен зі своєї причини — тож для них посилання туди, де їх записують:
// сертифікати заводить виписка, вклад потребує строку й ставки договору,
// внесок НПФ — рахунку.
function boughtBtn(kind, r) {
  if (kind === "bond") {
    return r.isin
      ? `<button class="sm" data-bought="${esc(r.isin)}"
          title="Записати покупку цього паперу — поля вже заповнені">Купив</button>`
      : "";
  }
  const to = { fund: "portfolio/all/statement", deposit: "portfolio/all/record",
    npf: "portfolio/@first:npf/record" }[kind];
  return to ? `<a class="lnk fine-xs" href="${routeFor(to)}"
    title="Туди, де цей вид записують">записати</a>` : "";
}

// Модалка покупки паперу з поради. Окремою функцією, бо читачів двоє:
// рядок поради й задача «Можеш купити X» на «Сьогодні».
export async function openBought(ctx, isin) {
  const r = (reinvest || []).find((x) => x.isin === isin) || { isin };
  const cost = r.cost_per_bond || {};
  const row = {
    isin, qty: 1,
    price_per_bond: { amount: cost.amount || "", currency: cost.currency || "" },
    fee: { amount: "" }, buy_date: today(), channel: r.cost_where || "", note: "",
  };
  await openEdit(ctx, {
    title: `Купив: ${esc(r.label || isin)}`,
    fields: lotFields(ctx, row),
    wire: (f) => { wireRefs(f); wireSuggest(ctx, f); },
    submit: "Записати покупку",
  }, (f) => ({ path: "lots", body: lotBody(f), msg: "Покупку записано" }));
}

// Розкриті пропозиції живуть поза рендером: ctx.reload() стирає main
// цілком, і без цього кожне оновлення згортало б те, що ти щойно відкрив.
// Спільне сховище (js/uistate.js), а не власний Set: той вмирав разом зі
// вкладкою, тобто перехід у «Портфель» і назад згортав усе.
const OPEN_SCOPE = "suggest";

export function wireReinvest(ctx, main) {
  main.querySelectorAll("[data-bought]").forEach((b) =>
    b.addEventListener("click", () => openBought(ctx, b.dataset.bought)));
  main.querySelectorAll("[data-sgorder]").forEach((b) =>
    b.addEventListener("click", async () => {
      if (b.dataset.sgorder === order) return;
      order = b.dataset.sgorder;
      // Перезапит, а не пересортування на місці: порядок вирішує бекенд.
      await loadReinvest(ctx);
      ctx.reload();
    }));
  main.querySelectorAll("[data-sgexp]").forEach((b) =>
    b.addEventListener("click", () => {
      const key = b.dataset.sgexp;
      const row = main.querySelector(`[data-sgdetail="${key}"]`);
      if (!row) return;
      // hidden, а не style.display: видимість рядка деталей — стан, і
      // атрибут його ЗАЯВЛЯЄ, тоді як інлайновий стиль лише малює.
      const open = row.hidden;
      row.hidden = !open;
      b.classList.toggle("open", open);
      b.setAttribute("aria-expanded", String(open));
      remember(OPEN_SCOPE, key, open);
    }));
}

// Найближча ПОДІЯ плану — дія (замок, зміна часток) чи вікно купівлі
// фонду, що закривається. НЕ терміни погашення (їх і так повно на
// «Майбутньому», тут місце для того, що вимагає РІШЕННЯ до дати, а не
// просто настане).
function nearestPlanEvent(doc, todayIso) {
  const items = [];
  (doc.actions || []).forEach((a) => items.push({
    date: a.date, label: a.name || (a.type === "lock" ? "замок" : "зміна часток"),
  }));
  (doc.instruments || []).forEach((it) => {
    if (it.buy_until) items.push({ date: it.buy_until, label: `${it.label}: вікно купівлі закривається` });
  });
  const upcoming = items.filter((e) => e.date >= todayIso).sort((a, b) => a.date < b.date ? -1 : 1);
  return upcoming[0] || null;
}

// Плитка «Цей місяць»: скільки з ПОТРІБНОГО вже зайшло.
//
// Знаменник — ТРЕБА, а не нестача понад план, і це не косметика. Гроші
// плану теж мусять реально надійти на рахунок, їх ніхто не кредитує
// наперед; міряючи проти нестачі, плитка лестила рівно на суму плану, а
// щойно план перекривав ціль — гасла в «—», хоч ціль стояла й місяць
// тривав.
//
// Ціна: month_progress_pct рахує бекенд саме проти month_target_uah, тож
// відсоток тут рахуємо самі. Обидва поля лишаються в документі байт у
// байт — їх жорстко читає інтеграція Home Assistant.
/** Плитка місяця. Експортована заради «Огляду»: там стоїть та сама
 *  плитка з тим самим числом, і друга її копія розійшлася б із цією при
 *  першій же правці знаменника — рівно та підміна, від якої існує
 *  contrib.js. */
export function monthTile(ctx, s) {
  const t = contribTriad(ctx);
  const done = s.month_deposited_uah === undefined ? s.month_invested_uah : s.month_deposited_uah;
  const doneLabel = s.month_deposited_uah === undefined
    ? `вкладено ${fmtUAH(s.month_invested_uah)}` // старий бекенд рахував купівлі
    : `внесено ${fmtUAH(s.month_deposited_uah)}`;
  const mp = s.month_plan;
  // РОЗКЛАД ВНЕСЕНОГО, а не пара валових чисел. «Внесено» тут — рахунки
  // РАЗОМ із подушкою й цілями (state_month.go), і без розкладу зняття з
  // матраца читалось би як загадковий мінус.
  //
  // Доти тут стояли два рядки, і обидва брехали. Перший — «нетто:
  // поповнення X − зняття Y» — рахував переказ гаманець↔матрац і як
  // поповнення, і як зняття: на живих даних «зняття 4 941» на дві третини
  // не було зняттям (довід повністю — при MonthWithdrawnUAH). Другий
  // писав «з них −3 283,16 ₴ У подушку й цілі», тобто відʼємну частину
  // додатного цілого, ще й із прийменником проти знаку.
  //
  // Тепер один рядок в ідіомі «Періоду», щоб два екрани читались
  // однаково, і обидва числа приходять з бекенда: рахувати їх у браузері
  // означало б друге означення того, що там уже є (CLAUDE.md §5).
  const outside = s.month_outside_uah || 0;
  const extra = `${outside
    ? `<div class="sub-xs">з них ${signedUAH2(outside)} у подушку й цілі, ${
      fmtUAH(s.month_contributed_uah || 0)} на рахунки</div>` : ""}
    ${s.month_invested_uah > 0
    ? `<div class="sub">куплено паперів на ${fmtUAH(s.month_invested_uah)}</div>` : ""}`;

  // ГОЛОВНЕ ЧИСЛО ПЛИТКИ — ПОКРИТТЯ ПЛАНУ МІСЯЦЯ, коли план є.
  //
  // Доти тут стояв відсоток від ЦІЛІ накопичення, і на живих даних це було
  // 17%: ціль вимагає 93 931 ₴/міс, а джерела доходу дають утричі менше.
  // Число правдиве й майже некорисне — воно міряє проти суми, якої людина не
  // вносить і не планує вносити цього місяця. Питання, яке ставлять щомісяця,
  // інше: «чи закинув я те, що збирався».
  //
  // Ціль нікуди не поділась — вона рядком під смугою. Два знаменники
  // лишаються на екрані обидва й підписані кожен: план каже, скільки
  // принесуть джерела доходу, ціль — скільки треба, щоб дійти куди хочеш.
  // Злити їх в один прогрес означало б повторити ту саму підміну, від якої
  // існує contrib.js.
  // Смуга в цілі своя, і вона тонка. Доти обидва знаменники стояли на
  // екрані, але міряти оком можна було лише один: план мав смугу, ціль —
  // сухий рядок тексту. Тепер їх видно поруч, і кожна лишається у своїй
  // шкалі — злити їх в один трек означало б ту саму підміну знаменника,
  // від якої існує contrib.js.
  //
  // Смуга цілі йде ПІСЛЯ свого рядка, а не перед ним, як смуга плану:
  // відсоток уже стоїть усередині тексту («— це 59%»), тож смуга під ним
  // читається як ілюстрація саме до нього. Верх плитки при цьому не
  // рухається — головне число там і далі про план.
  //
  // Колір — --oi-series-neutral, той самий сіро-нейтральний, яким лінія
  // цілі малюється на графіках. Акцентний брати не можна: дві сині смуги
  // одна під одною злились би; --oi-series-plan теж ні — це колір ПЛАНУ.
  const goalBar = (share) =>
    progressBar(share, { color: "var(--oi-series-neutral)", cls: "slim" });

  if (mp && mp.plan_uah > 0) {
    const cov = mp.covered_pct || 0;
    const goalShare = shareOfNeed(done, t.need) || 0;
    const goalLine = t.hasGoal
      ? `<div class="sub-xs">ціль вимагає ${fmtUAH(t.need)}/міс — це ${
        Math.round(goalShare)}%</div>
         ${goalBar(goalShare)}`
      : "";
    return tile("Цей місяць", `${Math.round(cov)}%`,
      `${progressBar(cov)}
       <div class="sub">${doneLabel} з ${fmtUAH(mp.plan_uah)} за планом місяця${mp.left_uah > 0
    ? ` · <span class="t-warn">ще закинути ${fmtUAH(mp.left_uah)}</span>`
    : ` · <span class="t-ok">закинуто все</span>`}</div>
       ${goalLine}${extra}`);
  }

  // Далі знаменник рівно один, тож і смуга одна — другої тут не з чого
  // будувати.
  if (t.hasGoal) {
    const share = shareOfNeed(done, t.need) || 0;
    return tile("Цей місяць", `${Math.round(share)}%`,
      `${progressBar(share)}
       <div class="sub">${doneLabel} з ${fmtUAH(t.need)}${
  t.hasPlan ? ` · ${CONTRIB.plan.label.toLowerCase()} дає ${fmtUAH(t.plan)}` : ""}</div>
       ${extra}`);
  }
  // Без цілі «треба» не існує — лишається стара пара з бекенда.
  if (s.month_target_uah > 0) {
    return tile("Цей місяць", `${s.month_progress_pct || 0}%`,
      `${progressBar(s.month_progress_pct || 0)}
       <div class="sub">${doneLabel} з ${fmtUAH(s.month_target_uah)}</div>
       ${extra}`);
  }
  // Ні цілі, ні плану доходу — міряти нема від чого взагалі.
  return tile("Цей місяць", "—",
    `<div class="sub">задай ціль і дедлайн — план порахується сам</div>`);
}

// Друга половина плитки: чи є план, чи вистачає його на ціль, і якщо ні
// ні на що дивитись — найближча дата, коли доведеться щось вирішити.
export function planTileSub(ctx, doc) {
  const t = contribTriad(ctx);
  if (!t.hasPlan) {
    return `<div class="sub"><a class="lnk" href="${routeFor("planflow")}">додай перше джерело доходу</a></div>`;
  }
  if (t.hasGoal) {
    // Обидва канонічні слова в одному рядку — щоб плитка сама пояснювала,
    // від чого рахується нестача.
    return t.gap > 0
      ? `<div class="sub">${CONTRIB.gap.label.toLowerCase()} ${fmtUAH(t.gap)}/міс до потрібних ${fmtUAH(t.need)}/міс</div>`
      : `<div class="sub t-ok">із запасом виводить на ціль</div>`;
  }
  const ev = doc && nearestPlanEvent(doc, today());
  return ev
    ? `<div class="sub">${monthYearGen(ev.date)} — ${esc(ev.label)}</div>`
    : `<div class="sub">задай <a class="lnk" href="${routeFor("policy/strategy/main")}">мету
      капіталу</a>, щоб побачити, чи цього досить</div>`;
}

