// Черга задач: що саме треба зробити, по одному рядку на рішення.
//
// ЧОМУ ЦЕ ЗАМІНИЛО БАНЕР
//
// «Що робити» довго була оглядом: банер із трьома станами, чотири плитки й
// картка виплат. Плитки відповідали на «як справи», а не на «що робити», і
// вся відповідь на питання розділу трималась на одному банері — тобто на
// ОДНІЙ пораді за раз. Поповнити резерв, внести в НПФ, підтвердити
// виплату, що вже надійшла, — усе це або жило десь-інде, або не жило ніде.
//
// Гірше: обидві кнопки банера (data-go) не мали слухача взагалі. ctx.goto
// прибрали ще торік, коли швидкі дії стали звичайними <a href>, а банер
// переписати забули — тобто єдина CTA на головній сторінці нічого не
// робила. Тут таких кнопок немає за побудовою: CTA задачі — це <a href>.
//
// ЧОМУ ТУТ НЕМАЄ ЖОДНОЇ АРИФМЕТИКИ
//
// Черга рахується в бекенді (internal/api/state_tasks.go) і приходить
// готовою в summary.tasks — уже впорядкована, з готовою прозою. Спершу вона
// була зібрана тут, і це працювало рівно доти, доки споживач був один;
// щойно те саме питання поставила інтеграція Home Assistant, друга
// реалізація стала неминучою. Дві реалізації одного питання в цьому проєкті
// вже коштували чотирьох різних «капіталів» на одному екрані — саме проти
// цього існує state/capital.go.
//
// Тому цей модуль уміє рівно одне: намалювати те, що прийшло. Уся його
// власна робота — вирішити, КУДИ веде дія, бо адрес бекенд не знає й знати
// не має (там хеш-маршрути з nav.js, яких у Home Assistant не існує).

import { esc, curSym, dayMonth, cur2 as fmtCur } from "../format.js";
import { empty } from "../components.js";
import { routeFor } from "../routes.js";

// Токен дії → куди веде й що написано на кнопці.
//
// Мапа живе ТУТ, а не в бекенді, і підпис лежить поруч із маршрутом, а не
// приходить рядком: бекенд називає ДІЮ, веб знає МІСЦЯ. Інакше кожен розріз
// дерева навігації ставав би зміною контракту стану — і Home Assistant
// перевидавав би сутності через те, що у вебі переїхала сторінка.
const ACTIONS = {
  "record-buy": { to: "buy", label: "Записати покупку" },
  "top-up-deposit": { to: "topup", label: "Поповнити" },
  "fill-reserve": { to: "entry/reserve", label: "Записати рух" },
  "record-npf": { to: "entry/npf", label: "Записати внесок" },
  "confirm-payment": { to: "plan/payouts", label: "Відмітити" },
  // Веде НЕ в календар, хоч дія в обох — «позначити отриманим». Календар
  // відповідає на «чи прийшло», маршрут — на «куди це піде», а питання
  // цієї задачі саме друге: гроші приходять сьогодні, і рішення про них
  // ухвалюється зараз, а не при звірці.
  "confirm-route": { to: "plan/route", label: "Розкласти" },
  "record-receipt": { to: "planflow", label: "Відмітити надходження" },
  "review-limits": { to: "risk/limits", label: "Подивитись ліміти" },
  "see-suggestions": { to: "now/buy", label: "Що купити" },
  "review-deposit": { to: "assets/deposits", label: "Подивитись вклад" },
  "how-to-fund": { to: "assets/funds", label: "Як завести сертифікат" },
};

const GROUPS = [
  { sev: "now", label: "Зараз" },
  { sev: "soon", label: "Скоро (30 дн.)" },
  { sev: "watch", label: "Тримай на оці" },
];

/** Задачі зі стану. Порядок уже правильний — бекенд віддає впорядкованим,
 *  і перевпорядковувати тут означало б завести другий порядок на ті самі
 *  рядки. */
export function tasksOf(ctx) {
  return (ctx.summary || {}).tasks || [];
}

/** Задачі одного виду інструмента — для сторінки цього інструмента.
 *
 *  Фільтр по полю замість другої збірки: саме заради цього в задачі є kind.
 *  Задачі без виду (виплати, надходження плану, довідник НБУ) сюди не
 *  потрапляють — вони не про цей інструмент і на його сторінці читались би
 *  як його проблеми. */
export function tasksOfKind(ctx, kind) {
  return tasksOf(ctx).filter((t) => t.kind === kind);
}

function taskRow(t) {
  const a = ACTIONS[t.action];
  const cta = a ? `<a class="task-a" href="${routeFor(a.to)}">${esc(a.label)}</a>` : "";
  return `<div class="task" data-sev="${esc(t.sev)}">
    <div class="task-sev" aria-hidden="true"></div>
    <div class="task-t"><b>${esc(t.title)}</b>${t.when
  ? `<span class="task-h">${esc(t.when)}</span>` : ""}
      <div class="task-w">${esc(t.why)}</div></div>
    ${cta}</div>`;
}

/** Порожній стан — НЕ «задач немає».
 *
 *  «Все добре» нічого не каже про те, коли повертатись, а це єдине, що в
 *  цей момент цікавить. Тому порожня черга відповідає ДАТОЮ. */
function emptyHTML(ctx) {
  const np = (ctx.summary || {}).next_payment;
  const why = np
    ? `Наступна дія — коли ${dayMonth(np.date)} надійде виплата ${
      fmtCur(Number(np.amount), curSym(np.currency))}.`
    : "Наступна дія — коли надійдуть гроші або зміняться умови.";
  return `<div class="card">${empty(
    "Зараз нічого не потребує рішення", why,
    { href: routeFor("now/buy"), label: "Подивитись, що купити" })}</div>`;
}

/** Черга задач списком, згрупована за терміновістю.
 *
 *  Власного заголовка картка НЕ має: сторінку вже названо оболонкою
 *  (app.js малює <h1> із nav.js), і другий такий самий рядок під ним — не
 *  структура, а заїкання. */
export function tasksHTML(ctx, list = null) {
  const tasks = list || tasksOf(ctx);
  if (!tasks.length) return emptyHTML(ctx);
  const group = (g) => {
    const items = tasks.filter((t) => t.sev === g.sev);
    if (!items.length) return "";
    return `<h3 class="sg-h">${esc(g.label)}</h3>${items.map(taskRow).join("")}`;
  };
  return `<div class="card tasks">${GROUPS.map(group).join("")}</div>`;
}

/** Зріз черги для сторінки інструмента: та сама картка, лише вужча.
 *
 *  Порожній стан тут НЕ малюється, і це різниця з головною сторінкою.
 *  «Що робити» без задач мусить сказати, коли повертатись, — вона про це й
 *  питає. Сторінка ОВДП питає інше («як я працюю з ОВДП»), і порожня рамка
 *  «тут нічого робити» над таблицею позицій була б відповіддю не на те. */
export function kindTasksHTML(ctx, kind) {
  const list = tasksOfKind(ctx, kind);
  if (!list.length) return "";
  return tasksHTML(ctx, list);
}
