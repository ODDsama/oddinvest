// Ідіома «зараз → стане»: три рядки, якими малюються наслідки будь-якої
// гіпотези.
//
// ЧОМУ ОКРЕМИЙ МОДУЛЬ. Вони народились у «Плані купівель» і жили там
// доти, доки гіпотеза була одна. Щойн поруч став валютний шок — той
// самий документ стану, те саме «до/після», ті самі стрілки, — це вже
// другий випадок, тобто рівно той поріг, який CLAUDE.md §3 називає
// приводом винести спільне. Скопійовані стрілки розійшлися б у першій же
// правці: одна картка почала б казати «без змін», друга — малювати
// «0 → 0».
//
// ЖОДНОГО РАХУНКУ ТУТ НЕМАЄ. Обидва числа приходять готовими з сервера, і
// єдине, що робить цей модуль, — вирішує, чи вони різні, і як це
// показати. Віднімання «стане мінус зараз» законне рівно тому, що обидва
// документи народжені одним кодом (buildStateWith), і на це є тести;
// будь-яка інша арифметика в браузері — це друга копія, історію якої
// розказано в шапці handlers_whatif.go.

import { esc } from "../format.js";

// moved — чи рух узагалі стався. Півкопійки — не рух, а шум округлення:
// без цього порога рядок «без змін» не показувався б майже ніколи.
const moved = (now, will) => Math.abs((will || 0) - (now || 0)) > 0.005;

// delta — числовий рядок «зараз → стане».
//
// tail — підпис, який пояснює саме це число (наприклад ціль частки);
// стоїть після «стане», бо стосується того, куди прийшли, а не звідки.
export function delta(label, now, will, fmt, tail = "") {
  const arrow = moved(now, will)
    ? `<b>${fmt(will || 0)}</b>`
    : `<span class="muted">без змін</span>`;
  return `<div class="pv-row"><span>${esc(label)}</span>
    <span><span class="muted">${fmt(now || 0)} →</span> ${arrow}${tail}</span></div>`;
}

// targetTail — «· ціль N%» дрібним. Порожньо, коли цілі немає: нуль тут
// був би твердженням, що ціль задана й дорівнює нулю.
export const targetTail = (t) =>
  t == null ? "" : ` <span class="muted fine-xs">· ціль ${t}%</span>`;

// dateDelta — те саме для дат.
//
// Дати порівнюються як РЯДКИ: обидві ISO, і Date тут дав би лише привід
// думати про часовий пояс.
export function dateDelta(label, now, will) {
  const a = now || "—", b = will || "—";
  const arrow = a === b ? `<span class="muted">без змін</span>` : `<b>${esc(b)}</b>`;
  return `<div class="pv-row"><span>${esc(label)}</span>
    <span><span class="muted">${esc(a)} →</span> ${arrow}</span></div>`;
}
