// Рейка кроків: послідовність, у якій читається сторінка інструмента.
//
// ЧОМУ ЦЕ НЕ ЗВИЧАЙНІ ЯКОРІ
//
// Застосунок живе в shadow root. href="#write" не знайде нічого — у
// документі такого id немає, — і, гірше, замінить хеш цілком, збивши
// маршрутизатор. Це вже записано в app.js біля кнопки «До вмісту».
//
// Тому крок — це ТРЕТІЙ СЕГМЕНТ адреси (#/instr/bonds/write), а механізм
// уже існував: parseRoute віддає його як anchor, _route кличе _reveal,
// той бере селектор із ANCHORS і доводить до блоку. Раніше цим користувався
// рівно один запис (planflow); тепер їх шість, і всі — імена кроків.
//
// Виграш саме той, заради якого це й робилось: на крок можна поставити
// закладку, надіслати його посиланням і повернутись «назад» браузером.
//
// ЧОМУ КРОКИ НЕ ЗНИКАЮТЬ
//
// Крок, якому нема чого сказати, малює порожній стан і лишається на місці.
// Нумерована послідовність, у якої зникає п'ятий пункт, — зламана
// послідовність: людина бачить «1 2 3 4 6» і шукає, що вона пропустила.
// Виняток один і названий у самій воронці: у резерву кроку «Що зробити»
// немає ЗА ПРИРОДОЮ, бо він нічого не заробляє й помічник його не радить.

import { esc } from "../format.js";

/** Кроки воронки. Ключ збігається з іменем у routes.js ANCHORS — і саме
 *  тому імена спільні для всіх інструментів: крок «Записати» на ОВДП і на
 *  вкладах це той самий крок тієї самої послідовності. */
export const STEPS = [
  { key: "state", label: "Стан" },
  { key: "mine", label: "Що в мене" },
  { key: "next", label: "Що далі" },
  { key: "act", label: "Що зробити" },
  { key: "write", label: "Записати" },
  { key: "terms", label: "Умови" },
];

/** Рейка. path — «розділ/сторінка», current — ключ кроку з ctx.anchor.
 *
 *  Посилання, а не кнопки: браузер задарма дає фокус, Enter, «відкрити в
 *  новій вкладці» й закладку — та сама аргументація, що в меню розділів. */
export function stepRailHTML(path, keys, current) {
  const items = STEPS.filter((s) => keys.includes(s.key));
  return `<nav class="steps" aria-label="Кроки">${items.map((s, i) =>
    `<a class="step-l" href="#/${path}/${s.key}"${
      s.key === current ? ` aria-current="true"` : ""}>${i + 1} · ${esc(s.label)}</a>`)
    .join("")}</nav>`;
}

/** Блок одного кроку.
 *
 *  tabindex="-1" — щоб _reveal міг посадити на нього фокус: коли ціль не
 *  форма, читач екрана має приземлятись на заголовок блоку, а не на
 *  перше-ліпше поле десь посеред таблиці. */
export function stepHTML(key, body) {
  const s = STEPS.find((x) => x.key === key);
  const n = STEPS.indexOf(s) + 1;
  return `<section class="step" id="step-${key}" tabindex="-1"
      aria-labelledby="step-${key}-t">
    <h2 class="step-t" id="step-${key}-t">${n} · ${esc(s.label)}</h2>
    ${body}</section>`;
}

/** Підсвітка поточного кроку.
 *
 *  Один делегований слухач на рейку, а не перемальовування сторінки:
 *  перехід усередині тієї самої сторінки її НЕ перемальовує (app.js
 *  порівнює section/sub і бачить, що вони ті самі), тож aria-current
 *  інакше застряг би на тому кроці, з якого прийшли.
 *
 *  Слухач живе в main, який заміняється цілком на кожному переході між
 *  сторінками, — тож і витоку немає. */
export function wireSteps(main) {
  const rail = main.querySelector(".steps");
  if (!rail) return;
  rail.addEventListener("click", (e) => {
    const a = e.target.closest(".step-l");
    if (!a) return;
    rail.querySelectorAll(".step-l").forEach((x) => x.removeAttribute("aria-current"));
    a.setAttribute("aria-current", "true");
  });
}
