// Скільки чого за стратегією: ціль кожного виду в ГРИВНЯХ і те, наскільки
// вона закрита.
//
// ЧИМ ЦЕ ВІДРІЗНЯЄТЬСЯ ВІД «СТРУКТУРИ ЗА ВИДОМ» (views/risk.js). Питання
// різні, і саме тому карток дві. «Структура» стоїть у «Портфелі» й
// відповідає на «ЧИМ Я РИЗИКУЮ»: її одиниця — відсоток капіталу, і читають
// її, щоб побачити перекіс. Ця стоїть у «Що купити» й відповідає на
// «СКІЛЬКИ ЩЕ ДОКЛАСТИ»: її одиниця — гривня, і читають її перед тим, як
// витратити гроші.
//
// Числа в обох з ОДНОГО джерела (rebalance у зведенні), тож розійтися вони
// не можуть за побудовою. Різні в них лише питання, порядок рядків і
// одиниця — а це рівно те, чого не можна злити в одну картку, не
// зіпсувавши обидві.
//
// ЧОМУ ГРОШІ МІСЯЦЯ ТУТ ДІЛЯТЬСЯ, А ВІЛЬНА ГОТІВКА — НІ. Різниця не в
// зручності, а в тому, чи існує правило поділу.
//
// Готівка на рахунках не ділиться ніде в застосунку, і це лишається чинним:
// пропорції для неї ніхто не задавав, тож будь-який поділ був би правилом,
// яке застосунок вигадав за людину. Тому в лівій половині стоїть «бракує до
// цілі» — факт, а не рішення.
//
// Гроші МІСЯЦЯ — інша річ: правило для них у налаштуваннях уже є, і не одне,
// а два, обидва задані користувачем. Цільові частки кажуть, у якій пропорції
// тримати капітал; стеля «з вільних у резерв» — скільки з нових грошей іде в
// подушку. Права половина лише прикладає їх до відомої суми, нічого не
// вигадуючи.
//
// І саме тому чисел праворуч ДВА. За часткою — пропорція, яку задано прямо;
// на вирівнювання — та сама ціль, але як напрямок руху. Обидва законні, і
// вибір між ними залежить від того, чого людина хоче від цього місяця, —
// тобто це рішення, а не обчислення. Показати одне означало б зробити цей
// вибір за неї мовчки.
//
// ПОРЯДОК РЯДКІВ. Резерв завжди перший, і не тому, що «важливіший»: його
// ціль АБСОЛЮТНА (місяці витрат), а не частка капіталу, тож у відсоткових
// пунктах вона не міряється взагалі й із рештою рядків непорівнянна.
// Поставити його в спільне сортування означало б упорядкувати за числом,
// якого в нього немає. Аргумент той самий, з якого buildRebalance
// (state_rebalance.go) навмисно не дає резерву target_pct.
//
// Види між собою — за дефіцитом у ВІДСОТКОВИХ ПУНКТАХ, спадно. Саме за
// в.п., а не за відсотком заповнення, і це не смак: це ТА САМА міра, якою
// planScore у handlers_reinvest.go ранжує поради в режимі «під план».
// Список порад із цієї сторінки прибраний — він повторював чергу задач, — але
// міра лишається спільною навмисно: щойно він повернеться, карта й список
// мусять збігтися, а не сперечатись.
//
// Закриті й перебрані цілі йдуть донизу: докладати туди нема чого.

import { esc, pct, plural, monthYear, uah2 as fmtUAH } from "../format.js";
import { infoBtn } from "../info.js";
import { needsSetting } from "../components.js";
import { KIND_GROUP } from "../constants.js";
import { routeFor } from "../routes.js";

// Сталий порядок при однаковому дефіциті. Без нього два види з однаковим
// розривом ставали б у порядку, у якому їх поклав бекенд, — а це порядок
// збірки, не сенсу, і мінявся б він мовчки.
const KIND_ORDER = ["bonds", "funds", "deposits", "npf"];

// Резерв — із summary.reserve, а не з рядка ребалансу.
//
// У ребалансі його рядок є, але БЕЗ цілі, і це зроблено навмисно: ціль
// резерву задана в місяцях витрат, і виведена з них частка капіталу давала
// б число, яке нічого не означає (на живих даних — «385% капіталу»). Ціль у
// ГРИВНЯХ при цьому цілком осмислена, і лежить вона саме тут: target_uah,
// uah і gap_uah приходять уже точними.
function reserveRow(s) {
  const r = s.reserve;
  const now = (r && r.uah) || s.reserve_uah || 0;
  const target = (r && r.target_uah) || 0;
  if (!(target > 0)) {
    // Резерв є, цілі немає — рядок довідковий. Сховати його означало б
    // показати неповну картину саме тому, хто ще не задав витрати.
    return now > 0 ? { key: "reserve", title: "Резерв", nowUAH: now, noTarget: true } : null;
  }
  const months = r.target_months || 0;
  const mp = s.month_plan;
  return {
    key: "reserve",
    title: "Резерв",
    nowUAH: now,
    targetUAH: target,
    fillPct: (now / target) * 100,
    deficitUAH: r.gap_uah || 0,
    basis: `ціль ${months} ${plural(months, "місяць", "місяці", "місяців")} витрат`,
    // Частка в капіталі — довідкова: ЦІЛЬОВОЇ частки в резерву немає й не
    // буде (ціль у нього абсолютна), тож пари «зараз · ціль» тут не існує.
    sharePct: (r && r.share_pct) || 0,
    absolute: true,
    // Місячна частка подушки й те, що з неї вже відкладено — обидва з
    // картки резерву, а не з плану місяця: стеля живе там, і другий
    // екземпляр того самого числа розійшовся б із першим.
    monthReserveUAH: r.fill_month_uah || 0,
    monthMovedUAH: r.fill_moved_uah || 0,
    monthLeftUAH: r.fill_now_uah || 0,
    hasPlan: !!mp,
  };
}

// Рядки видів. Резерв звідси ВИКИДАЄТЬСЯ: він уже прийшов зі свого джерела
// вище, і без цього фільтра стояв би в картці двічі — раз із ціллю в
// гривнях, раз без жодної.
function kindRows(s) {
  const rows = (s.rebalance || [])
    .filter((r) => r.dimension === "kind" && r.key !== "reserve");
  const gapPP = (r) => (r.target_pct || 0) - (r.current_pct || 0);
  const ord = (r) => {
    const i = KIND_ORDER.indexOf(r.key);
    return i < 0 ? KIND_ORDER.length : i;
  };
  const withTarget = rows.filter((r) => r.target_pct > 0).map((r) => ({
    key: r.key,
    title: KIND_GROUP[r.key] || r.key,
    nowUAH: r.current_uah || 0,
    targetUAH: r.target_uah || 0,
    fillPct: r.fill_pct || 0,
    deficitUAH: r.deficit_uah || 0,
    basis: `ціль ${r.target_pct}% портфеля`,
    unitUAH: r.bond_cost_uah || 0,
    feasible: r.feasible !== false,
    sharePct: r.current_pct || 0,
    targetPct: r.target_pct || 0,
    monthShareUAH: r.month_share_uah || 0,
    monthBalanceUAH: r.month_balance_uah || 0,
    row: r,
  }));
  withTarget.sort((a, b) => {
    // Закрите — донизу, і це перший критерій: рядок, у який нема чого
    // докладати, не має стояти над тим, у який є.
    const ca = a.deficitUAH > 0 ? 0 : 1, cb = b.deficitUAH > 0 ? 0 : 1;
    if (ca !== cb) return ca - cb;
    const d = gapPP(b.row) - gapPP(a.row);
    if (Math.abs(d) > 0.01) return d;
    return ord(a) - ord(b);
  });
  const noTarget = rows
    .filter((r) => !(r.target_pct > 0) && (r.current_uah || 0) > 0)
    .map((r) => ({
      key: r.key, title: KIND_GROUP[r.key] || r.key,
      nowUAH: r.current_uah || 0, noTarget: true,
      transitUAH: r.transit_uah || 0,
    }));
  return { withTarget, noTarget };
}

// Ліва половина рядка: стан НАКОПИЧУВАЛЬНО.
//
// Головне число — ЧАСТКА В ПОРТФЕЛІ проти цільової, а не заповнення цілі.
// Доти тут стояло заповнення, і на живих даних воно давало «Фонди 381%» —
// формально правильно (ціль закрита вчетверо), а читалось як частка
// портфеля, якою воно не є. Дві частки поруч, у тій самій шкалі, ставлять
// питання й відповідь на одну лінію: 38% при цілі 10%.
//
// Заповнення нікуди не поділось — воно переїхало в дрібний рядок і стало
// ПІДПИСОМ («ціль закрита на 381%»), а не голим числом. Саме голизна й
// збивала: у відсотка мусить бути сказано, від чого він.
//
// Смужка тим самим кольоровим правилом, що й у «Структурі»: перебір —
// попередження, розрив — інформація, закрито — успіх. Однакове питання,
// розфарбоване по-різному на двох сторінках, читалось би як два різні виміри.
function stateHTML(r) {
  const over = r.nowUAH - r.targetUAH;
  const short = r.deficitUAH > 0;
  const color = over > 0.005 ? "var(--oi-warn)" : short ? "var(--oi-info)" : "var(--oi-ok)";
  const bar = Math.max(0, Math.min(100, r.fillPct));
  const tail = short
    ? `<span class="t-warn">бракує ${fmtUAH(r.deficitUAH)}</span>`
    : over > 0.005
      ? `<span class="t-warn">перебір ${fmtUAH(over)}</span>`
      : `<span class="t-ok">ціль закрита ✅</span>`;
  // Найдешевший вхід — лише там, де він існує І де ще є що добирати. У НПФ
  // його немає взагалі (внести можна будь-яку суму), і нуль там означає саме
  // це, а не «не дізнались»; а під закритою ціллю ціна кроку — просто шум:
  // крок нікуди робити.
  const unit = short && r.unitUAH > 0
    ? (r.feasible
      ? ` · найдешевший вхід ${fmtUAH(r.unitUAH)}`
      : ` · <span class="t-warn">⚠ найдешевший вхід ${fmtUAH(r.unitUAH)} — це більше
          за всю цільову суму</span>`)
    : "";
  // У резерву цільової ЧАСТКИ немає й не буде: його ціль абсолютна, у
  // місяцях витрат. Тож ліворуч у нього стоїть частка капіталу без пари, а
  // ціль називає той самий дрібний рядок, що й у решти.
  const head = r.absolute
    ? `<b>${esc(r.title)}</b><span><b>${pct(r.sharePct, 0)}</b>
       <span class="muted">капіталу</span></span>`
    : `<b>${esc(r.title)}</b><span><b>${pct(r.sharePct, 0)}</b>
       <span class="muted">· ціль ${pct(r.targetPct, 0)}</span></span>`;
  return `<div class="kv wrap">${head}</div>
    <div class="progress mt-xs mb-xs"><span style="--oi-fill:${bar}%;--oi-c:${color}"></span></div>
    <div class="sub">є ${fmtUAH(r.nowUAH)} з ${fmtUAH(r.targetUAH)} · ${esc(r.basis)}
      · ${tail}${unit}</div>
    <div class="sub-xs">ціль закрита на ${pct(r.fillPct, 0)}</div>`;
}

// Права половина рядка: гроші ЦЬОГО МІСЯЦЯ, двома числами.
//
// Два, а не одне, бо питання «куди покласти місячні гроші» має дві однаково
// законні відповіді, і вибір між ними — рішення людини, а не арифметика.
// «За часткою» тримає пропорцію й перекосу не помічає; «на вирівнювання»
// веде портфель до цілей і виду в перекосі не дає нічого. Підпис мусить
// назвати цю різницю, інакше два числа на одне питання читаються як помилка.
function monthHTML(r, has) {
  if (!has) return "";
  if (r.absolute) {
    // Про долю решти тут НЕ кажемо: розкладеться вона чи ні, залежить від
    // того, чи є рядки видів, і рішення про це ухвалюється вище. Обіцянка
    // «решта ділиться нижче» на порожньому портфелі була б неправдою.
    if (!(r.monthReserveUAH > 0)) return `<div class="sub muted">—</div>`;
    // Уже відкладене показуємо ЛИШЕ коли воно є: рядок «з них покладено 0»
    // під кожним місяцем, у якому ще не дійшли руки, був би шумом. А коли
    // воно є — саме воно й пояснює, чому «ще відкласти» менше за частку.
    return `<div class="kv"><span class="muted">у резерв</span>
        <b>${fmtUAH(r.monthReserveUAH)}</b></div>
      ${r.monthMovedUAH > 0
    ? `<div class="kv"><span class="muted">ще відкласти</span>
         <b>${fmtUAH(r.monthLeftUAH)}</b></div>
       <div class="sub-xs">з них уже покладено ${fmtUAH(r.monthMovedUAH)}</div>`
    : `<div class="sub-xs">стеля «з вільних у резерв», прикладена до грошей місяця</div>`}`;
  }
  const zero = !(r.monthShareUAH > 0) && !(r.monthBalanceUAH > 0);
  if (zero) {
    return `<div class="sub muted">—</div>`;
  }
  // Вид у переборі, який усе одно щось дістає на вирівнювання, мусить
  // пояснити себе сам: ліворуч «перебір», праворуч додатне число, і без
  // рядка нижче це читається як суперечність. Бази справді різні — ліва
  // від сьогоднішнього портфеля, права від того, яким він стане, — і
  // ціль, виражена ЧАСТКОЮ, росте разом із ним.
  const over = r.nowUAH > r.targetUAH + 0.005;
  const why = over && r.monthBalanceUAH > 0
    ? `<div class="sub-xs">перебір ліворуч міряний від сьогоднішнього портфеля; після
       місяця він виросте, ціль разом із ним — і цей вид опиниться вже нижче за неї</div>`
    : !(r.monthBalanceUAH > 0) && r.monthShareUAH > 0
      ? `<div class="sub-xs">вирівнювання дає нуль: вид уже понад ціль</div>`
      : "";
  return `<div class="kv"><span class="muted">за часткою</span>
      <b>${fmtUAH(r.monthShareUAH)}</b></div>
    <div class="kv"><span class="muted">на вирівнювання</span>
      <b>${fmtUAH(r.monthBalanceUAH)}</b></div>${why}`;
}

// Рядок цілком: дві половини, розділені вертикаллю. Права порожня, коли
// плану місяця немає, — і тоді грид просто не малюється.
function rowHTML(r, hasMonth) {
  if (r.noTarget) {
    return `<div class="mb"><div class="kv">
      <span><b>${esc(r.title)}</b> <span class="muted">цілі немає</span></span>
      <span class="muted">${fmtUAH(r.nowUAH)}</span></div>
      <div class="sub">${
        r.key === "reserve"
          ? "ціль резерву задається місяцями витрат — «Політика → Резерв»"
          : r.key === "deposits"
            // Питання цієї картки — «скільки ще докласти», і на вклад воно
            // не ставиться взагалі: докладати туди нема куди, бо це не ціль,
            // а черга. Скільки в ній стоїть виправдано — єдине, що тут варте
            // гривні, і тому названо саме в гривнях.
            ? (r.transitUAH > 0
                ? `черга до валютного паперу тримає ${fmtUAH(r.transitUAH)}`
                  + (r.nowUAH > r.transitUAH
                      ? `; ${fmtUAH(r.nowUAH - r.transitUAH)} чекають понад неї` : "")
                : "цілі немає навмисно: вклад — черга до валютного паперу, а не вид під частку")
            : "показано довідково: частка є, цілі під неї не ставили"}</div></div>`;
  }
  if (!hasMonth) return `<div class="mb">${stateHTML(r)}</div>`;
  return `<div class="mb duo">
    <div class="duo-a">${stateHTML(r)}</div>
    <div class="duo-b">${monthHTML(r, true)}</div>
  </div>`;
}

// Підсумок місяця над рядками: скільки план заводить, скільки вже внесено і
// скільки лишилось закинути.
//
// Гілкуємось на НАЯВНІСТЬ блока, а не на істинність чисел: нуль у «лишилось»
// означає «план місяця закритий» — стан, про який якраз і треба сказати, — а
// відсутність блока означає «плану доходу немає». Те саме правило записане в
// contrib.js, і сплутати ці два стани тут коштувало б найдорожче: людина
// побачила б «закинути 0 ₴» там, де насправді нема з чого рахувати.
function monthHeadHTML(s) {
  const mp = s.month_plan;
  if (!mp) {
    return `<div class="sub">Плану доходу ще немає, тож розкласти гроші місяця нема з чого.
      Джерела заводяться в <a class="lnk" href="${routeFor("plan/inflow")}">Плані → Що
      заходить</a> — і тоді права колонка скаже, скільки з них куди.</div>`;
  }
  const done = s.month_deposited_uah || 0;
  const parts = [`План на ${monthYear(mp.month + "-01")} — <b>${fmtUAH(mp.plan_uah)}</b>`];
  if (mp.expense_uah > 0) {
    parts.push(`надходження ${fmtUAH(mp.income_uah)} − витрати ${fmtUAH(mp.expense_uah)}`);
  }
  if (mp.extra_uah > 0) parts.push(`з них позапланово ${fmtUAH(mp.extra_uah)}`);
  parts.push(`внесено ${fmtUAH(done)}`);
  parts.push(mp.left_uah > 0
    ? `<b class="t-warn">лишилось закинути ${fmtUAH(mp.left_uah)}</b>`
    : `<b class="t-ok">план місяця закритий</b>`);
  // Скільки з обіцяного вже підтверджено фактом. Без цього рядка план і
  // факт злипаються в одне число, і незрозуміло, наскільки йому вірити.
  const marks = mp.sources > 0
    ? `<div class="sub-xs">відмічено ${mp.marked} з ${mp.sources} ${
      plural(mp.sources, "джерела", "джерел", "джерел")}${mp.received_uah > 0
      ? ` · підтверджено фактом ${fmtUAH(mp.received_uah)}` : ""} — решта поки обіцянка.</div>`
    : "";
  const rm = (s.reserve && s.reserve.fill_month_uah) || 0;
  const res = rm > 0
    ? `<div class="sub-xs">З них <b>${fmtUAH(rm)}</b> іде в резерв: подушка забирає своє
       першим, і колонка «цього місяця» ділить уже те, що лишилось. Стеля береться саме
       з нових грошей — від того, що випадково лежить на брокерському рахунку цієї
       миті, подушка більше не залежить.</div>`
    : "";
  return `<div class="sub">${parts.join(" · ")}.</div>${marks}${res}`;
}

/** Картка «Скільки чого за стратегією» для сторінки «Що купити». */
export function allocationCardHTML(ctx) {
  const s = ctx.summary || {};
  const res = reserveRow(s);
  const { withTarget, noTarget } = kindRows(s);
  const targeted = (res && !res.noTarget ? [res] : []).concat(withTarget);
  if (!targeted.length) {
    return needsSetting(`Скільки чого за стратегією ${infoBtn("allocation")}`,
      "Цілей ще немає, тож і рахувати заповнення нема від чого. Частки за видом "
      + "(ОВДП / фонди / вклади / НПФ) задаються в «Частках і межах», ціль резерву — "
      + "місяцями витрат у «Резерві». Задай хоч одну — і тут з'явиться, скільки в неї "
      + "треба грошей і скільки вже стоїть.",
    routeFor("policy/mix"));
  }

  const rest = (res && res.noTarget ? [res] : []).concat(noTarget);
  const needSum = targeted.reduce((a, r) => a + (r.deficitUAH || 0), 0);
  const free = s.account_uah || 0;
  // Сума цілей за видом — те саме число й те саме формулювання, що в
  // «Структурі»: нерозподілене показуємо, а не розтягуємо до сотні мовчки.
  const targetSum = withTarget.reduce((a, r) => a + ((r.row.target_pct) || 0), 0);

  const money = needSum > 0
    ? `<div class="sub">Бракує разом <b>${fmtUAH(needSum)}</b>; вільних на рахунках ${
      fmtUAH(free)}.${free < needSum
      ? " За раз усе не закриється — порядок рядків і є відповідь, з чого починати."
      : " Вистачає на все одразу; що саме брати — на сторінці кожного інструмента."}</div>`
    : `<div class="sub t-ok">Усі задані цілі закриті. Нові гроші вже нічого не «добирають» —
       вибір лишається за дохідністю, а список порад — на сторінці кожного інструмента.</div>`;

  const mp = s.month_plan;
  const hasMonth = !!mp && mp.plan_uah > 0;
  // Нерозподілена частина місячних грошей — тим самим числом, що й
  // нерозподілені відсотки цілей нижче, лише в гривнях: у ці види
  // застосунок нічого не веде, бо ціль під них не ставили.
  const avail = hasMonth
    ? mp.plan_uah - ((s.reserve && s.reserve.fill_month_uah) || 0) : 0;
  const monthFoot = hasMonth && targetSum > 0 && targetSum < 99.5
    ? `<div class="sub">Через діру в цілях <b>${fmtUAH(avail * (100 - targetSum) / 100)}</b>
       із грошей місяця не мають куди піти: ${(100 - targetSum).toFixed(0)}% портфеля
       не кероване жодною ціллю, тож застосунок сам ці гроші нікуди не веде.</div>`
    : "";
  // «До розкладу» обіцяємо лише тоді, коли є по чому розкладати. Рядків
  // видів немає, поки капітал нульовий: частка від нуля не міряється, і
  // buildRebalance їх свідомо не малює. Обіцяти в шапці розклад, якого під
  // нею не буде, — це той самий клас помилки, що й нуль замість прочерку.
  const canSplit = withTarget.length > 0;
  const cols = hasMonth
    ? `<div class="duo duo-h"><div class="duo-a">За стратегією — усього</div>
       <div class="duo-b">Цього місяця${canSplit ? ` — ${fmtUAH(avail)} до розкладу` : ""}</div></div>`
    : "";
  const noSplit = hasMonth && !canSplit
    ? `<div class="sub">Решта — <b>${fmtUAH(avail)}</b> — поки не розкладається: частки за
       видом міряються від портфеля, а його ще немає. Зʼявиться перший папір чи вклад — і
       права колонка почне казати, скільки з місячних грошей куди.</div>`
    : "";
  // Сума цілей, що не дає 100, — це ДІРА, а не «місце під резерв».
  //
  // Доти залишок був осмислений: цілі міряли частку всього капіталу, і під
  // ним жили подушка з готівкою. Відколи резерв вийшов зі знаменника,
  // тримати місце нема для кого — усі готові набори розподіляють рівно
  // сотню, і тест це стереже. Тож недобір тепер треба назвати недобором.
  const whole = targetSum > 0 && targetSum < 99.5
    ? ` Цілі за видом дають ${targetSum.toFixed(0)}% замість 100 — ${
      (100 - targetSum).toFixed(0)}% портфеля не кероване жодною ціллю. Це не «місце під
      резерв»: подушка в цей знаменник не входить узагалі. Довести до сотні —
      <a class="lnk" href="${routeFor("policy/mix")}">Частки й межі</a> або готовий набір
      у <a class="lnk" href="${routeFor("policy/strategy")}">Стратегії</a>.`
    : targetSum > 100.5
      ? ` Цілі за видом у сумі дають ${targetSum.toFixed(0)}% — більше за портфель, тож
          усі одразу недосяжні.` : "";

  return `<div class="card">
    <h2 class="h-row">Скільки чого за стратегією ${infoBtn("allocation")}</h2>
    <div class="note">Ліворуч — скільки чого МАЄ бути й скільки вже стоїть; праворуч —
      куди йдуть гроші цього місяця. Закрите й перебране — донизу, решта за розривом до
      цілі у ВІДСОТКОВИХ ПУНКТАХ портфеля: тим самим розривом помічник ранжує поради
      в режимі «під план», тож карта й поради не можуть радити різне. Праворуч два
      числа навмисно: «за часткою» тримає пропорцію, «на вирівнювання» веде портфель
      до цілей — і котре з них твоє, вирішуєш ти, а не застосунок.</div>
    ${monthHeadHTML(s)}
    ${cols}
    ${targeted.map((r) => rowHTML(r, hasMonth)).join("")}
    ${rest.length ? `<div class="rule-top">${rest.map((r) => rowHTML(r, false)).join("")}</div>` : ""}
    ${noSplit}${monthFoot}
    ${money}
    <div class="sub">Частки міряються від портфеля БЕЗ резерву: у подушки своя ціль, у
      місяцях витрат, і вона ні з ким не конкурує — саме тому зібрана подушка більше не
      ламає стратегію. Невкладена готівка при цьому в знаменнику лишається, тож поки
      гроші лежать на рахунку, всі види разом стоять трохи нижче цілі.${whole}
      Ті самі числа у відсотках — <a class="lnk"
      href="${routeFor("portfolio/structure")}">Портфель → Структура</a>.</div>
  </div>`;
}
