// «Сьогодні» — єдина домашня сторінка. Знак ODD у шапці веде сюди.
//
// Єдина вкладка без майстер-списку: у неї немає сутності, яку можна
// вибрати, — вона про портфель ЦІЛКОМ.
//
// ДОТИ ДОМАШНІХ БУЛО ДВІ: «Огляд» і «Робота → Що робити». Обидві несли
// героя капіталу, чергу задач і плитку місяця, лише в різному порядку й
// з різними підписами під тим самим числом, — і на питання «що мені
// сьогодні робити» застосунок мав дві відповіді. Злито в одну за
// рішенням власника (2026-09-22): черга звідти, плитки й контекст звідси.
//
// ПОРЯДОК БЛОКІВ ВЕДЕ ПИТАННЯМ, А НЕ РОЗМІРОМ ЧИСЕЛ. Спершу що потребує
// рішення — черга ПЕРШОЮ й цілком, «Тримай на оці» згорнуто; далі
// скільки в мене; і аж тоді контекст: місяць, наступна виплата, план,
// що заходить, найближча віха, борг.
//
// ВАЛЮТНОГО РЕБАЛАНСУ ТУТ НЕМАЄ: картка живе лише в «Портфель →
// Структура», а сюди приходить задачею в черзі (review-rebalance), коли
// відхилення можна виправити бодай одним квитком. Картка-дубль на
// головній показувала той самий розрив щодня, навіть коли зробити з ним
// було нічого.
//
// ЖОДНОГО ВЛАСНОГО ЧИСЛА. Кожен блок або бере готове зі зведення, або
// кличе ту саму функцію, що малює це число на своїй вкладці: плитка
// місяця — monthTile, найближча віха — nextLineHTML із «Шляху», черга —
// tasksHTML, той самий, що на сторінці інструмента. Друга копія
// будь-якого з них розійшлася б із першою тихо.
//
// ПРОГРЕСУ ТУТ БІЛЬШЕ НЕМАЄ, і від нього лишився один рядок. Сітка з
// чотирнадцяти віх стояла тут суцільним блоком і була картою без
// напрямку: жодна віха не названа найближчою, жодне число не каже,
// скільки лишилось. Вона переїхала на власну вкладку «Шлях» цілком —
// разом із доріжками, полем колекції та стрічкою датованих віх.

import {
  esc, uah0, signedUAH, pct, capitalUAH, outsideUAH, dayMonth,
  plural, approxOther, cur2, REAL_FX,
} from "../format.js";
import { tile, empty } from "../components.js";
import { routeFor } from "../routes.js";
import { tasksHTML } from "./tasks.js";
import { monthTile, planTileSub } from "./now-view.js";
import { nextLineHTML } from "./path.js";
import { debtOverviewHTML } from "./debts.js";

/** Головне число й три поруч.
 *
 *  «За 30 днів» тут — рядок під капіталом, і число приходить ГОТОВИМ
 *  (capital_delta_30 зі зведення). Довго його не було: щоденний знімок
 *  тримав капітал, але різниці за вікно не рахував ніхто, а порахувати
 *  її тут означало б завести в браузері арифметику над історією — саме
 *  те, проти чого стоїть увесь цей файл. Внесене ззовні стоїть поруч у
 *  тому самому рядку: без нього «+12 000» читалось би як заробіток. */
function heroHTML(ctx) {
  const s = ctx.summary || {};
  const cap = capitalUAH(s);
  const xirr = (s.xirr || {}).UAH;
  const d = s.capital_delta_30;
  const sub = [
    // Та сама сума в іншій валюті — доларах у гривневому документі, гривні
    // в доларовому (format.js: approxOther).
    approxOther(s, cap),
    d ? `за 30 днів ${signedUAH(d.delta_uah)}, з них внесено ${signedUAH(d.contributed_uah)}` : "",
    // Резерв і цілі — обидва, одним рядком: питання в них одне («скільки
    // з капіталу не працює»), і два рядки поспіль про це читались би як
    // дубль. Назвати лише подушку означало б сховати другу половину.
    outsideUAH(s) > 0
      // «Поза дохідністю», а НЕ «не працюють»: і подушка (0032), і ціль
      // (0062) можуть лежати на вкладі й заробляти. Стара проза була
      // неточна ще до появи цільових вкладів, а з ними стала прямою
      // неправдою — 50 000 під 13% вона називала грішми, які не працюють.
      // Що саме заробляє, каже blended_yield_base_uah.
      ? `з них ${uah0(outsideUAH(s))} у резерві й цілях — поза дохідністю портфеля` : "",
    // Накопичений купон — зароблене, але ще не виплачене. Він уже в
    // капіталі (облігації — «номінал + накопичений купон»), тож рядок
    // каже «з них», а не «плюс».
    s.accrued_uah > 0 ? `з них ${uah0(s.accrued_uah)} накопиченого купона` : "",
  ].filter(Boolean).map((t) => `<div class="sub">${esc(t)}</div>`).join("");

  return `<div class="tiles flush">
    ${tile("Капітал", uah0(cap), sub, { hero: true })}
    ${tile("Дохідність портфеля",
    s.blended_yield_pct ? pct(s.blended_yield_pct) : "—",
    // Другий рядок — лише коли лінійки дві: у валюті звітності ≠ гривні
    // бекенд віддає реальну рівною номінальній, і повторювати число під
    // ним означало б підписати «реальних» те, що й так єдине.
    s.blended_yield_pct && s.blended_yield_real_pct !== s.blended_yield_pct
      ? `<div class="sub-xs">${pct(s.blended_yield_real_pct)} ${REAL_FX} —
         після податку й знецінення</div>` : "")}
    ${tile("Заробило, річних", xirr ? pct(xirr) : "—",
    xirr ? `<div class="sub-xs">XIRR — з урахуванням дат внесків</div>`
      : `<div class="sub-xs">гроші ще замолоді, щоб міряти</div>`)}
    ${tile("Вільні гроші", uah0(s.account_uah || 0), idleSubHTML(s))}
    ${savingsRateTile(s)}
  </div>`;
}

/** Норма заощаджень — яка частка доходу справді відкладається.
 *
 *  Стоїть поруч із дохідністю навмисно, і саме в цьому суть плитки: на
 *  стадії набору норма визначає накопичений капітал СИЛЬНІШЕ за
 *  дохідність, і вона єдина цілком у твоїх руках. Доти застосунок показував
 *  усе про 0.5 в.п. дохідності й нічого про 5 в.п. норми.
 *
 *  Обидві половини названі в підписі, тож число перевіряється діленням, а
 *  не береться на віру. Обидві — за одне й те саме вікно місяців: доти
 *  знаменником був дохід ЦЬОГО місяця, і пів року внесків проти одного
 *  місяця зарплати давали 161%.
 *
 *  Мовчить без плану доходу: ділити нема на що, а нуль читався б як
 *  «нічого не відкладаю» — зовсім інше твердження. */
function savingsRateTile(s) {
  const r = s.savings_rate_pct;
  if (!r) return "";
  const gross = s.savings_base_uah || 0;
  const months = s.actual_months || 0;
  const sub = `<div class="sub-xs">${uah0(s.actual_monthly_uah || 0)}/міс
    з ${uah0(gross)}/міс доходу${months ? ` — обидва в середньому за ${months}
    ${plural(months, "місяць", "місяці", "місяців")}` : ""}</div>`;
  return tile("Норма заощаджень", pct(r), sub);
}

/** Підпис під «Вільними грішми»: простій, якщо він є, інакше поріг покупки.
 *
 *  Простій приходить готовим (idle зі зведення): скільки вже можна вкласти,
 *  з якого дня лежить і що це коштує на місяць за сьогоднішньою порадою.
 *  Ціна є не завжди — без поради для цих грошей у цього брокера її нема з
 *  чого взяти, і тоді рядок каже лише скільки й відколи. */
function idleSubHTML(s) {
  const idle = s.idle;
  if (idle && idle.investable_uah > 0) {
    const since = idle.since ? ` · лежать з ${esc(dayMonth(idle.since))}` : "";
    // Ціна — окремим полем (idle_cost): це порада про сьогоднішній
    // ринок, а не факт про гаманець, і без поради її просто немає.
    const c = s.idle_cost;
    const cost = c && c.cost_month_uah > 0
      ? ` · ≈ ${esc(signedUAH(-c.cost_month_uah))}/міс за сьогоднішньою порадою` : "";
    return `<div class="sub-xs">можна вкласти ${esc(uah0(idle.investable_uah))}${since}${cost}</div>`;
  }
  return s.reinvest_min_uah > 0
    ? `<div class="sub-xs">поріг покупки ${uah0(s.reinvest_min_uah)}</div>` : "";
}

