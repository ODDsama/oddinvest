// Класичний КРУД однією проводкою: створити, виправити, видалити.
//
// ЩО ЦЕ ЛАГОДИТЬ. Шість PUT-ендпойнтів жили на сервері без ЖОДНОГО екрана:
// lots, deposits, conversions, reserve, funds, npf. Помилку в записаному
// лоті, русі грошей, конвертації, резерві, операції фонду чи внеску НПФ
// виправляли єдиним способом — видалити й набрати заново. І це не забудькува-
// тість: щоб дописати правку одному розділу, треба було написати ще один
// список полів (той, що в модалці), стежити, щоб він не розійшовся з тим, що
// у формі додавання, і повторити це шість разів. Дорого — значить не зроблено.
//
// Тому правка тут не окрема можливість, яку хтось колись допише, а ЧАСТИНА
// стандартної проводки: викликав wireCrud — маєш усі три дії. Список полів
// один (fields.js), збирач тіла один, і форма додавання з модалкою правки
// фізично не можуть розійтись, бо це той самий код із іншим аргументом.
//
// Запис на бекенд робить forms.js і тільки він: apply/onSubmit/onSubmitFunded/
// onDelete/openEdit уже вміють тост, перемальовування, підтвердження й
// автопоповнення рахунку. Тут — лише те, ЩО саме йому передати.

import { onSubmit, onSubmitFunded, onDelete, openEdit, apply } from "./forms.js";
import { wireRefs, wireSuggest } from "./refs.js";

/** Прив'язати створення, правку й видалення одного ресурсу.
 *
 *  spec:
 *    resource — ІМʼЯ ресурсу ("lots"). Воно ж значення data-res на кнопках
 *               рядка, тобто саме воно розводить два гріди на одній
 *               сторінці. За замовчуванням воно ж і шлях в API.
 *    path       — (id) => шлях, коли він не збігається з іменем. Потрібне
 *               вкладеним ресурсам: поповнення вкладу живе за адресою
 *               term-deposits/{вклад}/topups/{id}, і вкладів на сторінці
 *               кілька, тож ім'я в розмітці мусить нести ще й номер вкладу
 *               ("topups:12") — інакше проводка одного вкладу підв'язала б
 *               кнопки всіх.
 *    createPath — шлях для POST, коли він теж не збігається з іменем.
 *    form     — селектор форми додавання. null, якщо на цій сторінці її
 *               немає (журнал у «Активах» показує ті самі рядки, а форма
 *               стоїть на кроці «Записати» іншої сторінки).
 *    fields   — (ctx, row) => розмітка полів. row === null означає форму
 *               додавання, row !== null — модалку правки. ОДНА функція на
 *               обидва випадки; саме через це вони не можуть розійтись.
 *    body     — (form, row) => тіло запиту або null, щоб тихо скасувати.
 *               Спільне для POST і PUT, як і мапери xxxFromReq на бекенді.
 *               row === null при створенні, сам запис — при правці. Другий
 *               аргумент потрібен там, де в тілі мусить поїхати те, чого у
 *               формі НЕМАЄ: вклад приймає PUT цілком, разом із полями
 *               закриття, і правка ставки без них мовчки «відкрила» б
 *               назад розірваний вклад.
 *    rows     — записи, які видно на сторінці: за ними правка знаходить, що
 *               підставити в поля.
 *    funded   — (form) => {check, date, what} для операцій, які витрачають
 *               гроші. Тільки для СТВОРЕННЯ: у PUT бекенд перевірки нестачі
 *               не має, і вигадувати її на клієнті означало б завести другу
 *               копію арифметики — рівно те, чим уже двічі закінчувались
 *               спроби порахувати суму операції в браузері.
 *    title    — як називається один запис («Лот», «Рух»): іде в заголовок
 *               модалки й у питання перед видаленням.
 *    confirm  — (row) => текст питання. Типове питання називає лише вид і
 *               номер; там, де видалення тягне за собою наслідки (скасування
 *               продажу повертає залишок лота), його треба сказати вголос.
 */
export function wireCrud(ctx, main, spec) {
  const {
    resource, form = null, fields, body, rows = [],
    funded = null, title = "Запис", confirm = null, msg = {},
    path = (id) => resource + "/" + id, createPath = resource,
  } = spec;
  if (!main) return;
  const byId = new Map((rows || []).map((r) => [String(r.id), r]));

  // --- створення ---
  const addForm = form ? main.querySelector(form) : null;
  if (addForm) {
    const build = (f) => {
      const b = body(f, null);
      if (!b) return null;
      const req = { path: createPath, body: b, msg: msg.add || (title + " додано") };
      return funded ? { ...req, ...funded(f) } : req;
    };
    if (funded) onSubmitFunded(ctx, addForm, build);
    else onSubmit(ctx, addForm, build);
  }

  // --- правка ---
  // Селектор із ресурсом, а не голе [data-edit]: два гріди на сторінці
  // інакше поділили б одну проводку, і кнопка сусіда пішла б у чужий шлях.
  main.querySelectorAll('[data-res="' + resource + '"][data-edit]').forEach((btn) => {
    btn.addEventListener("click", () => {
      const row = byId.get(btn.dataset.edit);
      // Кнопка без запису — не мовчання, а стан, якого не має бути: рядок
      // намальовано, а даних під ним немає. Тост замість тихого нічого.
      if (!row) { ctx.toast("Запис не знайдено — онови сторінку", false); return; }
      openEdit(ctx, {
        title: title + " #" + row.id,
        fields: fields(ctx, row),
        // Поля модалки — ті самі, що у формі додавання, тож і проводка
        // полів та сама. Без неї «інший…» біля брокера не відкривав би
        // поля назви, а підказка ISIN мовчала б: обидві вішають слухачі
        // після рендера, а рендер тут відбувається пізніше за проводку
        // сторінки.
        wire: (f) => { wireRefs(f); wireSuggest(ctx, f); },
      }, (f) => {
        const b = body(f, row);
        return b ? {
          method: "PUT", path: path(row.id), body: b,
          msg: msg.edit || "Збережено",
        } : null;
      });
    });
  });

  // --- видалення ---
  onDelete(ctx, main, '[data-res="' + resource + '"][data-del]', (btn) => {
    const row = byId.get(btn.dataset.del);
    return {
      path: path(btn.dataset.del),
      confirm: confirm && row
        ? confirm(row)
        : "Видалити " + title.toLowerCase() + " #" + btn.dataset.del + "?",
      msg: msg.del || (title + " видалено"),
    };
  });
}

/** Правка поля просто в рядку: зберігається на blur, change і Enter.
 *
 *  Доти цей прийом існував ДВІЧІ й майже однаково — довідники в
 *  «Налаштуваннях» і продажі в ОВДП, — і обидві копії робили те саме:
 *  зібрати поля за data-field, звірити з тим, що було, зібрати тіло,
 *  дописати числам Number(), відправити PUT. Розходились вони в дрібниці:
 *  довідники слухали ще й Enter, продажі — ні.
 *
 *  Доречний він там, де правити треба ОДНЕ поле у вже записаному рядку, і
 *  модалка з дванадцятьма полями заради однієї назви була б церемонією.
 *  Там, де правлять операцію цілком, — wireCrud вище.
 *
 *  change поруч із blur потрібен випадайці й полю дати: вибір мишею чи в
 *  календарі фокуса не знімає, тож на самому blur правка зберігалась би аж
 *  після кліку кудись повз.
 *
 *  extra(row) дописує в тіло те, чого в полях немає: бекенд часткового
 *  оновлення не знає, і надіслати саму кількість означало б обнулити ціну.
 *  guard(values) може заборонити запис — порожня назва в довіднику. */
export function inlineEdit(ctx, root, {
  rows, fields: fieldSel, path, extra = null, guard = null, msg = "Збережено",
}) {
  if (!root) return;
  root.querySelectorAll(rows).forEach((row) => {
    const els = [...row.querySelectorAll(fieldSel)];
    if (!els.length) return;
    const key = () => els.map((f) => f.value.trim()).join("|");
    row.dataset.was = key();
    const commit = async () => {
      if (key() === row.dataset.was) return;
      const values = {};
      els.forEach((f) => {
        // Числові поля йдуть числом: порожнє = 0, тобто «не задано».
        // Відсотки лишаються рядком — так порожнє відрізняється від нуля.
        values[f.dataset.field] = f.dataset.num
          ? Number(f.value.trim()) || 0
          : f.value.trim();
      });
      if (guard && !guard(values)) return;
      // Позначку «збережено» ставимо ПІСЛЯ перевірок, але ДО запиту: інакше
      // blur, який приходить одразу за Enter, відправив би те саме вдруге.
      row.dataset.was = key();
      await apply(ctx, {
        method: "PUT", path: path(row), body: { ...values, ...(extra ? extra(row) : {}) },
      }, msg);
    };
    els.forEach((f) => {
      f.addEventListener("blur", commit);
      f.addEventListener("change", commit);
      f.addEventListener("keydown", (e) => { if (e.key === "Enter") f.blur(); });
    });
  });
}
