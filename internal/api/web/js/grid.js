// Грід операцій: таблиця, описана колонками, а не розміткою.
//
// Двадцять сім таблиць у шістнадцяти файлах, і кожна писала свої
// <thead>/<tbody> руками. Спільними в них були лише класи CSS — і ставились
// вони не всюди: .table-scroll мали дванадцять із двадцяти семи, а решта на
// вузькому екрані розсувала по горизонталі ВСЮ сторінку разом із шапкою.
// Саме такі розбіжності й означають «розкидано»: правило існує, але діє
// рівно там, де про нього згадали.
//
// ЧОГО ТУТ НЕМАЄ І ЧОМУ.
//
// Сортування по кліку на заголовок. Порядок кожної таблиці — це доменне
// рішення: позиції йдуть за розміром, рухи грошей — за датою спадання,
// поради «Що купити» приходять уже впорядкованими з бекенда, бо їх ранжує
// налаштування reinvest_rank. Дозволити перевпорядкувати означало б
// дозволити сховати відповідь, яку застосунок щойно дав. Порожній шов «а
// тут можна сортувати» у цьому коді читається як зразок і тиражується —
// рівно так свого часу розрослась і вмерла section() (disclosure.js).
//
// Пагінація. Найдовший список застосунку — виписка руху грошей за всі роки,
// і він коротший за екран прокрутки. Сторінки розбивали б те, що поміщається
// цілком.
//
// Картка-на-рядок для вузького екрана. Вона є, але тільки в .pos-table, і
// вона рукотворна: сітка 3×3 під конкретні сім колонок портфеля, де відомо,
// що головне, а що дрібним рядком під ним. Загальний будівник цього не знає,
// тож картка з нього вийшла б стовпчиком «підпис: значення» — тобто тією ж
// таблицею, лише вищою. Замість вигаданої картки грід дає колонці право
// сказати «на телефоні мене можна не показувати» (prio), а решта
// прокручується всередині своєї коробки, як і всі таблиці застосунку.
//
// Усі три рішення оборотні однією правкою В ОДНОМУ місці — колонки описані
// специфікацією саме заради цього.

import { esc } from "./format.js";
import { empty as emptyState } from "./components.js";

function attrStr(map) {
  return Object.entries(map || {}).map(([k, v]) =>
    (v == null || v === "" ? "" : " " + k + '="' + esc(String(v)) + '"')).join("");
}

/** Таблиця операцій.
 *
 *  cols — [{key, label, num?, prio?, cls?, cell}]:
 *    key   — машинне ім'я колонки. Потрапляє в data-col, і саме за ним CSS
 *            знаходить комірку. НЕ підпис: розкладка, прив'язана до тексту
 *            заголовка, тихо ламається від перейменування — так і було в
 *            таблиці позицій, де мобільні області шукались по
 *            data-label="Назва".
 *    label — підпис у шапці.
 *    num   — число: вирівнюється праворуч.
 *    prio  — 3 означає «на вузькому екрані сховати». Без пріоритету колонка
 *            лишається завжди.
 *    cell  — (row, i) => готова РОЗМІТКА. Екранує викликач, як і всюди в
 *            застосунку: у комірці частіше стоїть пігулка, посилання чи
 *            кнопка, ніж голий рядок, і автоматичне екранування їх з'їло б.
 *
 *  caption — чим є ця таблиця, одним рядком. Видно лише читачеві екрана
 *  (.sr-only), і саме тому воно тут обов'язкове за змістом, а не за
 *  сигнатурою: заголовок картки над таблицею для зрячого пояснює все, а
 *  для того, хто слухає, таблиця починається одразу з «Дата, Сума, …».
 *
 *  foot — підсумок. Масив комірок [{cell, num?, span?}] дає ОДИН рядок із
 *  класом .tot, під яким уже є правило (base.css): вагою, а не заливкою,
 *  бо підсумок відрізняється тим, що він підсумок.
 *
 *  Рядком розмітки — коли підсумок не один рядок. Такий випадок у
 *  застосунку рівно один і не вигаданий: підвал таблиці потоків плану має
 *  шість рядків із різними colspan, і кожен із них там не заради краси —
 *  вони показують ЧИСЛАМИ подвійне віднімання, про яке інакше довелося б
 *  попереджати прозою. Загальний вигляд «масив рядків із масивів комірок»
 *  описав би це, але з одним користувачем це був би опис одного випадку
 *  мовою, придуманою для нього ж.
 *
 *  empty — текст порожнього стану. Порожній рядок означає «не малювати
 *  нічого»: у згорнутій секції архіву порожній стан був би повідомленням
 *  про відсутність того, чого й не обіцяли.
 *
 *  head: false прибирає шапку. Потрібне ВИПИСЦІ — таблиці, де перша
 *  колонка сама і є підписом рядка («Було на рахунках», «− куплено»), а
 *  над стовпчиком чисел писати нічого: слово «Сума» там лише повторило б
 *  те, що видно. Для того, хто слухає, лишається caption.
 */
export function opsGrid({
  cols, rows, empty = "", caption = "", cls = "", id = "", rowAttrs = null,
  foot = null, head: withHead = true,
}) {
  const list = rows || [];
  if (!list.length) return empty ? emptyState("", empty) : "";

  const cellCls = (c) => [c.num ? "num" : "", c.cls || ""].filter(Boolean).join(" ");

  const head = cols.map((c) =>
    "<th scope=\"col\"" + attrStr({
      "data-col": c.key, "data-prio": c.prio, class: cellCls(c),
    }) + ">" + esc(c.label || "") + "</th>").join("");

  // rowAttrs — те, що потрібне рядкові, а не комірці: до якого лота
  // належить продаж і в якій він валюті. Правка-на-місці збирає тіло з
  // полів рядка, а lot_id і валюти серед них немає (PUT замінює запис
  // цілком, але в таблиці ці два поля не показують). Без гачка їх довелось
  // би або показати зайвими колонками, або вгадувати.
  const body = list.map((row, i) => "<tr"
    + attrStr({ "data-row": row.id, ...(rowAttrs ? rowAttrs(row) : {}) }) + ">"
    + cols.map((c) => "<td" + attrStr({
      "data-col": c.key, "data-prio": c.prio, class: cellCls(c),
    }) + ">" + c.cell(row, i) + "</td>").join("")
    + "</tr>").join("");

  // Підсумок описується так само, як колонки: {key, cell?} або {span}.
  // span потрібен першій комірці — «Разом» майже завжди розтягнуте на
  // кілька колонок, а порожні <td> замість нього читались би як нулі.
  const footRow = Array.isArray(foot)
    ? '<tr class="tot">' + foot.map((c) =>
      "<td" + attrStr({ colspan: c.span, class: c.num ? "num" : "" }) + ">"
      + (c.cell || "") + "</td>").join("") + "</tr>"
    : foot || "";
  const tfoot = footRow ? "<tfoot>" + footRow + "</tfoot>" : "";

  return '<div class="table-scroll"><table'
    + attrStr({ id, class: ("grid-table " + cls).trim() }) + ">"
    + (caption ? '<caption class="sr-only">' + esc(caption) + "</caption>" : "")
    + (withHead ? "<thead><tr>" + head + "</tr></thead>" : "") + "<tbody>" + body + "</tbody>" + tfoot + "</table></div>";
}

/** Стандартна комірка дій: правка й видалення, завжди в цьому порядку й
 *  завжди цими значками.
 *
 *  Порядок не косметика. Видалення незворотне, і коли воно стоїть першим,
 *  промах пальцем коштує запису; коли останнім — промах коштує зайвого
 *  діалогу. Доти порядок був який вийде, бо кнопки дописувались по одній і
 *  здебільшого була лише одна — ✕.
 *
 *  res — РЕСУРС, якому належить рядок ("lots", "deposits"). Він у розмітці
 *  не для краси: на сторінці «Гроші» стоять два гріди поруч (рухи й
 *  конвертації), і проводка, яка шукала б просто [data-del], підв'язала б
 *  кнопки сусіда до свого шляху — видалення руху пішло б у /conversions.
 *  З ресурсом у атрибуті кожна проводка бачить рівно свої кнопки. */
export function rowActions(res, id, { edit = true, del = true, label = "" } = {}) {
  const own = ' data-res="' + esc(res) + '" ';
  // aria-label, а не самий title: усередині кнопки стоїть значок, і читач
  // екрана без підпису оголосив би «кнопка ✎». Наявні кнопки правки в
  // «Плані» вже підписані саме так («Змінити потік Зарплата»), і грід не
  // має права бути глухішим за них. label — чим є САМЕ ЦЕЙ рядок; без
  // нього лишається номер, бо «виправити запис» на двадцяти рядках
  // однакове й тому марне.
  const what = label ? esc(label) : "запис #" + esc(id);
  return (edit ? '<button class="sm"' + own + 'data-edit="' + esc(id)
    + '" title="Виправити" aria-label="Виправити ' + what + '">✎</button>' : "")
    + (del ? '<button class="sm warn"' + own + 'data-del="' + esc(id)
      + '" title="Видалити" aria-label="Видалити ' + what + '">✕</button>' : "");
}

/** Колонка дій — та сама в кожному гріді, тож описується один раз.
 *
 *  Порожній підпис навмисно: слово «Дії» над стовпчиком із двох значків
 *  займає більше місця, ніж пояснює. Тому, хто слухає, про них скаже
 *  caption таблиці, а самі кнопки мають title. */
export function actionsCol(res, opts = {}) {
  return {
    key: "acts", label: "", cls: "row-actions nowrap",
    cell: (row) => rowActions(res, row.id, {
      ...opts,
      label: typeof opts.label === "function" ? opts.label(row) : opts.label,
    }),
  };
}
