// Поля форми: одна функція на вид поля замість ста сімнадцяти рукописних
// <label>.
//
// Розмітка тут НЕ нова — вона дослівно та, що вже стояла в розділах:
// <label> сам собі обгортка, підпис текстом перед полем, ніяких зайвих
// div'ів, розкладку дає CSS (base.css при `form`). Змінилось одне: тепер її
// пише одне місце.
//
// Навіщо, якщо результат той самий. Двадцять шість форм писались копіюванням
// сусідньої, і копіювалась не лише вдала розмітка: `inputmode="decimal"` на
// сумі стоїть у більшості форм і немає в кількох, `required` розставлений як
// пам'ять підказала, а плейсхолдери сум мають три різні формати. Кожна така
// розбіжність окремо нічого не варта — разом вони означають, що «як тут
// заведено» доводиться щоразу з'ясовувати читанням сусіда.
//
// ГОЛОВНЕ, ЗАРАДИ ЧОГО ЦЕ Є: той самий масив полів обслуговує і форму
// додавання, і модалку правки. openEdit() (forms.js) цього вимагав від
// початку — «той самий набір, що й у формі додавання, саме тому розмітку
// малює одна функція», — але вимагав СЛОВАМИ. Доки список полів писався
// двічі, два списки розходились на першій же зміні, і саме тому шість
// PUT-ендпойнтів жили без жодного екрана: правку було дорого дописувати.
//
// Чого тут свідомо немає — валідації. Її робить бекенд і лише він: у
// застосунку вже є єдиний шлях помилки (transport.js розгортає {"error"} →
// toast), і друга, клієнтська, думка про те, що таке правильна сума,
// розійшлася б із першою мовчки.

import { esc, today } from "./format.js";

// Атрибути з мапи. Порожні (null/undefined/false/"") пропускаються, true
// пишеться голим словом — саме так поводяться required, hidden і checked.
function attrs(map) {
  return Object.entries(map).map(([k, v]) => {
    if (v == null || v === false || v === "") return "";
    return v === true ? ` ${k}` : ` ${k}="${esc(String(v))}"`;
  }).join("");
}

/** Поле загального вигляду. Решта функцій — це воно з іншими типовими
 *  значеннями, і саме тому вони не приймають `type`: якщо доводиться
 *  задавати тип руками, потрібне не поле, а нова іменована функція. */
export function field(name, label, {
  type = "", value = "", ph = "", required = false, inputmode = "",
  min = "", max = "", step = "", cls = "", title = "", labelCls = "", after = "",
} = {}) {
  const input = `<input${attrs({
    name, type, value, placeholder: ph, required, inputmode,
    min, max, step, class: cls, title,
  })}>`;
  // after — розмітка ВСЕРЕДИНІ <label>, одразу під полем: жива підказка
  // («зараз 31% · ціль 35%» під часткою валюти). Саме всередині, а не
  // поруч: підпис, поле й підказка — один зоровий об'єкт, і винесення
  // підказки назовні розірвало б його першим же переносом рядка.
  return `<label${attrs({ class: labelCls })}>${esc(label)}${input}${after}</label>`;
}

/** Сума в мажорних одиницях. inputmode="decimal" — щоб на телефоні
 *  відкривалась цифрова клавіатура з крапкою, а не буквенна. */
export function money(name, label, opts = {}) {
  return field(name, label, { inputmode: "decimal", ph: "0.00", ...opts });
}

/** Відсоток. Технічно те саме поле, що й сума, і зведення їх в одне було б
 *  економією в один рядок — але тоді «поміняти щось у всіх відсоткових
 *  полях» перестало б бути можливим одною правкою, а такі правки тут уже
 *  траплялись (усі ставки колись переїхали з type="number" на inputmode). */
export function pct(name, label, opts = {}) {
  return field(name, label, { inputmode: "decimal", ph: "0.0", ...opts });
}

/** Ціле число: кількість паперів, місяців, днів. */
export function num(name, label, opts = {}) {
  return field(name, label, { type: "number", step: "1", ...opts });
}

/** Дата. Типове значення — сьогодні: у цьому застосунку майже кожну
 *  операцію записують того ж дня, коли вона сталась. Явне value: "" вимикає
 *  це для полів, які означають «поки не сталось» (дата закриття). */
export function date(name, label, opts = {}) {
  return field(name, label, { type: "date", value: today(), ...opts });
}

/** Рядок. */
export function text(name, label, opts = {}) {
  return field(name, label, opts);
}

/** Прапорець. Підпис ПІСЛЯ поля й .row-h на обгортці: галочка з підписом
 *  згори виглядала б як обрізане поле вводу.
 *
 *  Служить і полем форми, і перемикачем У РЯДКУ таблиці — це той самий
 *  елемент із іншим одягом. Рядок вкладу має перемикач «поповнюваний», у
 *  якого немає ані імені (він не подається формою, а шле PUT одразу), ані
 *  місця під повний підпис; йому потрібні свій клас обгортки й свій
 *  data-атрибут, і саме тому labelCls та own існують.
 *
 *  Порожнє name законне: перемикач поза формою іменувати нічим. */
export function check(name, label, {
  checked = false, title = "", labelCls = "row-h", attrs: own = {},
} = {}) {
  return `<label${attrs({ class: labelCls, title })}>`
    + `<input${attrs({ name, type: "checkbox", class: "w-auto", checked, ...own })}>`
    + `${esc(label)}</label>`;
}

/** Випадайка з готового списку. opts — пари [значення, підпис], як усюди в
 *  застосунку (RANKS у strategy.js, destOptions у plan-flows.js).
 *
 *  Для посилання на СУТНІСТЬ це не те: там список приходить із бази й має
 *  вміти «інший…». Такі поля будує refs.js. */
export function selectOf(name, label, options, selected = "", { title = "" } = {}) {
  const opts = options.map(([v, t]) =>
    `<option${attrs({ value: v, selected: String(v) === String(selected) })}>${esc(t)}</option>`).join("");
  return `<label${attrs({ title })}>${esc(label)}`
    + `<select${attrs({ name })}>${opts}</select></label>`;
}

/** Багаторядкове поле. У застосунку рівно одне — вклеювання історії
 *  ЧВОПА, — і воно тут не «про запас»: без нього єдина форма застосунку
 *  лишалась би рукописною, тобто правило «розмітку полів пише одне місце»
 *  мало б виняток, а виняток із правила читається як дозвіл. */
export function textarea(name, label, { value = "", ph = "", rows = 4 } = {}) {
  return `<label${attrs({})}>${esc(label)}`
    + `<textarea${attrs({ name, rows, placeholder: ph })}>${esc(value)}</textarea></label>`;
}

/** Нотатка. Окремою функцією, попри те, що це звичайний text(): вона стоїть
 *  останнім полем у ЧОТИРНАДЦЯТИ формах, завжди з тим самим іменем і тим
 *  самим підписом, і три з них розійшлись були на «Примітка». */
export function note(name = "note", label = "Нотатка", opts = {}) {
  return text(name, label, opts);
}

/** Форма цілком. fields — масив рядків розмітки (порожні пропускаються, щоб
 *  умовне поле писалось виразом, а не склейкою рядків).
 *
 *  extra — розмітка між полями й кнопкою: живі підказки ([data-lockhint]),
 *  згорнуті «Ще» з рідковживаними полями. */
export function formHTML({
  id, fields = [], submit = "Записати", extra = "", cls = "", attrs: own = {},
}) {
  // own — атрибути самої форми. Потрібні там, де форм на сторінці кілька й
  // однакових: у кожного поповнюваного вкладу своя форма поповнення, і
  // розрізняє їх data-topup-form із номером вкладу. Через id це не
  // виражається — id мусив би бути унікальним рядком, який потім треба
  // зібрати назад у селекторі.
  return `<form${attrs({ id, class: cls, ...own })}>${fields.filter(Boolean).join("")}${extra}`
    + `<div class="form-actions"><button type="submit">${esc(submit)}</button></div></form>`;
}
