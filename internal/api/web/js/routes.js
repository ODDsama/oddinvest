// Маршрути застосунку: розбір хеша й адреси форм.
//
// Окремим модулем, а не всередині app.js, з однієї причини: адреси
// потрібні РОЗДІЛАМ — саме вони будують посилання «Купівля»,
// «Поповнення», «Відкрити налаштування». Якби routeFor жив у app.js,
// розділ мусив би імпортувати app.js, який імпортує сам розділ, і граф
// імпортів замкнувся б у кільце. Модулі таке переживають, але кільце в
// графі — це те, що читач помічає останнім і плутається першим.
//
// Саме хеш, а не шлях: статику віддає http.FileServerFS
// (internal/api/server.go), і будь-який шлях, крім "/", повернув би 404
// — SPA-fallback довелось би дописувати в Go. Хеш цього не вимагає й дає
// рівно те, чого бракувало: «назад» у браузері, закладку на «Портфель» і
// посилання просто на форму.
//
// Граматика: #/<розділ> і #/<розділ>/<якір>.

import { TABS } from "./constants.js";

const TAB_KEYS = TABS.map(([k]) => k);

/** Розібрати хеш у пару «розділ + якір». Невідомий розділ — «Огляд»:
 *  зіпсоване посилання має відкривати застосунок, а не порожнечу. */
export function parseRoute(hash) {
  const parts = String(hash || "").replace(/^#\/?/, "").split("/").filter(Boolean);
  return {
    tab: TAB_KEYS.includes(parts[0]) ? parts[0] : "overview",
    anchor: parts[1] || "",
  };
}

// Куди веде кожен якір. Той самий словник, що жив усередині _goto, лише
// перевернутий: тепер він читається як частина маршруту, а не як
// побічний ефект натискання кнопки.
//
// topup — секція вкладів у «Портфелі» (не плутати з deposit: то
// поповнення грошового рахунку в «Грошах»).
export const ANCHORS = {
  buy: { tab: "portfolio", sel: "#lotForm" },
  topup: { tab: "portfolio", sel: "#termDepForm" },
  deposit: { tab: "money", sel: "#cashForm" },
  convert: { tab: "money", sel: "#convForm" },
  planflow: { tab: "plan", sel: "#planFlowForm" },
};

/** Адреса, за якою відкривається потрібна форма або розділ. */
export function routeFor(what) {
  const a = ANCHORS[what];
  return a ? `#/${a.tab}/${what}` : `#/${TAB_KEYS.includes(what) ? what : "portfolio"}`;
}
