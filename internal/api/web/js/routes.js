// Маршрути застосунку: розбір хеша й адреси форм.
//
// Окремим модулем, а не всередині app.js, з однієї причини: адреси
// потрібні РОЗДІЛАМ — саме вони будують посилання «Купівля»,
// «Поповнення», «Відкрити налаштування». Якби routeFor жив у app.js,
// розділ мусив би імпортувати app.js, який імпортує сам розділ, і граф
// імпортів замкнувся б у кільце. Модулі таке переживають, але кільце в
// графі — це те, що читач помічає останнім і плутається першим.
//
// Саме хеш, а не шлях: статику віддає http.FileServerFS
// (internal/api/server.go), і будь-який шлях, крім "/", повернув би 404
// — SPA-fallback довелось би дописувати в Go. Хеш цього не вимагає й дає
// рівно те, чого бракувало: «назад» у браузері, закладку на «Портфель» і
// посилання просто на форму.
//
// Граматика: #/<розділ>/<підрозділ> і #/<розділ>/<підрозділ>/<якір>.
// Другий сегмент більше не якір, а сторінка: дерево живе в nav.js.

import { PATHS, FIRST, HOME } from "./nav.js";

// Закладки, зроблені до появи другого ярусу. Не 404 і не тихий відкат на
// «Зараз»: адреса вела в конкретне місце, і воно нікуди не поділось —
// лише переїхало.
//
// Таблиця коротка навмисно. Голий розділ без підрозділу вона не описує:
// для нього є правило FIRST нижче, і воно покриває не лише шість старих
// ключів, а й будь-яке «набрав половину адреси» в майбутньому. Сюди
// потрапляє тільки те, чий ЗМІСТ поїхав в інше місце.
const LEGACY = new Map([
  ["overview", "now/todo"],
  ["portfolio", "assets/positions"],
  ["portfolio/buy", "entry/bond"],
  ["portfolio/topup", "entry/deposit"],
  // deposit тут — поповнення грошового РАХУНКУ, не вкладу: два різні
  // «поповнення» жили поруч у старій таблиці якорів і плутались.
  ["money/deposit", "entry/cash"],
  ["money/convert", "entry/convert"],
  ["plan/planflow", "plan/inflow/planflow"],
  // «Майбутнє» злилося з «Планом» ще торік, і закладка на нього досі
  // може лежати в чиємусь браузері.
  ["future", "plan/goal"],
]);

// Куди веде адреса, якої немає в дереві. Порядок кроків має значення:
// «money/deposit» мусить піти в таблицю переїздів РАНІШЕ, ніж спрацює
// правило голого розділу, — інакше «money» знайшлось би саме собою й
// відкрило б баланси замість форми.
//
// Зациклитись це не може навіть із помилкою в таблиці: значення, якого
// немає в PATHS, наступним проходом не знайдеться ні тут, ні в LEGACY,
// впаде в правило голого розділу або в HOME — і на цьому спиниться.
function resolveLegacy(parts) {
  const one = parts[0] || "";
  const hit = LEGACY.get(`${one}/${parts[1] || ""}`) || LEGACY.get(one);
  if (hit) return hit;
  if (FIRST.has(one)) return `${one}/${FIRST.get(one)}`;
  return HOME;
}

/** Розібрати хеш. redirect — канонічний шлях, на який треба замінити
 *  адресу; порожній рядок означає, що адреса вже канонічна.
 *
 *  Заміняти адресу мусить той, хто маршрутизує, і саме через
 *  location.replace(): присвоєння лишило б стару адресу в історії, «назад»
 *  повернуло б на неї, вона знову перенаправила б уперед — і кнопка
 *  «назад» перестала б працювати взагалі. */
export function parseRoute(hash) {
  const parts = String(hash || "").replace(/^#\/?/, "").split("/").filter(Boolean);
  if (PATHS.has(`${parts[0]}/${parts[1]}`)) {
    return { section: parts[0], sub: parts[1], anchor: parts[2] || "", redirect: "" };
  }
  const to = resolveLegacy(parts);
  const seg = to.split("/");
  return { section: seg[0], sub: seg[1], anchor: seg[2] || "", redirect: to };
}

// Якорі — тільки для сторінок, де форм БІЛЬШЕ ОДНОЇ. Доти їх було п'ять,
// бо кожна форма жила в згорнутій секції спільної вкладки й без якоря до
// неї було не дійти. Тепер купівля, вклад, готівка й конвертація — окремі
// сторінки, тобто самі собі адреса, і в списку лишилось одне: «Що
// заходить» несе форму потоку, форми дій і надходження, і посилання
// «додай перше джерело доходу» мусить сказати, яку саме з них відкрити.
//
// Порожніх записів «про запас» тут немає навмисно: мертвий якір читається
// як зразок і тиражується.
export const ANCHORS = {
  planflow: "#planFlowForm",
};

// Куди веде кожне іменоване посилання на форму. Імена лишились старі —
// їх пишуть розділи (routeFor("buy")), і перейменування зачепило б п'ять
// місць заради нуля користі.
const FORM_ROUTE = {
  buy: "entry/bond",
  topup: "entry/deposit",
  deposit: "entry/cash",
  convert: "entry/convert",
  planflow: "plan/inflow/planflow",
};

/** Адреса, за якою відкривається потрібна форма, сторінка або розділ. */
export function routeFor(what) {
  if (FORM_ROUTE[what]) return `#/${FORM_ROUTE[what]}`;
  if (PATHS.has(what)) return `#/${what}`;
  if (FIRST.has(what)) return `#/${what}/${FIRST.get(what)}`;
  return `#/${HOME}`;
}
