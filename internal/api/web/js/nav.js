// на що дивишся, і на кожен блок можна поставити закладку.
//
// ГОЛОВНЕ РІШЕННЯ ЦЬОГО ДЕРЕВА: ВІСЬ — ІМЕННИК, А НЕ ДІЄСЛОВО
//
// Доти розділів було вісім, і три з них різали портфель по ПОВЕРХНЯХ:
// «Активи» тримали дані, «Записати» — форми, «Політика» — умови. Щоб
// попрацювати з ОВДП, треба було стрибати між трьома, і питання «як я
// працюю з ОВДП» не мало жодного місця, де воно тримається одним поглядом.
//
// Тепер інструмент — це ОДНА сторінка з шести кроків: стан, що в мене, що
// далі, що зробити, записати, умови. Розділ «Записати» цим розпускається.
//
// Його стара аргументація («питання „чим це записати“ одне, а місць було
// чотири») варта прямої відповіді, бо інакше наступний автор відновить
// його тим самим доводом. Вона була правильна щодо ДІАГНОЗУ й неправильна
// щодо осі: форми справді були розсіяні, але розсіяні саме тому, що кожна
// стояла посеред ЧУЖОГО питання — купівля в «Портфелі», бо там журнал
// лотів. Зібрати їх за дієсловом означало завести восьме питання
// («записати»), яке ні до чого не належить. Зібрати за іменником —
// повернути кожну туди, де стоїть її сутність. Правило «один підрозділ —
// одна сутність» лишилось чинним; змінилось те, ЩО вважається сутністю.
//
// Ціна названа й прийнята: дієслівного входу більше немає, і той, хто
// думає «мені треба щось записати», мусить спершу згадати, ЩО саме.
//
// ЩО НЕ ПІШЛО У ВОРОНКИ
//
// 1. «Виписка» і «Звірка» — пакетні входи, названі МЕХАНІЗМОМ навмисно:
//    обидва заводять кілька сутностей одразу. Виписка Inzhur
//    розкладається на операції з сертифікатами, лот ОВДП і рух грошей —
//    три гілки в handlers_import.go. Покласти її під «Фонди» означало б
//    збрехати на дві третини, тож вона в «Грошах», де рухається рахунок.
//
// 2. «Що купити» лишилось у «Зараз» ЦІЛИМ. Помічник ранжує ОВДП, фонд,
//    вклад і НПФ однією реальною дохідністю — це головне, що він уміє, і
//    рознести його по воронках означало б зламати рівно те, заради чого
//    він існує. Воронка показує свій зріз і посилається сюди.
//
// 3. «Ризик» влився в «Портфель». Складу й ризику розводити нічим: «що я
//    маю», «як воно виросло», «як розкладене», «де ліміти», «з чим
//    порівняти» — п'ять кутів одного погляду. Розводило їх те, що в
//    «Активах» лежали ще й посутнісні сторінки; вони пішли у воронки, і
//    решта злиплась сама.
//
// 4. «Політика» лишилась окремою, і це не непослідовність. Крок «Умови» у
//    воронці ПОСИЛАЄТЬСЯ на неї, а не повторює її поля: та сама ціль
//    керує кількома видами одразу (частки міряються від одного капіталу),
//    і два місця редагування одного числа розійшлись би.
//
