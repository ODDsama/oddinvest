/** Усі дозволені шляхи: "розділ/підрозділ" → усе, що про нього відомо.
 *
 *  Одна мапа замість трьох пошуків по дереву. Її читають маршрутизатор
 *  (чи існує такий шлях), оболонка (заголовок сторінки, чи широка вона) і
 *  майбутня перевірка мертвих посилань: літерал href="#/…", якого тут
 *  немає, — це поламане посилання, і знайти його має скрипт, а не читач. */
export const PATHS = new Map();

/** Розділ → його перший підрозділ. Саме сюди веде заголовок групи в
 *  меню, і саме цим розкривається голий "#/assets": адреса без другого
 *  сегмента не помилка, а половина набраної адреси. */
export const FIRST = new Map();

for (const g of NAV) {
  FIRST.set(g.key, g.items[0].key);
  for (const it of g.items) {
    PATHS.set(`${g.key}/${it.key}`, {
      section: g.key,
      sub: it.key,
      label: it.label,
      sectionLabel: g.label,
      wide: !!it.wide,
    });
  }
}
