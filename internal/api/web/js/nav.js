//
// Окремим файлом, а не в constants.js, з тієї ж причини, з якої routes.js
// не живе в app.js: constants.js — довідник ЗНАЧЕНЬ домену (типи виплат,
// види операцій, підписи інструментів), і дерево навігації там було б
// єдиним записом іншої природи.
//
// ЯРУСІВ ТРИ: вкладка → рядок → панель. Адреса — #/<tab>/<item>/<pane>,
// тобто закладку можна поставити не на сторінку, а на КОНКРЕТНУ позицію
// в конкретному розрізі.
//
// ГОЛОВНЕ РІШЕННЯ ЦЬОГО ДЕРЕВА: ВІСЬ — СУТНІСТЬ, А НЕ ЇЇ ВИД
//
// Доти воронка з шести кроків належала ВИДУ: сторінка «ОВДП» показувала
// всі папери разом, і щоб подивитись на конкретний, доводилось шукати
// його в таблиці. Але працюють не з «ОВДП» — працюють з папером, який
// гаситься в березні. Тепер рядок майстер-списку і є сутністю, а вибір
// паперу автоматично є вибором виду: чипи-фільтри над списком дають той
// самий зріз, який доти вимагав окремої сторінки.
//
// Розділ «Інструменти» цим розпускається — уже вдруге за життя цього
// файлу, і вдруге з тієї самої причини: він групував по тому, ЧИМ річ є,
// а не по самій речі.
//
// ЩО СЮДИ НЕ ПЕРЕЇХАЛО, І ЧОМУ ЦЕ ТУТ НАПИСАНО
//
// Ці доводи прийшли зі старого дерева. Вони чинні й після переїзду, а
// сторінки, при яких вони стояли, зникли — тож без цього абзацу їх не
// було б де прочитати.
//
// 1. «Виписка» і «Звірка» — панелі «Усіх рахунків», названі МЕХАНІЗМОМ
//    навмисно: обидві заводять кілька сутностей одразу. Виписка Inzhur
//    розкладається на операції з сертифікатами, лот ОВДП і рух грошей —
//    три гілки в handlers_import.go. Покласти її під конкретний фонд
//    означало б збрехати на дві третини.
//
// 2. «Що купити» лишилось у «Роботі» ЦІЛИМ. Помічник ранжує ОВДП, фонд,
//    вклад і НПФ однією реальною дохідністю — це головне, що він уміє, і
//    рознести його по рядках портфеля означало б зламати рівно те, заради
//    чого він існує. Панель «Що зробити» показує свій зріз і посилається
//    сюди.
//
// 3. «Політика» лишилась окремою вкладкою, і це не непослідовність.
//    Панель «Умови» ПОСИЛАЄТЬСЯ на неї, а не повторює її поля: та сама
//    ціль керує кількома видами одразу (частки міряються від одного
//    капіталу), і два місця редагування одного числа розійшлись би.
//
// 4. У резерву П'ЯТЬ панелей, а не шість. Панелі «Що зробити» в нього
//    немає ЗА ПРИРОДОЮ: /api/reinvest виду «резерв» не віддає взагалі, бо
//    реальної дохідності в резерву не існує — це гроші, і в сьогоднішніх
//    гривнях вони дають мінус знецінення. Поставити його в один стовпчик
//    із паперами можна було б лише вигадавши число.
//
//    У ЦІЛІ НАКОПИЧЕННЯ панелей так само п'ять, і довід той самий слово в
//    слово: це теж гроші, і дохідності в них теж немає. Різниця між ними —
//    не в природі грошей, а в тому, що з ними буде: подушку тримають, щоб
//    НЕ витратити, ціль — щоб витратити у названу дату. Через це в цілі є
//    сума й дедлайн, і саме тому вона окремий рядок, а не місце зберігання
//    всередині резерву.
//
// ЧОГО ТУТ НЕМАЄ: поля `wide`
//
// Ширина сторінки перестала бути її властивістю. Доти «Позиції» й
// «Календар виплат» просили собі ширшу колонку, бо колонка була одна на
// весь застосунок. Тепер ширину задає розкладка: майстер-список має
// фіксовану ширину, інспектор бере решту — і таблиця на сім колонок
// прокручується всередині себе, а не розсовує сторінку.

