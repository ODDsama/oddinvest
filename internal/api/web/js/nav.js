// Дерево навігації: розділи, підрозділи й похідні від них покажчики.
//
// Окремим файлом, а не в constants.js, з тієї ж причини, з якої routes.js
// не живе в app.js: constants.js — довідник ЗНАЧЕНЬ домену (типи виплат,
// види операцій, підписи інструментів), і дерево навігації там було б
// єдиним записом іншої природи. Доки розділів було шість пар
// «ключ — підпис», це не заважало; тридцять п'ять підрозділів із
// метаданими вже заважає.
//
// ЧОМУ ВІСІМ ГРУП, А НЕ ШІСТЬ ВКЛАДОК
//
// Стара схема (constants.js) казала: розділ відповідає рівно на одне
// питання, а розділ, який не тримає своє питання одним поглядом, — привід
// його рознести. Правило лишається чинним; змінилось те, що виконати його
// шістьма вкладками стало неможливо, і замість розносу застосовувалось
// згортання: section() ховала половину вкладки під <details>. Це лікує
// показ, а не вагу — рендериться все одно все, і «План» вантажив тисячу
// п'ятсот рядків заради однієї картки.
//
// Тому ярусів тепер два. Верхній лишився тим самим списком питань, лише
// довшим; нижній — це ті ж таки section(), яким дали адресу. Виграш не
// косметичний: підрозділ є ОКРЕМОЮ сторінкою, тобто малюється лише те, на
// що дивишся, і на кожен блок можна поставити закладку.
//
// ТРИ РІШЕННЯ, ЯКІ ВАРТО ЗНАТИ, ПЕРШ НІЖ ЦЕ ПРАВИТИ
//
// 1. Один підрозділ — одна сутність. «Фонди й НПФ» одним рядком і
//    «Вклади й резерв» одним рядком були б поверненням до тієї самої
//    злипанки, від якої тікали: у фонду й НПФ спільного рівно стільки ж,
//    скільки в вкладу з матрацом, тобто нічого, крім того, що і те, і
//    те — гроші.
//
// 2. «Записати» збирає форми, які жили в трьох різних розділах: купівля
//    й продаж — у «Портфелі», готівка, конвертація, виписка й звірка — у
//    «Грошах», потоки й дії — у «Плані». Питання «чим це записати» одне,
//    а місць було чотири. Розділ має два яруси, і другий (Виписка,
//    Звірка) названий МЕХАНІЗМОМ навмисно: обидва входи заводять кілька
//    сутностей одразу, тож посутнісного імені в них немає й бути не може.
//    Виписка Inzhur, наприклад, розкладається на операції з
//    сертифікатами, лот ОВДП і рух грошей на рахунку — три гілки в
//    handlers_import.go. Покласти її під «Фонди» означало б збрехати на
//    дві третини.
//
// 3. «Політика» пішла з «Налаштувань». Причина вже була записана в
//    settings.js: «у політику заходять регулярно, у довідники — раз на
//    кілька місяців», — але розв'язана вона була згортанням. Це різні
//    питання: «чого я хочу» (цілі, частки, ліміти, припущення) і «як воно
//    налаштоване» (довідники брокерів і фондів, бекап). У «Налаштуваннях»
//    лишилось два підрозділи, і це не недогляд: там службовий кут
//    застосунку, і саме він мусить працювати, коли бекенд ліг.
//
// wide — сторінка має право бути ширшою за смугу читання. Раніше це саме
// правило жило в CSS літералом main[data-tab="portfolio"], тобто політика
// ширини трималась на магічному імені вкладки; тепер вона стоїть поруч зі
// сторінкою, якої стосується.
//
// gap — розділювач перед пунктом у меню. Єдиний його користувач —
// «Виписка», початок другого ярусу «Записати».

