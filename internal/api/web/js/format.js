// Форматування — числа, гроші, дати, українська множина.
//
// Один модуль на весь застосунок. Доти, доки ці функції жили двома
// копіями (веб-UI й бічна панель Home Assistant), вони встигли розійтись
// у дрібницях: у панелі був `esc`, у вебі — ні, і саме тому веб не
// екранував вивід. Копія була б непомітною, поки не почала б брехати.

import { CURRENCY_SYM } from "./constants.js";

/** Екранування для вставки в innerHTML. Обов'язкове для всього, що
 *  прийшло з бекенда: ISIN, назви брокерів і фондів, нотатки. */
export const esc = (s) =>
  String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

export const curSym = (c) => CURRENCY_SYM[c] || c;

/** Сьогоднішня дата ISO — у ЛОКАЛЬНІЙ зоні, а не через toISOString.
 *
 *  Той дає UTC, тобто з півночі до 03:00 за Києвом — учорашнє число. А
 *  ставиться воно типовим значенням у КОЖНЕ поле дати (fields.js), тож
 *  поповнення, введене о пів на першу ночі першого вересня, лягло б у
 *  серпень — і не в тому місяці порахувались би і план, і темп, і серія.
 *
 *  Поруч monthKeyOffset (views/plan-receipts.js) рахує місяць локально й
 *  обіцяє, що браузер і сервер не називатимуть різні місяці одним іменем.
 *  Ця функція те саме обіцяння порушувала. */
export const today = () => {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${
    String(d.getDate()).padStart(2, "0")}`;
};

// --- дати ---

const MON_NOM = ["січень", "лютий", "березень", "квітень", "травень", "червень",
  "липень", "серпень", "вересень", "жовтень", "листопад", "грудень"];
const MON_GEN = ["січня", "лютого", "березня", "квітня", "травня", "червня",
  "липня", "серпня", "вересня", "жовтня", "листопада", "грудня"];

/** Українська множина: 1 рік / 2-4 роки / 5+ років (з винятком 11-14). */
export function plural(n, one, few, many) {
  const d = n % 10, h = n % 100;
  if (d === 1 && h !== 11) return one;
  if (d >= 2 && d <= 4 && (h < 10 || h >= 20)) return few;
  return many;
}

/** 32 -> «2 роки 8 місяців» (замість «2.6 р.»). */
export function humanMonths(m) {
  m = Math.max(0, Math.round(m));
  const y = Math.floor(m / 12), mo = m % 12, parts = [];
  if (y) parts.push(`${y} ${plural(y, "рік", "роки", "років")}`);
  if (mo) parts.push(`${mo} ${plural(mo, "місяць", "місяці", "місяців")}`);
  return parts.join(" ") || "менше місяця";
}

/** «2029-02-19» -> «лютий 2029». */
export function monthYear(iso) {
  const p = String(iso || "").split("-");
  if (p.length < 2) return String(iso || "");
  return `${MON_NOM[+p[1] - 1] || p[1]} ${p[0]}`;
}

/** «2026-07» -> «лип», а січень — «січ 26»: підпис осі, де місяців дванадцять
 *  і повні назви злиплись би в сіру смугу. Рік показуємо лише там, де він
 *  міняється, — інакше на кожному стовпчику стояло б те саме число. */
export function monthShort(iso) {
  const p = String(iso || "").split("-");
  if (p.length < 2) return String(iso || "");
  const m = +p[1];
  const short = (MON_NOM[m - 1] || p[1]).slice(0, 3);
  return m === 1 ? `${short} ${p[0].slice(2)}` : short;
}

/** «2029-03-17» -> «березня 2029»: родовий відмінок для конструкцій
 *  «до <місяця>», де називний дав би «до березень». */
export function monthYearGen(iso) {
  const p = String(iso || "").split("-");
  if (p.length < 2) return String(iso || "");
  return `${MON_GEN[+p[1] - 1] || p[1]} ${p[0]}`;
}

/** «2026-07-22» -> «22 липня», а якщо не цьогоріч — «20 січня 2027»:
 *  без року дата наступної виплати читається як «ось-ось». */
export function dayMonth(iso) {
  const p = String(iso || "").split("-");
  if (p.length < 3) return monthYear(iso);
  const d = `${+p[2]} ${MON_GEN[+p[1] - 1] || p[1]}`;
  return p[0] === String(new Date().getFullYear()) ? d : `${d} ${p[0]}`;
}

// --- числа й гроші ---

/** Компактно для осей і підписів: 1,2М / 34к / 567. */
export const compact = (v) => {
  const a = Math.abs(v);
  if (a >= 1e6) return (v / 1e6).toFixed(1).replace(".", ",") + "М";
  if (a >= 1e3) return Math.round(v / 1e3) + "к";
  return String(Math.round(v));
};

/** Гривні без копійок: суми рівня «капітал» і «внесок», де копійка
 *  рішення не змінює, зате заважає порівнювати рядки поглядом. */
export const uah0 = (v) => Math.round(Number(v) || 0).toLocaleString("uk") + " ₴";

/** Гривні без копійок ЗІ ЗНАКОМ: дельти й рухи, де «+5 000» і «−5 000»
 *  — різні відповіді, а голе число читалось би як сума. Нуль без знака. */
export const signedUAH = (v) => {
  const n = Math.round(Number(v) || 0);
  return (n > 0 ? "+" : n < 0 ? "−" : "") + Math.abs(n).toLocaleString("uk") + " ₴";
};

/** Мінус ОДНИМ знаком на весь застосунок: U+2212, як у signedUAH вище.
 *  toLocaleString дає для від'ємних звичайний дефіс, і доки від'ємних сум
 *  у таблицях не було, різниці не бачив ніхто. Щойно в податковій картці
 *  зʼявився рядок «− НКД», в одному рядку стали поруч «-852,45 ₴» і
 *  «−10,65 ₴» — два різні знаки для одного значення. */
const dec2 = (v) => (Number(v) || 0)
  .toLocaleString("uk", { minimumFractionDigits: 2, maximumFractionDigits: 2 })
  .replace(/^-/, "−");

/** Гривні з копійками: дивіденд 16.33 ₴ і податок 2.66 ₴ — числа, де
 *  округлення до гривні з'їдає п'яту частину значення. */
export const uah2 = (v) => dec2(v) + " ₴";

/** Довільна валюта з копійками. */
export const cur2 = (v, c) => dec2(v) + " " + curSym(c);

/** Об'єкт {amount, currency} з бекенда.
 *
 *  Символом, а не кодом. Доти тут стояло `${m.currency}`, тобто «40 000,00
 *  UAH», — і поруч, у тій самій колонці, uah2() писав «446 220 ₴». Один
 *  стовпчик, два записи однієї валюти: числа в ньому читають зверху вниз,
 *  і на кожному переході око спотикається об зміну нотації.
 *
 *  Це той самий довід, що записаний нижче при pct: доти кожен розділ
 *  форматував сам, і те саме поле показувалось по-різному залежно від
 *  того, де на нього дивишся. Різниця лише в тому, що там розходились
 *  знаки після коми, а тут — сама валюта. */
export const money = (m) =>
  m ? `${Number(m.amount).toLocaleString("uk", { minimumFractionDigits: 2 })} ${curSym(m.currency)}` : "—";

/** Відсоток одним способом на весь застосунок.
 *
 *  Доти кожен розділ форматував сам: плитки з двома знаками, таблиця з
 *  одним, а `${r.rate_pct}%` місцями взагалі без округлення — і те саме
 *  поле показувалось по-різному залежно від того, де на нього дивишся.
 *
 *  null/undefined дають «—», а не «0.0%»: відсутнє число й нульове — не
 *  одне й те саме, і особливо не тоді, коли йдеться про дохідність. */
export const pct = (v, digits = 1) =>
  v == null ? "—" : `${Number(v).toFixed(digits)}%`;

/** Відсоткові пункти — РІЗНИЦЯ двох відсотків, а не відсоток.
 *
 *  Окремо від pct не заради краси: `${pct(v)} п.п.` дає «3.7% п.п.», де
 *  сказано двічі й по-різному про одну одиницю. Різницю дохідностей
 *  документ віддає вже не в одному місці (vs_portfolio_pp у ринковій
 *  кривій, edge_pp у перекладанні), тож нехай форматує її один. */
export const pp = (v, digits = 1) =>
  v == null ? "—" : `${Number(v).toFixed(digits)} п.п.`;

// --- похідні від документа стану ---

/** Капітал — це ВСЕ, що в тебе є: номінал паперів, гроші на рахунку,
 *  сертифікати фондів, тіло вкладів і резерв. Фонди довго рахувались
 *  окремо просто тому, що з'явились пізніше, і капітал через це
 *  занижувався на їхню вартість; резерв — той самий випадок.
 *
 *  «Усе, що працює» тут уже неточно: резерв не працює навмисно. Але це
 *  твої гроші, і сховати їх із капіталу означало б показати тебе
 *  біднішим, ніж ти є. Дохідність рахується окремо й резерву не бачить —
 *  саме там ця різниця й має бути видна. */
export const capitalUAH = (s) => {
  // Готове число з документа, коли воно є: складати ту саму суму на
  // фронтенді означало б четверте визначення капіталу — рівно те, через
  // що плитка й картка ребалансу показували різне. Сума лишається лише
  // запасним шляхом для старішого бекенда, який `capital_uah` не надсилає.
  if ((s || {}).capital_uah != null) return s.capital_uah;
  return ((s || {}).nominal_uah_eq || 0) + ((s || {}).account_uah || 0) +
    ((s || {}).funds_uah || 0) + ((s || {}).deposits_uah || 0) +
    ((s || {}).reserve_uah || 0) + ((s || {}).goals_uah || 0) +
    ((s || {}).npf_uah || 0);
};

/** Капітал, що НЕ працює: резерв плюс цілі накопичення, грн-екв.
 *
 *  Обидва в капіталі є, обидва нічого не заробляють, і питання про них одне
 *  — «скільки з цієї суми не інвестується». Тому й число одне: два рядки
 *  поспіль про те саме читались би як дубль, а назвати лише подушку
 *  означало б сховати другу половину.
 *
 *  Живе поруч із capitalUAH і з того самого доводу: третє означення «що не
 *  працює» розійшлося б із двома першими на першій же правці. Читачів троє
 *  — плитка «Капітал» на «Огляді» й на «Зараз», і старт кривої в
 *  «Майбутньому», де те саме віднімання робить і бекенд. */
export const outsideUAH = (s) =>
  ((s || {}).reserve_uah || 0) + ((s || {}).goals_uah || 0);

/** Собівартість сертифікатів — «вкладено» тієї ж природи, що й вартість
 *  входу лотів, тож у плитці вони стоять разом.
 *
 *  Готове число з документа, коли воно є: доти САМЕ ЦЮ суму складали в
 *  трьох місцях — тут, у добовій джобі перед записом у знімок, і на
 *  кривій уже з колонки знімка. Дві з трьох копій жили в різних мовах,
 *  тож помітити розходження не було де. Сума лишається запасним шляхом
 *  для старішого бекенда, який `funds_cost_uah` не надсилає. */
export const fundsCost = (s) => {
  if ((s || {}).funds_cost_uah != null) return s.funds_cost_uah;
  return ((s || {}).funds || []).reduce((a, f) => a + (f.cost_basis || 0), 0);
};

/** Собівартість того, що ПЕРЕОЦІНЮЄТЬСЯ: облігації плюс сертифікати.
 *
 *  Це не «скільки я вклав узагалі» — вклади й резерв сюди навмисно не
 *  входять. Облігація й сертифікат — єдині два інструменти, чия вартість
 *  може розійтися з ціною купівлі, тож лише для них різниця «вкладено
 *  проти вартості» щось означає. Вклад і резерв коштують рівно те, що в
 *  них лежить, і додавання їх сюди перетворило б цей розрив на нуль,
 *  розбавлений незмінними сумами.
 *
 *  Поруч у history.js живе snapCostUAH — інший знаменник (плюс вклади й
 *  резерв) і інше джерело (рядки знімків, а не документ стану). Вони
 *  відповідають на РІЗНІ питання: тут «скільки коштувало те, що
 *  переоцінюється», там «скільки всього коштує портфель на кожен день».
 *  Доти обидві формули стояли без імен, і збіг чи розбіжність їхніх
 *  чисел на сусідніх вкладках читались як помилка. */
export const marketCostUAH = (s) => ((s || {}).invested_uah || 0) + fundsCost(s);

/** Частка гривні — ВИВЕДЕНА, а не опублікована.
 *
 *  Бекенд валютні частки рахує лише для USD і EUR: рядка `rebalance` для
 *  гривні немає взагалі, і це навмисно (див. коментар про транзит у
 *  state_rebalance.go). Гривня — те, що лишається, і саме цим відніманням
 *  вона виводилась уже у двох місцях: у стовпчиках «факт vs ціль» і на
 *  бекенді, у помічнику реінвесту. Третя копія жила б тут, у картці
 *  «Валюта за стратегією», — тож формула переїхала в одне місце, а
 *  стовпчики стали її споживачем.
 *
 *  Копія в Go лишається: вона по той бік дроту й іншою мовою, і зшити їх
 *  можна було б лише новим полем контракту заради довідкового рядка. */
export const uahSharePct = (s) =>
  100 - ((s || {}).usd_share_pct || 0) - ((s || {}).eur_share_pct || 0);

/** Цільова частка гривні — той самий залишок, але від ЦІЛЕЙ.
 *
 *  Нуль знизу обов'язковий: суму валютних цілей ніхто не нормалізує (та
 *  сама політика, що в цілях за видом — введене не підмінюється), тож
 *  USD 60 + EUR 60 дали б «гривня −20%». Від'ємна частка не означає
 *  нічого; нуль означає «гривні в цілях не лишилось», і це правда. */
export const uahTargetPct = (s) => {
  const st = (s || {}).settings || {};
  return Math.max(0,
    100 - Number(st.usd_target_share_pct || 0) - Number(st.eur_target_share_pct || 0));
};

/** Скільки днів лишилось до дати (відʼємне — скільки минуло). */
export const daysUntil = (iso) =>
  Math.round((new Date(iso + "T00:00:00").getTime() - Date.now()) / 86400000);
