// Дрібні шматки розмітки, спільні для розділів.
//
// Тут живе тільки те, що не залежить ані від даних, ані від контексту, —
// чиста функція «значення -> HTML». Щойно шматку знадобився store чи
// summary, він уже не компонент, а частина розділу.

import { esc, pct } from "./format.js";
import { yieldCell } from "./yield.js";
import { KIND_LABEL } from "./constants.js";
import { routeFor } from "./routes.js";

/** Плитка. hero — головне число екрана: більший кегль і подвійна ширина.
 *  Рівно одна на розділ; друга «головна» плитка означала б, що головного
 *  немає. */
export function tile(l, v, extra = "", { hero = false } = {}) {
  return `<div class="tile${hero ? " hero" : ""}"><div class="lbl">${l}</div>` +
    `<div class="val">${v}</div>${extra}</div>`;
}

/** Смуга прогресу. Стеля живе тут, а не в арифметиці: бекенд відсотка не
 *  обмежує навмисно (state.go:984-986 — «смугу обрізає той, хто малює»), а
 *  доти кожен викликач писав власний Math.min(100, …) і надлишок зникав
 *  мовчки. Плитка «Цей місяць» друкувала 208% над смугою, не відрізнимою
 *  від рівно виконаного плану.
 *
 *  Понад 100% трек не росте — росте те, що він означає. Він стає шкалою
 *  «скільки зайшло», а межа сегментів каже, де закінчувалась норма:
 *  перший сегмент — 100/pct від ширини, другий — надлишок.
 *
 *  Розмітка для pct <= 100 збігається байт у байт із тією, що шість
 *  розділів досі пишуть інлайном (allocation, future, money-cards, risk).
 *  Вони не показують перевиконання, тож переїзд їм нічого не дасть — але
 *  дев'ятої копії цієї розмітки заводити не треба, вона тепер тут. */
export function progressBar(v, { color = "", cls = "" } = {}) {
  const p = typeof v === "number" && isFinite(v) && v > 0 ? v : 0;
  const c = color ? `;--oi-c:${color}` : "";
  const seg = (w, over = "") => `<span${over} style="--oi-fill:${w}%${c}"></span>`;
  const body = p > 100
    ? seg(100 / p * 100) + seg(100 - 100 / p * 100, ` class="over"`)
    : seg(p);
  return `<div class="progress${cls ? ` ${cls}` : ""}">${body}</div>`;
}

// У застосунку рівно два слова про дохідність, і жодне число не
// показується без одного з них.
//
// НОМІНАЛЬНА — скільки гривень додасться. Це те, що видно у виписці
// брокера й написано в договорі: твердий факт, який ні від чого не
// залежить.
//
// РЕАЛЬНА — скільки з того приросту робить багатшим, після поправки на
// знецінення. Це факт плюс припущення, і саме вона порівнює гривневий
// папір із доларовим.
//
// ГОЛОВНИМ ЧИСЛОМ ІДЕ НОМІНАЛЬНА, і це скасування попереднього рішення,
// яке стояло тут: «нею порівнюють, тож нею й показуємо». Довід був
// правильний рівно щодо ПОРЯДКУ рядків — і хибний щодо показу. Реальна
// збирається з трьох різних відрахувань (податок, знецінення, а тепер ще
// й інфляція окремою лінійкою), жодне з яких не показувалось, тож на
// екрані стояло 4.2% там, де в договорі 16%, і перевірити це число було
// ніяк. Тепер зверху те, що можна звірити з випискою, під ним реальна, а
// на клік — увесь ланцюжок (yield.js).
//
// ПОРЯДОК ПРИ ЦЬОМУ НЕ ЗМІНИВСЯ: сортує бекенд і сортує за реальною.
// Показ і порядок — різні питання.

/** Підпис під числом дохідності: реальна плюс, за наявності, основа
 *  («до погашення», «дивіденди + зміна ціни»). Порожній рядок, коли
 *  сказати нічого — щоб не малювати порожній рядок під значенням. */
export function yieldNote(real, basis = "") {
  const bits = [];
  if (real != null) bits.push(`${pct(real)} реальних`);
  if (basis) bits.push(esc(basis));
  return bits.length ? `<div class="sub-xs">${bits.join(" · ")}</div>` : "";
}

/** Пара «номінальна головна + реальна дрібно» одним шматком.
 *
 *  parts — розклад ставки з бекенда (rate_parts). Є він — число стає
 *  кнопкою, що відкриває ланцюжок; немає — лишається просто числом. */
export function yieldPair(real, nominal, basis = "", parts = null) {
  if (parts) return `${yieldCell(parts)}${basis ? `<div class="sub-xs">${esc(basis)}</div>` : ""}`;
  // Реальна під числом — лише коли вона інша: у валюті звітності ≠ гривні
  // бекенд віддає одну лінійку (номінал = реальна), і повтор під числом
  // був би підписом «реальних» до того, що й так єдине.
  return `${pct(nominal != null ? nominal : real)}${yieldNote(
    nominal != null && real !== nominal ? real : null, basis)}`;
}

/** Картка, якої ще немає: чому її не видно й що зробити, щоб була.
 *
 *  Доти такі картки просто поверталися порожнім рядком, і людина з
 *  повним портфелем не мала як дізнатись, чому «Концентрація» чи
 *  «Структура за видом» не з'являються ніколи: бракувало не даних, а
 *  одного числа в налаштуваннях, і про це ніде не було сказано.
 *
 *  Патерн у застосунку вже був — драбина, позиції, проєкції мають свої
 *  порожні стани, — просто застосований не всюди. Тут він в одному
 *  місці, щоб формулювання не розповзались.
 *
 *  Свідомо НЕ для карток, яким бракує самих паперів: банер «Огляду» вже
 *  каже «Додай папір — і застосунок почне вести драбину, календар і
 *  проєкції», і повторити це ще пʼятьма сірими плитками означало б
 *  зробити порожній екран гіршим, а не зрозумілішим. */
/** Порожній стан: чому тут нічого немає і що з цим зробити.
 *
 *  Два підвиди, і різниця між ними — чия це справа.
 *
 *  Даних ще немає — людина щойно почала, і доречна дія: «додай перший
 *  папір». Бракує налаштування — дані є, але картка мовчить, бо не
 *  вистачає одного числа, і доречне посилання рівно туди, а не заклик
 *  щось додавати.
 *
 *  action = { href, label } або нічого. */
export function empty(title, why, action = null) {
  return `<div class="empty">
    ${title ? `<div class="empty-t">${title}</div>` : ""}
    <div class="empty-w">${why}</div>
    ${action ? `<a class="lnk" href="${action.href}">${action.label}</a>` : ""}
  </div>`;
}

/** Пігулка виду інструмента: колір несе значення (ОВДП / фонд / вклад /
 *  резерв), тож завжди беремо той самий підпис із того самого словника —
 *  розбіжність тут читалась би як четвертий вид інструмента. */
export function kindPill(kind) {
  return `<span class="pill pill-${kind}">${KIND_LABEL[kind]}</span>`;
}

/** Легенда під графіком: кольоровий квадратик + підпис, кілька штук
 *  поспіль. Items — масив {color, label, faint?}; falsy-елемент
 *  пропускається, щоб умовний пункт («коридор ринку», «рік тому») писався
 *  одним виразом замість неповного рядка розмітки в кожному виклику. */
export function legend(items) {
  return `<div class="lg">${items.filter(Boolean).map((it) =>
    `<span><i${it.faint ? ` class="faint"` : ""} style="--oi-c:${it.color}"></i>${esc(it.label)}</span>`,
  ).join("")}</div>`;
}

/** Картка «бракує налаштування»: чого немає й де це задати.
 *
 *  Адреса — АРГУМЕНТ, а не константа. Доти тут стояв літерал "#/settings",
 *  і це було правдою рівно доти, доки цілі, частки й ліміти жили в
 *  «Налаштуваннях». Відколи вони переїхали в «Політику», посилання вело в
 *  довідники брокерів — тобто картка чесно казала, чого бракує, і
 *  відправляла не туди. Мовчазна помилка: сторінка відкривається, просто
 *  потрібного поля на ній немає.
 *
 *  Типове значення — розділ «Політика» цілком; кожен виклик уточнює його
 *  до тієї сторінки, де стоїть саме його поле. */
export function needsSetting(title, why, href = routeFor("policy")) {
  return `<div class="card"><h2 class="h-row">${title}</h2>
    ${empty("", why, { href, label: "Відкрити політику" })}</div>`;
}

