// Порядок рядків майстер-списку, поставлений власником.
//
// Дерево в nav.js задає порядок ПИТАНЬ: борг перший, бо доки він живий,
// він з'їдає гроші місяця раніше за все інше. Це правильний порядок, щоб
// пояснити застосунок, і не обов'язково той, у якому в нього заходять
// щодня. Збережений порядок лежить на бекенді (GET/PUT /api/nav-order),
// спільний для всіх пристроїв і всіх портфелів — розкладка списку
// належить людині, а не портфелю.
//
// Модуль ЧИСТИЙ: ні DOM, ні мережі. Не з любові до чистоти — так його
// імпортує node-перевірка (web-routes-check.mjs) і звіряє три твердження
// нижче. Читати з бекенда — справа оболонки, малювати — master.js.
//
// БЕКЕНД ПРО ЦІ ІДЕНТИФІКАТОРИ НЕ ЗНАЄ НІЧОГО (довід — у шапці
// api/handlers_navorder.go): він перевіряє форму, а зводить збережене з
// наявним ось цей файл. Тому обидві розбіжності треба пережити тихо, і
// вони різні:
//
//   рядок, якого в збереженому немає (новий у цій версії застосунку), —
//   стає В КІНЕЦЬ. Не на своє «природне» місце всередині чужого порядку:
//   там його не побачить той, хто вже звик до свого списку, а внизу — так.
//
//   збережений рядок, якого більше немає (панель прибрали), — мовчки
//   зникає. Це не втрата: сам рядок уже прибрали разом із його доводом.

/** Пункти вкладки в порядку `ids`. Порожній чи відсутній `ids` —
 *  природний порядок, тобто той самий масив без копіювання. */
export function applyOrder(items, ids) {
  const list = items || [];
  if (!Array.isArray(ids) || !ids.length) return list;
  const at = new Map(ids.map((id, i) => [id, i]));
  const known = list.filter((it) => at.has(it.id));
  known.sort((a, b) => at.get(a.id) - at.get(b.id));
  return known.concat(list.filter((it) => !at.has(it.id)));
}

/** Новий масив із рядком `id`, переставленим на крок `dir` (-1 вгору,
 *  +1 вниз). На краю списку вертає ТОЙ САМИЙ масив — викликач по цьому й
 *  бачить, що переставляти нема куди, і не пише зайвого на бекенд. */
export function moveInOrder(ids, id, dir) {
  const i = ids.indexOf(id);
  const j = i + dir;
  if (i < 0 || j < 0 || j >= ids.length) return ids;
  const out = ids.slice();
  out[i] = out[j];
  out[j] = id;
  return out;
}
