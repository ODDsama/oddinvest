// Розбір вклеєної таблиці «дата число».
//
// Модуль зʼявився тоді, коли той самий розбір знадобився вдруге: спершу
// його написали для історії ЧВОПА (npf.js), потім рівно те саме зажадала
// історія цін сертифікатів. Обидва беруть опубліковану емітентом таблицю й
// обидва мають бути однаково поблажливі — інакше людина, яка вклеїла
// пенсійну історію без клопоту, спіткнеться на фондовій.

/** parseDatedNumbers — рядки «дата число» у точки {date, value}.
 *
 *  Свідомо ліберальний до розділювача (пробіл, кома, крапка з комою,
 *  табуляція) і до коми як десяткової: історію копіюють із сайту чи з
 *  таблиці, і вимагати єдиного формату означало б змусити людину чистити
 *  текст руками. А от дату не вгадуємо: РРРР-ММ-ДД або помилка, бо 01.02 —
 *  це або січень, або лютий, і вгадування тут тихо зіпсувало б криву.
 *
 *  ЧОМУ РОЗБІР ДВОКРОКОВИЙ, а не одним split'ом по всіх розділювачах.
 *  Саме так він і був написаний спочатку — і кома як десяткова через це НЕ
 *  ПРАЦЮВАЛА, попри обіцянку в цьому ж коментарі: split з'їдав її як
 *  розділювач, і з «2026-06-30 1071,20» лишалось три шматки, а останнім
 *  брався «20». Тобто ціна 1071.20 тихо ставала двадцяткою — на найдорожчих
 *  за працею даних у базі й без жодної скарги. Спіймано вживу, у браузері,
 *  на змішаному вклеюванні.
 *
 *  Тому дата відрізається ПЕРШОЮ, а решта рядка трактується як одне число:
 *  розділювачем кома може бути лише між датою й числом, усередині числа
 *  вона десяткова.
 *
 *  bad — номери рядків, які не розібрались, щоб про них можна було сказати
 *  вголос. Порожні рядки не рахуються помилкою: вклеєний текст майже
 *  завжди має хвостовий перенос.
 */
export function parseDatedNumbers(text) {
  const out = [];
  const bad = [];
  (text || "").split(/\r?\n/).forEach((line, i) => {
    const s = line.trim();
    if (!s) return;
    // Дата — до першого розділювача; далі все, що лишилось, це число.
    const cut = s.search(/[\s,;]/);
    if (cut < 0) { bad.push(i + 1); return; }
    const date = s.slice(0, cut);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) { bad.push(i + 1); return; }
    const value = normalizeNumber(s.slice(cut));
    if (!/^\d+(\.\d+)?$/.test(value)) { bad.push(i + 1); return; }
    out.push({ date, value });
  });
  return { points: out, bad };
}

/** Число з хвоста рядка у форму, яку розуміє бекенд.
 *
 *  Знімає провідні розділювачі («2026-07-31, 1098.4»), пробіли між
 *  розрядами («1 071,20» — так копіюється з таблиці) і розбирається з
 *  комою: якщо в числі є і кома, і крапка, десятковим вважається ТОЙ, ЩО
 *  СТОЇТЬ ПРАВІШЕ, а другий — роздільник тисяч. Це не вгадування формату
 *  країни, а єдина інтерпретація, за якої «1,071.20» і «1.071,20» дають
 *  одне число.
 */
function normalizeNumber(tail) {
  let v = tail.replace(/^[\s,;]+/, "").replace(/[\s ]/g, "");
  const comma = v.lastIndexOf(",");
  const dot = v.lastIndexOf(".");
  if (comma >= 0 && dot >= 0) {
    v = comma > dot
      ? v.replace(/\./g, "").replace(",", ".")
      : v.replace(/,/g, "");
  } else if (comma >= 0) {
    v = v.replace(",", ".");
  }
  return v;
}
