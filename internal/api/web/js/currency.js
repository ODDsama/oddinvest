// Валюта звітності: у чому бекенд ВІДДАВ суми цього документа.
//
// Фронтенд нічого не ділить і не множить. Кожне число вже прийшло в
// потрібній валюті (internal/present на бекенді); тут лишилось знати, який
// символ поставити поруч, — і це знання живе в одному місці, а не в
// кожному помічнику format.js окремо.
//
// Джерело — поле currency зі зведення (/api/summary): його ставить
// оболонка, щойно зведення приїхало, ДО першого малювання. Відповіді
// інших маршрутів у тій самій валюті за побудовою (вони проходять той
// самий презентер), тож окремого коду на кожну з них не треба. Єдиний
// виняток — податковий звіт: він завжди в гривні й каже це власним полем
// currency, а картка читає саме його (money-cards.js).
//
// Не в localStorage і не в адресі: це не погляд браузера, а політика
// портфеля (settings.report_currency), і телефон із ноутбуком мусять
// бачити одне й те саме без другого перемикання.

import { CURRENCIES, CURRENCY_SYM } from "./constants.js";

/** Книжкова валюта (облік) і та, на яку перемикає кнопка в шапці. Через
 *  CURRENCIES, а не літералами: трійка валют живе в одному файлі. */
export const BOOK = CURRENCIES[0];
export const ALT = CURRENCIES[1];

let code = BOOK;

/** Поставити валюту зведення. Невідоме або порожнє — книжкова. */
export function setCurrency(c) {
  code = CURRENCIES.includes(c) ? c : BOOK;
}

/** Валюта, у якій зараз показуються суми. */
export const currency = () => code;

/** Символ поточної валюти — те, що format.js ставить після кожної суми. */
export const sym = () => CURRENCY_SYM[code] || code;
