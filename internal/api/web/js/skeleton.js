// Скелет панелі на час завантаження.
//
// Доти на цьому місці стояло слово «Завантаження…» посеред порожнього
// екрана. Воно каже, що треба чекати, і не каже ні скільки, ні чого — а
// коли вміст приїжджає, сторінка стрибає, бо розкладка виявляється
// зовсім іншою. Скелет має ФОРМУ того, що прийде: висота лишається тією
// самою до і після, тож стрибка немає зовсім.
//
// Форми навмисно грубі. Скелет не мусить збігатися з вмістом піксель у
// піксель — він мусить збігатися ЗА ЗРОСТОМ і за кількістю блоків;
// точніший лише дорожче коштує в підтримці, бо його доводиться правити
// разом із кожною панеллю.
//
// ЩО ЗМІНИЛА МАЙСТЕР-ДЕТАЛЬ: скелет описує ТІЛО ПАНЕЛІ, а не сторінку
// цілком. Шапка, вкладки, майстер-список і рейка панелей малюються
// одразу — вони не чекають ні на що, крім зведення, — і підмінювати їх
// сірими прямокутниками означало б ховати те, що вже готове. Рейки
// кроків у скелеті через це теж більше немає: вона тепер частина
// оболонки.

// Ширина приходить кастомною властивістю: конкретні відсотки тут —
// випадковий шум, який імітує різну довжину рядків, а не рішення.
const line = (w) => `<div class="skel-line" style="--oi-w:${w}"></div>`;

const tiles = (n) =>
  `<div class="skel-tiles">${Array.from({ length: n }, () =>
    `<div>${line("55%")}${line("80%")}</div>`).join("")}</div>`;

const card = (rows) =>
  `<div class="skel-card">${line("38%")}${Array.from({ length: rows }, (_, i) =>
    line(`${92 - (i % 3) * 14}%`)).join("")}</div>`;

const chart = () => `<div class="skel-card">${line("38%")}<div class="skel-chart"></div></div>`;

const table = (rows) =>
  `<div class="skel-card">${line("30%")}<div class="skel-rows">${
    Array.from({ length: rows }, () => `<div class="skel-row"></div>`).join("")}</div></div>`;


// Що з чого складається. Ключі двох сортів: "вкладка" і "вкладка/панель".
//
// Форма на кожну з тридцяти панелей була б помилкою рівно тієї природи,
// від якої застерігає шапка файлу: тридцять форм не встигне правити
// ніхто, і за півроку скелет обіцятиме екран, якого вже немає. Тому за
// замовчуванням форма береться на ВКЛАДКУ — панелі однієї вкладки схожі
// за зростом, — а поіменно перелічені лише ті, де вміст відрізняється не
// на відтінок: крива замість таблиці, таблиця замість карток.
//
// Ключ по ПАНЕЛІ, а не по рядку: рядків у «Портфелі» скільки завгодно, а
// панелей шість, і саме панель вирішує, що там буде — плитки стану чи
// таблиця позицій.
const SHAPES = {
  work: () => card(6) + tiles(4) + card(5),
  // Панелі позиції: за замовчуванням плитки й таблиця. Перше малювання
  // тут найдорожче в застосунку (вісім GET-ів позицій), тож скелет
  // мусить відпрацювати чесно — інакше панель стрибне на цілий екран
  // рівно тоді, коли її вже читають.
  portfolio: () => tiles(4) + card(4),
  money: () => tiles(5) + card(5),
  plan: () => card(2) + card(4) + table(4),
  policy: () => card(4) + card(5),
  settings: () => card(3) + card(6),

  "portfolio/positions": () => tiles(4) + table(8),
  "portfolio/growth": () => chart() + table(6),
  "portfolio/have": () => table(8),
  "portfolio/record": () => card(6) + card(6),
  "money/flows": () => card(4) + table(8),
  "money/import": () => card(6),
  "money/reconcile": () => card(6),
  "plan/main": () => card(2) + card(4) + table(4),
};

// Коли не знайшлось ні того, ні того. Такого не має ставатись — адреса
// приходить із nav.js, а там усі вкладки перелічені, — але скелет не той
// код, який має право кинути виняток посеред завантаження.
const FALLBACK = () => card(4) + card(4);

/** Розмітка скелета для панелі. aria-hidden, бо читачеві екрана про
 *  сірі прямокутники сказати нічого — про очікування він дізнається з
 *  aria-busy на самому <main>. */
export function skeleton(tab, pane) {
  const shape = SHAPES[`${tab}/${pane}`] || SHAPES[tab] || FALLBACK;
  return `<div class="skel" aria-hidden="true">${shape()}</div>`;
}
