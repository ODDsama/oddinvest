// Скелет розділу на час завантаження.
//
// Доти на цьому місці стояло слово «Завантаження…» посеред порожнього
// екрана. Воно каже, що треба чекати, і не каже ні скільки, ні чого — а
// коли вміст приїжджає, сторінка стрибає, бо розкладка виявляється
// зовсім іншою. Скелет має ФОРМУ свого розділу: висота лишається тією
// самою до і після, тож стрибка немає зовсім.
//
// Форми навмисно грубі. Скелет не мусить збігатися з вмістом піксель у
// піксель — він мусить збігатися ЗА ЗРОСТОМ і за кількістю блоків;
// точніший лише дорожче коштує в підтримці, бо його доводиться правити
// разом із кожним розділом.

// Ширина приходить кастомною властивістю: конкретні відсотки тут —
// випадковий шум, який імітує різну довжину рядків, а не рішення.
const line = (w) => `<div class="skel-line" style="--oi-w:${w}"></div>`;

const tiles = (n) =>
  `<div class="skel-tiles">${Array.from({ length: n }, () =>
    `<div>${line("55%")}${line("80%")}</div>`).join("")}</div>`;

const card = (rows) =>
  `<div class="skel-card">${line("38%")}${Array.from({ length: rows }, (_, i) =>
    line(`${92 - (i % 3) * 14}%`)).join("")}</div>`;

const chart = () => `<div class="skel-card">${line("38%")}<div class="skel-chart"></div></div>`;

// Рейка кроків воронки: вузька смуга, яка теж тримає висоту.
const rail = () => `<div class="skel-rail"></div>`;

const table = (rows) =>
  `<div class="skel-card">${line("30%")}<div class="skel-rows">${
    Array.from({ length: rows }, () => `<div class="skel-row"></div>`).join("")}</div></div>`;


// Що з чого складається. Ключі двох сортів: "розділ" і "розділ/підрозділ".
//
// Форма на кожен із тридцяти п'яти підрозділів була б помилкою рівно тієї
// природи, від якої застерігає шапка файлу: тридцять п'ять форм не встигне
// правити ніхто, і за півроку скелет обіцятиме екран, якого вже немає.
// Тому за замовчуванням форма береться на РОЗДІЛ — сторінки одного розділу
// схожі за зростом, — а поіменно перелічені лише ті чотири, де вміст
// відрізняється не на відтінок: крива замість таблиці, таблиця замість
// карток.
const SHAPES = {
  // Черга задач замість банера: одна картка на кілька рядків, і саме її
  // форму треба тримати, поки триває запит.
  now: () => card(6) + tiles(4) + card(5),
  // Воронка: рейка кроків, плитки стану, таблиця позицій і форма запису.
  // Перше малювання тут найдорожче в застосунку (вісім GET-ів позицій),
  // тож скелет мусить відпрацювати чесно — інакше сторінка стрибне на
  // цілий екран рівно тоді, коли її вже читають.
  instr: () => rail() + tiles(4) + table(6) + card(4) + card(6),
  // «Портфель» тримає п'ять сторінок ДВОХ форм: дві з таблицею, три з
  // картками. За замовчуванням — форма більшості, а «Позиції» та «Як
  // росте» названі поіменно нижче.
  portfolio: () => tiles(2) + card(4) + card(4),
  money: () => tiles(5) + card(5),
  plan: () => card(2) + card(4) + table(4),
  policy: () => card(4) + card(5),
  settings: () => card(3) + card(6),

  "instr/reserve": () => rail() + tiles(3) + table(6) + card(6),
  "portfolio/positions": () => tiles(4) + table(8),
  "portfolio/growth": () => chart() + table(6),
  "money/flows": () => card(4) + table(8),
  "money/import": () => card(6),
  "money/reconcile": () => card(6),
  "plan/goal": () => chart() + chart() + card(3),
  "plan/payouts": () => table(8),
};

// Коли не знайшлось ні того, ні того. Такого не має ставатись — маршрут
// приходить із nav.js, а там усі розділи перелічені, — але скелет не той
// код, який має право кинути виняток посеред завантаження.
const FALLBACK = () => card(4) + card(4);

/** Розмітка скелета для сторінки. aria-hidden, бо читачеві екрана про
 *  сірі прямокутники сказати нічого — про очікування він дізнається з
 *  aria-busy на самому <main>. */
export function skeleton(section, sub) {
  const shape = SHAPES[`${section}/${sub}`] || SHAPES[section] || FALLBACK;
  return `<div class="skel" aria-hidden="true">${shape()}</div>`;
}
