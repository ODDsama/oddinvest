// Зведений XIRR: скільки портфель заробив НАСПРАВДІ, одним числом і в
// гривні.
//
// Окремий файл, а не рядки в state_builder.go, з механічної причини:
// `make sources-boundary` валить будь-яке `s.st.` у будівнику, а курс на
// дату — це читання сховища. Прецедент є (state_plan_buys.go ходить у
// сховище сам), і довід той самий: ключ запиту — пара (валюта, дата) —
// відомий лише ПІСЛЯ того, як потоки побудовані, тож sources, який нічого
// не рахує й не знає про сьогодні, прочитати цього не може за побудовою.
//
// ЩО ТУТ СКАСОВАНО. Шапка domain/xirr.go казала: «Рахується ОКРЕМО ПО
// КОЖНІЙ ВАЛЮТІ: змішування валют в одному XIRR дає безглузді числа, тому
// конвертації тут нема свідомо». Це правда рівно наполовину, і половину
// треба назвати. Безглузде — скласти Flow{USD,100} із Flow{UAH,100} у 200:
// Amount тут голий int64, одиниці він не знає, і така сума не означає
// нічого. Але звести КОЖЕН потік до гривні за курсом ЙОГО ВЛАСНОЇ дати й
// розвʼязати один IRR у гривні — інша операція, і вона законна: це
// дохідність з погляду того, хто витрачає гривню, а валютний результат у
// ній доданок, а не спотворення. Рівно так уже рахується податковий звіт,
// і саме там колись зʼясувалось, чого варта конвертація одним сьогоднішнім
// курсом: податок за 2022 рік виходив у півтора раза більшим.
package api

import (
	"context"
	"sort"

	money "github.com/Rhymond/go-money"

	"github.com/ODDsama/oddinvest/internal/domain"
	"github.com/ODDsama/oddinvest/internal/state"
)

// xirrCurrencies — порядок обходу валют при згортанні в гривню.
//
// Зріз, а не мапа, і це інваріант, а не стиль: сума float залежить від
// порядку доданків, а TestBuildStateIsDeterministic вимагає, щоб документ
// не змінювався між викликами без причини. Обхід map[string][]Flow дав би
// різний порядок і плаваюче останнє знаке.
var xirrCurrencies = []string{money.UAH, money.USD, money.EUR}

// totalReturn — зведений результат по всіх валютах разом, у гривні.
//
// byCur — потоки, зібрані будівником; broken каже, що хоч одна валюта не
// зібралась. Повертає nil, коли сказати нічого: nil на екрані стає
// відсутньою плиткою, а не прочерком, і це навмисно.
func (s *Server) totalReturn(ctx context.Context, byCur map[string][]domain.Flow,
	broken bool, today domain.Date) *state.TotalReturn {

	// Валюта, яка не зібралась, робить зведене число ТИХО НЕПОВНИМ. Для
	// валютної плитки пропуск нешкідливий — плитки просто немає, і це
	// видно; тут зникла б частина портфеля всередині числа, яке обіцяє
	// бути про весь портфель.
	if broken {
		return nil
	}

	asOf := newAsOfRates(s.st)
	var flows []domain.Flow
	for _, cur := range xirrCurrencies {
		for _, f := range byCur[cur] {
			u, err := asOf.uah(ctx, money.New(f.Amount, cur), f.Date)
			if err != nil {
				return nil
			}
			flows = append(flows, domain.Flow{Date: f.Date, Amount: u})
		}
	}

	// УСЕ АБО НІЧОГО на пропущений курс, і копіювати сюди правило
	// податкового звіту НЕ МОЖНА.
	//
	// Там пропущена подія — недорахована стаття доходу: звіт лишається
	// читабельним, а скільки їх було, каже note(). Тут пропущений потік —
	// це зникла КУПІВЛЯ, тобто знаменник. Термінальна вартість датована
	// сьогодні, курс на сьогодні є завжди, а те, що за неї заплатили,
	// перетворюється на нуль (asOfRates.uah повертає 0 і рахує missing).
	// Дохідність тоді летить у стелю — і це навіть не схоже на поломку,
	// просто дуже приємне число.
	//
	// Дірки в історії курсів не гіпотетичні, а гарантовані: backfill у
	// cmd/oddinvestd тягне ЛИШЕ долар, євро набирається добовою джобою з
	// дня встановлення. Тобто єровий лот, куплений до встановлення, курсу
	// не має за побудовою.
	//
	// Підставити найранішу відому точку — не вихід: долар у 2019-му
	// коштував 27, найраніша точка на свіжій базі 44, і таке «уточнення»
	// вигадало б збиток у 40% і подало його як факт. Мовчання дешевше за
	// вигадку, і воно вже є мовою цього застосунку.
	if asOf.missing > 0 {
		return nil
	}
	if len(flows) < 2 {
		return nil
	}
	sort.Slice(flows, func(i, j int) bool { return flows[i].Date < flows[j].Date })

	gain, invested := domain.RealizedGain(flows)
	if invested <= 0 {
		return nil
	}
	out := &state.TotalReturn{
		GainUAH:      round2(float64(gain) / 100),
		GainPct:      round2(float64(gain) / float64(invested) * 100),
		MinDays:      xirrMinMoneyDays,
		FXMaxLagDays: asOf.maxLag,
	}
	// Поріг рахується на ЗЛИТИХ потоках, і це не те саме, що середнє чи
	// максимум валютних. Конвертація міняє ваги: купівля на $1 000 важить
	// сорок із гаком тисяч, а не тисячу. Портфель зі старою доларовою ногою
	// і свіжою гривневою може дозріти зведено, коли гривнева плитка ще
	// мовчить, — і навпаки.
	days := domain.MoneyWeightedDays(flows, today)
	out.MoneyDays = round2(days)
	if days < xirrMinMoneyDays {
		return out
	}
	r, err := domain.XIRR(flows)
	if err != nil || r > 1.0 || r < -0.95 {
		return out
	}
	pct := round2(r * 100)
	out.XIRRPct = &pct
	return out
}
