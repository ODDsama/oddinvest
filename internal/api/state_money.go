// Зовнішні гроші портфеля — одне означення на всіх, хто про них питає.
//
// Питання «які гроші зайшли ЗЗОВНІ, а які просто переклались усередині»
// стоїть у чотирьох місцях: «внесено за місяць» і фактичний темп
// (state_month.go), рух капіталу за 30 днів (state_delta.go) і бенчмарк
// «Усі гроші» (rivals.go). Доти склад журналів був переписаний у кожному з
// них руками — і розійшовся в трьох напрямках одночасно: темп бачив лише
// поповнення гаманця, а дельта й бенчмарк рахували ще й внесок у НПФ.
//
// СКЛАД — ТРИ ЖУРНАЛИ, і він не довільний, а виводиться з того, як гроші
// рухаються насправді (усі виклики cash.add у state_builder.go):
//
//   - рахунок брокера КРЕДИТУЮТЬ лише deposits, купони, продаж і дивіденд
//     фонду, відсотки й повернення тіла вкладу. Три останні — дохід НА
//     капітал, а не новий капітал;
//   - усе інше з рахунку СПИСУЄ: лот, сертифікат фонду, внесок у НПФ, тіло
//     й поповнення вкладу, обидві ноги конвертації.
//
// Тобто весь портфельний контур живиться виключно з `deposits`, а поза ним
// у капіталі (state.Capital) лишаються рівно два кошики — резерв і цілі.
// Отже: deposits + reserve_ops + goal_ops.
//
// НПФ СЮДИ НЕ ВХОДИТЬ, і це найлегша помилка в усьому файлі. Внесок у
// пенсійний виглядає як поповнення й записаний окремим журналом, але він
// СПИСУЄТЬСЯ з рахунку (state_builder.go), а форма НПФ заводить парний
// рядок у deposits сама (funded-потік, web/js/npf.js). Порахувати його тут
// означає порахувати ті самі гроші двічі — рівно те, що робили дельта й
// бенчмарк, поки склад не мав спільного означення.
//
// Тут лише СКЛАД і порядок, без вікна, без курсу й без знака: що з цими
// рухами робити — питання кожного читача окремо. Темп бере нето за 183 дні,
// «внесено» — за календарний місяць, дельта — від дати знімка.
package api

import "github.com/ODDsama/oddinvest/internal/domain"

// moneyMove — один рух зовнішніх грошей: + зайшли, − вийшли.
//
// Нативна валюта, мінорні одиниці: переводить у гривню читач, і кожен своїм
// курсом (темп і дельта — сьогоднішнім, бенчмарк — курсом дня руху).
type moneyMove struct {
	Date     domain.Date
	Amount   int64
	Currency string
}

// externalMoves — усі рухи зовнішніх грошей портфеля, журнал за журналом.
//
// Порядок сталий (гаманець, резерв, цілі), хоч жоден читач на нього й не
// спирається: усі троє або підсумовують, або сортують самі. Сталий він
// заради тестів, які звіряють списки.
func externalMoves(src *sources) []moneyMove {
	out := make([]moneyMove, 0, len(src.deposits)+len(src.reserveOps)+len(src.goalOps))
	for _, d := range src.deposits {
		out = append(out, moneyMove{Date: d.Date, Amount: d.Amount, Currency: d.Currency})
	}
	// Резерв і цілі — друга нога переказу гаманець → матрац. Перша нога
	// лежить у deposits від'ємною, і поодинці вона виглядає як втрата
	// капіталу; разом вони дають нуль, як і має бути. А відкладене зовні,
	// що на рахунок брокера не заходило, це й далі чесний внесок.
	for _, op := range src.reserveOps {
		out = append(out, moneyMove{Date: op.Date, Amount: op.Amount, Currency: op.Currency})
	}
	for _, op := range src.goalOps {
		out = append(out, moneyMove{Date: op.Date, Amount: op.Amount, Currency: op.Currency})
	}
	return out
}
