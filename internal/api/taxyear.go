// Період звітності — одне поняття на застосунок.
//
// Доти їх було два, і жили вони за один файл одне від одного. /api/tax
// типово брав КОВЗНІ дванадцять місяців (сьогодні мінус рік), а
// /api/export/csv — КАЛЕНДАРНИЙ рік. Тобто картка «скільки забрала
// держава» і файл, який із неї вивантажують, відповідали на різні
// питання, і зійтись вони могли хіба випадково.
//
// Виграє календарний рік: декларація річна, і період, який не збігається
// з жодним звітним, не потрібен нікому. Це зміна поведінки за
// замовчуванням для /api/tax — свідома. Маршрут не входить у контракт
// MQTT (інтеграція його не читає), а картка друкує «з … по …» просто над
// таблицею, тож зміна себе показує сама.

package api

import (
	"fmt"
	"net/url"
	"strconv"
	"time"

	"github.com/ODDsama/oddinvest/internal/domain"
)

// taxYear — період звітності з параметрів запиту.
//
// Пріоритет: ?year= → пара ?from=&?to= → поточний календарний рік.
//
// Пара лишається саме як запасний шлях, а не як рівноправна: нею
// користуються, коли треба подивитись «останні пів року», і повертається
// тоді year == 0 — ознака, що періодом керує не рік. Клієнту це потрібно,
// щоб не малювати «2026» над таблицею за довільний відрізок.
func taxYear(q url.Values, now time.Time) (year int, from, to domain.Date, err error) {
	if s := q.Get("year"); s != "" {
		y, cerr := strconv.Atoi(s)
		// Верхня межа — не педантизм: рік із чотирьох цифр із помилкою
		// (20226) дав би порожній період і мовчазний нуль замість помилки.
		if cerr != nil || y < 1990 || y > 2200 {
			return 0, "", "", fmt.Errorf("рік %q не схожий на рік", s)
		}
		return y, domain.Date(fmt.Sprintf("%d-01-01", y)), domain.Date(fmt.Sprintf("%d-12-31", y)), nil
	}

	qf, qt := q.Get("from"), q.Get("to")
	if qf != "" || qt != "" {
		from, to = domain.Date(qf), domain.Date(qt)
		if from == "" {
			from = "1970-01-01"
		}
		if to == "" {
			to = domain.NewDate(now)
		}
		if to.Before(from) {
			return 0, "", "", fmt.Errorf("кінець періоду %q раніший за початок %q", to, from)
		}
		return 0, from, to, nil
	}

	y := now.Year()
	return y, domain.Date(fmt.Sprintf("%d-01-01", y)), domain.Date(fmt.Sprintf("%d-12-31", y)), nil
}
