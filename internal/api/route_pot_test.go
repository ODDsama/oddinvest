// Інваріант горщика маршруту: лічильник дозволу не буває більший за сам
// горщик.
//
// Тест ПРЯМИЙ, а не через buildRoute, і це не лінощі. Дірка була в тому,
// що після ноги обрізався лише один лічильник із трьох, а завищене число
// стає видимим аж на НАСТУПНІЙ події й лише коли в неї інший дозвіл — тобто
// фікстура мусила б звести докупи дві ноги, два різні uses, ціль із живим
// розривом і нульовою місячною стелею. Такий тест ловив би ваду через
// чотири механізми, і зламався б від правки будь-якого з них.
//
// Тут перевіряється рівно те, що зламалось: сам інваріант.

package api

import "testing"

func TestRoutePotClampHoldsForAllThree(t *testing.T) {
	// Стан після ноги, яка все витратила на папери: горщик спорожнів, а
	// дозволи лишились такими, якими були до неї. spend сюди не зазирав —
	// він кличеться лише на вирізки.
	p := &routePot{minor: 0, eligible: 1000, goalsEligible: 1200}
	p.clamp()
	if p.eligible != 0 || p.goalsEligible != 0 {
		t.Errorf("порожній горщик лишив дозволи живими: подушка %d, цілі %d",
			p.eligible, p.goalsEligible)
	}
}

// Обрізання НЕ ЧІПАЄ того, що й так у межах. Без цього тесту метод міг би
// «полагодити» ваду, обнуливши все підряд, — і заборона стала б тотальною
// замість точної.
func TestRoutePotClampLeavesFittingCountersAlone(t *testing.T) {
	p := &routePot{minor: 5000, eligible: 5000, goalsEligible: 0}
	p.clamp()
	if p.eligible != 5000 {
		t.Errorf("подушка %d, чекали 5000: рівність горщику — не перевищення", p.eligible)
	}
	if p.goalsEligible != 0 {
		t.Errorf("цілі %d, чекали 0: нуль означає «сюди не можна», і його не піднімають",
			p.goalsEligible)
	}
}
