// Накопичувальні позиції: капітал, що росте й нічого не платить.
//
// Модель рукава знає три стани грошей — готівка, працюючий пул і
// замкнене. Замкнене лежить за номіналом, не росте й віддає реальні
// купони за графіком: так поводиться ОВДП, так поводиться тіло вкладу,
// так поводиться сертифікат REIT, чиї дивіденди стоять у календарі.
//
// Накопичувальний фонд не поводиться так НІЯК. Він не платить нічого — і
// саме тому доти лежав у замкненому цеглиною: обіцянка 25% річних не
// давала ані копійки в календар, а замкнене не росте за побудовою. Фонд,
// який обіцяє подвоїти гроші за три роки, у проєкції не додавав нічого.
//
// Тому четвертий стан. Він росте власною ставкою, не дає потоку, а в
// задану дату закривається: тіло з доходом мінус податок падає в готівку
// й далі реінвестується нарівні з рештою — за тодішньою ставкою, а не за
// своєю, бо фонду вже немає.
package domain

import "math"

// Accum — одна накопичувальна позиція в рукаві. Суми в НАТИВНІЙ валюті
// рукава, як і решта полів Sleeve.
type Accum struct {
	// Value0 — сьогоднішня ринкова вартість; Cost0 — за скільки куплено.
	//
	// Обидві, а не одна: податок береться з ДОХОДУ, тобто з різниці між
	// продажем і купівлею, а не з приросту за час симуляції. Позиція, яка
	// вже подорожчала до сьогодні, несе цей неоподаткований приріст із
	// собою, і рахувати податок від сьогоднішньої вартості означало б
	// його подарувати.
	Value0 float64
	Cost0  float64
	// RatePct — власна СКЛАДНА річна ставка, у валюті рукава.
	RatePct float64
	// CloseM — місяць, коли фонд закривається й повертає гроші
	// (0 = не закривається, росте до кінця горизонту).
	CloseM int
	// TaxPct — податок на дохід при закритті, %.
	TaxPct float64
}

// CompoundFromSimple — проста середньорічна дохідність за years років,
// переведена у складну річну.
//
// Різниця не косметична, і саме на ній тримається окреме поле в
// довіднику. Фонд обіцяє «середньорічну ПРОСТУ 25% за три роки»: це
// сумарний приріст 75%, тобто ×1.75. Застосунок же компаундить щомісяця,
// і 25% складних за ті самі три роки дають ×1.95. Однакова назва, різні
// одиниці, приріст завищений на чверть — а на екрані обидва звуться
// «дохідність, %».
//
// years <= 0 означає, що обіцянка вже складна, і чіпати її не треба.
func CompoundFromSimple(simplePct float64, years int) float64 {
	if years <= 0 {
		return simplePct
	}
	total := 1 + simplePct/100*float64(years)
	if total <= 0 {
		// Проста дохідність, яка з'їдає більше за все тіло. Складного
		// еквівалента в такої немає — лишається сказати «мінус усе».
		return -100
	}
	return (math.Pow(total, 1/float64(years)) - 1) * 100
}

// accumState — накопичувальна позиція під час симуляції.
type accumState struct {
	value, cost float64
	rM          float64 // місячна ставка, порахована раз
	closeM      int
	taxPct      float64
	closed      bool
}

// grow — місяць m: позиції ростуть, і ті, що цього місяця закрились,
// віддають гроші. Повертає суму, яка стала готівкою.
//
// Зростання нараховується й у місяць закриття: фонд працює до останнього
// дня, а не завмирає за місяць до нього.
func (p *projState) grow(m int) float64 {
	released := 0.0
	for i := range p.accum {
		a := &p.accum[i]
		if a.closed {
			continue
		}
		a.value *= 1 + a.rM
		if a.closeM > 0 && m >= a.closeM {
			// Податок — з доходу, і лише якщо дохід є. Збиткова позиція
			// податку не породжує, а мінус на ставці 14% додав би грошей
			// із повітря.
			if gain := a.value - a.cost; gain > 0 {
				a.value -= gain * a.taxPct / 100
			}
			released += a.value
			a.value, a.closed = 0, true
		}
	}
	return released
}

// accumTotal — скільки зараз коштують іще не закриті позиції.
func (p *projState) accumTotal() float64 {
	sum := 0.0
	for i := range p.accum {
		sum += p.accum[i].value
	}
	return sum
}
