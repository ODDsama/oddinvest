// Накопичувальні позиції: капітал, що росте й нічого не платить.
//
// Модель рукава знає три стани грошей — готівка, працюючий пул і
// замкнене. Замкнене лежить за номіналом, не росте й віддає реальні
// купони за графіком: так поводиться ОВДП, так поводиться тіло вкладу,
// так поводиться сертифікат REIT, чиї дивіденди стоять у календарі.
//
// Накопичувальний фонд не поводиться так НІЯК. Він не платить нічого — і
// саме тому доти лежав у замкненому цеглиною: обіцянка 25% річних не
// давала ані копійки в календар, а замкнене не росте за побудовою. Фонд,
// який обіцяє подвоїти гроші за три роки, у проєкції не додавав нічого.
//
// Тому четвертий стан. Він росте власною ставкою, не дає потоку, а в
// задану дату закривається: тіло з доходом мінус податок падає в готівку
// й далі реінвестується нарівні з рештою — за тодішньою ставкою, а не за
// своєю, бо фонду вже немає.
package domain

import "math"

// Accum — одна накопичувальна позиція в рукаві. Суми в НАТИВНІЙ валюті
// рукава, як і решта полів Sleeve.
type Accum struct {
	// Value0 — сьогоднішня ринкова вартість; Cost0 — за скільки куплено.
	//
	// Обидві, а не одна: податок береться з ДОХОДУ, тобто з різниці між
	// продажем і купівлею, а не з приросту за час симуляції. Позиція, яка
	// вже подорожчала до сьогодні, несе цей неоподаткований приріст із
	// собою, і рахувати податок від сьогоднішньої вартості означало б
	// його подарувати.
	Value0 float64
	Cost0  float64
	// RatePct — власна СКЛАДНА річна ставка, у валюті рукава.
	RatePct float64
	// CloseM — місяць, коли фонд закривається й повертає гроші
	// (0 = не закривається, росте до кінця горизонту).
	CloseM int
	// TaxPct — податок на дохід при ЗАКРИТТІ, %; ExitTaxPct — при
	// достроковому продажу сертифікатів.
	//
	// Два числа, бо це дві різні події й настає рівно одна. Дожити до
	// закриття означає отримати дохід дивідендами (14%); вийти раніше —
	// продати папери й заплатити з різниці цін (23%). Модель накопичення
	// веде фонд до закриття й бачить перше; декумуляція питає «а якщо
	// гроші потрібні зараз» і бачить друге.
	TaxPct     float64
	ExitTaxPct float64
}

// CompoundFromSimple — проста середньорічна дохідність за years років,
// переведена у складну річну.
//
// Різниця не косметична, і саме на ній тримається окреме поле в
// довіднику. Фонд обіцяє «середньорічну ПРОСТУ 25% за три роки»: це
// сумарний приріст 75%, тобто ×1.75. Застосунок же компаундить щомісяця,
// і 25% складних за ті самі три роки дають ×1.95. Однакова назва, різні
// одиниці, приріст завищений на чверть — а на екрані обидва звуться
// «дохідність, %».
//
// years <= 0 означає, що обіцянка вже складна, і чіпати її не треба.
func CompoundFromSimple(simplePct float64, years int) float64 {
	if years <= 0 {
		return simplePct
	}
	total := 1 + simplePct/100*float64(years)
	if total <= 0 {
		// Проста дохідність, яка з'їдає більше за все тіло. Складного
		// еквівалента в такої немає — лишається сказати «мінус усе».
		return -100
	}
	return (math.Pow(total, 1/float64(years)) - 1) * 100
}

// accumState — накопичувальна позиція під час симуляції.
type accumState struct {
	value, cost float64
	rM          float64 // місячна ставка, порахована раз
	closeM      int
	taxPct      float64
	exitTaxPct  float64
	closed      bool
}

// grow — місяць m: позиції ростуть, і ті, що цього місяця закрились,
// віддають гроші. Повертає суму, яка стала готівкою.
//
// Зростання нараховується й у місяць закриття: фонд працює до останнього
// дня, а не завмирає за місяць до нього.
func (p *projState) grow(m int) float64 {
	released := 0.0
	for i := range p.accum {
		a := &p.accum[i]
		if a.closed {
			continue
		}
		a.value *= 1 + a.rM
		if a.closeM > 0 && m >= a.closeM {
			// Податок — з доходу, і лише якщо дохід є: збиткова позиція
			// податку не породжує, а мінус на ставці 14% додав би грошей
			// із повітря. Формула та сама, що й у продажу, тож і функція
			// та сама — різниться лише ставка (дохід при закритті проти
			// різниці цін при достроковому виході).
			released += netAfterExitTax(a.value, a.cost, a.taxPct)
			a.value, a.closed = 0, true
		}
	}
	return released
}

// AccumCloseValue — скільки накопичувальна позиція віддасть грошима на
// закритті: виросла вартість мінус податок із доходу. 0, якщо фонд не
// закривається (CloseM == 0).
//
// Експортоване, бо це число потрібне ЗА МЕЖАМИ симуляції — профіль
// надходжень малює закриття фонду подією на осі, а симуляція вміє лише
// вмішати його в загальний потік місяця й забути, звідки воно взялось.
//
// Формула тут не дублюється: та сама послідовність, що й у projState.grow
// (зростання за closeM місяців, далі netAfterExitTax), і тест стереже, що
// обидва шляхи дають те саме число. Інакше це стало б п'ятим означенням
// однієї арифметики — рівно тим, від чого в цьому файлі вже є
// netAfterExitTax.
func AccumCloseValue(a Accum) float64 {
	if a.CloseM <= 0 {
		return 0
	}
	value := a.Value0 * math.Pow(1+MonthlyRate(a.RatePct), float64(a.CloseM))
	return netAfterExitTax(value, a.Cost0, a.TaxPct)
}

// accumTotal — скільки зараз коштують іще не закриті позиції.
func (p *projState) accumTotal() float64 {
	sum := 0.0
	for i := range p.accum {
		sum += p.accum[i].value
	}
	return sum
}

// netAfterExitTax — скільки лишиться з позиції на руки, якщо продати її
// зараз: вартість мінус податок із ДОХОДУ, тобто з різниці між продажем і
// купівлею. Збиткова позиція податку не породжує.
//
// Одна функція на чотири місця (порахувати ліквідність і продати — для
// обох видів фондів) навмисно. Доти формула стояла копіями, і мутація це
// показала: прибрати податок з одного лише підрахунку ліквідності тест
// не помічав, бо продаж рахував правильно й місяць вичерпання не рухався.
// Дві копії однієї формули не мусять розходитись мовчки.
func netAfterExitTax(value, cost, taxPct float64) float64 {
	net := value
	if gain := value - cost; gain > 0 {
		net -= gain * taxPct / 100
	}
	if net < 0 {
		return 0
	}
	return net
}

// accumNet — скільки дали б накопичувальні позиції, якби їх продали
// сьогодні: вартість мінус податок із доходу за ДОСТРОКОВОЮ ставкою.
func (p *projState) accumNet() float64 {
	sum := 0.0
	for i := range p.accum {
		a := &p.accum[i]
		if a.closed {
			continue
		}
		sum += netAfterExitTax(a.value, a.cost, a.exitTaxPct)
	}
	return sum
}

// sellAccum — продати сертифікатів на want грошей ПІСЛЯ податку.
// Повертає, скільки вдалося виручити.
//
// Дострокова ставка, а не та, що при закритті: фонд не дожив, тож і
// подія інша. Позиції беруться в порядку списку — вибирати «вигіднішу»
// означало б порадити стратегію виходу, а застосунок цього не робить.
func (p *projState) sellAccum(want float64) float64 {
	got := 0.0
	for i := range p.accum {
		a := &p.accum[i]
		if got+1e-9 >= want || a.closed || a.value <= 0 {
			continue
		}
		// Продавши позицію повністю, отримаєш на руки net, а не value.
		net := netAfterExitTax(a.value, a.cost, a.exitTaxPct)
		if net <= 0 {
			continue
		}
		need := want - got
		if need >= net {
			got += net
			a.value, a.cost = 0, 0
			continue
		}
		// Часткова: продаємо пропорційну частку позиції разом із її
		// собівартістю, інакше податок на залишку рахувався б від чужої
		// бази й наступний продаж дав би більше, ніж має.
		part := need / net
		got += need
		a.value -= a.value * part
		a.cost -= a.cost * part
	}
	return got
}
