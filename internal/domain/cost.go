// Скільки коштувало взяти лот.
//
// Вираз «ціна × кількість, плюс комісія, якщо вона є» був виписаний у
// чотирьох місцях: гаманець у state_builder.go, виписка руху грошей у
// cashflow.go, підсумок місяця в state_month.go і потоки XIRR тут поруч.
// Чотири однакові дев'ять рядків — і жодного механізму, який тримав би їх
// однаковими: досить одному забути `+ Fee`, і два числа на одному екрані
// розійдуться рівно на комісію, обидва лишаючись правдоподібними.
//
// Це не гігієна заради гігієни. Питання «чи вистачає грошей на цю покупку»
// відповідається ЦИМ числом, а списує з рахунку потім state_builder — своїм.
// Доки формула одна, розійтись їм нема як.
package domain

import money "github.com/Rhymond/go-money"

// LotCost — повна вартість лота у валюті лота: ціна за папір × кількість
// плюс сумарна комісія брокера. Нульова чи відсутня комісія нічого не
// додає.
func LotCost(l Lot) (*money.Money, error) {
	cost := MulQty(l.PricePerBond, l.Qty)
	if l.Fee == nil || l.Fee.IsZero() {
		return cost, nil
	}
	return cost.Add(l.Fee)
}
