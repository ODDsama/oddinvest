package domain

import "math"

// Декумуляція: скільки протримається портфель, якщо перестати вносити й
// почати знімати.
//
// Питання, зворотне до всього іншого в застосунку. Модель накопичення
// відповідає на «скільки я накопичу»; ця — на «на скільки цього
// вистачить», і власна функція їй потрібна не з примхи: projState.step
// поняття зняття не має взагалі, а від'ємний внесок зламав би логіку
// порога — floor(cash/threshold) від'ємної готівки перекидав би в роботу
// гроші, яких немає.
//
// ПРИПУЩЕННЯ, і кожне з них можна оскаржити. Записані тут, бо картка
// показує одне число, а стоїть за ним ось це:
//
//  1. Зняття беруться спершу з готівки, потім із працюючої частини.
//     Тобто продаємо лише те, що продається без втрат.
//  2. ЗАМКНЕНЕ (номінал ОВДП, тіло вкладів, сертифікати) достроково НЕ
//     продається — воно лише віддає купони й погашення за графіком.
//     Це найконсервативніша з розумних угод: ОВДП на вторинці продати
//     можна, але за ціною, якої застосунок не знає, а вклад — із
//     втратою відсотків.
//  3. Зняття індексується знеціненням: withdrawUAH задається в
//     СЬОГОДНІШНІХ гривнях, бо саме в них людина знає свої витрати, а
//     через десять років та сама корзина коштує більше.
//  4. Розподіл між валютами — ПРОПОРЦІЙНИЙ до їхньої сьогоднішньої
//     частки. Не «спершу гривня»: це вимагало б припущення про те, в
//     чому саме людина витрачає, а пропорційне зняття ще й тримає
//     валютну структуру незмінною, як і зробив би той, хто ребалансує.
//
// Повертає місяць, на якому зняття вперше НЕ вдалося покрити повністю.
// -1 = не вичерпується за maxMonths (потоки покривають зняття).
func DrawdownMonths(sleeves []Sleeve, devalPct, withdrawUAH float64, maxMonths int) int {
	if withdrawUAH <= 0 || len(sleeves) == 0 {
		return -1
	}
	dM := MonthlyRate(devalPct)
	sts := make([]projState, len(sleeves))
	for i, s := range sleeves {
		sts[i] = projState{cash: s.Cash0, locked: s.Nominal0}
	}
	// liquidOf — скільки з рукава МОЖНА зняти, у сьогоднішніх гривнях:
	// готівка плюс працююча частина, без замкненого.
	//
	// Саме ліквідна вартість, а не повна, задає й частку рукава в знятті.
	// Ділити пропорційно ПОВНІЙ означало б призначити рукаву, у якого
	// майже все в номіналі, більше, ніж він може дати, — і недобір нікуди
	// не подівся б, хоч у сусідньому рукаві гроші є. Портфель «вичерпувався
	// б» першого ж місяця, маючи пів мільйона готівки в іншій валюті.
	liquidOf := func(i, m int) float64 {
		today, _ := sleeves[i].toUAH(sts[i].cash+sts[i].invested, dM, m)
		return today
	}
	nativeOf := func(i, m int, todayUAH float64) float64 {
		s := sleeves[i]
		if s.isUAH() {
			return todayUAH * math.Pow(1+dM, float64(m))
		}
		if s.Rate0 <= 0 {
			return 0
		}
		return todayUAH / s.Rate0
	}

	for m := 1; m <= maxMonths; m++ {
		// Крок росту й надходжень. Внеску немає — це й є декумуляція, — а
		// поріг лишається той самий: гроші, які не пішли на життя, знову
		// стають до роботи, щойно їх вистачає на найдешевший папір.
		for i, s := range sleeves {
			sts[i].step(MonthlyRate(s.rateAt(m)), 0, s.Threshold, s.Coupon[m], s.Redeem[m])
		}
		// Скільки треба зняти цього місяця, у сьогоднішніх гривнях. Саме
		// стала сума: індексація сидить у тому, що вартість портфеля
		// дисконтується, а не в тому, що зростає потреба.
		liquid := 0.0
		for i := range sleeves {
			liquid += liquidOf(i, m)
		}
		// Ліквідного менше за потребу — далі тягнути нема з чого. Замкнене
		// ще може лишатись, і саме тому місяць називається «на скільки
		// вистачило», а не «коли портфель обнулився».
		if liquid+0.005 < withdrawUAH {
			return m
		}
		short := withdrawUAH
		for i := range sleeves {
			part := withdrawUAH * liquidOf(i, m) / liquid
			take := nativeOf(i, m, part)
			// Спершу готівка, потім працююча частина. Замкнене не чіпаємо.
			got := math.Min(take, sts[i].cash)
			sts[i].cash -= got
			if rest := take - got; rest > 0 {
				fromInvested := math.Min(rest, sts[i].invested)
				sts[i].invested -= fromInvested
				got += fromInvested
			}
			// Повертаємо взяте назад у сьогоднішні гривні, щоб порахувати
			// недобір у тій самій одиниці, у якій його задано.
			back, _ := sleeves[i].toUAH(got, dM, m)
			short -= back
		}
		if short > 0.005 {
			return m
		}
	}
	return -1
}
