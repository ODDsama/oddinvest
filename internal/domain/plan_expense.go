// Планова витрата: вирішені разові гроші з датою й станом «сплачено».
//
// Довід, чому це не plan_flows із cadence=once і не ціль, лежить у шапці
// міграції 0056 — повторювати його тут означало б завести другу копію,
// яка розійдеться.
//
// У домені, а не в store, бо питання «чи тисне вона в жовтні» ставлять
// ТРОЄ незалежних читачів: план місяця, вихід із кредитного ліміту й
// таблиця боргу на горизонті. Три однакові порівняння дат розійшлися б на
// першій же правці, і розійшлися б тихо — саме та межа, що вже проведена
// для domain.Debt.

package domain

// Контури, з яких платиться витрата. Рядок належить рівно одному:
// відняти його з обох означало б витратити ті самі гроші двічі (довід —
// у шапці 0056).
const (
	// PaidFromCard — побутовий контур. Гроші лишаються там, куди прийшли,
	// і витрата тисне на стелю витрат та на таблицю горизонту.
	PaidFromCard = "card"
	// PaidFromPlan — портфельний контур. Витрата тисне на гроші місяця, на
	// стелі подушки/цілей/боргу й на ноги маршруту.
	PaidFromPlan = "plan"
)

// PlanExpense — одна вирішена разова витрата.
//
// Amount мінорні й ЗАВЖДИ ДОДАТНІ: напрям несе сама сутність, а не знак
// (те саме правило, що в plan_flows). Currency своя, а не гривнева: ціна
// речі названа у своїй валюті, а гривневий еквівалент змінюється щодня.
type PlanExpense struct {
	ID       int64
	Name     string
	Amount   int64
	Currency string
	// DueDate — коли гроші мають піти. Обовʼязкова: витрата без дати не
	// тисне ні на який місяць, тобто не робить нічого.
	DueDate  Date
	PaidFrom string
	// PaidDate — коли гроші пішли. Порожня = ще винна. Датою, а не
	// прапорцем: сплачена ДО звірки картки вже сидить у виміряному мінусі,
	// сплачена після — ні.
	PaidDate Date
	Place    string
	Note     string
}

// Paid — гроші пішли. Методом, а не порівнянням у кожного читача: їх
// четверо (місяць, стеля, горизонт, черга задач), і чотири однакові рядки
// з порожнім літералом розійшлись би на першій правці — той самий довід,
// що при Goal.Done.
func (p PlanExpense) Paid() bool { return p.PaidDate != "" }

// Overdue — дата минула, а гроші не пішли.
//
// Не «застаріла»: витрата й далі винна, і саме це відрізняє її від
// разового потоку, який у минулому місяці просто зникає (planFlowNative).
func (p PlanExpense) Overdue(today Date) bool {
	return !p.Paid() && p.DueDate.Before(today)
}

// PressDate — дата, на яку гроші РЕАЛЬНО підуть.
//
// Для непростроченої це сама DueDate. Для простроченої — СЬОГОДНІ, а не та
// дата, яку вже проґавили: питання «коли мені знадобляться ці гроші» має
// відповідь «уже», і минула дата не стоїть у ньому ніде — ні у фільтрі
// місяця звірки, ні в таблиці горизонту.
func (p PlanExpense) PressDate(today Date) Date {
	if p.DueDate.Before(today) {
		return today
	}
	return p.DueDate
}

// PressMonth — місяць, у якому витрата тисне, зсувом від today.
// −1 означає «не тисне ніде».
//
// ПРОСТРОЧЕНА ПАДАЄ В ПОТОЧНИЙ МІСЯЦЬ, а не зникає й не лишається у
// своєму. Обидві альтернативи неправдиві: минулий місяць уже прожито й
// змінити в ньому нічого не можна, а зникнувши, витрата перестала б
// вимагати грошей, яких вона й далі вимагає.
//
// Сплачена не тисне взагалі — і саме тому має власну гілку, а не
// нульову суму: нуль читався б як «витрати не сталося».
func (p PlanExpense) PressMonth(today Date) int {
	if p.Paid() {
		return -1
	}
	if m := MonthsBetween(today, p.DueDate); m > 0 {
		return m
	}
	return 0
}
