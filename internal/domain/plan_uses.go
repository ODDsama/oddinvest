// Дозвіл потоку: на що саме ці гроші можуть піти.
//
// ЧОМУ ЦЕ ДОЗВІЛ, А НЕ ПОДІЛ. Скільки з надходження піде в подушку чи в
// ціль, уже означено — стелями reserve_fill_share_pct і
// goals_fill_share_pct. Другий відсоток на потоці був би ДРУГИМ
// означенням того самого розміру, і розійшлися б вони тихо: людина
// поставила б потоку «30% у резерв», стеля дала б інше число, і котре з
// них правда, не сказав би жоден екран. Перелік кошиків відповідає на
// інше питання — «чи можна цим грошам туди взагалі», — і з розміром не
// конкурує ніяк.
//
// ЧОМУ ПОРОЖНЄ ЗНАЧЕННЯ ОЗНАЧАЄ «БУДЬ-КУДИ». Той самий прийом, що з
// PlanFlow.Dest: наявні рядки лишаються значити те, що значили, і
// заповнювати їх міграцією не треба. Але головне попереду — кошики
// додаються. Коли з'явились цілі накопичення, кожен явний перелік,
// набраний до них, мовчки означав би «на цілі не можна» — заборону, якої
// ніхто не ставив. Порожнє значення від цього застраховане за побудовою.
//
// ЧОМУ РЯДОК, А НЕ БІТОВА МАСКА. Маска в SQLite читається як число, і
// «6» у дампі бази не каже нічого. Рядок "reserve,goals" читається без
// довідника — тим самим доводом, яким Dest лишився рядком "npf:<id>".
package domain

import (
	"fmt"
	"strings"
)

// Кошики, куди може піти надходження. Порядок оголошення — це порядок
// ЧЕРГИ НАПОВНЕННЯ (подушка → цілі → папери → пенсійний), і канонічний
// запис його тримає: інакше діф ревізій показував би правку там, де
// змінився лише порядок галочок у формі.
const (
	UsePlanReserve = "reserve"
	// UsePlanDebt — дострокове погашення боргу. Стоїть ПІСЛЯ подушки й
	// ПЕРЕД цілями: збирати на авто під нуль відсотків, маючи розстрочку
	// під пʼятдесят, — та сама втрата, що вже названа для подушки, лише
	// більша. Обовʼязкові платежі сюди не входять узагалі: вони не вибір, а
	// зобовʼязання, і відповідає за них MonthPlan.DebtDueUAH.
	UsePlanDebt   = "debt"
	UsePlanGoals  = "goals"
	UsePlanInvest = "invest"
	UsePlanNPF    = "npf"
)

// planUseOrder — той самий порядок, у вигляді, придатному для обходу.
var planUseOrder = []string{UsePlanReserve, UsePlanDebt, UsePlanGoals, UsePlanInvest, UsePlanNPF}

// PlanUseLabel — кошик українською. Тут, а не в браузері: підпис ходить у
// помилку валідації, а другий словник на дві мови розійшовся б із першим.
var PlanUseLabel = map[string]string{
	UsePlanReserve: "резерв",
	UsePlanDebt:    "погашення боргу",
	UsePlanGoals:   "цілі накопичення",
	UsePlanInvest:  "інвестиції",
	UsePlanNPF:     "пенсійний",
}

// ParsePlanUses — канонічний рядок дозволу з набору токенів.
//
// Порожній набір і повний набір дають ОДНЕ Й ТЕ САМЕ — "", тобто «без
// обмежень». Це не недогляд: перелік із усіх чотирьох кошиків нічого не
// забороняє, а записаний явно він застарів би на першому ж новому кошику
// (довід у шапці файла). Заборонити все не можна взагалі — набір, який
// не дозволяє нікуди, означав би гроші, які нема куди подіти, і форма
// такого варіанта не пропонує.
func ParsePlanUses(tokens []string) (string, error) {
	seen := map[string]bool{}
	for _, t := range tokens {
		t = strings.TrimSpace(t)
		if t == "" {
			continue
		}
		if _, ok := PlanUseLabel[t]; !ok {
			return "", fmt.Errorf("невідомий кошик %q: буває %s", t,
				strings.Join(planUseOrder, ", "))
		}
		seen[t] = true
	}
	if len(seen) == 0 || len(seen) == len(planUseOrder) {
		return "", nil
	}
	var out []string
	for _, k := range planUseOrder {
		if seen[k] {
			out = append(out, k)
		}
	}
	return strings.Join(out, ","), nil
}

// PlanUsesList — дозвіл переліком, для API й для екрана. Порожній рядок
// розгортається в УСІ кошики: назовні «без обмежень» мусить виглядати як
// «можна всюди», інакше браузеру довелось би знати про порожнє значення
// те саме, що знає сховище.
func PlanUsesList(uses string) []string {
	if strings.TrimSpace(uses) == "" {
		return append([]string(nil), planUseOrder...)
	}
	var out []string
	for _, k := range planUseOrder {
		if planUsesHas(uses, k) {
			out = append(out, k)
		}
	}
	return out
}

// PlanUsesNarrowed — дозвіл звужений, тобто його варто показати. Окремою
// функцією, бо перевірка на порожнечу в трьох місцях UI розійшлася б із
// тим, що вважає звуженням бекенд.
func PlanUsesNarrowed(uses string) bool { return strings.TrimSpace(uses) != "" }

// PlanUseAllowed — чи дозволений цей кошик. Порожній дозвіл дозволяє все.
//
// ЗВУЖЕНИЙ ДОЗВІЛ ЗАБОРОНЯЄ НОВИЙ КОШИК, і це не вада, а ціна явності:
// перелік «резерв, інвестиції», набраний до появи цілей накопичення,
// каже про цілі рівно те, що в ньому написано, — нічого. Іншого чесного
// прочитання немає: припустити «мабуть, і туди теж можна» означало б
// дозволити те, чого людина не називала.
//
// Саме тому «без обмежень» зберігається ПОРОЖНІМ рядком, а не повним
// переліком (довід у шапці файла): типовий потік від цієї пастки
// застрахований за побудовою, а звужує дозвіл той, хто справді хоче
// заборони.
func PlanUseAllowed(uses, bucket string) bool {
	if strings.TrimSpace(uses) == "" {
		return true
	}
	return planUsesHas(uses, bucket)
}

func planUsesHas(uses, bucket string) bool {
	for _, part := range strings.Split(uses, ",") {
		if strings.TrimSpace(part) == bucket {
			return true
		}
	}
	return false
}
