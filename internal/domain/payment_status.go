package domain

// StatusReceived — єдиний статус виплати, який застосунок пише.
//
// Колись їх було два: «отримано» і «перевкладено». Другий відповідав на
// питання, яке не має відповіді по одній виплаті (див. міграцію 0017), і
// був зведений до першого. У дампах, зроблених до тієї міграції, він ще
// може трапитись — саме тому Arrived нижче читає обидва.
const (
	StatusReceived   = "received"
	statusReinvested = "reinvested" // спадок; лише для читання старих дампів
)

// Arrived — чи вважати виплату вже отриманою, тобто чи класти її на
// рахунок. Так, якщо дата вже минула АБО користувач сам позначив її.
//
// Один предикат на весь застосунок. Доти їх було ТРИ, і два з них
// перевіряли різне: зведення вимагало саме «received»/«reinvested», а
// звіт про рух коштів і податковий звіт приймали будь-який непорожній
// статус. Розійтись вони не могли — CHECK у міграції 0001 і UPDATE у 0017
// не лишають інших значень, а SetPaymentStatus приймає лише «received», —
// але це рівно та форма, яка стає багом від першого ж нового статусу.
//
// Позначка тут не косметична, і саме тому дата сама по собі — не
// відповідь. Графік НБУ каже, коли виплата ПОВИННА прийти, а не коли вона
// прийшла: гроші лягають у брокера в різний час дня, а часом і наступного.
// Тому день-у-день не зараховуємо нічого самі — інакше з ранку баланс
// показував би гроші, яких ще немає, і звірка з брокером щоразу
// розходилась би рівно на купон. Кнопка «Отримано» — це і є спосіб
// сказати «вже прийшли», не чекаючи опівночі.
//
// statuses — мапа "ISIN|дата" → статус, як її віддає сховище.
func Arrived(statuses map[string]string, today Date) func(isin string, d Date) bool {
	return func(isin string, d Date) bool {
		if d.Before(today) {
			return true
		}
		st := statuses[isin+"|"+string(d)]
		return st == StatusReceived || st == statusReinvested
	}
}
