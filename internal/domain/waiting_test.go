package domain

import "testing"

// Ціна очікування — проста ставка ACT/365 на суму, що лежить.
// 10 000 ₴ під 12% за 30 днів: 10000 × 0.12 × 30/365 = 98.63 ₴.
func TestWaitCostIsSimpleACT365(t *testing.T) {
	got := WaitCost(10000_00, 12, 30)
	if got != 9863 {
		t.Errorf("ціна очікування %d, чекали 9863 (98.63 ₴)", got)
	}
}

// Нуль днів — нуль ціни. «Набереться сьогодні» не є очікуванням, і
// від'ємні дні («набралось учора») теж не борг часу.
func TestWaitCostZeroWithoutWaiting(t *testing.T) {
	for _, days := range []int{0, -5} {
		if got := WaitCost(10000_00, 12, days); got != 0 {
			t.Errorf("днів %d: ціна %d, чекали 0", days, got)
		}
	}
}

// Ставка й сума без діла — теж умови: нема чого вкладати або нема під
// скільки, отже й недоотримати нічого.
func TestWaitCostZeroWithoutBase(t *testing.T) {
	if got := WaitCost(0, 12, 30); got != 0 {
		t.Errorf("порожній рахунок: %d, чекали 0", got)
	}
	if got := WaitCost(10000_00, 0, 30); got != 0 {
		t.Errorf("нульова ставка: %d, чекали 0", got)
	}
	if got := WaitCost(10000_00, -3, 30); got != 0 {
		t.Errorf("від'ємна ставка: %d, чекали 0", got)
	}
}

// Подвоєння днів подвоює ціну: проста ставка, не складна. Тест стереже
// саме цю домовленість — на трьох тижнях різниця з компаундом у копійках,
// але формула мусить лишитись тією, яку описує підпис під числом.
//
// Копійка допуску — не послаблення перевірки, а сама природа округлення:
// 30 днів дають 369.86 ₴, і подвоєне округлене (739.72) на копійку менше
// за округлене подвоєне (739.73). Складний відсоток розійшовся б тут на
// гривні, а не на копійку.
func TestWaitCostIsLinearInDays(t *testing.T) {
	one := WaitCost(50000_00, 9, 30)
	two := WaitCost(50000_00, 9, 60)
	if d := two - 2*one; d < -1 || d > 1 {
		t.Errorf("60 днів = %d, 30 днів = %d; чекали вдвічі ±копійка", two, one)
	}
}
