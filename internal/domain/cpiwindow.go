package domain

// Де стоїть нинішня інфляція серед історії — той самий факт, що й курс
// серед курсів, і та сама межа над ним.
//
// МЕЖА, ЯКУ ЦЕЙ ФАЙЛ НЕ ПЕРЕХОДИТЬ, описана в шапці fxwindow.go і діє
// тут дослівно, тож не переписується: перцентиль — вимірювання минулого,
// а не твердження про майбутнє. Ні поля «сигнал», ні порога, за яким
// щось спрацьовує, тут немає й бути не може. Інфляція має ту саму
// властивість, що й гривня: рекордна вона рівно до наступного разу
// (2022-й дав 26.6% після 10.0%, 2023-й — 5.1% після 26.6%).
//
// ЩО САМЕ РОЗМІЩУЄТЬСЯ. Не рівень цін — його «нинішнього значення» не
// існує, індекс лише росте, — а РІЧНИЙ ТЕМП: нинішня інфляція серед
// річних інфляцій попередніх місяців. Саме це число людина й тримає в
// голові, коли питає «зараз дорого дорожчає чи як звичайно».

// minCPIPoints — той самий поріг, що minFXPoints, і з того самого
// міркування: перцентиль по трьох точках приймає чотири значення й
// виглядає таким самим точним, як по ста двадцяти.
const minCPIPoints = 12

// CPIWindow — місце нинішнього річного темпу серед історії вікна.
type CPIWindow struct {
	Years  int
	Points int
	// Percentile — яка частка місяців вікна мала НИЖЧУ річну інфляцію.
	Percentile float64
	// MedianBP / MinBP / MaxBP — справжні точки ряду, % × 100.
	MedianBP int64
	MinBP    int64
	MaxBP    int64
}

// CPIPlace розміщує нинішній річний темп серед темпів вікна.
//
// yoyBP — опубліковані річні зміни (% × 100) у довільному порядку; відбір
// за датою робить викликач, бо дати живуть у сховищі.
//
// Від'ємні значення тут ЗАКОННІ (дефляція буває), тож, на відміну від
// FXPlace, ряд не фільтрується за додатністю: викинути мінус означало б
// зробити дефляційний місяць невидимим саме там, де він найцікавіший.
func CPIPlace(yoyBP []int64, nowBP int64, years int) (CPIWindow, bool) {
	if len(yoyBP) < minCPIPoints {
		return CPIWindow{}, false
	}
	pct, med, lo, hi := placeAmong(yoyBP, nowBP)
	return CPIWindow{
		Years:      years,
		Points:     len(yoyBP),
		Percentile: pct,
		MedianBP:   med,
		MinBP:      lo,
		MaxBP:      hi,
	}, true
}
