package domain

import "sort"

// Позика в самого себе: узяв із подушки — повертаєш із відсотком (0057).
//
// ЧОМУ ЦЕ ОКРЕМА МАТЕМАТИКА, А НЕ DebtSchedule. У боргу перед банком є
// графік: банк призначає платежі, і питання «коли скінчиться» має
// відповідь. Тут графіка немає й бути не може — повертаєш, коли й скільки
// зміг, а єдине, що застосунок може сказати чесно, це «стільки ще винен
// СЬОГОДНІ». Тому тут не графік, а залишок на дату.
//
// ЩО РОБИТЬ ЦЕ ЧИСЛО. Ціль подушки піднімається рівно на НАРАХОВАНИЙ
// відсоток, а не на весь залишок: тіло вже вирахуване з подушки самим
// зняттям, і додати його вдруге означало б порахувати ту саму гривню двічі
// (довід повністю — у шапці міграції 0057).

// LoanRepay — одне повернення в подушку.
type LoanRepay struct {
	Date   Date
	Amount int64 // мінорні, > 0
}

// ReserveLoanBalance — скільки ще винен подушці на дату asOf і скільки з
// того наросло відсотком.
//
// ТРИ РІШЕННЯ, кожне з ціною:
//
//  1. ACT/365 — той самий рахунок днів, що в XIRR і EstimateAccrued.
//     Третя конвенція в застосунку означала б, що на тому самому нулі
//     одне місце каже «винен», а друге «квит».
//
//  2. Відрізками між подіями, і відсоток ПРИЄДНУЄТЬСЯ до боргу. Це
//     звичайна позика. Тримати «несплачений відсоток» окремо від тіла
//     вимагало б правила «що гасити першим», а такого правила тут не
//     існує: гроші повернення просто лягають у подушку, контрагента, який
//     розніс би платіж, немає.
//
//  3. Залишок затиснутий нулем знизу. Переплата не робить борг відʼємним —
//     це звичайне поповнення понад ціль, і показувати його боргом зі
//     знаком мінус означало б плутати надлишок із заборгованістю.
//
// principal — тіло ДОДАТНИМ числом. Порожня чи неправильна дата, нульове
// тіло й відʼємна ставка дають нуль без вигадування: позики, яку не можна
// порахувати, застосунок не показує зовсім.
func ReserveLoanBalance(principal, rateBP int64, taken Date, repays []LoanRepay, asOf Date) (owed, accrued int64) {
	if principal <= 0 || !taken.Valid() || !asOf.Valid() || asOf.Before(taken) {
		return 0, 0
	}
	// Повернення в хронологічному порядку: відрізок між подіями і є
	// одиницею нарахування, тож переставлені місцями рядки дали б інший
	// відсоток на тих самих грошах.
	ev := make([]LoanRepay, 0, len(repays))
	for _, r := range repays {
		if r.Amount > 0 && r.Date.Valid() && !r.Date.Before(taken) && !r.Date.After(asOf) {
			ev = append(ev, r)
		}
	}
	sort.SliceStable(ev, func(i, j int) bool { return ev[i].Date.Before(ev[j].Date) })

	owed = principal
	at := taken
	step := func(to Date) {
		if owed <= 0 {
			return
		}
		days := DaysBetween(at, to)
		if days > 0 && rateBP > 0 {
			// owed × rate × days / 365, усе в цілих: множення до
			// ділення, щоб на коротких відрізках не лишався нуль.
			i := roundDiv(owed*rateBP*int64(days), 10000*365)
			owed += i
			accrued += i
		}
		at = to
	}
	for _, r := range ev {
		step(r.Date)
		if owed -= r.Amount; owed < 0 {
			owed = 0
		}
	}
	step(asOf)
	if owed <= 0 {
		// Позика закрита: надбавки до цілі більше немає. Саме звідси
		// береться «повернув — ціль вернулась до базової», і окремого
		// механізму під це не потрібно.
		return 0, 0
	}
	return owed, accrued
}
