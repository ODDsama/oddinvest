package domain

import "sort"

// Holdings — чим портфель володіє СЬОГОДНІ, зведене за один прохід.
//
// Друга фаза розбиття buildState. Доти зріз lots обходився там сімома
// циклами, а RemainingQtyNow викликався по чотири рази на лот, і кожен
// виклик — це ще один прохід по всіх продажах. Коштувало це не стільки
// часу, скільки правильності: залишок і фільтр «уже погашений» щоразу
// писались наново, і два з семи циклів рахували їх ІНАКШЕ за решту. Саме
// звідси взявся баг, у якому погашений папір лічився двічі — і номіналом,
// і грішми, що з нього повернулись.
//
// Тут навмисно немає ні грошей у гривні, ні курсів: Holdings живе в
// domain, а конвертація — в internal/fx, який domain імпортує. Тобто
// межа не питання смаку, її ставить напрямок залежностей. Усе, що
// потребує грн-еквівалента, лишається у фазах будівника.
type Holdings struct {
	// Lots — усі лоти, ВКЛЮЧНО з повністю проданими й погашеними. Фази
	// фільтрують самі: одним потрібен залишок, іншим — уся куплена
	// кількість (внески місяця рахуються по факту покупки, і продаж
	// наступного дня її не скасовує).
	Lots []LotHolding
	// Funds — позиції фондів ЗНАЧЕННЯМИ й у сталому порядку за назвою.
	//
	// Значеннями навмисно. FundPositions віддає map[string]*FundPosition,
	// і будівник дописував у неї PayoutDay з довідника. Доки зведення
	// будувались двічі, мутація нікого не зачіпала — друга мапа була
	// свіжа. Щойно зведення стало одне, така мутація поповзла б усюди,
	// причому мовчки. Тепер єдиний писар — конструктор.
	Funds []FundHolding
}

// LotHolding — лот разом із тим, що з нього виводиться.
type LotHolding struct {
	Lot
	// Remaining — скільки паперів лишилось після продажів (0, якщо продано
	// все або більше).
	Remaining int64
	// Bond — папір із довідника НБУ. Known == false, якщо його там немає:
	// так буває, коли папір щойно розміщений або лот прийшов із виписки
	// раніше за оновлення довідника.
	Bond  Bond
	Known bool
	// Matured — строк уже минув, гроші повернулись на рахунок.
	//
	// ⚠️ Порожня дата тут вважається погашеною, і це НЕ помилка копіювання,
	// а поведінка, яку цей тип зберігає: Date.Before — порівняння рядків,
	// тож "" «раніше» за будь-яку дату. Викликачі (номінал, експозиція
	// брокера) саме так і поводились. Positions трактує порожню дату
	// інакше — і навмисно, бо там у вибірці лишаються папери без довідника.
	// Розбіжність справжня, але зводити її треба окремо й свідомо, а не
	// побічним ефектом перенесення.
	Matured bool
}

// Held — папір, який ще в портфелі: є залишок, є в довіднику й не погашений.
func (l LotHolding) Held() bool { return l.Remaining > 0 && l.Known && !l.Matured }

// FundHolding — позиція фонду разом із фактом із довідника.
type FundHolding struct {
	FundPosition
}

// NewHoldings зводить лоти, продажі й операції фондів на дату asOf.
//
// payoutDays — день виплати з довідника фондів, назва → число місяця.
// Мапа, а не []store.Fund: domain не знає про сховище й не має знати.
//
// fundMarks — позначки ціни сертифікатів (0034). Окремим параметром, а не
// полем поруч із payoutDays: вони з різних таблиць і з різним часом життя,
// а тип на два поля запросив би третє «про запас».
func NewHoldings(lots []Lot, sales []Sale, bonds map[string]Bond,
	fundOps []FundOp, fundMarks []FundPrice, payoutDays map[string]int64, asOf Date) Holdings {
	// Продажі — ОДИН прохід замість одного на кожен лот. RemainingQtyNow
	// сам по собі O(len(sales)), і чотири виклики на лот перетворювали
	// звичайну вибірку на квадрат.
	soldByLot := make(map[int64]int64, len(lots))
	for _, s := range sales {
		soldByLot[s.LotID] += s.Qty
	}

	h := Holdings{Lots: make([]LotHolding, 0, len(lots))}
	for _, l := range lots {
		rem := l.Qty - soldByLot[l.ID]
		if rem < 0 {
			// Той самий затиск, що й у RemainingQtyNow: продано більше, ніж
			// куплено, — це дірка в журналі, але від'ємна кількість поповзла б
			// у номінал і зробила б капітал меншим за реальний.
			rem = 0
		}
		b, ok := bonds[l.ISIN]
		h.Lots = append(h.Lots, LotHolding{
			Lot: l, Remaining: rem, Bond: b, Known: ok,
			Matured: ok && b.Maturity.Before(asOf),
		})
	}

	pos := FundPositions(fundOps, fundMarks)
	names := make([]string, 0, len(pos))
	for name := range pos {
		names = append(names, name)
	}
	sort.Strings(names)
	h.Funds = make([]FundHolding, 0, len(names))
	for _, name := range names {
		p := *pos[name]
		p.PayoutDay = payoutDays[name]
		h.Funds = append(h.Funds, FundHolding{FundPosition: p})
	}
	return h
}
