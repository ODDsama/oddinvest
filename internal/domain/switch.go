// Перекладання: за якою ціною варто продати папір і купити інший.
//
// ЩО ЦЕ ЗАКРИВАЄ. Помічник реінвесту (api/handlers_reinvest.go) розподіляє
// лише НОВІ гроші: питання «а те, що вже лежить, досі найкраще?» не
// ставилось ніде. Тобто половина портфеля переоцінювалась щодня, а друга
// половина — жодного разу після купівлі.
//
// ЧОМУ ПОРІГ, А НЕ ВИГОДА. Цін вторинного ринку в застосунку немає й не
// буде (README, «Чого тут свідомо немає»), тож порахувати вигоду прямо
// нема з чого. Але питання можна перевернути: не «скільки я виграю за
// відомою ціною», а «за якої ціни виграш дорівнює нулю». Ціна тут стає
// ВИХОДОМ, а не входом, і зовнішнього джерела не потребує зовсім —
// достатньо подивитись на поріг і на котирування брокера поруч.
//
// МАТЕМАТИКА, І ЧОМУ ВОНА ТАКА КОРОТКА. Продати за X і вкласти виручку
// під ставку альтернативи r проти «дотримати до погашення» — це, на
// перший погляд, порівняння двох капіталів на якомусь горизонті, і
// горизонт довелось би вибирати (а вибір горизонту вирішував би
// відповідь). Насправді горизонт скорочується: якщо купони теж
// перевкладати під r, то капітал обох шляхів у будь-який момент
// відрізняється рівно на різницю сьогоднішніх сум. Тому поріг —
// це просто ТЕПЕРІШНЯ ВАРТІСТЬ решти виплат за ставкою альтернативи.
//
// Наслідок, який варто назвати: «строку окупності» тут немає й бути не
// може. Виграш від перекладання реалізується в момент угоди, бо він і є
// різницею двох сьогоднішніх сум; питання «через скільки місяців
// відіб'ється» ставиться до порівняння з різним ТАЙМІНГОМ, а тут його
// вже згорнуто.
//
// ЧОГО ТУТ СВІДОМО НЕМАЄ.
//
// Ставка альтернативи приходить ГОТОВОЮ й НОМІНАЛЬНОЮ у валюті паперу.
// Ані рейтингу альтернатив, ані знецінення, ані податку цей файл не знає:
// рейтинг один на застосунок (reinvestSuggestions), а перехід
// «реальна ↔ номінальна» живе поруч із realYield в api/devaluation.go.
// Друга копія будь-чого з цього означала б, що «Що купити» і «Чи продати»
// радять різне — рівно та розбіжність, проти якої в now-view.js уже стоїть
// окреме попередження.
//
// Податку в проводці немає, бо його немає в законі: дохід за ОВДП —
// і купон, і результат продажу — не оподатковується ПДФО. Саме тому
// фонди рахуються інакше (див. handlers_reinvest.go), а тут жодного
// податкового доданка немає навмисно.
//
// Комісії за продаж немає, бо її ніде взяти: domain.Sale її не тримає, і
// вигадане число тут спотворило б саме той поріг, заради якого все це
// рахується. Комісія брокера зсуває поріг угору на свою величину — це
// поправка, яку робить людина, дивлячись на власний тариф.
//
// Порогів для фондів, вкладів і НПФ немає: у сертифіката немає ані чистої
// ціни, ані НКД, а строковий вклад розривається за правилами договору, а
// не ринку. Спроба звести їх до однієї формули дала б число, яке виглядає
// як поріг, не бувши ним.

// SwitchInput — папір, який тримаємо, і ставка того, у що перекладаємо.
type SwitchInput struct {
	ISIN string
	// Payments — графік виплат на ОДИН папір (той самий вигляд, якого
	// чекає YTM поруч). Минулі відсіюються тут.
	Payments []Payment
	Today    Date
	// AltRatePct — НОМІНАЛЬНА річна ставка альтернативи у валюті цього
	// паперу, %. Саме номінальна: дисконтуються номінальні гривні, і
	// реальна ставка тут занизила б поріг рівно на все знецінення.
	AltRatePct float64
}

// SwitchResult — вердикт за відомою ціною.
type SwitchResult struct {
	// HoldRatePct — НОМІНАЛЬНА річна дохідність, яку дає утримання паперу,
	// якщо сьогодні за нього дають саме цю ціну. Це та дохідність, від
	// якої відмовляєшся, продаючи: рахується як YTM купівлі власного
	// паперу за сьогоднішнім котируванням.
	HoldRatePct float64
	// GainPerBond — на скільки виручка за один папір більша за теперішню
	// вартість решти його виплат. Додатнє означає «перекладати вигідно».
	GainPerBond *money.Money
}

// BreakEvenClean — ЧИСТА ціна за один папір, за якої перекладання нічого
// не змінює: нижче за неї продавати збитково, вище — вигідно.
//
// Чиста, а не брудна, бо саме чисту називає брокер у котируванні. НКД
// віднімається тим самим EstimateAccrued, яким його рахує решта
// застосунку, — щоб поріг і НКД у картці позиції не розійшлись.
func BreakEvenClean(in SwitchInput) (*money.Money, error) {
	pv, err := switchPV(in)
	if err != nil {
		return nil, err
	}
	accrued, err := EstimateAccrued(in.Payments, in.ISIN, in.Today)
	if err != nil {
		return nil, err
	}
	if accrued == nil || accrued.IsZero() {
		return pv, nil
	}
	return pv.Subtract(accrued)
}

// SwitchVerdict — те саме питання з відомою ціною.
//
// clean — чиста ціна за ОДИН папір, як її називає брокер.
func SwitchVerdict(in SwitchInput, clean *money.Money) (SwitchResult, error) {
	if clean == nil || clean.Amount() <= 0 {
		return SwitchResult{}, fmt.Errorf("перекладання: ціна має бути додатною")
	}
	accrued, err := EstimateAccrued(in.Payments, in.ISIN, in.Today)
	if err != nil {
		return SwitchResult{}, err
	}
	dirty := clean
	if accrued != nil && !accrued.IsZero() {
		if dirty, err = clean.Add(accrued); err != nil {
			return SwitchResult{}, err
		}
	}
	// Дохідність утримання — це YTM ПОКУПКИ ВЛАСНОГО ПАПЕРУ сьогодні за
	// сьогоднішнім котируванням. Не метафора: якби папір не належав тобі,
	// ти купив би його за ці ж гроші й отримав би ті ж виплати, — отже
	// саме від цієї дохідності ти відмовляєшся, продаючи.
	rate, err := YTM(dirty, in.Today, in.Payments, in.ISIN)
	if err != nil {
		return SwitchResult{}, err
	}
	pv, err := switchPV(in)
	if err != nil {
		return SwitchResult{}, err
	}
	gain, err := dirty.Subtract(pv)
	if err != nil {
		return SwitchResult{}, err
	}
	return SwitchResult{HoldRatePct: rate * 100, GainPerBond: gain}, nil
}

// switchPV — теперішня вартість решти виплат на один папір за ставкою
// альтернативи.
//
// День рахується так само, як у XIRR (ACT/365), і це не дрібниця: поріг
// і вердикт мусять сходитись у нулі. Візьми тут 365.25 — і ціна, за якої
// BreakEvenClean обіцяє рівність, дала б у SwitchVerdict дохідність, що
// відрізняється від ставки альтернативи на третьому знаку.
//
// Заокруглення до мінорної одиниці — половина вгору за модулем. Це поріг,
// а не сума в журналі: копійка тут не з чим не звіряється, а лишити його
// дробовим означало б завести другий вид грошей у пакеті, де гроші цілі.
func switchPV(in SwitchInput) (*money.Money, error) {
	r := in.AltRatePct / 100
	if r <= -1 {
		return nil, fmt.Errorf("перекладання: ставка альтернативи %.2f%% поза межами", in.AltRatePct)
	}
	var sum float64
	var cur string
	var n int
	for _, p := range in.Payments {
		if p.ISIN != in.ISIN || p.PerBond == nil {
			continue
		}
		// Виплата в сам день продажу належить продавцю — та сама межа, що
		// в HolderQty і в YTM, і розходитись їм не можна.
		if !p.PayDate.After(in.Today) {
			continue
		}
		years := float64(DaysBetween(in.Today, p.PayDate)) / 365.0
		sum += float64(p.PerBond.Amount()) / math.Pow(1+r, years)
		cur = p.PerBond.Currency().Code
		n++
	}
	if n == 0 {
		return nil, fmt.Errorf("перекладання: у %s немає майбутніх виплат після %s", in.ISIN, in.Today)
	}
	return money.New(int64(math.Round(sum)), cur), nil
}
