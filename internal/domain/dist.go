// Розподільні позиції: капітал, що не росте й платить власною ставкою.
//
// Другий бік того самого поділу, що й accum.go. Накопичувальний фонд
// росте й не платить; розподільний платить і не росте (подорожчання
// сертифіката застосунок не моделює — його ніхто не обіцяв).
//
// Доти розподільний лежав у замкненому капіталі разом із номіналом ОВДП,
// і з цього виходили дві розбіжності.
//
// Перша: дохід рахувався як (invested+locked)×СТАВКА РУКАВА, тобто фонд
// приносив стільки, скільки приносить облігація. Для ОВДП це правда за
// побудовою — саме її купон і задає ставку рукава. Для фонду ні: він
// платить свою дивідендну, і на портфелі, де фонд і облігації розходяться
// на кілька пунктів, картка «коли дохід покриє життя» відповідала не про
// той портфель.
//
// Друга й гірша: у симуляцію дивіденди фонду приходили ЛИШЕ НА РІК
// уперед. Календар оцінює їх на 12 місяців (FundDividendFlows), ці ж
// потоки лягали в купони рукава — і на тринадцятому місяці фонд у моделі
// замовкав назавжди. На десятирічному горизонті це дев'ять років, у які
// позиція не давала нічого й не зникала.
//
// Тепер потік фонду народжується тут і живе весь горизонт. Оцінка
// календаря лишається календарю: там питання «що впаде на рахунок
// найближчим часом», і рік уперед для нього рівно стільки, скільки
// заслуговує припущення.
package domain

// Dist — одна розподільна позиція в рукаві. Суми в НАТИВНІЙ валюті
// рукава.
type Dist struct {
	// Value — ринкова вартість позиції. Не змінюється: увесь дохід іде
	// виплатами, а зростання ціни модель не обіцяє.
	Value float64
	// RatePct — власна дохідність, складна річна, у валюті рукава. Та
	// сама, що й у календарі: обіцянка фонду, якщо задана, інакше
	// виміряна дивідендна.
	RatePct float64
}

// distState — розподільна позиція під час симуляції.
type distState struct {
	value float64
	rM    float64 // місячна ставка, порахована раз
}

// pay — виплати цього місяця, які стають готівкою.
func (p *projState) pay() float64 {
	out := 0.0
	for i := range p.dist {
		out += p.dist[i].value * p.dist[i].rM
	}
	return out
}

// distTotal — вартість розподільних позицій.
func (p *projState) distTotal() float64 {
	sum := 0.0
	for i := range p.dist {
		sum += p.dist[i].value
	}
	return sum
}
