package domain

import "sort"

// Де стоїть сьогоднішній курс серед історії — і чому це ФАКТ, а не сигнал.
//
// Курси НБУ за десять років лежать у базі з першого дня (fx_rates), але
// читались рівно двома способами: крайні точки для знецінення (deval.go) і
// курс на дату для перерахунку операції. Питання «конвертувати зараз чи
// почекати» не спиралось на них узагалі — ребаланс казав «валюти бракує на
// X в.п.» і замовкав, хоча відповідь «поточний курс вищий за 92% усіх
// місяців останніх трьох років» лежала за один запит.
//
// МЕЖА, ЯКУ ЦЕЙ ФАЙЛ НЕ ПЕРЕХОДИТЬ. Порада зі стратегії названа в README
// свідомо відсутньою, і перцентиль — найкоротший шлях її туди протягти:
// від «курс у 92-му перцентилі» до «зачекай» рівно один рядок коду. Цього
// рядка тут немає й бути не може. Перцентиль — вимірювання минулого, а не
// твердження про майбутнє: гривня падає стрибками, і найвищий за десять
// років курс був найвищим рівно до наступного тижня. Застосунок наводить
// факт і залишає рішення людині — так само, як робить із рівнями аукціонів
// у state_market.go.
//
// Наступному авторові: якщо сюди захотілось додати поле «рекомендація»,
// «сигнал» чи поріг, за яким щось спрацьовує, — його місце не тут, і
// аргумент вище пояснює чому.

// minFXPoints — менше за рік історії вікном не вважаємо.
//
// Не для краси: перцентиль по трьох точках приймає рівно чотири значення
// (0, 33, 67, 100), і будь-яке з них виглядає таким самим точним, як
// пораховане по ста двадцяти. Число, точність якого не видно з нього
// самого, гірше за його відсутність.
const minFXPoints = 12

// FXWindow — місце поточного курсу в історії одного вікна.
type FXWindow struct {
	// Years — довжина вікна: 1, 3 або 10 років.
	Years int
	// Points — скільки точок реально знайшлось. Показується поруч із
	// перцентилем: вікно «10 років» на базі, якій три місяці, існувати не
	// може, і мовчазне його малювання було б брехнею про глибину даних.
	Points int
	// Percentile — яка частка точок вікна НИЖЧА за поточний курс, 0..100.
	//
	// Рівні точки рахуються половиною. Інакше повторюваний курс (а
	// помісячна історія їх дає) стрибав би між 0 і 100 від одного
	// заокруглення НБУ: якщо всі сто точок дорівнюють поточній, «нижчих
	// нуль» і «нижчих сто» однаково неправда, а половина — 50 — це рівно
	// те, що про такий ряд можна чесно сказати.
	Percentile float64
	// MedianE4 — СПРАВЖНЯ точка з історії (нижня медіана), а не середнє
	// двох сусідніх. Інтерпольоване число не було курсом жодного дня, а
	// стоїть воно поруч із фактичними мінімумом і максимумом, тобто в
	// ряду, де решта — факти.
	MedianE4 int64
	MinE4    int64
	MaxE4    int64
}

// FXPlace розміщує поточний курс серед курсів вікна.
//
// rates — значення ×10⁴ у довільному порядку; відбір за датою робить
// викликач, бо дати живуть у сховищі, а цей пакет про сховище не знає.
//
// ok=false, коли точок менше за minFXPoints або курс недодатний — тоді
// вікна немає зовсім, і викликач мусить нічого не малювати, а не
// показувати нулі.
func FXPlace(rates []int64, nowE4 int64, years int) (FXWindow, bool) {
	if nowE4 <= 0 || len(rates) < minFXPoints {
		return FXWindow{}, false
	}
	sorted := make([]int64, 0, len(rates))
	for _, r := range rates {
		if r > 0 {
			sorted = append(sorted, r)
		}
	}
	if len(sorted) < minFXPoints {
		return FXWindow{}, false
	}
	pct, med, lo, hi := placeAmong(sorted, nowE4)
	return FXWindow{
		Years:      years,
		Points:     len(sorted),
		Percentile: pct,
		MedianE4:   med,
		MinE4:      lo,
		MaxE4:      hi,
	}, true
}

// placeAmong — спільне ядро розміщення числа серед ряду.
//
// Винесене, щойно з'явився ДРУГИЙ ряд, який ставлять те саме питання:
// курс серед курсів (FXPlace) і річна інфляція серед річних інфляцій
// (CPIPlace). Правила тут не косметичні, і копія неминуче розійшлася б
// саме на них: рівні точки рахуються ПОЛОВИНОЮ (інакше повторюване
// значення стрибає між 0 і 100 від одного заокруглення), а медіана —
// СПРАВЖНЯ точка ряду (нижня), а не середнє двох сусідніх, бо стоїть
// вона поруч із фактичними мінімумом і максимумом.
//
// values мусить бути непорожнім; сортує функція сама.
func placeAmong(values []int64, now int64) (pct float64, median, lo, hi int64) {
	sorted := make([]int64, len(values))
	copy(sorted, values)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i] < sorted[j] })

	var below, equal int
	for _, v := range sorted {
		switch {
		case v < now:
			below++
		case v == now:
			equal++
		}
	}
	pct = (float64(below) + float64(equal)/2) / float64(len(sorted)) * 100
	return pct, sorted[(len(sorted)-1)/2], sorted[0], sorted[len(sorted)-1]
}
