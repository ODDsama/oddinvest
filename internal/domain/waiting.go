// Ціна очікування: скільки коштує НЕ купити зараз.
//
// Питання «чекати три тижні до купона чи взяти те, на що стане вже
// сьогодні» має дві половини. Перша — коли саме набереться (readyOn в
// internal/api/ready_on.go). Друга — скільки коштує сам час, і вона тут.
//
// Порівнюються не дохідності, а ГРОШІ: ставка альтернативи сама по собі
// нічого не каже, бо очікування коштує рівно стільки, скільки ці гроші
// заробили б за ці дні. Обидва числа беруться з того самого переліку
// порад — ставка альтернативи вже пораховані там, і вигадувати нічого не
// доводиться.
//
// Чого тут свідомо немає: другої половини порівняння — виграшу від того,
// що дочекався кращого паперу. Він залежить від строку, який лишиться до
// погашення на момент покупки, від того, чи буде цей папір у продажу, і
// від ціни, якої ми не знаємо (README, «ринкової ціни облігацій»). Ціна
// очікування — факт про гроші, які точно лежать; «виграш від очікування»
// був би припущенням про папір, який ще не куплено. Показуємо перше й
// лишаємо рішення людині — той самий принцип, що з рівнями аукціонів і
// перцентилем курсу поруч.
package domain

import "math"

// WaitCost — скільки НЕ заробить сума за дні очікування, якщо ставка
// альтернативи annualPct річних.
//
// ACT/365 — той самий рахунок днів, що в XIRR і в порозі перекладання
// (domain/switch.go). Інша база дала б інше число на тих самих даних, і
// «за 21 день» у двох місцях застосунку означало б різне.
//
// Проста ставка, не складна: три тижні складним відсотком відрізняються
// від простого на копійки, а формула, у яку треба вдивлятись, щоб
// зрозуміти число під кнопкою, коштує дорожче за ці копійки.
//
// Від'ємні дні дають нуль: «набереться вчора» — це не борг часу, а
// відсутність очікування.
func WaitCost(amountMinor int64, annualPct float64, days int) int64 {
	if amountMinor <= 0 || days <= 0 || annualPct <= 0 {
		return 0
	}
	return int64(math.Round(float64(amountMinor) * annualPct / 100 * float64(days) / 365))
}
