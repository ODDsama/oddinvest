// Сертифікати фондів (Inzhur REIT і подібні).
//
// Від облігації такий папір відрізняється всім, на чому тримається решта
// моделі: немає дати погашення, немає номіналу, немає графіка купонів.
// Натомість є ринкова ціна, яка змінюється, нерегулярні дивіденди — і
// податок на них. Останнє важливо окремо: купон ОВДП звільнений від
// податку, а дивіденд фонду ні, тож порівнювати їхні «дохідності» до
// податку означало б підсовувати фонду фору, якої в нього немає.

// FundOpKind — тип операції в журналі фонду.
type FundOpKind string

const (
	FundBuy      FundOpKind = "buy"
	FundSell     FundOpKind = "sell"
	FundDividend FundOpKind = "dividend"
)

// FundOp — одна операція. Amount і Tax — у мінорних одиницях, завжди
// додатні; напрямок задає Kind.
type FundOp struct {
	ID       int64
	Date     Date
	Fund     string
	Kind     FundOpKind
	Qty      int64
	Amount   int64
	Tax      int64
	Currency string
	Broker   string
	Note     string
	// PairID зв'язує дві операції в одну КОНВЕРТАЦІЮ між фондами: продаж
	// в одному фонді й купівля в іншому — це не два незалежні рішення, а
	// один переказ. Без цього зв'язку пара рахувалась як справжній продаж
	// за гроші: гаманець рухався двічі, а на різниці цін нараховувався
	// прибуток, якого ти не отримував. 0 — пари немає.
	PairID int64
}

// FundPrice — одна позначка ціни сертифіката: ціна на дату, не привʼязана
// до моїх операцій.
//
// Fund — НАЗВА, як у FundOp: сховище тримається за fund_id, домен працює за
// назвою, і межа між ними лишається там, де стояла. FundID поруч потрібен
// не моделі, а екрану довідника, де рядок фільтрується саме за id, — а
// тримати їх разом дешевше, ніж мапити назву назад.
//
// Price — ×10⁴ від гривні, той самий масштаб, що FundPosition.LastPrice:
// 11.1120 ₴ = 111120.
type FundPrice struct {
	ID     int64
	FundID int64
	Fund   string
	Date   Date
	Price  int64
}

// FundPosition — стан одного фонду, зведений із журналу операцій.
type FundPosition struct {
	Fund     string
	Currency string
	Qty      int64
	// PayoutDay — число місяця, коли фонд платить дивіденди (0 = невідомо).
	// З операцій не виводиться: одна виплата ритму не задає, а дві поспіль
	// можуть розійтись через вихідні. Заповнюється з довідника.
	PayoutDay int64
	// CostBasis — скільки вкладено в поточний залишок (мінорні). Продаж
	// зменшує його пропорційно проданій частці, тож це саме собівартість
	// того, що лишилось, а не сума всіх колись сплачених грошей.
	CostBasis int64
	// LastPrice — остання відома ціна за сертифікат у СОТИХ мінорної
	// одиниці, тобто 1/10000 гривні: 11.1120 ₴ = 111120. Зайва точність
	// тут не примха — ціна сертифіката справді має чотири знаки, і
	// округлення до копійки на 1738 сертифікатах розходиться на гривні.
	//
	// Джерел ДВА, і найсвіжіше з них виграє: операція купівлі/продажу, яка
	// принесла ціну з собою, і позначка (FundPrice), вклеєна руками.
	//
	// Друге джерело зʼявилось разом із міграцією 0034 і СКАСУВАЛО те, що
	// тут стояло доти («виписка приносить ціну з собою, тож окреме джерело
	// котирувань не потрібне»). Довід був правильний для розподільного
	// фонду, який докуповують регулярно, і хибний для накопичувального:
	// MilTech не платить нічого, купують його раз, і ціна заморожувалась
	// на ціні купівлі назавжди — тобто весь дохід паперу був невидимий.
	LastPrice     int64
	LastPriceDate Date
	// PriceMarked — LastPrice прийшла з РУЧНОЇ ПОЗНАЧКИ, свіжішої за останню
	// операцію.
	//
	// Потрібне не арифметиці, а екрану: LastPriceDate без нього мовчки
	// міняє сенс — то дата виписки, то дата, яку я вписав сам. У застосунку,
	// де yield_basis існує саме щоб число називало своє джерело, така пара
	// була б єдиним місцем, де воно його не називає.
	PriceMarked bool
	// DividendsGross/DividendsTax — за весь час; Realized — результат
	// закритих продажів (виручка мінус собівартість проданого, мінус
	// податок).
	DividendsGross int64
	DividendsTax   int64
	Realized       int64
	// Short — скільки сертифікатів продано понад куплені. Журнал, у якому
	// продано більше, ніж придбано, неповний: у ньому бракує надходження.
	//
	// Раніше такий мінус мовчки занулювався «щоб не тягнути далі», і
	// позиція виглядала здоровою. На реальних даних це коштувало дорого:
	// у REIT продано 1854 сертифікати проти 421 купленого, застосунок
	// показував правдоподібні 305 — і півтори тисячі сертифікатів, що
	// взялися нізвідки, не помітив ніхто. Тепер розбіжність не зникає, а
	// називається вголос.
	Short int64
}

// Inconsistent — чи має позиція дірку в журналі.
func (p FundPosition) Inconsistent() bool { return p.Short > 0 }

// MarketValue — вартість залишку за останньою відомою ціною, у мінорних
// одиницях (ділення на 100 знімає зайвий розряд точності LastPrice).
func (p FundPosition) MarketValue() int64 { return p.Qty * p.LastPrice / 100 }

// FundPositions зводить журнал у позиції. Операції мають бути
// відсортовані за датою: собівартість рахується послідовно, і продаж до
// купівлі дав би від'ємний залишок.
//
// Собівартість — середньозважена, а не FIFO: у безстрокового інструмента
// без податкової потреби розрізняти партії FIFO лише додав би складності.
// marks — позначки ціни, вклеєні руками (може бути nil).
func FundPositions(ops []FundOp, marks []FundPrice) map[string]*FundPosition {
	out := map[string]*FundPosition{}
	for _, op := range ops {
		p := out[op.Fund]
		if p == nil {
			p = &FundPosition{Fund: op.Fund, Currency: op.Currency}
			out[op.Fund] = p
		}
		switch op.Kind {
		case FundBuy:
			p.Qty += op.Qty
			p.CostBasis += op.Amount
			if op.Qty > 0 {
				p.LastPrice = op.Amount * 100 / op.Qty
				p.LastPriceDate = op.Date
			}
		case FundSell:
			if op.Qty > 0 {
				p.LastPrice = op.Amount * 100 / op.Qty
				p.LastPriceDate = op.Date
			}
			sold := int64(0)
			if p.Qty > 0 {
				// Собівартість проданої частки — пропорційно до залишку.
				sold = p.CostBasis * op.Qty / p.Qty
			}
			p.CostBasis -= sold
			p.Qty -= op.Qty
			if p.Qty < 0 {
				// Мінус далі не тягнемо — інакше він поповз би в ринкову
				// вартість і зробив би капітал від'ємним, — але й не
				// ховаємо: скільки саме не сходиться, лишається в Short.
				p.Short += -p.Qty
				p.Qty = 0
			}
			if p.CostBasis < 0 {
				p.CostBasis = 0
			}
			p.Realized += op.Amount - sold - op.Tax
		case FundDividend:
			p.DividendsGross += op.Amount
			p.DividendsTax += op.Tax
		}
	}
	// Позначки ціни — ДРУГЕ джерело тієї самої величини, і найсвіжіше з
	// двох виграє. Не «завжди позначка»: журнал приносить ціну задарма й на
	// дату, коли гроші справді рухались. І не «завжди операція»: тоді
	// вклеєна руками ціна не мала б жодного ефекту саме на тому фонді,
	// заради якого її й заводять. Те саме правило, що в NPFPositions.
	//
	// На однаковій даті виграє ПОЗНАЧКА (>=): вона точна, а виведена з
	// операції несе округлення суми до копійки. Але PriceMarked при цьому
	// лишається хибним — позначка в день операції лише повторює виписку, а
	// не додає нової дати, і називати її незалежним джерелом було б
	// перебільшенням.
	//
	// Позначка на фонд БЕЗ операцій позиції не створює: нуль сертифікатів
	// дає нуль вартості, а порожній рядок у картці «Фонди» був би позицією,
	// якої немає. Позначити ціну наперед, до першої купівлі, при цьому
	// можна — вона просто чекає в базі й малює криву.
	latest := map[string]FundPrice{}
	for _, m := range marks {
		if m.Price <= 0 {
			continue
		}
		if cur, ok := latest[m.Fund]; !ok || m.Date >= cur.Date {
			latest[m.Fund] = m
		}
	}
	for name, p := range out {
		m, ok := latest[name]
		if !ok || m.Date < p.LastPriceDate {
			continue
		}
		p.PriceMarked = m.Date > p.LastPriceDate
		p.LastPrice, p.LastPriceDate = m.Price, m.Date
	}
	return out
}

// Мінімальний вік грошей і смуга правдоподібності для ануалізації —
// ті самі, що й у портфельного XIRR. Три дні тримання з приростом 0.4%
// дають 60% річних, і це не дохідність, а арифметика ділення на малий
// строк.
const (
	fundReturnMinDays = 30.0
	fundReturnMax     = 1.0
	fundReturnMin     = -0.95
)

// ReturnMeasurable — чи є взагалі ЩО міряти повною дохідністю.
//
// XIRR позиції фонду тавтологічний рівно тоді, коли ВСІ вкладені гроші
// оцінюються сьогодні рівно в себе й більше нічого не рухалось: термінальна
// вартість дорівнює собівартості, потоків фактично два — −A і +A, — і
// відповідь дорівнює нулю незалежно від дат, сум і того, що робив фонд. Це
// не «дохідність 0%», це ВІДСУТНІСТЬ ВИМІРУ.
//
// Саме вона витісняла обіцянку фонду в state_funds.go, бо гілка виміряного
// стоїть першою: накопичувальний MilTech, куплений один раз, показував нуль
// номінальних і відʼємні реальні там, де фонд обіцяє 25% простих за три
// роки. Ціна в нього рухається щодня — застосунок просто не мав звідки її
// взяти, і мовчання про це видавав за виміряний нуль.
//
// Умова названа ПРЯМО через виродження, а не через «є друга точка ціни»
// (перша спроба, відкинута під час тестування). Дві точки ціни ще не роблять
// вимір можливим: якщо вклеїти опубліковану історію фонду ЦІЛКОМ до своєї
// купівлі, дат стає багато, а термінал усе одно лишається ціною тієї самої
// купівлі — і нуль повертається. Натомість позиція, зібрана двома купівлями
// за різними цінами, тавтологічною не є й без жодної позначки, бо середня
// собівартість уже не дорівнює останній ціні.
//
// Три виходи з виродження, і кожен — справжній рух: ринкова вартість
// розійшлась із собівартістю (ціна відома на іншому рівні), дивіденд (гроші
// реально прийшли) або продаж (ціну дав ринок).
//
// Рівність тут строга, тож теоретично можливий хибний негатив: ціна пішла
// вгору й повернулась рівно до середньої собівартості, і чесний нуль буде
// прихований. Ціна цього — рядок покаже обіцянку й скаже про це в
// yield_basis; ціна протилежної помилки — мовчазний нуль замість обіцянки,
// і вона вже коштувала цілої фази.
func (p FundPosition) ReturnMeasurable() bool {
	return p.MarketValue() != p.CostBasis || p.DividendsGross > 0 || p.Realized != 0
}

// FundTotalReturn — ПОВНА дохідність позиції фонду, % річних: дивіденди
// після податку І зміна ціни разом, ануалізовані по фактичних датах
// операцій (XIRR з термінальною ринковою вартістю).
//
// Навіщо, коли поруч є DividendYieldNet. Та міряє лише дохідну частину,
// і поряд з облігацією це нечесно: YTM ловить УВЕСЬ дохід паперу — і
// купон, і дисконт до номіналу, — а фонд показував самі дивіденди, тож
// у спільній таблиці систематично виглядав гіршим, ніж є. REIT, який
// платить 5.8% і дорожчає, — це не 5.8%.
//
// Природа числа при цьому інша, і ховати це не можна: YTM облігації —
// обіцянка на майбутнє, а тут ФАКТ по вже прожитому. Сертифікат не
// гаситься, майбутніх виплат за графіком у нього немає, тож іншого
// чесного способу порахувати повну дохідність не існує.
func FundTotalReturn(ops []FundOp, marks []FundPrice, fund string, asOf Date) (float64, bool) {
	if p := FundPositions(ops, marks)[fund]; p == nil || !p.ReturnMeasurable() {
		return 0, false
	}
	flows := FundFlowsOne(ops, marks, fund, asOf)
	if len(flows) < 2 {
		return 0, false
	}
	if MoneyWeightedDays(flows, asOf) < fundReturnMinDays {
		return 0, false
	}
	r, err := XIRR(flows)
	if err != nil || r > fundReturnMax || r < fundReturnMin {
		return 0, false
	}
	return math.Round(r*10000) / 100, true
}

// FundPriceStaleDays — після скількох днів остання відома ціна перестає
// описувати сьогоднішній стан.
//
// Поріг потрібен через дірку, знайдену вживу: ReturnMeasurable дивиться,
// чи розійшлась вартість із собівартістю, а розійшлась вона НАЗАВЖДИ після
// першої ж позначки. Тобто піврічної давнини ціна пройде охорону так само,
// як учорашня, — і XIRR розтягне її на сьогоднішній горизонт, систематично
// занизивши фонд, який весь цей час ріс. Той самий клас помилки, що й
// початковий нуль, лише повільніший: число виглядатиме виміряним і буде
// хибним.
//
// Лікуємо ПОКАЗОМ, а не блокуванням: ціну не скасовуємо й на обіцянку не
// відкочуємось. Поріг, за яким «вимір скасовується», був би вигаданим
// числом у головній колонці — рівно те, від чого застосунок відмовляється
// всюди. Тут він лише вмикає підказку, і ціна помилки в ньому дорівнює
// зайвому рядку в списку завдань.
//
// 45 днів, а не 30: фонд публікує ціну щонайменше щомісяця, тож місяць —
// це ще ритм, а півтора вже пропущений крок. Числа в налаштуваннях немає
// навмисно — налаштування заводять там, де відповідь залежить від людини,
// а тут вона залежить від фонду.
const FundPriceStaleDays = 45

// PriceStale — чи застаріла ціна, за якою оцінена позиція.
//
// Порожня позиція мовчить: у нуля сертифікатів ціна ні на що не впливає, і
// нагадувати про неї означало б просити роботу задарма.
func (p FundPosition) PriceStale(asOf Date) bool {
	if p.Qty <= 0 || p.LastPriceDate == "" {
		return false
	}
	return DaysBetween(p.LastPriceDate, asOf) > FundPriceStaleDays
}

// fundPriceReturnMinDays — коротший відрізок ануалізувати не варто: два дні
// різниці ціни, розтягнуті на рік, дають тризначні відсотки. Число те саме,
// що npfNavReturnMinDays, але константа своя — та живе під власним доводом
// (ЧВОПА публікують щодня), і зчепити їх означало б, що зміна порогу для
// пенсійного рахунку мовчки зсуне поріг фондів.
const fundPriceReturnMinDays = 180

// FundPricePoints — усі відомі точки ціни сертифіката: позначені руками
// разом із виведеними з операцій, по одній на дату.
//
// Обʼєднання, а не вибір одного джерела, і з тієї ж причини, що в
// NPFNavPoints: операції дають точки задарма, але накопичувальний фонд
// купують раз, а руками заводиться опублікована фондом історія. Позначка
// важить більше за виведену з операції: вона точна, а виведена несе
// округлення суми до копійки.
func FundPricePoints(marks []FundPrice, ops []FundOp, fund string) []FundPrice {
	byDate := map[Date]FundPrice{}
	for _, op := range ops {
		if op.Fund != fund || op.Qty <= 0 {
			continue
		}
		if op.Kind != FundBuy && op.Kind != FundSell {
			continue
		}
		byDate[op.Date] = FundPrice{Fund: fund, Date: op.Date, Price: op.Amount * 100 / op.Qty}
	}
	for _, m := range marks {
		if m.Fund == fund && m.Price > 0 {
			byDate[m.Date] = m
		}
	}
	out := make([]FundPrice, 0, len(byDate))
	for _, v := range byDate {
		out = append(out, v)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Date < out[j].Date })
	return out
}

// FundPriceReturn — зростання ЦІНИ сертифіката, % річних складних.
//
// Time-weighted: дати й розміри моїх купівель на нього не впливають — це
// «як спрацював сам фонд». Поруч живе FundTotalReturn, і це ІНШЕ число:
// воно про те, скільки заробили МОЇ гроші з урахуванням дат. При
// нерівномірних купівлях вони розходяться, і зводити їх в одне означало б
// відповідати на друге питання числом від першого.
//
// І на відміну від НПФ, це число НЕ витісняє обіцянку: yield_basis уже має
// три значення, одне з яких зайняте фактом, і четверте зробило б основу
// рядка залежною від того, який із двох вимірів випадково дозрів першим.
// Воно стоїть окремим полем поруч із обіцянкою — саме щоб її можна було
// спростувати, а не щоб її замінити.
func FundPriceReturn(points []FundPrice, asOf Date) (float64, bool) {
	var pts []FundPrice
	for _, p := range points {
		if p.Price > 0 && !p.Date.After(asOf) {
			pts = append(pts, p)
		}
	}
	if len(pts) < 2 {
		return 0, false
	}
	sort.Slice(pts, func(i, j int) bool { return pts[i].Date < pts[j].Date })
	first, last := pts[0], pts[len(pts)-1]
	days := DaysBetween(first.Date, last.Date)
	if days < fundPriceReturnMinDays {
		return 0, false
	}
	growth := float64(last.Price) / float64(first.Price)
	if growth <= 0 {
		return 0, false
	}
	r := (math.Pow(growth, 365.0/float64(days)) - 1) * 100
	if r > fundReturnMax*100 || r < fundReturnMin*100 {
		return 0, false
	}
	return math.Round(r*100) / 100, true
}

// FundPriceChange — ПРОСТА зміна ціни сертифіката за весь відрізок відомої
// кривої: скільки відсотків і за скільки днів.
//
// Це не другий вимір того самого, що FundPriceReturn, а відповідь на інше
// питання, і різниця тут принципова. FundPriceReturn — % РІЧНИХ складних, і
// саме тому воно навмисно мовчить на відрізку коротшому за пів року:
// ануалізувати два тижні означає намалювати сотні відсотків з дрібниці.
// Але крива в UI малюється вже з двох точок, і вісь у неї не починається з
// нуля — тобто рух 0.9% розтягнутий на все полотно й виглядає крутішим,
// ніж є. Підпис «+0.88% за 14 днів» — те, що не дає його так прочитати, і
// на будь-якій довжині відрізка він чесний, бо нічого не екстраполює.
//
// Порогу днів тут немає з тієї ж причини: порогу нема чого захищати.
// Обмеження рівно одне — щоб було що ділити.
//
// Рахує бекенд, хоча обидві точки в UI вже є: друга копія арифметики
// дохідності в браузері двічі закінчувалась різними числами на одному
// екрані (див. CLAUDE.md §5).
func FundPriceChange(points []FundPrice, asOf Date) (pct float64, days int, ok bool) {
	var pts []FundPrice
	for _, p := range points {
		if p.Price > 0 && !p.Date.After(asOf) {
			pts = append(pts, p)
		}
	}
	if len(pts) < 2 {
		return 0, 0, false
	}
	sort.Slice(pts, func(i, j int) bool { return pts[i].Date < pts[j].Date })
	first, last := pts[0], pts[len(pts)-1]
	if first.Price <= 0 {
		return 0, 0, false
	}
	r := (float64(last.Price)/float64(first.Price) - 1) * 100
	return math.Round(r*100) / 100, DaysBetween(first.Date, last.Date), true
}

// NetOfTax — ставка після податку на дохід, % річних.
//
// Потрібна, щоб фонд можна було порівнювати з рештою в ОДНІЙ мірі. Купон
// ОВДП від податку звільнений, ставка вкладу в помічнику вже нетто
// («ставка вкладу після податку»), а обіцянка фонду йшла туди брутто — і
// в спільній таблиці фонд систематично виглядав кращим, ніж є.
//
// years задає, КОЛИ береться податок, і це не дрібниця.
//
// years > 0 — фонд зі строком: дохід накопичується всередині й
// оподатковується один раз, у кінці. Тоді податок б'є по СУМАРНОМУ
// приросту, а не щороку: 20.51% річних за три роки це ×1.75, податок 14%
// з приросту лишає ×1.645, тобто 18.05% річних. Оподаткувати щороку було
// б неправильно — держава не бере податок з паперу, який ти не продав.
//
// years == 0 — безстроковий: дохід приходить виплатами, і кожна
// оподатковується одразу, тож ставка просто зменшується на податок.
func NetOfTax(ratePct, taxPct, years float64) float64 {
	if taxPct <= 0 || ratePct <= 0 {
		return ratePct
	}
	if years <= 0 {
		return ratePct * (1 - taxPct/100)
	}
	total := math.Pow(1+ratePct/100, years)
	net := 1 + (total-1)*(1-taxPct/100)
	if net <= 0 {
		return -100
	}
	return (math.Pow(net, 1/years) - 1) * 100
}

// FundISINPrefix — префікс синтетичного ключа фонду в календарі.
const FundISINPrefix = "fund:"

// IsFundISIN — чи належить потік фонду. Потрібне там, де фондам не місце:
// у ціновому ризику (сертифікат не переоцінюється зміною ставок ОВДП) і в
// ризику перевкладення (безстроковий папір нічого не «повертає» — дивіденд
// не є поверненням тіла).
func IsFundISIN(isin string) bool { return strings.HasPrefix(isin, FundISINPrefix) }

// FundDividendFlows — ОЦІНКА майбутніх дивідендів фонду на months місяців
// уперед.
//
// Це єдине місце в календарі, де стоїть не зобовʼязання, а припущення, і
// саме тому воно окремо: купон ОВДП і відсоток вкладу записані в договорі,
// а дивіденд фонду — ні. Але без нього календар показував дві третини
// потоку й мовчав про решту, а «скільки я отримую щомісяця» рахувалось з
// фондами в одному місці й без них у сусідньому.
//
// Сума — рівними частками від річної дохідності на сьогоднішню вартість:
// точнішого припущення все одно немає, бо виплата залежить від результату
// місяця. yieldPct береться з обіцянки фонду, якщо вона задана, бо
// виміряна дивідендна ділить ОСТАННЮ виплату на СЬОГОДНІШНЮ вартість — і
// на позиції, яку активно докуповують, суттєво занижена.
func FundDividendFlows(p *FundPosition, yieldPct float64, months int, from Date, reinvest bool) []FundPayout {
	if p == nil || p.PayoutDay <= 0 || yieldPct <= 0 || months <= 0 {
		return nil
	}
	if p.MarketValue() <= 0 {
		return nil
	}
	isin := FundISINPrefix + p.Fund
	out := make([]FundPayout, 0, months)
	qty := p.Qty
	d := from
	for i := 0; i < months; i++ {
		// Вартість перераховується щомісяця від ПОТОЧНОЇ кількості: у
		// фонда, який докуповує сам, вона росте без жодного мого рішення,
		// і дванадцятий місяць, порахований від сьогоднішньої кількості,
		// спирався б на число, про яке ми вже знаємо, що воно застаріле.
		// Позиція користувача росте на ~9% за рік. Для решти фондів qty не
		// міняється, і цикл поводиться рівно як доти.
		//
		// Ціна лишається СЬОГОДНІШНЬОЮ. Форвардної ціни сертифіката
		// застосунок не вигадує ніде (див. шапку route.go), і тут не почне:
		// компаундиться кількість, яку ми справді можемо порахувати, а не
		// ціна, якої ми не знаємо.
		mv := qty * p.LastPrice / 100
		per := int64(math.Round(float64(mv) * yieldPct / 100 / 12))
		if per <= 0 {
			break
		}
		next, ok := NextPayoutDate(int(p.PayoutDay), d)
		if !ok {
			break
		}
		split := FundReinvestSplit{Gross: per, Cash: per}
		if reinvest {
			split = SplitFundDividend(per, p.LastPrice)
			qty += split.Units
		}
		out = append(out, FundPayout{
			CashflowItem: CashflowItem{Date: next, ISIN: isin,
				Type: PayCoupon, Amount: money.New(split.Cash, p.Currency)},
			Split: split,
		})
		// Наступний місяць: від дня ПІСЛЯ знайденої дати, інакше та сама
		// повернеться знов.
		d = next.AddDays(1)
	}
	return out
}

// FundPayout — одна ОЦІНЕНА виплата фонду.
//
// Amount у вкладеному CashflowItem — те, що ляже НА РАХУНОК, а не вся
// нарахована сума. Різниця не косметична: у фонда, який докуповує
// сертифікати сам, вона відрізняється на порядок, і саме через неї
// маршрут вів у НПФ гроші, яких ніколи не буде. Уся нарахована лишається
// поруч у Split — календарю вона потрібна, бо дохід нікуди не дівається.
type FundPayout struct {
	CashflowItem
	Split FundReinvestSplit
}

// FundReinvestSplit — як ділиться одна виплата фонду, що докуповує сам.
// Усі суми мінорні, у валюті фонду. У звичайного фонда Units і Spent
// нульові, а Cash дорівнює Gross.
type FundReinvestSplit struct {
	Gross int64
	Units int64
	Spent int64
	Cash  int64
}

// SplitFundDividend ділить виплату gross за ціною сертифіката priceE4
// (×10⁴ гривні — той самий масштаб, що FundPosition.LastPrice).
//
// ЧОМУ ОКРЕМА ЕКСПОРТОВАНА ФУНКЦІЯ, А НЕ ТРИ РЯДКИ В ЦИКЛІ ВИЩЕ. Ці числа
// бачить не лише календар: маршрут пише ними прозу («докупив 6
// сертифікатів на 66,75 ₴»). Порахувати їх удруге в api/ означало б другу
// копію арифметики — рівно те, від чого стереже CLAUDE.md §5.
//
// МАСШТАБИ. gross у копійках, priceE4 — сота частина копійки. Тому
// gross*100/priceE4 дає саме штуки, а units*priceE4/100 — знову копійки.
//
// ОКРУГЛЕННЯ В РІЗНІ БОКИ, І ЦЕ НАВМИСНО. Штуки — ВНИЗ: фонд не купує
// 6.2 сертифіката. Витрачене — ДО НАЙБЛИЖЧОЇ КОПІЙКИ: ціна має чотири
// знаки, а платять копійками, і обрізання вниз лишало б щомісяця до
// копійки зайвої «готівки», тобто фонд поволі створював би гроші.
//
// Cash не буває відʼємним за побудовою: units*priceE4 <= gross*100, а
// заокруглення числа, яке не перевищує цілого gross, того gross не
// перевищить.
func SplitFundDividend(gross, priceE4 int64) FundReinvestSplit {
	out := FundReinvestSplit{Gross: gross, Cash: gross}
	if gross <= 0 || priceE4 <= 0 {
		// Ціни не знаємо — ділити нічим, уся виплата лишається готівкою.
		// Живий виклик сюди не доходить (нульова ціна дає нульову
		// MarketValue, і потік не народжується взагалі), але функція
		// експортована й ділити на нуль мовчки не має права.
		return out
	}
	out.Units = gross * 100 / priceE4
	if out.Units <= 0 {
		// Виплати не стало на цілий сертифікат — уся вона приходить
		// грошима. Це не виняток, а звичайний місяць дрібної позиції.
		return out
	}
	out.Spent = (out.Units*priceE4 + 50) / 100
	out.Cash = gross - out.Spent
	return out
}

// NextPayoutDate — коли фонд заплатить наступного разу.
//
// Правило фонду: виплата кожного payDay числа за ПОПЕРЕДНІЙ місяць. Якщо
// число припадає на вихідний, платять наступного робочого дня — тож дата
// може виїхати на понеділок або вівторок.
//
// Свят тут немає навмисно: виробничий календар довелось би вести руками й
// щороку оновлювати, а помилка в один-два дні на питання «коли чекати
// наступну виплату» не впливає. Вихідні натомість відомі назавжди.
func NextPayoutDate(payDay int, from Date) (Date, bool) {
	if payDay < 1 || payDay > 31 || from == "" {
		return "", false
	}
	t := from.Time()
	if t.IsZero() {
		return "", false
	}
	// Цього місяця, а якщо вже минуло — наступного.
	y, m := t.Year(), t.Month()
	for i := 0; i < 2; i++ {
		d := shiftOffWeekend(time.Date(y, m, payDay, 0, 0, 0, 0, time.UTC))
		if !d.Before(t) {
			return Date(d.Format(dateLayout)), true
		}
		if m == time.December {
			y, m = y+1, time.January
		} else {
			m++
		}
	}
	return "", false
}

// shiftOffWeekend — субота й неділя переносяться на понеділок.
func shiftOffWeekend(d time.Time) time.Time {
	switch d.Weekday() {
	case time.Saturday:
		return d.AddDate(0, 0, 2)
	case time.Sunday:
		return d.AddDate(0, 0, 1)
	default:
		return d
	}
}

// DividendYieldNet — чиста дивідендна дохідність позиції, % річних:
// ОСТАННЯ виплата після податку, приведена до року за ритмом виплат.
//
// Саме після податку: у фонду немає обіцяної ставки, є лише те, що він
// реально платить, а дивіденд оподатковується, на відміну від купона ОВДП.
//
// Чому не «сума за 365 днів ÷ вартість», як було раніше: та формула міряє
// не дохідність паперу, а те, скільки історії встигло накопичитись. Фонд,
// куплений три місяці тому, показував би близько чверті своєї справжньої
// дохідності — і не тому, що погано платить, а тому, що ще не встиг
// заплатити дванадцять разів. Позиція з підчищеним журналом виглядала так
// само. Останню виплату натомість фонд щойно зробив, і вона про сьогодні.
//
// Ритм береться з фактичних проміжків між виплатами (медіана — щоб один
// зсунутий місяць не перекосив усе), а не задається константою: щомісячний
// фонд і щоквартальний однаково не мають підганятись під чуже припущення.
// Одна-єдина виплата ритму не дає, тож для неї береться місяць — найчастіший
// для REIT-фондів випадок.
//
// on — сьогоднішня дата.
func DividendYieldNet(ops []FundOp, p *FundPosition, on Date) (float64, bool) {
	if p == nil || p.MarketValue() <= 0 {
		return 0, false
	}
	// Лише виплати останнього року: торішній ритм до сьогоднішньої
	// дохідності стосунку не має.
	var recent []FundOp
	for _, op := range ops {
		if op.Fund != p.Fund || op.Kind != FundDividend {
			continue
		}
		if d := DaysBetween(op.Date, on); d >= 0 && d <= 365 {
			recent = append(recent, op)
		}
	}
	if len(recent) == 0 {
		return 0, false
	}
	sort.Slice(recent, func(i, j int) bool { return recent[i].Date < recent[j].Date })
	last := recent[len(recent)-1]
	net := last.Amount - last.Tax
	if net <= 0 {
		return 0, false
	}

	// Медіана проміжків між сусідніми виплатами; менше двох виплат —
	// вважаємо місячний ритм.
	//
	// Якщо в довіднику заданий день виплати, ритм відомий точно: фонд
	// платить раз на місяць у це число. Тоді ні медіана, ні припущення не
	// потрібні — 365/12 замість круглих 30 прибирає похибку в 1.5%, яку
	// давав «місяць = 30 днів».
	period := 30.0
	if p.PayoutDay > 0 {
		period = 365.0 / 12
	} else if len(recent) >= 2 {
		gaps := make([]int, 0, len(recent)-1)
		for i := 1; i < len(recent); i++ {
			if g := DaysBetween(recent[i-1].Date, recent[i].Date); g > 0 {
				gaps = append(gaps, g)
			}
		}
		if len(gaps) > 0 {
			sort.Ints(gaps)
			period = float64(gaps[len(gaps)/2])
		}
	}
	if period < 1 {
		period = 1
	}
	annual := float64(net) * 365 / period
	return math.Round(annual/float64(p.MarketValue())*10000) / 100, true
}
