-- Недержавний пенсійний фонд — четвертий інструмент поряд з ОВДП, фондами
-- і вкладами.
--
-- Чому не fund_ops, хоча облік на вигляд той самий (одиниці × ціна):
-- fund_ops.qty — ЦІЛІ сертифікати, і FundPositions виводить ціну як
-- amount*100/qty (domain/funds.go). Одиниці пенсійних активів дробові до
-- шести знаків: 1000 ₴ за ЧВОПА 3.472156 зараховують 287.897… одиниці.
-- Округлити нічим — гроші губляться на кожному внеску, а перемасштабувати
-- fund_ops.qty означає тихо змінити ціну й вартість усіх наявних фондів.
-- Це блокер даних, а не смак.
--
-- Друга причина не менш тверда: funds_uah — ОПУБЛІКОВАНЕ поле контракту з
-- визначеним змістом («вартість сертифікатів фондів»), і його
-- перевизначення вимагало б інкременту SchemaVersion, тобто зламало б
-- єдину гарантію, на яку спирається ha-oddinvest. А funds_yield_pct
-- перетворився б у змішування замкненої 25-річної обіцянки з виміреними
-- дивідендами REIT — тобто в число, за яким нічого не зробиш.
--
-- Чим НПФ економічно відрізняється від сертифіката:
--   * до пенсії з нього не приходить НІЧОГО. CashflowItem не породжує
--     взагалі — ні купона, ні дивіденда, ні погашення;
--   * доступ лише з access_date (50 років = 10 до державної пенсії),
--     далі виплати мінімум десять років. Це найдовша й абсолютно
--     неліквідна позиція портфеля;
--   * податок працює у ДВА боки: внесок дає право на податкову знижку
--     (приплив наступного року), а виплата оподатковується.
--
-- Масштаби. units_e6 і nav_e6 — ×10⁶, amount — копійки, як усюди.
-- Свідомо НЕ ×10⁴, яким живе FundPosition.LastPrice: там ціна
-- сертифіката з чотирма знаками, тут ЧВОПА з шістьма, і зайва точність
-- не примха — на десятках тисяч одиниць четвертий знак розходиться на
-- гривні. Зв'язок між трьома числами:
--   amount(коп)  = units_e6 * nav_e6 / 10^10
--   nav_e6       = amount * 10^10 / units_e6   -- ЧВОПА, виведена з операції
-- Друга формула й робить окреме джерело котирувань непотрібним: кожен
-- внесок приносить ЧВОПА на свою дату з собою, як виписка фонду приносить
-- ціну сертифіката.

-- Адміністратор — ТЕКСТ, а не FK на brokers, і це навмисно. Коментар до
-- 0013 визначає brokers як рахунки, чий баланс рухається («розміщення
-- вкладу дебетує його баланс»), — а баланс адміністратора НПФ не мій, з
-- нього нічого не списати. У brokers він лише виліз би у випадайках
-- лотів і вкладів як фальшивий рахунок. Концентрацію за контрагентом
-- дає вимір isin ключем npf:<name>, де вона й доречна.
--
-- credit_rate_bp — ставка ПДФО-знижки на внески × 100 (18% = 1800). Не
-- зашита в код з тієї ж причини, що income_tax_bp у 0022: це властивість
-- закону й мого доходу, а не застосунку, і завтра вона інша.
--
-- contrib_day — число місяця, коли я планую вносити. Потрібне лише
-- нагадуванню («цього місяця внеску ще нема»); нуль = не нагадувати.
-- Вивести його з операцій НЕ можна: один внесок ритму не задає, а два
-- поспіль розходяться через вихідні — та сама причина, через яку
-- FundPosition.PayoutDay береться з довідника, а не з виплат.
--
-- yield_simple_years — як у 0022: ненульове означає, що обіцянка задана
-- ПРОСТОЮ середньорічною за стільки років, нуль — складна.
CREATE TABLE npf_accounts (
    id                 INTEGER PRIMARY KEY AUTOINCREMENT,
    name               TEXT    NOT NULL UNIQUE,
    administrator      TEXT    NOT NULL DEFAULT '',
    currency           TEXT    NOT NULL DEFAULT 'UAH',
    nav_e6             INTEGER NOT NULL DEFAULT 0,
    nav_date           TEXT    NOT NULL DEFAULT '',
    expected_yield_bp  INTEGER NOT NULL DEFAULT 0,
    yield_simple_years INTEGER NOT NULL DEFAULT 0,
    access_date        TEXT    NOT NULL DEFAULT '',
    income_tax_bp      INTEGER NOT NULL DEFAULT 0,
    credit_rate_bp     INTEGER NOT NULL DEFAULT 0,
    contrib_day        INTEGER NOT NULL DEFAULT 0,
    note               TEXT    NOT NULL DEFAULT ''
) STRICT;

-- Журнал внесків. Один вид операції, тож поля kind тут немає: продажу в
-- НПФ не існує, дивідендів не існує, а виплата на пенсії — це інша
-- сутність з іншим графіком, і коли вона зʼявиться, вона зʼявиться
-- окремо, а не сьомим значенням у enum.
--
-- broker_id — ЗВІДКИ пішли гроші, тобто рахунок, чий баланс дебетується.
-- Це інший сенс, ніж administrator вище: там контрагент, який тримає мої
-- активи, тут мій рахунок, з якого списано. NULL = не привʼязано.
--
-- Ціна за одиницю навмисно не зберігається: вона завжди виводиться з
-- amount і units_e6, і окреме поле лише дало б їм розійтись — те саме
-- правило, що записане в шапці 0009 для fund_ops.
CREATE TABLE npf_ops (
    id        INTEGER PRIMARY KEY AUTOINCREMENT,
    npf_id    INTEGER NOT NULL REFERENCES npf_accounts(id),
    date      TEXT    NOT NULL,
    units_e6  INTEGER NOT NULL,
    amount    INTEGER NOT NULL,
    broker_id INTEGER REFERENCES brokers(id),
    note      TEXT    NOT NULL DEFAULT ''
) STRICT;

CREATE INDEX idx_npf_ops_npf_date ON npf_ops(npf_id, date);

-- Точки ЧВОПА, не привʼязані до моїх операцій.
--
-- Фонди історії цін не тримають, і в шапці domain/funds.go сказано чому:
-- виписка приносить ціну з собою, тож окреме джерело котирувань не
-- потрібне. Для НПФ цей аргумент не діє, і з двох причин:
--
--   * операцій щонайбільше дванадцять на рік проти десятків імпортованих
--     рядків у фонда — точок замало навіть на криву;
--   * фонд публікує ЧВОПА з 2006 року, тобто задовго до мого першого
--     внеску. Без цієї таблиці track record фонду не побачити взагалі, а
--     він і є єдиною підставою для expected_yield_bp.
--
-- Саме тому тут ще й пара «обіцяно / фактично» стає можливою: доки точок
-- менше двох, показуємо обіцянку і кажемо про це вголос (yield_basis),
-- від двох — виміряне зростання ЧВОПА, яке обіцянку витісняє. Те саме
-- правило витіснення, що в state_funds.go для FundTotalReturn.
--
-- UNIQUE(npf_id, date): дві різні ЧВОПА на один день — це не історія, а
-- суперечність. Вклеювання пачкою покладається на це й перезаписує день.
CREATE TABLE npf_nav (
    id     INTEGER PRIMARY KEY AUTOINCREMENT,
    npf_id INTEGER NOT NULL REFERENCES npf_accounts(id),
    date   TEXT    NOT NULL,
    nav_e6 INTEGER NOT NULL,
    UNIQUE(npf_id, date)
) STRICT;
