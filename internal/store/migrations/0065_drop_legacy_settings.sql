-- Спадкові ключі налаштувань більше не читаються — прибираємо й самі рядки.
--
-- goal_pessimistic/realistic/optimistic_uah лишились після 0008 (одна
-- ціль замість трьох), monthly_expenses_uah — після 0038 (витрати з
-- валютою). Обидві міграції скопіювали значення в нові ключі, і ті ключі
-- відтоді єдине джерело: запасне читання старих обслуговувало базу, яка
-- міграцій ще не пройшла, а такої не буває — міграції біжать на кожному
-- відкритті.
--
-- Запасне читання мало й власну ціну: очищена ціль мовчки поверталась зі
-- старої «оптимістичної» суми, бо порожнє нове поле читалось як «візьми
-- спадкове».
--
-- Поле monthly_expenses_uah У ДОКУМЕНТІ лишається: це виведена гривнева
-- сума витрат (settings.ResolveExpensesUAH), і її читають вісім місць та
-- інтеграція HA. Зникає лише однойменний рядок у сховищі.

DELETE FROM settings WHERE key IN (
    'goal_pessimistic_uah', 'goal_realistic_uah', 'goal_optimistic_uah',
    'monthly_expenses_uah'
);
