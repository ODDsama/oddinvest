-- Секрети застосунку: хеш пароля, ключ підпису сесій, хеш токена HA,
-- реквізити тунелю Cloudflare.
--
-- ЧОМУ НЕ settings. Таблиця settings цілком іде в бекап (ExportAll), у
-- добовий JSON-дамп поруч із базою і назад через POST /api/restore, а
-- GET /api/settings віддає всі ключі реєстру відкритим текстом. Жодне з
-- цих трьох місць секрету не витримує: дамп лежить файлом, бекап
-- завантажують у браузер, а відновлення чужої копії підмінило б пароль.
--
-- ЧОМУ НЕ В БЕКАПІ. Секрети — не дані портфеля: відновлення на іншій
-- машині не має ані заносити чужий пароль, ані вибивати свій. Таблиця
-- названа в derivedTables (backup_coverage_test.go), і саме так
-- «свідомо не в бекапі» відрізняється від «забули».
--
-- Пароль зберігається лише хешем (PBKDF2-SHA256, сіль на кожен), токен HA
-- — лише SHA-256; API-токен Cloudflare і токен конектора — відкритим
-- текстом, бо ними треба користуватись, а не звіряти. Назовні жоден із них
-- не віддається (API каже лише «є/немає»).
CREATE TABLE secrets (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at TEXT NOT NULL
) STRICT;
