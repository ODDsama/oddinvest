-- Дві властивості ДОГОВОРУ вкладу, яких застосунок доти не знав.
--
-- 1. is_reserve — цей вклад є подушкою, а не інвестицією.
--
-- Доти резерв був журналом рухів із текстовим «де лежить», а вклад —
-- окремою сутністю зі ставкою й датою. Покласти подушку на депозит
-- означало або записати її двічі (і роздути капітал), або записати
-- вкладом і втратити те, що це подушка. Обидва варіанти брехали.
--
-- Позначений вклад іде тілом у резерв, а не у вклади: він виходить зі
-- знаменника видів (у подушки своя, абсолютна ціль у місяцях витрат) і
-- перестає бути кандидатом реінвесту — купувати папір за аварійні гроші
-- помічник не має права.
--
-- 2. revocable — договір дозволяє забрати гроші достроково.
--
-- Дефолт нуля тут не «про всяк випадок», а ЗАКОН: за ЦКУ строковий вклад
-- фізособи безвідкличний, і дострокове повернення можливе лише там, де це
-- прямо написано в договорі. Той самий нуль дорівнює тому, як застосунок
-- трактував усі вклади доти (Liquidity.LockedUAH — «доведеться щось
-- ламати»), тож наявні дані лишаються описаними правильно, а прапорець
-- лише дозволяє сказати «мій договір дозволяє».
--
-- Різниця між ними в подушці вирішує все. Відкличний вклад — це ШТРАФ:
-- тіло повернуть, відсотки згорять. Безвідкличний — справжній ЗАМОК до
-- дати погашення, і подушка, замкнена глибше, ніж витрачається, не
-- подушка взагалі. Це два різні стани, і без колонки вони були одним.
--
-- Автозаповнення за фактом тут немає, на відміну від 0015: там
-- поповнення в базі ДОВОДИЛО, що вклад поповнюваний, а тут доказу немає
-- з жодного боку. Дострокове розірвання (closed_date) не доводить
-- відкличності: банк міг піти назустріч поза договором.
ALTER TABLE term_deposits ADD COLUMN is_reserve INTEGER NOT NULL DEFAULT 0;
ALTER TABLE term_deposits ADD COLUMN revocable INTEGER NOT NULL DEFAULT 0;
