-- Цілі накопичення в добовому знімку.
--
-- Та сама діра, що вже була тричі — з фондами (0012), вкладами (0016) і
-- резервом (0021), — і з тієї ж причини: знімок завели, коли цієї сутності
-- ще не існувало.
--
-- Без колонки наслідок гірший за «крива нижча за факт». `capital_uah`
-- знімка складається з частин, і цілі мовчки влились би в загальну суму
-- без власного рядка — тобто «Підсумок місяця» показував би приріст
-- капіталу в місяць, коли людина просто відклала на авто, і пояснити цей
-- приріст не було б чим.
--
-- Старі рядки лишаються з нулем. Це не спотворення, а факт: у ті дні цілей
-- у знімку ніхто не рахував. UI зобовʼязаний казати «тоді не рахували», а
-- не «тоді не було».
ALTER TABLE snapshots ADD COLUMN goals_uah INTEGER NOT NULL DEFAULT 0;
