-- plan_buys.broker: вільний текст -> broker_id.
--
-- ЦЕ ДОРОБКА 0010, А НЕ НОВЕ РІШЕННЯ. Та міграція прибрала назву брокера
-- рядком із чотирьох таблиць і пояснила чому: «кілька значень в одній
-- комірці — це порушення навіть 1NF, і перейменувати брокера означало
-- руками пройтись по чотирьох таблицях». 0033 завела plan_buys через
-- двадцять три міграції після того — і знову з колонкою `broker TEXT`.
--
-- Ціна була та сама, що й до 0010, лише тихіша: RenameBroker (store/refs.go)
-- міняє brokers.name, і всі, хто тримається за broker_id, підхоплюють
-- перейменування задарма. plan_buys не тримався — тож виправлення описки
-- в довіднику мовчки відчіплювало план купівель від рахунку, і pickBroker
-- переставав знаходити залишок там, де він насправді лежить.
--
-- '' -> NULL. Порожній рядок означав «обрати рахунок за залишком»
-- (pickBroker), і цю роль тепер бере NULL — те саме, що в lots, deposits
-- і term_deposits, де «не привʼязано» це теж NULL.
--
-- ЧОМУ ADD/DROP COLUMN, А НЕ ПЕРЕБУДОВА. Не через зовнішні ключі — на
-- plan_buys ніхто не посилається, тож заборона з 0010 сюди не діє. Через
-- документацію: у CREATE TABLE цієї таблиці живе сорок рядків коментарів
-- про те, чому мір дві, чому unit_price не дозволена паперу й чому минула
-- дата не приймається. Перебудова замінила б збережений текст схеми на
-- голі колонки, а довід про це вціліє лише в 0033, куди по нього ніхто не
-- піде. Прийом узятий звідти ж, звідки й привід, — з 0010.

ALTER TABLE plan_buys ADD COLUMN broker_id INTEGER REFERENCES brokers(id);

-- Назви в plan_buys заводились тим самим полем випадайки, що й усюди, тож
-- звірка за точною назвою знайде все, що справді вказує на брокера. Те,
-- що не знайшлось, лишається NULL — тобто «обрати за залишком», найм'якіший
-- із можливих наслідків: план не зникає, а лише перестає наполягати на
-- рахунку, якого в довіднику немає.
UPDATE plan_buys SET broker_id = (
    SELECT b.id FROM brokers b WHERE b.name = TRIM(plan_buys.broker)
) WHERE TRIM(broker) <> '';

ALTER TABLE plan_buys DROP COLUMN broker;

-- Індекс під щойно створений ключ — з тим самим доводом, що й п'ять у
-- 0042: дочірню сторону FK база не індексує сама, а `DELETE FROM brokers`
-- (у тому числі 26 разів усередині кожного відновлення) без нього робить
-- повний скан. Тут він у тій самій міграції, що й колонка, саме щоб
-- колонка й індекс не роз'їхались у часі — як це вже сталося з п'ятьма
-- іншими.
CREATE INDEX idx_plan_buys_broker ON plan_buys(broker_id);
