-- Податок на відсотки вкладу — «за законом»: ставкою на дату КОЖНОЇ
-- виплати, а не одним числом на вклад.
--
-- 0050 переписала старий дефолт 19,5% на 23% і назвала ціну вголос:
-- вклад, що платив до грудня 2024, отримав завищений історичний податок,
-- а договір через межу не описувався жодною з двох ставок. Тепер межа
-- живе в коді (domain.DepositTaxBPOn: до 2024-12-01 — 19,5%, далі — 23%),
-- а в записі — сентинел −1 «за законом» (domain.TaxBPByLaw).
--
-- Чіпаємо рівно законні ставки — 2300 і 1950. Перша — дефолт форми з
-- 0050 і після неї; друга може приїхати з відновленого старого дампу.
-- Будь-яке інше число (пільговий договір, «без податку» нулем) — вибір
-- власника, і міграція його не знає, тож не чіпає.
--
-- CHECK на tax_bp у таблиці немає (0013), тож −1 лягає без перебудови.
UPDATE term_deposits SET tax_bp = -1 WHERE tax_bp IN (2300, 1950);
