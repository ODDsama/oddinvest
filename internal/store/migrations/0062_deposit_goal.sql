-- goal_id — цей вклад належить ЦІЛІ НАКОПИЧЕННЯ, а не портфелю.
--
-- Дзеркало is_reserve з 0032, і заведене з того самого доводу: покласти
-- цільові гроші на депозит доти означало або записати їх двічі (і роздути
-- капітал), або записати вкладом і втратити те, що це гроші на авто.
--
-- ЧОМУ НЕ ПРАПОРЕЦЬ, ЯК У ПОДУШКИ. Подушка одна, тож їй вистачає
-- булевого is_reserve. Цілей багато — «на авто» і «на ремонт» лежать
-- різними вкладами, — і прапорець не зміг би сказати, ЧИЇ це гроші.
-- Прогрес цілі, її розрив і темп рахуються по кожній окремо, тож
-- посилання тут обовʼязкове, а не зручне.
--
-- Чого це коштує на екранах: тіло позначеного вкладу йде в
-- Capital.GoalsUAH замість вкладів (виходить зі знаменника видів рівно
-- як резервний), перестає бути кандидатом реінвесту (купувати папір за
-- гроші, обіцяні авто, помічник не має права — той самий аргумент, що в
-- шапці handlers_reserve.go) і дістає задачу «перевкласти сходинку» на
-- погашенні.
--
-- ЩО ЦЕ ЛАГОДИТЬ, і це головне. Доти цільові гроші лежали ЧИСТОЮ
-- ГОТІВКОЮ під 0% — вкладу в них не було взагалі, — тоді як ціна самої
-- цілі росла на інфляцію. Пʼятирічна ціль так гарантовано програвала
-- ~40% своєї ціни, і застосунок при цьому казав «темп тримається», бо
-- потрібний темп рахувався від НЕРУХОМОЇ сьогоднішньої ціни. Колонка
-- дає цим грошам ставку, а derive.go — вирок, який її враховує.
--
-- Взаємовиключності з is_reserve на рівні CHECK немає навмисно: її
-- стереже хендлер і віддає зрозумілу 400. Той самий вибір, що всюди в
-- цьому застосунку — зрозуміла помилка замість тихої відмови БД.
--
-- NULL (а не 0) = вклад нічий, тобто звичайна інвестиція. Нуль тут був
-- би id-ом, якого не буває, і FK на нього однаково не зійшовся б.
ALTER TABLE term_deposits ADD COLUMN goal_id INTEGER REFERENCES goals(id);

-- Індекс на FK — вимога 0042: без нього видалення цілі сканує всю
-- таблицю вкладів, а SQLite про це не попереджає.
CREATE INDEX idx_term_deposits_goal ON term_deposits(goal_id);
