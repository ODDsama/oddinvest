-- Профіль імпорту читає виписку КАРТКИ (фаза 28, E).
--
-- Виписка банку — не виписка брокера: у ній немає паперів і кількостей,
-- зате є те, чого немає в брокерській, — ЗАЛИШОК ПІСЛЯ ОПЕРАЦІЇ в кожному
-- рядку та MCC. Залишок останнього рядка і є звіркою картки (debt_marks),
-- а MCC відрізняє зняття готівки (під відсотком з першого дня) від
-- покупки (пільговий оборот). Три колонки, а не новий вид профілю:
-- розкладка колонок та сама, і читач CSV той самий; різниться лише те,
-- куди лягають рядки, — а це вирішує debt_id.
--
-- debt_id — до якої картки привʼязаний профіль. 0 = не картковий профіль
-- (як було). Без FK навмисно: import_profiles — конфіг, а не журнал, і
-- видалена картка не має тягти за собою розкладку колонок, яку людина
-- вивіряла півгодини; імпорт за профілем із неіснуючою карткою просто
-- відмовляє з названою причиною.
--
-- Чого тут свідомо НЕМАЄ: колонки для суми виписки (statement_due). CSV
-- банку її не несе, і звірка без неї — не звірка: StatementDue = 0
-- мовчки сховав би задачу «внести до розрахункової дати». Тому суму
-- виписки людина вводить у превʼю імпорту руками, і звірка пишеться
-- лише з нею.
ALTER TABLE import_profiles ADD COLUMN col_balance INTEGER NOT NULL DEFAULT -1;
ALTER TABLE import_profiles ADD COLUMN col_mcc INTEGER NOT NULL DEFAULT -1;
ALTER TABLE import_profiles ADD COLUMN debt_id INTEGER NOT NULL DEFAULT 0;
