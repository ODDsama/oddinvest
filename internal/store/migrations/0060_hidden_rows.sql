-- Рядки майстер-списку, які власник відмітив «не показувати».
--
-- # ЧОМУ НЕ ЕВРИСТИКА ПРО НУЛЬ
--
-- Перше, чого хотілось, — ховати те, у чому нуль: закритий фонд, порожній
-- рахунок НПФ. Це неправильно рівно з двох боків. Щойно заведений фонд теж
-- нульовий — і зник би зі списку саме тоді, коли на нього дивляться
-- найпильніше; а фонд, у якому лишився один сертифікат, нікуди б не подівся,
-- хоч дивитись на нього щодня вже нема чого. «Показувати» — це рішення
-- людини про конкретний рядок, а не властивість числа в ньому.
--
-- # ЧОМУ ТАБЛИЦЯ, А НЕ КЛЮЧ В app_state
--
-- Поруч уже лежить розкладка списку — порядок рядків (`nav_order`,
-- api/handlers_navorder.go), і спокуса покласти позначку туди ж велика.
-- Вона хибна: app_state за власним визначенням (шапка store.go) тримає те,
-- що належить ІНСТАЛЯЦІЇ, а не портфелю, і саме тому порядок вкладок там і
-- живе — перемикання портфеля не має перетасовувати список.
--
-- «fund:Inzhur Ocean» же осмислений лише всередині свого портфеля. Ключ без
-- розділення портфелів сховав би однойменний фонд і в дружини — мовчки, бо
-- жодного повідомлення про приховане не існує за задумом.
--
-- # ЧОМУ НЕ settings
--
-- Той самий довід, що в navorder: settings — фінансова політика за суворим
-- білим списком (settings_registry.go), і ключ про лівий список серед
-- ставок і лімітів стояв би не на своєму місці.
--
-- # ЩО САМЕ ЛЕЖИТЬ У row_id
--
-- Ідентифікатор рядка з web/js/master.js: "bond:UA4000237416",
-- "fund:Inzhur Ocean", "npf:ВПФ Династія", "deposit:7", "goal:3", "reserve".
-- База про них не знає нічого й не має знати — довід повністю в шапці
-- api/handlers_hidden.go. Тому TEXT без CHECK: перевіряти тут значення
-- означало б завести другу копію дерева з master.js.
--
-- Наслідок, який варто назвати: фонд і рахунок НПФ ідентифікуються НАЗВОЮ,
-- тож перейменування фонду знімає з нього позначку. Це не втрата даних —
-- рядок просто повертається в список, і сховати його знову коштує двох
-- натискань. Тримати натомість числовий id довелось би для сутностей, у
-- яких його в списку немає взагалі (резерв), тобто заводити другий спосіб
-- адресації рядка заради одного рідкісного випадку.
CREATE TABLE hidden_rows (
    portfolio_id INTEGER NOT NULL REFERENCES portfolios(id) ON DELETE CASCADE,
    row_id       TEXT    NOT NULL,
    PRIMARY KEY (portfolio_id, row_id)
) STRICT;
