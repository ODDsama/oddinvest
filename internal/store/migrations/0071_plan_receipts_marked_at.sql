-- Мить, коли надходження відмітили отриманим.
--
-- Відмітка знає лише МІСЯЦЬ (0027 пояснює чому), і доти цього вистачало:
-- частку в портфель і дозволені кошики вже отриманого надходження поточний
-- місяць однаково читав із ТЕПЕРІШНЬОГО потоку. Саме це й було вадою.
-- Власник 25 листопада перерозподілив, скільки з якого надходження йде в
-- кошики, — і ціль листопада перерахувалась, хоча всі надходження місяця
-- вже прийшли й були розкладені за старим розподілом.
--
-- Тепер отримане рахується за тією ревізією потоку, яка діяла на момент
-- приходу (engine.planFlowsArrived). Момент — кінець платіжного дня, і для
-- більшості випадків колонка не потрібна взагалі. Потрібна вона рівно для
-- одного: зарплата прийшла РАНІШЕ свого дня, її відмітили, а частку змінили
-- ще до платіжного дня. Без миті відмітки така правка переписала б уже
-- отримане — ту саму ваду, лише у вужчому вікні.
--
-- Порожній рядок — «невідомо»: усі відмітки, зроблені до цієї міграції.
-- Вони падають на кінець платіжного дня, тобто поводяться так, ніби
-- колонки немає. Вигадувати їм мить (now, перше число місяця) означало б
-- записати в базу факт, якого ніхто не спостерігав.
--
-- RFC3339 в UTC — той самий запис, що в plan_flow_revisions.changed_at,
-- бо порівнюються вони саме між собою.
