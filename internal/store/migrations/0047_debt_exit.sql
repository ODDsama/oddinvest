-- Ціль виходу з кредитного ліміту: дата, до якої баланс має стати нулем.
--
-- ЧОМУ ЦЕ НЕ НАЛЕЖИТЬ ДО ЧЕРГИ ПОГАШЕННЯ. Черга (0045) відповідає на
-- питання про АМОРТИЗАЦІЮ: борг має графік, платежі його гасять, і
-- порядок вирішує ставка. Кредитний ліміт поводиться інакше — зарплата
-- падає на картку плюсом, життя списується мінусом, баланс осцилює. Вийти
-- з ліміту означає не «сплатити графік», а зробити так, щоб дно перестало
-- бути відʼємним, і важіль тут не ставка, а ВИТРАТИ.
--
-- ЧОМУ ДАТА, А НЕ КІЛЬКІСТЬ МІСЯЦІВ (рішення власника). «За два місяці»
-- щомісяця означає іншу дату: ціль тікала б поперед темпу рівно з тією
-- швидкістю, з якою до неї йдуть, і відставання не зʼявилось би ніколи.
-- Дата стоїть на місці й дозволяє сказати «не встигаєш».
--
-- ПОРОЖНЬО = РЕЖИМУ НЕМАЄ. Перемикачем служить саме поле — той самий
-- прийом, що з npf_credit_pdfo_year_uah: окремий булевий прапорець поруч
-- був би другим джерелом одного стану, і вони розійшлися б.
--
