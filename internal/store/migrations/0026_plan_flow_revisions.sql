-- Журнал ревізій джерел доходу.
--
-- Проблема, яку він закриває, стара рівно настільки, скільки існує картка
-- «План проти факту»: план за минулий місяць виводився з СЬОГОДНІШНЬОЇ
-- таблиці потоків, тож виправлена на місці зарплата робила вигляд, ніби
-- вона була такою завжди. Довідка про це попереджала, але попередження —
-- не рішення: його читають один раз, а помиляються потім.
--
-- Тепер кожна правка потоку — записана подія з міткою часу, і місяці ДО
-- неї читаються з тієї ревізії, яка діяла тоді. Минуле більше не
-- виводиться, воно читається.
--
-- Це та сама ідея, що вже стоїть за month_target_uah у знімках («те, що
-- застосунок вважав ціллю ТОГО дня»), тільки не числом на день, а станом
-- рядка на момент: із потоків числа виводяться по-різному для різних
-- питань, тож зберігати треба саме рядок.
--
-- Широка таблиця, а не params TEXT (JSON) — з тієї самої причини, що
-- записана в 0025_plan.sql: решта бази типізована колонка за колонкою, а
-- JSON у TEXT не грепається й мовчки ковтає описку в імені поля.
CREATE TABLE plan_flow_revisions (
    id      INTEGER PRIMARY KEY AUTOINCREMENT,
    flow_id INTEGER NOT NULL,
    -- Момент правки, RFC3339 UTC. Саме момент, а не дата: за один день
    -- правок буває кілька, і порядок між ними — це те, що відрізняє
    -- «підвищив, потім передумав» від «передумав, потім підвищив».
    changed_at TEXT NOT NULL,
    -- seed   — стан на момент появи журналу (див. засів нижче);
    -- create — потік заведено; update — змінено; delete — видалено.
    op TEXT NOT NULL,
    -- Знімок потоку ПІСЛЯ правки. Для delete — останній відомий стан:
    -- журнал мусить пам'ятати, ЩО саме зникло, інакше видалення
    -- відрізнялось би від «ніколи не було».
    --
    -- Зовнішнього ключа на plan_flows навмисно немає: рядок журналу
    -- переживає той потік, про який він розповідає.
    name       TEXT    NOT NULL,
    kind       TEXT    NOT NULL,
    amount     INTEGER NOT NULL,
    currency   TEXT    NOT NULL,
    cadence    TEXT    NOT NULL,
    from_date  TEXT    NOT NULL,
    until_date TEXT    NOT NULL DEFAULT '',
    growth_bp  INTEGER NOT NULL DEFAULT 0,
    invest_bp  INTEGER NOT NULL DEFAULT 10000,
    note       TEXT    NOT NULL DEFAULT ''
) STRICT;

CREATE INDEX idx_plan_flow_rev_at ON plan_flow_revisions(changed_at);
CREATE INDEX idx_plan_flow_rev_flow ON plan_flow_revisions(flow_id, changed_at);

-- Засів: по одній ревізії на кожен наявний потік.
--
-- Без нього реконструкція на будь-яку дату після цієї міграції повертала б
-- ПОРОЖНІЙ план: потоки, яких ніколи не редагували, не мали б жодної
-- ревізії, і картка показала б нуль там, де зарплата була.
--
-- changed_at — саме «зараз», а НЕ from_date потоку, і це головне рішення
-- цієї міграції. from_date означав би заяву «цей потік увесь час був
-- таким» — рівно те припущення, від якого журнал і рятує. Наслідок чесний
-- і видимий: місяці до цього моменту картка малює контуром і каже, що план
-- за них виведено, а не записано. Місяць за місяцем це заростає саме.
--
-- datetime('now') робить міграцію невідтворюваною — той самий компроміс,
-- що вже прийнятий у 0011 (див. коментар у migrate.go). Тут він
-- неминучий: момент появи журналу — це і є момент, коли її застосували.
INSERT INTO plan_flow_revisions
    (flow_id, changed_at, op, name, kind, amount, currency, cadence,
     from_date, until_date, growth_bp, invest_bp, note)
SELECT id, strftime('%Y-%m-%dT%H:%M:%SZ', 'now'), 'seed', name, kind, amount,
       currency, cadence, from_date, until_date, growth_bp, invest_bp, note
FROM plan_flows;
