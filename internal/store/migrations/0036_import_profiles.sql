-- Профілі імпорту: як читати виписку НЕ від Inzhur.
--
-- НАВІЩО. internal/imports розумів рівно один формат, і будь-який інший
-- брокер означав ручне введення кожного лота. Причому перегляд перед
-- записом, дедуплікація, водяний знак і виявлення конфліктів із ручними
-- рухами вже були — вони не залежать від формату взагалі. Бракувало
-- єдиного: способу сказати, у якій колонці дата, а в якій сума.
--
-- ЧОМУ ТАБЛИЦЯ, А НЕ НАЛАШТУВАННЯ. Реєстр налаштувань
-- (api/settings_registry.go) — це фіксований перелік НАЗВАНИХ ключів, і
-- саме на цьому стоїть його гарантія: він драйвить валідацію, SettingsDoc
-- і тест узгодженості схеми. Ключі виду import_profile:<брокер>
-- зʼявляються з нізвідки під час роботи, тобто ламають рівно ту
-- властивість, заради якої реєстр існує.
--
-- ЧОМУ INZHUR СЮДИ НЕ ПЕРЕЇХАВ. Спокуса зробити його «просто ще одним
-- профілем» велика, і плану це навіть обіцяв — але виписка Inzhur не
-- зводиться до зіставлення колонок, і от чому. Кількість сертифікатів
-- лежить УСЕРЕДИНІ тексту операції («Купівля 123 сертифікати…»), а не в
-- своїй колонці. Податок стоїть окремим рядком і має прилипнути до
-- найближчої оподатковуваної події того самого фонду. Порядок рядків
-- задає серійний номер Excel, бо в даті немає часу, а податок і його
-- подія стоять в одному дні. Щоб профіль це виразив, у нього довелось би
-- вбудувати три гачки, потрібні рівно одному брокерові, — тобто порожні
-- шви (CLAUDE.md §3) для всіх інших.
--
-- Тому Inzhur лишається окремим розбирачем, а спільним стало те, що
-- справді спільне: рядок результату, пропуски з причиною, розбір грошей і
-- дат. Ціна названа: два шляхи розбору замість одного.
CREATE TABLE import_profiles (
    -- Ім'я — і ключ, і те, що видно в списку. Як у funds і brokers поруч:
    -- бекап тримається назв, і саме тому переживає нормалізацію.
    name TEXT PRIMARY KEY,
    -- format — xlsx | csv. Читач файлу, а не розкладка колонок: та сама
    -- виписка часто доступна в обох виглядах.
    format TEXT NOT NULL DEFAULT 'xlsx',
    -- header — скільки рядків шапки пропустити. Не завжди один: буває
    -- назва брокера рядком вище, буває порожній рядок під заголовком.
    header INTEGER NOT NULL DEFAULT 1,
    -- Індекси колонок, 0-based; -1 означає «колонки немає».
    --
    -- Дебет і кредит окремо, а не одна колонка зі знаком: так їх пишуть
    -- банки й брокери, і зводити їх у знак на вході означало б вирішувати
    -- за брокера, що вважати додатним. Коли колонка одна, її кладуть у
    -- debit, а credit лишають -1.
    col_date   INTEGER NOT NULL DEFAULT 0,
    col_op     INTEGER NOT NULL DEFAULT 1,
    col_ref    INTEGER NOT NULL DEFAULT -1,
    col_qty    INTEGER NOT NULL DEFAULT -1,
    col_debit  INTEGER NOT NULL DEFAULT -1,
    col_credit INTEGER NOT NULL DEFAULT -1,
    -- ops — словник «як брокер називає операцію» → «чим вона є у нас»,
    -- рядками виду «Купівля цінних паперів = bond_buy».
    --
    -- Текстом, а не JSON і не окремою таблицею. Це КОНФІГ, який людина
    -- пише руками, дивлячись у власну виписку, і в такому вигляді його
    -- видно цілком в одному полі форми. Окрема таблиця дала б четвертий
    -- набір КРУД-хендлерів заради словника на десять рядків; JSON —
    -- формат, у якому одруківку видно лише за помилкою розбору.
    ops TEXT NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT ''
) STRICT;
