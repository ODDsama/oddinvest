-- Журнал рішень: що радив помічник у той день, коли ти купував.
--
-- НАВІЩО. Помічник ранжує чотири види інструментів однією реальною
-- дохідністю й ніколи не звітує, чи його поради працювали. Через це вибір
-- режиму рейтингу (reinvest_rank у settings_registry.go) нічим не
-- підкріплений: три названі режими, і жодного способу дізнатись, який із
-- них тобі підходить. Журнал закриває саме це — не «скільки я заробив»
-- (на це є XIRR), а «наскільки обіцянка справдилась і наскільки я їй
-- слідую».
--
-- ЧОМУ ЦЕ НЕ ВИВОДИТЬСЯ З НАЯВНОГО. Рейтинг перераховується щодня з
-- поточного довідника, курсів і часток. Учорашній не відновлюється ніяк:
-- аукціонні рівні змінились, ліміти зрушились, папір міг зникнути з
-- обігу. Рядок тут — ЗНІМОК моменту рішення, і саме тому він пишеться
-- один раз і не оновлюється ніколи.
--
-- ЩО САМЕ ЗБЕРІГАЄМО, І ЧОМУ НЕ ВЕСЬ РЕЙТИНГ. Спокуса покласти сюди
-- JSON із топ-N альтернатив велика: «раптом знадобиться». Але споживач
-- один, і читає він рівно три числа — яким рядком стояв обраний, що
-- стояло першим і під скільки. Решта списку була б порожнім швом
-- (CLAUDE.md §3): зразком, який наступний автор почне тиражувати, не
-- маючи жодного читача.
--
-- ЧОГО ТУТ СВІДОМО НЕМАЄ.
--
-- Дохідності «за фактом» — вона не зберігається, а РАХУЄТЬСЯ на льоту з
-- лота й виплат (domain.PortfolioFlows + XIRR). Записана сюди, вона
-- застаріла б наступного ж дня, і журнал показував би вчорашню правду з
-- виглядом сьогоднішньої.
--
-- Рішень про ПРОДАЖ — продаж має власну арифметику (RealizedResult) і
-- власне питання. Помічник продажів не радить (пороги перекладання — це
-- факт про ціну, а не рядок рейтингу), тож «чи послухався» тут не має
-- сенсу.
--
-- Рішень з ІМПОРТУ виписки — операції фондів приїжджають файлом пачкою,
-- заднім числом і без моменту рішення. Записати їх сюди означало б
-- назвати рішенням те, що ним не було; хук стоїть у POST /api/funds,
-- куди веде лише «Виконано» з плану купівель.
CREATE TABLE decisions (
    id      INTEGER PRIMARY KEY AUTOINCREMENT,
    made_on TEXT    NOT NULL,             -- день рішення, ISO
    -- kind і ref — у тих самих словах, що plan_buys (0033) і /api/reinvest:
    -- bond → ISIN, fund → назва фонду, deposit → банк, npf → назва рахунку.
    -- Три різні словники довелось би перекладати один в одний на кожному
    -- кроці, і саме це вже було причиною спільного kind у 0033.
    kind     TEXT    NOT NULL,
    ref      TEXT    NOT NULL,
    currency TEXT    NOT NULL,
    amount   INTEGER NOT NULL DEFAULT 0,  -- мінорні: скільки грошей пішло
    -- real_pct — ОБІЦЯНКА обраного на момент рішення, %. Саме реальна
    -- (після податку й знецінення): лише вона порівнянна між видами й
    -- валютами, і саме за нею впорядкований рейтинг.
    real_pct REAL    NOT NULL,
    -- rank_pos — яким рядком обране стояло в рейтингу; 1 = верхній.
    -- top_* — що стояло першим і під скільки. Разом вони й відповідають
    -- на «чи слухаюсь я власного помічника, і чого це коштує».
    --
    -- top_label порожній, коли обране САМЕ й стояло першим: дублювати
    -- рядок сам у себе означало б показати «віддав перевагу X замість X».
    rank_pos     INTEGER NOT NULL DEFAULT 0,
    top_label    TEXT    NOT NULL DEFAULT '',
    top_real_pct REAL    NOT NULL DEFAULT 0,
    -- rank_mode — який режим рейтингу діяв. Без нього порівняння режимів
    -- між собою неможливе, а воно і є головна причина існування журналу.
    rank_mode TEXT NOT NULL DEFAULT '',
    -- op_id — на що рішення перетворилось: лот, операція фонду, вклад,
    -- внесок у НПФ. Яка саме таблиця, каже kind — окремої колонки на
    -- кожну не заводимо з тієї ж причини, що й у plan_buys.
    --
    -- Посилання БЕЗ зовнішнього ключа й без каскаду навмисно: видалений
    -- лот не скасовує того, що рішення було прийняте. Журнал описує
    -- МИНУЛЕ, а минуле не редагується разом із портфелем.
    op_id INTEGER NOT NULL DEFAULT 0,
    note  TEXT    NOT NULL DEFAULT ''
) STRICT;

-- Читається журнал завжди в хронологічному порядку.
CREATE INDEX idx_decisions_made_on ON decisions(made_on);
