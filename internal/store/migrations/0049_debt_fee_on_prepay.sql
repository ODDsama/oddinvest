-- Що робить дострокове погашення з КОМІСІЄЮ розстрочки.
--
-- ЧОМУ БЕЗ ЦЬОГО ПОЛЯ ЗАСТОСУНОК БРЕХАВ. Прохід уперед (api/payoff.go)
-- вважав, що комісія нараховується щомісяця, доки розстрочка жива, тож
-- закрити її на три місяці раніше означає не заплатити трьох комісій. Для
-- частини договорів це неправда: банк рахує комісії за ВЕСЬ строк одразу, і
-- сума дострокового погашення дорівнює залишку тіла ПЛЮС усі майбутні
-- комісії. Спіймано вживу на розстрочках власника в mono: сторінка обіцяла
-- «на 1 083 ₴ дешевше» там, де економія дорівнює нулю, а гроші лише йшли б
-- від власника раніше. Порада, строго гірша за бездіяльність, названа
-- економією, — найдорожча з можливих помилок цього екрана.
--
-- ТРИ СТАНИ, А НЕ ДВА, і третій не зайвий:
--
--   cancel — комісії майбутніх місяців скасовуються (припущення, яке діяло
--            досі й лишається правдою для товарних розстрочок «частинами»);
--   keep   — банк бере комісії за всі місяці однаково;
--   ''     — не з'ясовано.
--
-- Порожнє поводиться як keep, а не як cancel. Довід той самий, що при
-- payoffGraceCost: обіцяти економію, якої не перевіряли, гірше, ніж не
-- обіцяти нічого, і той, хто показує, мусить сказати «не знаю» словами
-- замість числа. Саме тому DEFAULT порожній: жоден наявний рядок не був
-- звірений із договором, і виставити їм cancel означало б записати
-- припущення як факт.
--
-- Колонка для РОЗСТРОЧКИ. У картки комісії немає взагалі: там відсоток
-- нараховують на залишок, і будь-який платіж зменшує його одразу — тобто
-- дострокове погашення картки скасовує майбутню ціну завжди.
ALTER TABLE debts ADD COLUMN fee_on_prepay TEXT NOT NULL DEFAULT ''
    CHECK (fee_on_prepay IN ('', 'cancel', 'keep'));
