-- Як пенсійний фонд віддає гроші: строком і періодичністю, а не разом.
--
-- Доти модель віддавала весь накопичений пенсійний капітал ОДНИМ платежем
-- на дату доступу — так поводиться Accum.CloseM. Для накопичувального
-- фонду, який закривається й повертає тіло, це правда. Для НПФ ні, і
-- помилка тут не косметична: за законом виплата на визначений строк іде
-- МІНІМУМ десять років, а одноразово можна забрати лише суму нижче межі
-- (155 700 ₴ у 2026 — 50% × прожитковий мінімум × 120 місяців).
--
-- Наслідок разової моделі був видимий: мільйон, що падає в готівку одного
-- місяця 2051 року, далі реінвестувався ринковою ставкою, і проєкція
-- малювала капітал, якого не буде. Тобто застосунок відповідав на «коли я
-- зможу перестати вносити» числом, завищеним на весь пенсійний потік.
--
-- payout_years — на скільки років розтягнута виплата. 10 за замовчуванням,
-- бо це законодавчий мінімум і найчастіший вибір; 0 означає «разово» й
-- лишає стару поведінку для рахунків, де сума нижче межі.
--
-- payout_freq — як часто платять: month | quarter | year. Фонд дає всі
-- три; місяць за замовчуванням, бо саме так пенсію й отримують.
--
-- Чому не одне поле «кількість виплат». Строк і періодичність — це два
-- РІЗНІ рішення, і людина ухвалює їх окремо: «десять років» вибирають за
-- законом і за віком, «щомісяця» — за звичкою до зарплати. Одне число
-- змусило б їх множити в голові, а на екрані стояло б «120», з якого не
-- прочитати ні строку, ні ритму.
ALTER TABLE npf_accounts ADD COLUMN payout_years INTEGER NOT NULL DEFAULT 10;
ALTER TABLE npf_accounts ADD COLUMN payout_freq TEXT NOT NULL DEFAULT 'month';
