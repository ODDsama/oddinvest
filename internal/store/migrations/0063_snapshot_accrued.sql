-- Накопичений купон у добовому знімку.
--
-- # НАВІЩО
--
-- Відколи облігації в капіталі оцінюються «номінал + накопичений купон»
-- (рішення власника 2026-09-22, state.Capital.BondsUAH), капітал знімка
-- мусить складатись із тих самих доданків — інакше «за 30 днів», «Підсумок
-- місяця» й віхи капіталу порівнювали б сьогоднішню суму з купоном із
-- минулою без нього й показували б купон як приріст.
--
-- # ЧОМУ DEFAULT −1
--
-- Той самий довід, що в 0052 (idle_uah) і 0061 (eur_share_bp): нуль тут —
-- законне значення («у день купона накопиченого немає», або «паперів
-- немає»), і зводити його з «тоді не рахували» не можна. Джоба пише лише
-- невідʼємні значення; −1 лишається виключно в рядках, старших за колонку,
-- і читачі (api/state_delta.go) порівнюють тоді капітал БЕЗ купона з обох
-- боків. Бекап, старший за колонку, поля не має й читається нулем — та
-- сама відома похибка, що й у двох попередніх.
ALTER TABLE snapshots ADD COLUMN accrued_uah INTEGER NOT NULL DEFAULT -1;
