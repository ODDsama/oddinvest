-- НПФ у добовому знімку.
--
-- Та сама діра, що вже була тричі — з фондами (0012), вкладами (0016) і
-- резервом (0021), — і з тієї ж причини: знімок завели, коли пʼятої
-- сутності ще не існувало. Без цих колонок крива «Капітал» показувала б
-- портфель без пенсійних грошей, тобто менший за фактичний, і стрибала б
-- униз рівно в день, коли НПФ заводять.
--
-- Колонок ДВІ, а не одна, і друга не косметична. Лінія прибутку на кривій
-- рахується як «капітал мінус собівартість», і собівартість там сумується
-- з invested_uah + funds_cost_uah + deposits_uah + reserve_uah
-- (web/js/views/history.js). Без npf_cost_uah внески потрапили б у
-- капітал, але не в собівартість, і прибуток завищився б рівно на весь
-- пенсійний баланс — саме ця помилка вже була з фондами, і саме заради
-- неї зʼявився funds_cost_uah у 0018.
--
-- Старі рядки лишаються з нулем. Це не спотворення, а факт: у ті дні НПФ
-- у знімку ніхто не рахував. UI зобовʼязаний казати «тоді не рахували», а
-- не «тоді не було».
ALTER TABLE snapshots ADD COLUMN npf_uah INTEGER NOT NULL DEFAULT 0;
ALTER TABLE snapshots ADD COLUMN npf_cost_uah INTEGER NOT NULL DEFAULT 0;
