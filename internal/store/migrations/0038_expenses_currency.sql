-- Місячні витрати дістають валюту.
--
-- Досі ключ звався `monthly_expenses_uah` і приймав лише гривню. Але
-- витрати мисляться тією валютою, у якій живуть: «півтори тисячі доларів
-- на місяць» — це не оцінка в чужих грошах, а сама одиниця, у якій людина
-- рахує своє життя. Щоб застосунок це прийняв, доводилось перемножувати
-- на курс руками — і робити це заново щоразу, як курс зрушить.
--
-- Через ціль резерву (місяці витрат × витрати) це не дрібниця: гривнева
-- ціль подушки при доларових витратах МУСИТЬ рости разом із курсом, а
-- вписана вручну — стоїть на місці й тихо занижується.
--
-- ЧОМУ НОВИЙ КЛЮЧ, А НЕ ДРУГИЙ ПОРУЧ ЗІ СТАРИМ. `monthly_expenses_uah`
-- бреше назвою рівно з тієї миті, як у ньому лежать долари, а назва тут
-- не косметика: `SettingsDoc.MonthlyExpensesUAH` читають вісім місць, і
-- всі вісім вважають число гривнями. Тому суму переносимо в ключ без
-- суфікса, валюту кладемо поруч, а старий ключ лишається ЗАПАСНИМ
-- ДЖЕРЕЛОМ — той самий прийом, що вже стоїть для goal_*_uah після 0008:
-- він більше не редагується, але відкат не втратить даних.
--
-- Перенос лише тоді, коли нового ще немає: повторний запуск міграції на
-- базі, де користувач уже ввів долари, не має права затерти їх гривнями.

INSERT OR REPLACE INTO settings (key, value)
SELECT 'monthly_expenses', value
FROM settings
WHERE key = 'monthly_expenses_uah'
  AND TRIM(value) <> ''
  AND NOT EXISTS (
      SELECT 1 FROM settings s2
      WHERE s2.key = 'monthly_expenses' AND TRIM(s2.value) <> ''
  );

INSERT OR REPLACE INTO settings (key, value)
SELECT 'monthly_expenses_currency', 'UAH'
FROM settings
WHERE key = 'monthly_expenses'
  AND TRIM(value) <> ''
  AND NOT EXISTS (
      SELECT 1 FROM settings s2
      WHERE s2.key = 'monthly_expenses_currency' AND TRIM(s2.value) <> ''
  );
