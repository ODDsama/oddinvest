-- Плановані купівлі: що я збираюсь узяти й коли.
--
-- ЧОМУ ВЗАГАЛІ В БАЗІ. Доти кошик покупки жив у localStorage, і аргумент
-- на це був записаний у шапці handlers_whatif.go: «збережений кошик — це
-- другий спосіб задати покупки». Він був правильний рівно доти, доки
-- кошик означав чернетку на дві хвилини. Питання змінилось, коли в рядка
-- зʼявилась ДАТА: рядок із майбутньою датою — це вже частина плану поруч
-- із потоками доходу й діями, він рухає точку незалежності, криву
-- капіталу й ціль так само, як замок чи зарплата. Тримати половину плану
-- в базі, а половину в браузері одного пристрою — ось де два джерела
-- правди, а не тут.
--
-- ЧОМУ ОДНА ТАБЛИЦЯ, А НЕ ЧОТИРИ (і чим це відрізняється від 0025).
-- Там дві таблиці розвело те, що потік і дія відповідають на РІЗНІ
-- питання: «скільки заходить» і «яке рішення я приймаю». Тут питання одне
-- на всі чотири види — «купити щось на суму X у валюті C у брокера B на
-- дату D»; різняться посилання й одиниця, тобто три колонки з
-- дванадцяти. Так само вже влаштована plan_actions поруч: одна таблиця з
-- type, у якій usd_bp/eur_bp мертві для lock, а amount/rate_bp/months —
-- для set_shares.
--
-- Вирішує ж не форма рядка, а те, що список читається як ОДНЕ ЦІЛЕ:
-- підсумок по валютах, нестача по брокерах і одне превʼю впливу на цілі.
-- Чотири таблиці означали б чотири набори КРУД-хендлерів, чотири форми —
-- і крок злиття в Go на кожному запиті, який відновлював би рівно ту
-- єдність, яку ми щойно розібрали.
CREATE TABLE plan_buys (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    kind       TEXT    NOT NULL,             -- bond | fund | deposit | npf
    -- ref — на що вказує рядок, У ТЕРМІНАХ СВОГО ВИДУ: ISIN паперу, назва
    -- фонду, id рахунку НПФ, назва банку для вкладу. Для вкладу це
    -- ЗАРАЗОМ і рахунок, з якого йдуть гроші (state_builder.go списує
    -- тіло через cash.add(dep.Bank, …)), тому колонка broker для нього не
    -- читається взагалі.
    ref        TEXT    NOT NULL DEFAULT '',
    -- ДВІ МІРИ, А НЕ ОДНА. Папір і сертифікат купують ШТУКАМИ, вклад і
    -- внесок у НПФ — СУМОЮ. Одна колонка «розмір» відповідала б одразу на
    -- два питання — рівно те, за що 0025 розвела amount і kind.
    qty        INTEGER NOT NULL DEFAULT 0,   -- штуки: папір, сертифікат
    amount     INTEGER NOT NULL DEFAULT 0,   -- мінорні: вклад, внесок НПФ
    -- unit_price — ціна ОДНОГО сертифіката, мінорні. Потрібна лише фонду,
    -- якого ще немає в портфелі: каталогу цін фондів у застосунку немає
    -- навмисно (ціна приходить із виписки разом з операцією), тож про
    -- некуплений фонд сказати нічого не можна. 0 = «візьми з позиції».
    --
    -- Паперу вона НЕ дозволена: ціна ОВДП — це номінал плюс НКД із
    -- довідника (unit_cost.go), і другий спосіб її задати став би другим
    -- джерелом правди про те саме число.
    unit_price INTEGER NOT NULL DEFAULT 0,
    -- currency: '' = вивести із самої сутності (папір, фонд, рахунок НПФ
    -- знають свою валюту). Задається лише там, де сутності ще немає.
    currency   TEXT    NOT NULL DEFAULT '',
    broker     TEXT    NOT NULL DEFAULT '',  -- '' = обрати за залишком (pickBroker)
    -- buy_date: '' = «купую зараз». Заповнена МАЙБУТНЯ дата переводить
    -- рядок з гіпотетичного портфеля у ПРОГНОЗ — див. state_plan_buys.go.
    -- Минула дата не приймається: покупка, яка вже сталася, описується
    -- операцією, а не планом.
    buy_date   TEXT    NOT NULL DEFAULT '',
    rate_bp    INTEGER NOT NULL DEFAULT 0,   -- вклад: ставка, %×100
    months     INTEGER NOT NULL DEFAULT 0,   -- вклад: строк, > 0
    -- is_reserve — планований вклад є ПОДУШКОЮ (0032). Без цієї колонки
    -- картка впливу ніколи не змогла б зрушити подушку й драбину доступу,
    -- тобто рядок про них завжди казав би «без змін» — а рядок, який
    -- структурно не може змінитись, гірший за його відсутність.
    is_reserve INTEGER NOT NULL DEFAULT 0,
    note       TEXT    NOT NULL DEFAULT ''
) STRICT;

-- Індекс за датою — як у plan_flows і plan_actions поруч: список завжди
-- читається ORDER BY buy_date, id.
CREATE INDEX idx_plan_buys_date ON plan_buys(buy_date);

-- ЧОГО ТУТ СВІДОМО НЕМАЄ.
--
-- revocable — за ЦКУ строковий вклад фізособи безвідкличний, і
-- відкличність є властивістю ДОГОВОРУ, якого ще не існує. Прапорець на
-- намірі був би обіцянкою за банк.
--
-- payout / capitalized / tax_bp — беруться тими самими дефолтами, що й у
-- формі відкриття вкладу. План не мусить знати про вклад більше, ніж
-- знає операція, якою він завершиться.
--
-- Журналу ревізій (як plan_flow_revisions) — той журнал існує заради
-- питання «яким план був у травні». План купівель історії не має за
-- побудовою: рядок або виконується (і стає операцією), або видаляється.
--
-- Колонки ручного порядку — «ORDER BY buy_date, id» уже відповідає на
-- питання «що раніше», а друге впорядкування суперечило б першому.
