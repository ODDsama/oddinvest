-- Результати аукціонів Мінфіну: під скільки розміщували кожен папір.
--
-- НАВІЩО ОКРЕМА ТАБЛИЦЯ, А НЕ КОЛОНКИ В `bonds`. ReplaceDirectory щоранку
-- робить `DELETE FROM payments; DELETE FROM bonds` і наливає довідник
-- заново. Історія, що жила б на `bonds`, стиралась би щодня — і стирання
-- було б непомітне: на екрані просто не з'являлась би крива, а причину
-- довелося б шукати в джобі.
--
-- І НАВІЩО БЕЗ FK НА `bonds(isin)`. Погашений папір іде з довідника НБУ,
-- бо його більше немає в обігу. Але «під скільки розміщували два роки в
-- березні» — питання про РИНОК, а не про папір, який ти тримаєш, і
-- відповідь на нього не має зникати разом з інструментом. Тут навмисно
-- інакше, ніж у `payments`: там ON DELETE CASCADE, бо графік виплат без
-- свого паперу справді нічого не означає.
--
-- Одиниці ті самі, що всюди: відсотки в базисних пунктах (× 100), суми в
-- мінорних одиницях своєї валюти. bid-to-cover теж × 100 — двох знаків
-- НБУ й не публікує.
--
-- Ключ (день, папір, номер аукціону) робить запис ІДЕМПОТЕНТНИМ: одне й
-- те саме розміщення можна перезаписати скільки завгодно разів, тож
-- повторний бекфіл нічого не дублює й нічого не коштує.
CREATE TABLE ovdp_auctions (
    auction_date  TEXT    NOT NULL,             -- ISO
    isin          TEXT    NOT NULL,             -- StockCode; = cpcode довідника
    auction_num   TEXT    NOT NULL DEFAULT '',  -- номер аукціону того дня
    currency      TEXT    NOT NULL,
    -- Строк, як його назвав САМ НБУ («1y», «1.5y», «2y»). Його ж
    -- класифікація тут авторитетна: криву читають у тих самих відрах, у
    -- яких Мінфін розміщує.
    bucket        TEXT    NOT NULL DEFAULT '',
    -- Днів до погашення на день аукціону. Зберігається ПОРУЧ із bucket,
    -- хоч одне з другого майже виводиться: якщо колись знадобиться інша
    -- нарізка строків, вона не потягне за собою повторного вичитування
    -- джерела по одному дню.
    days_to_repay INTEGER NOT NULL DEFAULT 0,
    repay_date    TEXT    NOT NULL DEFAULT '',
    income_bp     INTEGER NOT NULL,             -- дохідність розміщення, % × 100
    min_bp        INTEGER NOT NULL DEFAULT 0,   -- межі прийнятих заявок
    max_bp        INTEGER NOT NULL DEFAULT 0,
    btc_x100      INTEGER NOT NULL DEFAULT 0,   -- заявок до розміщеного
    sold_minor    INTEGER NOT NULL DEFAULT 0,   -- розміщено за номіналом
    PRIMARY KEY (auction_date, isin, auction_num)
) STRICT;

-- Два питання, два індекси: «коли цей папір востаннє розміщували» —
-- для помічника реінвесту; «що ринок платив за цей строк» — для кривої.
CREATE INDEX idx_ovdp_auctions_isin ON ovdp_auctions(isin, auction_date);
CREATE INDEX idx_ovdp_auctions_curve ON ovdp_auctions(currency, bucket, auction_date);
