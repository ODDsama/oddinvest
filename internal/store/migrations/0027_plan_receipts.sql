-- Відмітки надходжень: факт до плану доходу.
--
-- Плану надходжень (0025) фактичного двійника не було взагалі. Те, що на
-- картці «План проти факту» підписано словом «факт», — це deposits +
-- reserve_ops, тобто ПОПОВНЕННЯ портфеля. Питання «чи прийшла зарплата»
-- застосунок відповісти не міг: поповнення показує, скільки я відніс
-- брокерові, а не скільки мені заплатили.
--
-- Через це план бреше саме там, де дохід нерівний. Прийшли відпускні
-- наперед — план і далі малює 32 000/міс на два наступні місяці, хоча в них
-- буде нуль. Вийшов з відпустки й відпрацював два дні — прийшла третина.
-- Тепер кожну планову виплату можна відмітити: скільки прийшло насправді,
-- або що не прийшло зовсім.
--
-- Відмітка на МИНУЛИЙ місяць уточнює історію, на МАЙБУТНІЙ — править
-- прогноз: обидва напрямки заходять в одне й те саме ядро (planFlowAmount),
-- тож окремого означення надходження не з'являється.
CREATE TABLE plan_receipts (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    -- Потік, до якого прив'язана відмітка; 0 = «інше», позаплановий дохід.
    --
    -- Зовнішнього ключа на plan_flows навмисно немає — з тієї самої
    -- причини, що в plan_flow_revisions (0026): запис про факт мусить
    -- пережити той потік, про який він розповідає. Тому ж тут лежить name —
    -- знімок назви, щоб журнал читався й після того, як потік зник.
    flow_id INTEGER NOT NULL DEFAULT 0,
    -- Місяць "YYYY-MM", а не дата, і це рішення, а не спрощення.
    -- Порівняння план↔факт помісячне скрізь (buildPlanHistory, профіль,
    -- planTotal), а головне — «нічого не прийшло» дня не має взагалі, і з
    -- колонкою-датою його довелося б вішати на вигаданий день.
    month TEXT NOT NULL,
    name TEXT NOT NULL DEFAULT '',
    -- ВАЛОВА сума, мінорні, >= 0. Нуль легальний і означає «не прийшло» —
    -- саме заради нього ця таблиця й існує, тож він мусить відрізнятись від
    -- відсутнього рядка («місяць ще не відмічено»).
    --
    -- Валова, а не «скільки з цього піде в портфель»: частку в портфель
    -- застосовує ядро плану, і застосовує рівно один раз.
    amount INTEGER NOT NULL,
    -- Валюта мусить збігатися з валютою потоку (перевіряється в API).
    -- Інакше нативний шлях у проєкції довелося б конвертувати через
    -- гривню — рівно те, чого state_plan.go уникає навмисно.
    currency TEXT NOT NULL DEFAULT 'UAH',
    -- Частка в портфель, %×100. Читається ЛИШЕ при flow_id = 0.
    --
    -- Відмітка, прив'язана до потоку, успадковує частку З ПОТОКУ, а для
    -- минулого — з тієї його ревізії, яка діяла тоді (planAsOf). Саме це не
    -- дає пізнішій правці «частки в портфель» переписати вже записану
    -- історію — той самий принцип, заради якого існує журнал ревізій.
    -- У позапланового доходу успадковувати нема від чого, тож частка своя.
    invest_bp INTEGER NOT NULL DEFAULT 10000,
    -- Причина розходження: «вийшов з відпустки, 2 дні», «відпускні наперед».
    -- Без неї нуль у графіку читався б як провал плану, а не як факт.
    note TEXT NOT NULL DEFAULT ''
) STRICT;

CREATE INDEX idx_plan_receipts_month ON plan_receipts(month);

-- Часткова унікальність: одне планове джерело дає в місяці одну виплату
-- (cadence інакше й не вміє), а «іншого» за місяць може бути скільки
-- завгодно — премія і подарунок у тому самому серпні не конфліктують.
CREATE UNIQUE INDEX idx_plan_receipts_flow_month
    ON plan_receipts(flow_id, month) WHERE flow_id > 0;
