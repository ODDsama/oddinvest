-- Обіцяна дохідність фонду і день виплати дивідендів.
--
-- Навіщо обіцянка, коли поруч є дві виміряні дохідності. Виміряні мовчать,
-- поки не набереться історії: FundTotalReturn (дивіденди + зміна ціни)
-- потребує 30 днів, зважених грошима, а до того лишається сама дивідендна.
-- І от вона в парі з гривневим знеціненням дає число, яке вводить в оману:
-- Inzhur REIT обіцяє 9.5% у доларах, а застосунок показував −2.9% реальних —
-- бо приросту ціни ще не бачив, а штраф за знецінення вже відняв.
--
-- Наслідок був не косметичний: помічник реінвесту ранжує за реальною
-- дохідністю, тож фонд стояв у самому низу й ніколи не потрапляв у поради.
--
-- expected_yield_currency окремо від funds.currency НАВМИСНО. Сертифікат
-- гривневий (ціна, купівлі й дивіденди в гривні), але обіцянка може бути
-- валютною — саме випадок фонду, чия ціна йде за курсом НБУ. 9.5% у доларі
-- вже є РЕАЛЬНОЮ дохідністю, і гривневий штраф до неї застосовувати не
-- можна: приріст ціни в гривні і є тією компенсацією знецінення.
-- Порожньо = обіцянка в тій самій валюті, що й сам фонд.
--
-- payout_day — число місяця, коли фонд платить (0 = невідомо). Дає точний
-- ритм для приведення виплати до року замість медіани з фактичних
-- проміжків, якої на одній виплаті просто немає, і дозволяє сказати, коли
-- чекати наступну.
ALTER TABLE funds ADD COLUMN expected_yield_bp INTEGER NOT NULL DEFAULT 0;
ALTER TABLE funds ADD COLUMN expected_yield_currency TEXT NOT NULL DEFAULT '';
ALTER TABLE funds ADD COLUMN payout_day INTEGER NOT NULL DEFAULT 0;
