-- Чистий капітал у добовому знімку: капітал МІНУС борги.
--
-- Та сама діра, що вже була чотири рази — фонди (0012), вклади (0016),
-- резерв (0021), цілі (0040), — і з тієї ж причини: знімок завели, коли
-- цієї сутності ще не існувало.
--
-- ЧОМУ ОКРЕМА КОЛОНКА, А НЕ ПРАВКА capital_uah. Капітал — база часток,
-- драбини, лімітів концентрації й XIRR; відʼємний доданок зламав би суму
-- 100 і кожен інваріант, побудований у фазі 4. Тому капітал лишається
-- капіталом, а борг віднімається ПОРУЧ, окремим числом і окремою лінією
-- на кривій.
--
-- ЩО ЦЕ МІНЯЄ НА ЕКРАНІ. Доти крива казала «капітал росте» в місяці, коли
-- людина влізла в кредитний ліміт глибше, ніж доклала в папери. Обидва
-- твердження правдиві поодинці, і саме тому їх треба показати разом:
-- капітал справді ріс, а чистий капітал — падав.
--
-- Старі рядки лишаються з нулем. Це не спотворення, а факт: у ті дні
-- боргів у знімку ніхто не рахував. UI зобовʼязаний казати «тоді не
-- рахували», а не «тоді не було» — і саме тому лінія чистого капіталу
-- обривається там, де починаються нулі, а не падає в нуль.
ALTER TABLE snapshots ADD COLUMN net_worth_uah INTEGER NOT NULL DEFAULT 0;
