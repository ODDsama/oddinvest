-- сказав «лише подушка й цілі» — тепер він означає ще й «не в борг», і
-- вгадати, чи людина хотіла б туди борг, неможливо: обидві відповіді
-- правдоподібні. Отже, рішення лишається за нею, а форма дозволу тепер
-- показує п'ять галочок замість чотирьох, і відсутню видно.
