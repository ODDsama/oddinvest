-- П'ятий кошик дозволу — погашення боргу. Міграція потрібна не схемі, а
-- ЗНАЧЕННЮ вже записаних рядків.
--
-- ПРО ЩО ЦЕ. `uses` порожній означає «будь-куди», і саме тому він
-- застрахований від появи нових кошиків за побудовою (шапка
-- domain/plan_uses.go). Але дозвіл, набраний ЯВНО й повним переліком
-- чотирьох тодішніх кошиків, канонізувався в рядок
-- 'reserve,goals,invest,npf' — і з появою п'ятого той самий рядок почав
-- означати «у борг не можна». Заборону, якої ніхто не ставив.
--
-- Тому рядки, що перелічують УСІ чотири колишні кошики, повертаються до
-- порожнього: людина сказала «скрізь», і сказане мусить лишитись сказаним.
UPDATE plan_flows        SET uses = '' WHERE uses = 'reserve,goals,invest,npf';
UPDATE plan_receipts     SET uses = '' WHERE uses = 'reserve,goals,invest,npf';

-- Журнал ревізій — ТЕЖ, і це свідоме відхилення від правила «минуле не
-- переписуємо» (0026, 0030, 0041).
--
-- Правило захищає від того, щоб СЬОГОДНІШНЯ правка заднім числом
-- переписала історію. Тут навпаки: рядок казав «дозволено все» в день,
-- коли його записали, і лишити його недоторканим означало б заднім
-- числом заборонити те, чого тоді не існувало. Незміна тут і є
-- переписуванням минулого, лише мовчазним.
UPDATE plan_flow_revisions SET uses = '' WHERE uses = 'reserve,goals,invest,npf';

