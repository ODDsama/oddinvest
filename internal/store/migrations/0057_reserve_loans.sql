-- Позика в самого себе: узяв із подушки — повертаєш із відсотком.
--
-- ЩО ЦЕ. Доти зняття з резерву було безкоштовним: відʼємний рядок
-- reserve_ops (0020) збільшував розрив рівно на зняту суму, і на цьому
-- все. Ціна користування власною подушкою дорівнювала нулю, а звʼязку
-- «зняв → повернув» не існувало взагалі. Тепер зняття може відкрити
-- позику: доки її не закрито, ЦІЛЬ подушки піднята на нарахований
-- відсоток, а коли закрито — вертається до базової сама собою.
--
-- # ЧОМУ ЦЕ НЕ ТРЕТІЙ debts.kind
--
-- Спокуса завести 'reserve' поруч із 'card' і 'installment' сильна:
-- там уже є ставка, журнал, черга погашення й екран. І вона хибна.
--
-- Capital УЖЕ впав на зняту суму — резерв входить у капітал, і мінус у
-- reserve_ops його зменшив. Записати ту саму суму ще й боргом означало б
-- відняти її ДВІЧІ: на знятті 12 000 ₴ чистий капітал просів би на
-- 24 000 ₴. Борг перед подушкою не є зобовʼязанням перед кимось — це
-- обіцянка поповнити, і єдина його дія на числа — надбавка до цілі.
--
-- Звідси й уся арифметика, на якій стоїть фіча:
--
--   owed(t) = P + I(t) − repaid(t)     що ще винен
--   target  = base + Σ I(t)            ціль піднята на НАРАХОВАНИЙ відсоток
--   have    = B − P + repaid           подушка вже впала на тіло
--   gap     = (base − B) + owed        розрив ДО позики плюс залишок боргу
--
-- Останній рядок і є вся вигода моделі: тіло в ціль не додається, бо
-- подушка вже на нього впала, а надбавкою йде РІВНО відсоток. На повній
-- подушці (base == B) розрив дорівнює боргу до копійки; на недобраній він
-- більший рівно на те, чого бракувало й до позики.
--
-- Окремого механізму «повернути ціль назад» при цьому не треба: щойно
-- owed ≤ 0, надбавки немає, target == base.
--
-- # ЧОМУ ОКРЕМА ТАБЛИЦЯ, А НЕ КОЛОНКИ В reserve_ops
--
-- Той самий довід, яким 0039 розвів goals і reserve_ops: у позики є
-- ставка, дедлайн і закриття, яких у звичайного руху немає. Три мертві
-- колонки на КОЖНОМУ рядку журналу читались би як зразок і тиражувались.
--
-- Плюс 0020 навмисно тримає reserve_ops журналом з одним знаковим
-- полем і БЕЗ kind — додати туди «вид руху» означало б скасувати те
-- рішення заради сутності, яка живе окремо.
CREATE TABLE reserve_loans (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    portfolio_id INTEGER NOT NULL DEFAULT 1 REFERENCES portfolios(id) ON DELETE CASCADE,
    -- Зняття, що відкрило позику. ТІЛО СЮДИ НЕ ДУБЛЮЄТЬСЯ: воно вже є
    -- сумою цього рядка. Друга копія розійшлася б із ним на першій же
    -- правці руху — той самий довід, яким 0045 не зберігає «скільки
    -- платежів лишилось».
    op_id    INTEGER NOT NULL UNIQUE REFERENCES reserve_ops(id) ON DELETE CASCADE,
    -- Ставка ЗНІМКОМ на момент узяття, а не читанням налаштування
    -- щоразу. Прецедент — snapshots.month_target_uah (місячна ціль
    -- береться зі знімка ТОГО місяця) і plan_flow_revisions: інакше
    -- правка reserve_loan_rate_pct мовчки переписала б ціну позики,
    -- узятої торік.
    rate_bp  INTEGER NOT NULL,               -- %×100
    -- Власний дедлайн, необовʼязковий. Порожньо = «поверну колись»:
    -- позика від цього не зникає, лише не вміє бути простроченою.
    due_date TEXT NOT NULL DEFAULT '',
    note     TEXT NOT NULL DEFAULT ''
) STRICT;

CREATE INDEX idx_reserve_loans_portfolio ON reserve_loans(portfolio_id);

-- Повернення: ДОДАТНИЙ рух, привʼязаний до позики.
--
-- На відʼємному русі ця колонка не використовується — звʼязок у той бік
-- дає reserve_loans.op_id, і друга дорога до того самого факту дозволила б
-- рядкові суперечити самому собі.
--
-- NULL на додатному русі законний і означає рівно те, що написано: це
-- поповнення, яке нічого не гасить. Але ТИПОВО поповнення гасить
-- найстарішу відкриту позику (FIFO, у моделі, не тут) — інакше ноги
-- «Маршруту грошей» і кнопка «Розкласти», які постять у /api/reserve без
-- жодного поняття про позики, не гасили б борг ніколи.
ALTER TABLE reserve_ops ADD COLUMN loan_id INTEGER REFERENCES reserve_loans(id);

CREATE INDEX idx_reserve_ops_loan ON reserve_ops(loan_id);
