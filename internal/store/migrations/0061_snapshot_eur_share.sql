-- Частка EUR у добовому знімку: скільки відсотків капіталу того дня
-- стояло в євро.
--
-- # НАВІЩО, КОЛИ ПОРУЧ УЖЕ Є usd_share_bp
--
-- Долар мав колонку з першої міграції, євро не мало жодної. Доти це було
-- чесно: євро не було ані ціллю, ані питанням — валютна політика зводилась
-- до однієї цифри. Після дев'ятого питання конфігуратора (fxmix/fxdiv)
-- євро стало повноцінною ціллю поруч із доларом: воно є в
-- eur_target_share_pct, у валютному рядку ребалансу, у плитці «Частка EUR»,
-- у сенсорі HA й у повзунку. Не було ЛИШЕ руху факту в часі — «Як росте»
-- і «Підсумок місяця» показували долар і мовчали про євро, тобто половина
-- валютної політики жила без історії саме тоді, коли її почали задавати.
--
-- Частку тримаємо в базисних пунктах, як і долар: цілим числом, ×100 від
-- відсотка. /api/snapshots ділить назад на 100 разом з усіма іншими
-- колонками — збіг дільника з грошовим випадковий, і про це вже написано
-- там, де ділять.
--
-- # ЧОМУ DEFAULT −1, А НЕ 0
--
-- Це головне рішення міграції, і воно відрізняється від сусідніх колонок
-- знімка. Там нуль означає «тоді не рахували», і цього досить: у ГРОШОВІЙ
-- колонці нуль однаково не є станом, який хочеться показати, тож крива
-- просто обривається на початку й ніхто не помиляється.
--
-- Тут не так. Частка 0 % має власний зміст — «євро немає», — і на живому
-- портфелі це правда більшої частини історії. Тобто нуль звів би докупи
-- два різні твердження («не було» і «не питали») рівно там, де різниця й
-- потрібна: людина, яка щойно купила перший євровий папір, побачила б
-- рівну лінію нуля за півроку назад і прочитала б її як вимір.
--
-- Прецедент є поруч: 0052_snapshot_idle.sql завів idle_uah DEFAULT −1 з
-- того самого доводу, слово в слово («нуль тут має власний зміст»). Джоба
-- пише сюди лише невід'ємні значення, тож −1 лишається виключно в рядках,
-- старших за саму колонку, і обидва екрани показують їх прочерком.
--
-- Бекап, старший за колонку, поля не має й читається нулем — та сама
-- відома й прийнята похибка, що в idle_uah. Тому поле знімка йде БЕЗ
-- omitempty: інакше −1 не пережив би навіть свіжого бекапа.
ALTER TABLE snapshots ADD COLUMN eur_share_bp INTEGER NOT NULL DEFAULT -1;
