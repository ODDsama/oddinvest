-- Ринкова ціна ОВДП: скільки папір коштує в конкретного продавця.
--
-- # ЧОМУ ЦЯ ТАБЛИЦЯ ВЗАГАЛІ З'ЯВИЛАСЬ
--
-- Довідник НБУ знає про папір усе, крім єдиного, що потрібно перед
-- покупкою: ціни. Доти застосунок міряв крок номіналом плюс НКД і чесно
-- про це писав (`unit_cost.go`), але число було наближенням: на живих
-- даних папір коштує 1 100 ₴ там, де наближення давало 1 011 ₴. Помилка
-- йшла одразу в дві відповіді помічника — у дохідність поради (бо YTM
-- рахується САМЕ від ціни входу) і в розмір квитка розкладки.
--
-- Джерело — сторінки finomo.com.ua, які возять ціни шести роздрібних
-- брокерів. README («Чого тут свідомо немає») присвячував відсутності
-- ціни цілий абзац; той абзац цією роботою спростовано й переписано.
-- Сусідній абзац — про ціну, ВИВЕДЕНУ з аукціонного рівня, — лишається
-- правдою: справжня ціна вторинного ринку не привід вигадувати її з
-- первинного розміщення, а навпаки.
--
-- # ЧОМУ БЕЗ portfolio_id
--
-- Той самий табір, що `bonds`, `payments`, `fx_rates`, `ovdp_auctions`,
-- `cpi_points` (поіменний перелік — у шапці 0054). Ціна паперу в брокера
-- одна на всіх: колонка `portfolio_id` тут означала б, що в дружини той
-- самий ISIN у того самого брокера коштує інакше.
--
-- ВИБІР ціни портфельний, і це не суперечність. Яку з цих цін застосунок
-- візьме в квиток, вирішує зіставлення з ТВОЇМИ брокерами
-- (`brokers.quote_source` нижче), а воно вже належить портфелю. Факт
-- спільний, вибір із фактів — свій; довід повторено в `unit_cost.go`,
-- щоб наступний автор не потягнув колонку сюди.
--
-- # І ЧОМУ БЕЗ FK НА bonds(isin)
--
-- Слово в слово з 0024: `ReplaceDirectory` щоранку робить
-- `DELETE FROM payments; DELETE FROM bonds` і наливає довідник заново.
-- Ключ або валив би це видалення, або (з CASCADE) щоранку мовчки витирав
-- ціни. Плюс погашений папір іде з довідника, а «за скільки його
-- віддавали» лишається фактом про ринок.
--
-- Звідси ж і власна колонка `currency`: без FK довідник може бути
-- порожній, а ціна без своєї валюти читалась би як гривня. Той самий
-- довід, що в `ovdp_auctions.currency`.
--
-- # ДВІ ДАТИ, А НЕ ОДНА
--
-- `quote_date` — коли ціна названа джерелом; `fetched_at` — коли ми
-- питали. Свіжість судиться ПЕРШОЮ, бо це факт про ринок. З однією датою
-- продавець, який перестав котирувати папір, виглядав би свіжим рівно
-- доти, доки ми тиснемо кнопку, — тобто наша старанність підмінила б
-- собою рух ринку.
--
-- # ЦІНА БРУДНА
--
-- `price_minor` — разом із накопиченим купонним доходом, тобто та сума,
-- яку віддаєш за одну штуку. Перевірено XIRR'ом за фактичними датами
-- виплат на п'яти паперах: дохідність, порахована з цього числа,
-- збігається з опублікованою до третього знака (16.600 % проти 16.60 %),
-- тоді як та сама ціна, прочитана як чиста, дала б 15.975 %. ДОДАВАТИ ДО
-- НЕЇ НКД НЕ МОЖНА — помилка вийде тиха, однобічна і в −0,6 в.п.
--
-- # КЛЮЧ І ЙОГО НАСЛІДОК
--
-- (папір, продавець, дата) робить запис ідемпотентним: кнопку можна
-- тиснути скільки завгодно разів на день, дублікатів не буде. Неглибока
-- історія виходить сама собою — це НАСЛІДОК ключа, а не можливість:
-- екрана для неї немає й не планується, а зростання обмежене тим, як
-- часто людина тисне кнопку (фонової джоби тут немає навмисно).
CREATE TABLE ovdp_quotes (
    isin        TEXT    NOT NULL,
    -- Латинський КЛЮЧ продавця, як його пише джерело: Privat24, Inzhur,
    -- Univer, BtcBroker, ICU, Kinto — або ім'я власного брокера, коли
    -- ціну вписали руками. Ключ, а не український підпис: підпис у
    -- вітрині перейменують, і зіставлення розсиплеться мовчки.
    --
    -- Справедливої вартості НБУ тут НЕМАЄ, хоч джерело її й возить поруч.
    -- Вона регулярно дорівнює рівно номіналу, і потрапивши в один список
    -- із пропозиціями, одного дня виграла б «де дешевше» — вказавши на
    -- місце, де купити не можна взагалі.
    source      TEXT    NOT NULL,
    quote_date  TEXT    NOT NULL,             -- ISO, дата САМОЇ ціни
    price_minor INTEGER NOT NULL,             -- брудна ціна за 1 шт
    currency    TEXT    NOT NULL,
    -- Звідки взялось число, а не хто продає: 'finomo' — обхід, 'manual' —
    -- вписане руками. На екрані це різні за надійністю речі, а прохід
    -- джерелом не має права чіпати те, що людина ввела сама.
    --
    -- Ручний рядок існує тому, що покриття джерела нерівне: mono ОВДП
    -- продає, а ціни не публікує ніде — сторінка monobank.ua/ovdp порожня
    -- JS-оболонка без жодного ISIN у розмітці. Без ручного числа брокер,
    -- у якому лежать гроші, просто випадав би з порівняння.
    origin      TEXT    NOT NULL DEFAULT 'finomo',
    fetched_at  TEXT    NOT NULL,             -- RFC3339 UTC: коли МИ питали
    PRIMARY KEY (isin, source, quote_date)
) STRICT;

-- Одне питання — один індекс: «почім цей папір зараз». Лівий стовпець
-- ключа вже `isin`, тож `WHERE isin IN (…)` накритий і без нього; цей
-- потрібен рівно заради спадного порядку дати, бо читаємо ми завжди
-- НАЙСВІЖІШЕ, а не все.
CREATE INDEX idx_ovdp_quotes_fresh ON ovdp_quotes(isin, source, quote_date DESC);

-- Зіставлення власного брокера з ключем продавця в джерелі.
--
-- Порожньо = не зіставлено, і такий брокер у вибір ціни не потрапляє
-- зовсім. Це не поломка, а чесна відповідь: у mono ціни ми не знаємо,
-- доки її не вписали, і мовчки підставити замість неї ціну Приват24
-- означало б порадити крок за числом, якого в твоєму брокері немає.
--
-- Колонкою, а не таблицею зіставлень: відповідність тут один-до-одного й
-- живе разом із брокером, а окрема таблиця вимагала б власного КРУДу
-- заради двох рядків.
ALTER TABLE brokers ADD COLUMN quote_source TEXT NOT NULL DEFAULT '';
