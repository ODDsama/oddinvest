-- Строк, вид і податок фонду.
--
-- Модель фондів стояла на трьох «немає»: немає дати погашення, немає
-- номіналу, немає графіка купонів (domain/funds.go). Для Inzhur REIT це
-- правда. Для Inzhur MilTech хибні всі три: усередині корпоративні
-- облігації одного емітента з погашенням 26.07.2029, на цю дату фонд
-- закривається, а тіло з доходом повертається дивідендом.
--
-- kind — чи платить фонд узагалі. Вивести це з payout_day НЕ можна: нуль
-- там означає «день невідомий», і розподільний фонд без заповненого дня
-- тихо став би накопичувальним, тобто перестав би платити в моделі. Тому
-- поле окреме: '' = розподільний, як усі фонди досі, 'accum' =
-- накопичувальний, весь дохід сидить у ціні сертифіката.
--
-- close_date — коли фонд закривається й повертає гроші. Без неї
-- накопичувальний ріс би обіцяною ставкою до самого дедлайну цілі, а це
-- вигадка: облігації MilTech гасяться в липні 2029, дедлайн цілі —
-- січень 2030, і на останні пів року приросту взятись нізвідки.
--
-- buy_until — доки фонд можна купувати. MilTech закриває залучення
-- 31.12.2026; без цієї дати помічник пропонував би його й у 2028-му, а
-- «Що купити» радило б неможливе.
--
-- income_tax_bp — податок на дохід фонду × 100 (14% = 1400). Купон ОВДП
-- від податку звільнений, дохід фонду ні, і в спільну таблицю вони
-- можуть потрапити лише в одній мірі — правило, на якому тримається весь
-- state_funds.go. Ставка не зашита: тримати до закриття й вийти раніше —
-- це 14% дивідендом проти 23% на різницю цін, тобто число залежить від
-- наміру власника, а не від застосунку.
--
-- yield_simple_years — ОДНЕ поле замість пари «прапорець + строк»
-- навмисно. Ненульове означає «обіцянка задана ПРОСТОЮ середньорічною за
-- стільки років»; нуль — складна, як усі інші ставки застосунку.
-- Прапорець «проста» без строку був би станом, з якого нічого не
-- порахувати, тож такого стану просто немає.
--
-- Навіщо воно: фонд обіцяє «середньорічну просту 25% за три роки», а
-- expected_yield_bp іде в MonthlyRate і компаундиться щомісяця. Проста
-- 25% за три роки — це ×1.75, тобто 20.5% складних; складна 25% — ×1.95.
-- Однакова назва, різні одиниці, приріст завищений на чверть.
