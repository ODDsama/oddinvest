-- Борги: кредитна картка з пільговим циклом і розстрочки.
--
-- ЧЕТВЕРТА ПРИРОДА ГРОШЕЙ, і саме тому окрема сутність.
--
-- Не `plan_flows`: у потоку немає ні тіла, ні ставки, а платіж за боргом
-- тіло ЗМЕНШУЄ. Потік описує «скільки й коли приходить чи йде», борг —
-- «скільки я винен і під скільки», і друге з першого не виводиться.
--
-- Не «ціль зі знаком мінус», попри схожість форми (сума, дата, журнал).
-- У цілі немає ставки взагалі, а в боргу ставка і Є головне число: саме
-- вона ставить борг у чергу й дозволяє порівняти його з дохідністю
-- паперів. І гроші під ціллю лишаються в капіталі, а гроші боргу — ні.
--
-- Не `brokers`: та таблиця за коментарем 0013 — рахунки, чий баланс
-- рухається В ПОРТФЕЛІ. Картка живе в побутовому контурі, і плюс на ній
-- у капітал не входить (рішення власника; довід — у шапці domain/debt.go).
--
-- ГОЛОВНА МЕЖА ВСІЄЇ СУТНОСТІ, без якої числа розійдуться:
--
--   оборот у межах пільгового періоду — лише НАГЛЯД (два пороги, дата,
--   «скільки вільно»); грошей місяця й капіталу він не торкається, бо
--   побут уже описаний налаштуванням monthly_expenses та часткою
--   invest_bp потоку, і відняти його вдруге означало б відняти двічі;
--
--   заборгованість, що ВИПАЛА з пільгового, готівка з ліміту й будь-яка
--   розстрочка — справжній борг під ставку: у чергу погашення, у рейтинг
--   «Що купити» й у поділ надходжень.
CREATE TABLE debts (
    id       INTEGER PRIMARY KEY AUTOINCREMENT,
    name     TEXT    NOT NULL,
    -- CHECK, а не вільний текст, на відміну від funds.kind: там третє
    -- значення (drip) додалось без міграції саме тому, що види фондів
    -- відкриті. Тут їх два й вони протилежні за механікою; описка в
    -- цьому полі зробила б борг НЕВИДИМИМ обом гілкам розрахунку, а не
    -- просто дивним рядком у списку.
    kind     TEXT    NOT NULL CHECK (kind IN ('card', 'installment')),
    currency TEXT    NOT NULL DEFAULT 'UAH',
    -- Розстрочка ВСЕРЕДИНІ картки: її щомісячна частина падає у виписку
    -- цієї картки й бере участь у пільговому порозі. NULL = самостійний
    -- борг зі своїм графіком (інший банк, інший рахунок).
    --
    -- Рекурсивний FK замість другої таблиці: питання одне («скільки й під
    -- скільки я винен»), список читається як одне ціле, і черга погашення
    -- впорядковує обидва види разом.
    card_id  INTEGER REFERENCES debts(id),

    -- --- лише картка (для розстрочки мертві) ---
    limit_amount      INTEGER NOT NULL DEFAULT 0,  -- сам ліміт, мінорні
    -- Розрахункова дата — ЧИСЛО МІСЯЦЯ (у ПУМБ на вибір 10, 20 або 30), а
    -- не «N днів пільгового». Пільговий «до 62 днів» — це НАСЛІДОК циклу
    -- «покупка в цьому періоді → сплатити до розрахункової дати
    -- наступного», а не самостійний строк: покупка в перший день циклу
    -- має ~62 дні, в останній — ~31. Зберігати тут 62 означало б зберегти
    -- найкращий випадок як правило.
    statement_day     INTEGER NOT NULL DEFAULT 0 CHECK (statement_day BETWEEN 0 AND 31),
    apr_bp            INTEGER NOT NULL DEFAULT 0,  -- ставка ПІСЛЯ пільгового, %×100
    -- Підвищена ставка за прострочення мінімалки — окремим полем, бо це
    -- ДРУГА ціна другої помилки. Пропустити мінімалку й не закрити повну
    -- суму — різні провини з різними наслідками, і одне число на них
    -- сховало б дешевшу.
    apr_overdue_bp    INTEGER NOT NULL DEFAULT 0,
    min_payment_bp    INTEGER NOT NULL DEFAULT 0,  -- мінімалка, % від використаного ×100
    min_payment_floor INTEGER NOT NULL DEFAULT 0,  -- і не менше ніж, мінорні
    late_fee          INTEGER NOT NULL DEFAULT 0,  -- штраф за прострочення, мінорні

    -- --- лише розстрочка (для картки мертві) ---
    principal          INTEGER NOT NULL DEFAULT 0, -- тіло на старті, мінорні
    payments_total     INTEGER NOT NULL DEFAULT 0,
    first_payment_date TEXT    NOT NULL DEFAULT '',
    -- Комісія рахується ВІД ПОЧАТКОВОЇ СУМИ, а не від залишку — так її
    -- беруть і ПУМБ, і решта. Саме через це «1,99% на місяць» у графіку
    -- дає ~43% річних, а не 24%: тіло спадає, а комісія ні. Число тут
    -- зберігається таким, як його називає банк; чесну ставку рахує XIRR
    -- у domain/debt.go, і другого її означення в базі немає навмисно.
    fee_month_bp    INTEGER NOT NULL DEFAULT 0,
    -- Скільки ПЕРШИХ місяців комісії немає (товарна розстрочка ПУМБ:
    -- 0% перші три, далі 3%). Окремою колонкою, бо ставка міняється в
    -- часі, і одне число було б помилковим в обидва боки — 0% на весь
    -- строк або 3% з першого дня.
    fee_free_months INTEGER NOT NULL DEFAULT 0,

    -- Скільки платежів ЛИШИЛОСЬ, тут НЕМАЄ навмисно: воно виводиться з
    -- first_payment_date, payments_total і сьогодні. Колонка була б
    -- другою правдою про той самий графік і розійшлася б із ним мовчки
    -- на першому ж місяці, коли її забудуть зменшити.
    opened_date TEXT NOT NULL DEFAULT '',
    -- Борг закрито. Не видалення: журнал і є історія того, як його
    -- гасили, а стерти її означало б карати за успіх (довід 0039).
    closed_date TEXT NOT NULL DEFAULT '',
    place       TEXT NOT NULL DEFAULT '',
    note        TEXT NOT NULL DEFAULT ''
) STRICT;

CREATE INDEX idx_debts_card ON debts(card_id);

-- debt_ops — рухи МІЖ звірками: те, що людина знає точно й памʼятає.
--
-- amount ЗАВЖДИ додатне, напрям задає kind — те саме правило, що в
-- plan_flows (0025) і term_deposits: одна колонка не повинна відповідати
-- одразу на два питання.
--
--   payment — унесено на картку / сплачено за розстрочкою (борг меншає);
--   draw    — покупка карткою (борг більшає, ПІЛЬГОВИЙ поширюється);
--   cash    — зняття готівки чи переказ із ліміту (борг більшає, і
--             пільгового в нього НЕМАЄ НІКОЛИ — відсоток нараховується з
--             першого дня). Окремий вид, а не позначка на draw, бо це
--             різні гроші з різною ціною, і зводити їх в одну суму
--             означало б назвати безкоштовний оборот платним або навпаки.
CREATE TABLE debt_ops (
    id      INTEGER PRIMARY KEY AUTOINCREMENT,
    debt_id INTEGER NOT NULL REFERENCES debts(id),
    date    TEXT    NOT NULL,
    kind    TEXT    NOT NULL CHECK (kind IN ('payment', 'draw', 'cash')),
    amount  INTEGER NOT NULL,               -- мінорні, > 0
    note    TEXT    NOT NULL DEFAULT ''
) STRICT;

CREATE INDEX idx_debt_ops_debt ON debt_ops(debt_id, date);

-- debt_marks — звірка з додатком банку. ОКРЕМОЮ ТАБЛИЦЕЮ, дзеркало
-- fund_prices (0034) і npf_nav (0028), і з того самого доводу: зовнішнє
-- джерело правдивіше за реконструкцію.
--
-- ЧОМУ ЦЕ ГОЛОВНИЙ МЕХАНІЗМ КАРТКИ, А НЕ ЗАПАСНИЙ. Баланс кредитки
-- рухається щодня десятком дрібних покупок. Вимагати журналу кожної
-- означало б завести журнал, якого ніхто не веде, — і застосунок показував
-- би впевнене число, яке відстало на тиждень. Тому баланс = остання
-- звірка + великі рухи після неї, а вік звірки показується поруч (лікуємо
-- ПОКАЗОМ, як price_stale у фазі 13).
--
-- ТРИ ЧИСЛА ОДНИМ РЯДКОМ, бо вони знімаються з одного екрана в один
-- момент. Розведені по трьох рядках, вони розійшлися б у часі, і
-- «скільки вільно» рахувалось би з балансу сьогоднішнього й виписки
-- позавчорашньої.
CREATE TABLE debt_marks (
    id      INTEGER PRIMARY KEY AUTOINCREMENT,
    debt_id INTEGER NOT NULL REFERENCES debts(id),
    date    TEXT    NOT NULL,
    -- ЗНАКОЗМІННИЙ, і це не недогляд: власник кладе на картку всю
    -- зарплату, виводить її в плюс і потім просаджує. Плюс — його власні
    -- гроші на картці, мінус — використаний ліміт. Одна вісь, бо це один
    -- баланс; два поля вимагали б правила «що робити, коли задані обидва».
    balance       INTEGER NOT NULL,
    -- Сума до сплати за виставленою випискою: скільки внести до
    -- розрахункової дати, щоб не платити відсотків ЗОВСІМ.
    statement_due INTEGER NOT NULL DEFAULT 0,
    -- Частина боргу, на яку пільговий не поширюється (готівка, перекази).
    -- Вона вже під відсотком, скільки б часу не лишалось до дати.
    non_grace     INTEGER NOT NULL DEFAULT 0,
    note          TEXT    NOT NULL DEFAULT '',
    -- Дві звірки на одну дату — це виправлення одруківки, а не дві
    -- правди. Той самий UNIQUE, що в fund_prices(fund_id, date).
    UNIQUE (debt_id, date)
) STRICT;

CREATE INDEX idx_debt_marks_debt ON debt_marks(debt_id, date);
