-- Рахунків (гаманця) більше немає: журнал поповнень і знять, обмін валют
-- і дві колонки знімка, що жили від них.
--
-- Ревізія 2026-10-03, рішення власника: рахунків у застосунку він не веде
-- (лише Inzhur, і то тому, що його підтягує виписка). Межею портфеля
-- тепер є сам інструмент — покупка заходить, виплата виходить
-- (engine/state_flows.go), — тож журнал рахунку став другим, нікому не
-- потрібним означенням тих самих грошей. Контракт стану перейшов на
-- schema 4.
--
-- ЧОМУ ВИДАЛЯЄМО, А НЕ ЛИШАЄМО ЛЕЖАТИ. Таблиця без коду — пастка для
-- наступного читача схеми (CLAUDE.md §3). Рішення власника — «видалити
-- після копії»: повна копія бази робиться автоматично перед міграцією
-- (`<db>.pre-0068_drop_cash_accounts`, migrate.go), а JSON-дамп власник
-- знімає перед деплоєм. Рухи Inzhur за потреби відтворюються повторним
-- імпортом виписок.
--
-- Знімки втрачають account_uah (залишок рахунків того дня) і idle_uah
-- (простій). Читачі знімків — капітал і рівні «Ціни моїх рішень» — тепер
-- складаються без готівки, і саме тому стара історія лишається
-- порівнянною сама з собою: з капіталу на кожну дату готівка зникла
-- однаково.
--
-- Дітей у deposits і conversions немає, тож вимикати ключі не треба.
DROP TABLE deposits;
DROP TABLE conversions;

ALTER TABLE snapshots DROP COLUMN account_uah;
ALTER TABLE snapshots DROP COLUMN idle_uah;
