-- Як у брокера заходять операції з сертифікатами фондів: випискою чи руками.
--
-- ДОТИ брокер із фондами був один — Inzhur, і його журнал вела виписка.
-- Форми додавання операції фонду не було навмисно: друге джерело тих самих
-- даних розійшлося б із випискою на першому ж імпорті (рядок, набраний
-- рукою, виписка принесла б ще раз, уже дублем).
--
-- З'явився другий брокер (ICU), у якого виписки, яку ми вміємо читати,
-- немає. Для нього «руками» — єдиний вхід, і забороняти його заради
-- Inzhur означало б не мати журналу зовсім. Тому правило тепер не «фонди
-- не вносять руками», а «руками не вносять туди, куди пише виписка», і
-- властивість ця — брокера: виписку дає установа, а не фонд.
--
-- entry = ''          — операції вносять руками (типове: новий брокер
--                       виписки не має, доки її не навчились читати);
-- entry = 'statement' — операції приносить виписка; POST /api/funds на
--                       такого брокера відхиляється, правка й видалення
--                       вже заведених рядків лишаються.
--
-- Рядком, а не 0/1, з тієї ж причини, що й funds.kind: рядок довідника
-- правиться на місці одним PUT, який шле значення полів як є.
--
-- Дозаповнення: «виписка» — той, під ким імпорт уже писав (нотатка
-- 'виписка' в fund_ops — її ставить лише імпорт), і брокер із назвою
-- inzhur, навіть якщо виписку ще не вантажили: саме під цією назвою імпорт
-- пише за замовчуванням.
ALTER TABLE brokers ADD COLUMN entry TEXT NOT NULL DEFAULT ''
    CHECK (entry IN ('', 'statement'));

UPDATE brokers SET entry = 'statement'
WHERE name = 'inzhur' COLLATE NOCASE
   OR id IN (SELECT broker_id FROM fund_ops WHERE note = 'виписка' AND broker_id IS NOT NULL);
