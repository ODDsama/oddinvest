-- Призначення на ДОХОДІ — стерти: воно ніколи нічого не означало.
--
-- Колонка dest (0030) описує, що сталося з грошима ПІСЛЯ витрати:
-- внесок у пенсійний — це рух із ліквідного боку, який не зникає, а стає
-- пенсійним капіталом. Проєкція розгортає цю другу половину рівно з
-- відʼємної місячної суми (state_projection.go: `if v := ...; v < 0`),
-- тобто для kind='income' поле не читає ніхто.
--
-- Мовчазний нуль виявився дорожчим за помилку. Форма показувала селект
-- однаково обом видам, список малював під рядком пігулку «НПФ · переказ,
-- а не витрата» — і на доходному рядку («Бонус IBWT», 250 $) застосунок
-- стверджував рух, якого не було в жодному його числі. Тепер API таке
-- поєднання відхиляє (handlers_plan.go), а форма ховає поле на доході;
-- цей рядок прибирає те, що встигло осісти до заборони.
UPDATE plan_flows SET dest = '' WHERE kind = 'income' AND dest <> '';

