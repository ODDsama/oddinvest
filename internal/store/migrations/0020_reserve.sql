-- Резерв («матрац») — гроші, відкладені НА ЧОРНИЙ ДЕНЬ.
--
-- Четверта сутність поряд з ОВДП, фондами й вкладами, і за природою вона
-- від них усіх відрізняється: немає ні дохідності, ні строку, ні ціни.
-- Саме тому вона й потрібна — це єдине, що доступне миттєво й без втрат,
-- коли гроші раптом знадобились насправді.
--
-- Не плутати з таблицею `deposits`: та тримає рух коштів НА РАХУНКАХ
-- БРОКЕРІВ, тобто гроші, які чекають на вкладення. Резерв — навпаки,
-- гроші, які вкладати не збираються. Тому й окрема таблиця: якби резерв
-- був ще одним «брокером», помічник реінвесту порахував би його
-- купівельною спроможністю й запропонував купити папір за аварійні
-- гроші.
--
-- Журнал рухів, а не поточний залишок: залишок — це Σ сум, а історія дає
-- побачити, як резерв набирався, і не змушує гадати, коли він змінився.
--
-- ВАЖЛИВО про переміщення гаманець → резерв. Окремої сутності переказу в
-- застосунку немає (див. коментар про переказ між брокерами в
-- state_builder), тож переміщення записується двома ногами: мінусом у
-- `deposits` і плюсом тут. Через це «внесено за місяць» рахується нетто
-- по ОБОХ журналах разом — інакше відкладання виглядало б як втрата
-- капіталу, псуючи місячний прогрес, фактичний темп і бенчмарк.
CREATE TABLE reserve_ops (
    id       INTEGER PRIMARY KEY AUTOINCREMENT,
    date     TEXT    NOT NULL,
    amount   INTEGER NOT NULL,                    -- + відклав / − взяв, мінорні
    currency TEXT    NOT NULL DEFAULT 'UAH',
    -- Місце зберігання (готівка, сейф, окрема картка). Вільний текст, а не
    -- довідник: на відміну від брокера, за ним нічого не рахується — це
    -- підпис для людини, щоб не забути, де саме лежить.
    place    TEXT    NOT NULL DEFAULT '',
    note     TEXT    NOT NULL DEFAULT ''
) STRICT;

CREATE INDEX idx_reserve_ops_date ON reserve_ops(date);
