-- Кошик «дострокове погашення боргу» зникає з дозволів потоку.
--
-- # ЧОМУ
--
-- Кошик debt (0041) означав «цим грошам можна в дострокове погашення», і
-- читала його рівно одна річ — вирізка боргу в розкладці надходження. Вона
-- брала частку від PlanDebtUAH, тобто від ПОРТФЕЛЬНИХ грошей, і зменшувала
-- базу, від якої далі міряються цільові частки ОВДП, фондів і пенсійного.
--
-- Власник: «борг має відніматись від планового доходу, але не впливати на
-- ті відсотки які я вже зазначив шо буду класти в портфель». Обовʼязковий
-- платіж так уже й поводився — його гасить картковий контур, і до плану
-- доходить лише переповнення (MonthPlan.DebtFromPlanUAH). Дострокове —
-- ні.
--
-- Тепер розкладка й маршрут не ведуть гроші в борг зовсім. Дострокове
-- погашення лишилось свідомою дією людини, а стеля на сторінці боргу
-- міряється від КАРТКОВИХ грошей — там дозволів потоку немає за
-- побудовою, бо в цей контур гроші потрапляють якраз тим, що НЕ дійшли до
-- портфеля.
--
-- Тобто питання «чи можна цим грошам у борг» стало питанням без
-- механізму. Галочка, яка нічого не робить, гірша за її відсутність:
-- людина ставить її, чекає наслідку й не дістає жодного.
--
-- # ЧОМУ ВИЧИЩАЄМО, А НЕ ЛИШАЄМО ЛЕЖАТИ
--
-- PlanUseAllowed невідомого слова не знає, тож стара база читалась би й
-- так — але зі значенням "reserve,debt" вона казала б неправду вдвічі:
-- по-перше про кошик, якого немає, по-друге про сам ДОЗВІЛ. Рядок
-- "reserve,debt" — це «лише подушка й борг», і без вичищення він
-- назавжди лишився б звуженням, у якому друга половина мертва, а перша
-- діє. Людина, яка колись поставила дві галочки, дістала б одну — і
-- ніде б цього не побачила.
--
-- Порожній результат означає «будь-куди», і це саме те, що треба:
-- потоку, якому дозволяли ЛИШЕ борг, тепер не заборонено нічого. Обернути
-- це на «нічого не можна» було б заборонóю, якої ніхто не ставив (той
-- самий довід, що при порожньому значенні в 0041).
--
-- # ЧОМУ ТРИ ТАБЛИЦІ
--
-- Дозвіл живе в потоці (plan_flows), у журналі його ревізій
-- (plan_flow_revisions — минулі місяці читаються з тієї ревізії, що діяла
-- тоді) і в самій відмітці надходження (plan_receipts — «інше» власного
-- потоку не має). Вичистити лише перший означало б, що серпень і далі
-- памʼятає кошик, якого вересень уже не знає.
--
-- # ЯК
--
-- Кому — це кома, і слово може стояти першим, останнім або посередині.
-- Обгортаємо значення комами, вирізаємо ',debt,' одним replace і знімаємо
-- обгортку: так усі три позиції ловляться однаково, без CASE на кожну.
-- Порожнє значення лишається порожнім (',' → ',' → ''), тож рядки, яким
-- нічого не забороняли, не змінюються взагалі.

UPDATE plan_flows
   SET uses = trim(replace(',' || uses || ',', ',debt,', ','), ',')
 WHERE uses LIKE '%debt%';

UPDATE plan_flow_revisions
   SET uses = trim(replace(',' || uses || ',', ',debt,', ','), ',')
 WHERE uses LIKE '%debt%';

UPDATE plan_receipts
   SET uses = trim(replace(',' || uses || ',', ',debt,', ','), ',')
 WHERE uses LIKE '%debt%';
