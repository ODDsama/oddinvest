-- Позначки ціни сертифіката: ціна на дату, не привʼязана до моїх операцій.
--
-- ЦЕ СКАСУВАННЯ ЗАПИСАНОГО РІШЕННЯ, і його треба назвати вголос. Шапка 0009
-- каже: «Ціна за сертифікат навмисно не зберігається: вона завжди
-- amount/qty, і окреме поле лише дало б їм розійтись». Шапка 0028
-- посилається на той самий довід, пояснюючи, чому НПФ потрібна npf_nav, а
-- фондам аналог — ні: «виписка приносить ціну з собою».
--
-- Довід був правильний рівно для РОЗПОДІЛЬНОГО фонду, який докуповують
-- регулярно, а дивіденди приходять щомісяця. Для НАКОПИЧУВАЛЬНОГО він
-- хибний, і хибний найдорожчим способом:
--
--   * Inzhur MilTech не платить ні купона, ні дивіденда — увесь дохід
--     сидить у ціні сертифіката. Виписка приносить ціну лише в мить
--     КУПІВЛІ, а купують такий папір раз;
--   * тому для позиції з однією купівлею MarketValue назавжди дорівнює
--     CostBasis, а FundTotalReturn (domain/funds.go) дає рівно два потоки —
--     «−A у день купівлі» і «+A сьогодні», — тобто XIRR нуль з ok=true.
--     Нуль тут не вимір, а тотожність: терміналом стоїть та сама ціна, за
--     якою я купив;
--   * і цей нуль ВИТІСНЯВ обіцянку фонду (state_funds.go), тобто на екрані
--     стояло 0% номінальних і відʼємні реальні там, де фонд обіцяє 25%
--     простих за три роки.
--
-- Зауваження 0009 при цьому лишається чинним і не пом'якшується: ціни в
-- fund_ops як не було, так і немає, і вона й далі виводиться як
-- amount*100/qty. Ця таблиця не дублює її, а стоїть ПОРУЧ — рівно так само,
-- як npf_nav стоїть поруч із ЧВОПА, виведеною з внеску.
--
-- МАСШТАБ. price_e4 — ×10⁴ від гривні, тобто рівно те, чим живе
-- FundPosition.LastPrice: 11.1120 ₴ = 111120. Свідомо НЕ ×10⁶, як nav_e6 у
-- 0028: там ЧВОПА з шістьма знаками, тут ціна сертифіката з чотирма, і
-- інший масштаб змусив би модель перемасштабовувати на кожному читанні —
-- тобто завів би друге місце, де ціна може розійтись сама з собою.
--
-- КЛЮЧ — fund_id, А НЕ НАЗВА, і це не стиль. RenameFund (store/refs.go)
-- міняє лише funds.name; fund_ops тримається за fund_id і перейменування
-- підхоплює задарма — саме заради цього 0010 і перебудувала таблицю.
-- Позначка ціни, привʼязана до назви, відчепилась би від фонду тихо, при
-- виправленні описки в довіднику, тобто рівно від тієї біди, яку 0010
-- лікувала.
--
-- UNIQUE(fund_id, date): дві різні ціни на один день — це не історія, а
-- суперечність. Вклеювання пачкою покладається на це й перезаписує день.
-- Окремого індексу немає навмисно: UNIQUE уже дає індекс по (fund_id,
-- date), а це саме той порядок, у якому таблицю й читають.
CREATE TABLE fund_prices (
    id       INTEGER PRIMARY KEY AUTOINCREMENT,
    fund_id  INTEGER NOT NULL REFERENCES funds(id),
    date     TEXT    NOT NULL,
    price_e4 INTEGER NOT NULL,
    UNIQUE(fund_id, date)
) STRICT;
