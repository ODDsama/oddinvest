-- Індекс споживчих цін НБУ: друга лінійка реальності поруч зі знеціненням.
--
-- ЧОМУ ВЗАГАЛІ. realYield (internal/api/devaluation.go) дефлює ЛИШЕ гривню
-- і ЛИШЕ курсом долара за десять років; будь-яка інша валюта повертається
-- неторканою. Тобто в модель зашито припущення «долар купівельну
-- спроможність тримає», і жодного способу перевірити його в застосунку
-- немає — ряду цін не було ніде. README казав це вголос у трьох місцях
-- («інфляція — ряду ІСЦ у застосунку немає»). Ця таблиця його заводить.
--
-- ЩО САМЕ ЗБЕРІГАЄМО — ЛИШЕ ОПУБЛІКОВАНЕ. Індекс (рівень цін) — похідна
-- від ланцюжка місячних змін, і його місце в domain (CLAUDE.md §5), а не
-- в колонці: збережений рівень розійшовся б із перерахованим на першій же
-- правці бази, і розійшовся б мовчки.
--
-- yoy_bp зберігається ПОПРИ те, що виводиться з ланцюга m/m. Це не
-- дублювання, а єдина ЗОВНІШНЯ звірка: якщо ланцюг поплив (пропущений
-- місяць, зсув на місяць, помилка масштабу), розбіжність із опублікованим
-- річним темпом видно одразу, і на цьому стоїть тест
-- TestCPIChainMatchesPublishedYoY. Без другої точки помилку ланцюга не
-- ловить ніщо — вона тиха за побудовою.
--
-- МАСШТАБ — базисні пункти, як RateBP і TaxBP поруч і як rate_e4/price_e4
-- у сусідніх рядах. НБУ публікує один знак після коми (1.4, 12.0, −0.3),
-- тож bp тримає джерело точно, а float64 не зʼявляється в ланцюжку
-- зберігання взагалі.
--
-- КЛЮЧ — period 'YYYY-MM', тобто місяць, ДО ЯКОГО належить число. Це не
-- дрібниця: сам НБУ адресує ці дані датою «станом на 1-ше», тобто
-- відповідь на date=202501 містить дані за ГРУДЕНЬ 2024 (перевірено на
-- трьох контрольних точках, довід — у шапці nbu.Inflation). Зсув
-- знімається на межі клієнта й до бази не доходить; тут period завжди
-- означає звітний місяць.
--
-- КРУДУ ТУТ НЕ БУДЕ, і це не порушення правила «де є операції — там
-- повний КРУД» (CLAUDE.md §2). Те правило про сутності, які ЗАВОДИТЬ
-- людина; ряд ІСЦ приходить із НБУ бекфілом і добовою джобою, як курси й
-- аукціони. Виправляти опубліковану статистику руками нема чого й нема
-- підстав.
--
-- НЕ СКОУПОВАНА ДО ПОРТФЕЛЯ — довідник, як fx_rates, bonds і
-- ovdp_auctions (0054 називає їх спільним словом «довідкове»). Ціни в
-- країні одні на всіх, і колонка portfolio_id тут означала б, що в
-- дружини може бути своя інфляція.
CREATE TABLE cpi_points (
    period TEXT    NOT NULL,  -- 'YYYY-MM', звітний місяць
    mom_bp INTEGER NOT NULL,  -- % до попереднього місяця × 100
    yoy_bp INTEGER NOT NULL,  -- % до того самого місяця торік × 100
    PRIMARY KEY (period)
) STRICT;
