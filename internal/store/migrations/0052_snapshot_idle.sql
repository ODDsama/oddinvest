-- Простій у добовому знімку: скільки вільних грошей брокера ВЖЕ можна
-- було вкласти того дня (цілі квитки по кожній парі брокер × валюта,
-- грн-екв.).
--
-- Навіщо колонка, коли є account_uah. Баланс не каже, чи можна ним щось
-- купити: 900 ₴ при квитку в 1 000 — не простій, а «збирається на квиток».
-- Простій — та частина, яка лежить уже понад ціну паперу; саме її ціну
-- («−X ₴/міс») показує застосунок, і саме її відсутність день за днем
-- відзначає віха «Місяць без простою».
--
-- DEFAULT −1, а не 0, і це важливо. У попередніх колонках знімка нуль
-- означав «тоді не рахували», і крива на ньому просто обривалась. Тут нуль
-- має власний зміст — «простою не було», — і саме він потрібен віхі. Тож
-- «не рахували» мусить бути іншим числом: старі рядки дістають −1, і серія
-- днів без простою починається з першого знімка, який простій знає.
-- Джоба пише сюди лише невідʼємні значення.
ALTER TABLE snapshots ADD COLUMN idle_uah INTEGER NOT NULL DEFAULT -1;
