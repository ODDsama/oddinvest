-- Планові витрати: вирішені разові витрати з датою й станом «сплачено».
--
-- ЩО ЦЕ ВЗАГАЛІ. «Замінити котел у листопаді за 30 000», «страховка до
-- 14-го», «гуми навесні» — гроші, які людина вже вирішила витратити, але
-- ще не витратила. Доти застосунок про них не знав нічого: план місяця
-- обіцяв усі свої гроші портфелю, стеля витрат рахувала так, ніби попереду
-- лише звичайний побут, а маршрут вів у папери те, що за місяць піде на
-- котел.
--
-- # ЧОМУ ЦЕ НЕ plan_flows З kind=expense І cadence=once
--
-- Форма рядка справді майже однакова: назва, сума, валюта, дата. Список у
-- UI виглядатиме схоже. Тому довід тут механічний, а не смаковий — інакше
-- ця шапка була б самовиправданням.
--
-- 1. ПРОСТРОЧЕНА ЗНИКАЄ, І ПОЛАГОДИТИ ЦЕ ЛОКАЛЬНО НЕМОЖЛИВО. Разова
--    витрата з датою минулого місяця дає нуль у КОЖНОМУ місяці, у
--    поточному теж: planFlowNativePast обриває минуле (`case "once": if
--    raw < 0`), а planFlowNative платить лише у свій місяць (`if m !=
--    start`). Тобто «прострочена й далі тисне» в потоках не виконується за
--    побудовою. Правка йшла б у planFlowAmount — ЄДИНЕ означення
--    періодичності в застосунку, на якому стоять проєкція, профіль
--    надходжень, колонка «дає ₴/міс», історія плану й чутливість. Разом із
--    витратою підтягувалась би й прострочена премія, а це вже неправда про
--    дохід.
--
-- 2. СТАНУ ВИКОНАННЯ В ПОТОЦІ НЕМАЄ, А НАЙБЛИЖЧИЙ СУСІД ОЗНАЧАЄ
--    ПРОТИЛЕЖНЕ. Єдине місце, де в плану є факт, — plan_receipts (0027),
--    але вона заміщає СУМУ, і нуль там уже зайнятий: він означає «не
--    прийшло». Для витрати нуль означав би «витрати не сталося» — одна
--    колонка, дві протилежні відповіді.
--
-- 3. «СПЛАЧЕНО» ПЕРЕПИСУВАЛО Б ІСТОРІЮ ПЛАНУ. UpdatePlanFlow пише ревізію
--    в plan_flow_revisions у тій самій транзакції, а buildPlanHistory
--    реконструює минулі місяці через planAsOf. Кожне натискання «сплачено»
--    ставало б подією журналу правок, і вересневий план у картці «План
--    проти факту» переписувався б дією, яка до плану стосунку не має.
--    Журнал 0026 існує рівно проти цього.
--
-- 4. ПОЛОВИНА КОЛОНОК ПОТОКУ МЕРТВА В КОЖНОМУ РЯДКУ: cadence (завжди
--    once), growth_bp (для разової безглузда), until_date, invest_bp (у
--    витрати немає частки, що доходить до портфеля), dest, uses (API
--    відхиляє їх для витрат) — шість із тринадцяти. Дослівно той довід,
--    яким 0039 розвела цілі й резерв.
--
-- І окремо для цієї фази: buildDebtExit НЕ читає витратні потоки навмисно
-- (вони вже сидять або в заявлених monthly_expenses, або у виміряному
-- спаленні картки). Планова витрата в стелю ввійти мусить — у plan_flows
-- довелося б завести колонку «а цей рядок рахувати ще й у стелі», тобто ту
-- саму колонку на два питання, проти якої написана шапка 0025.
--
-- # ОДИН РЯДОК — ОДИН КОНТУР (paid_from)
--
-- Гроші течуть двома контурами: Gross = Income (доходить до портфеля за
-- invest_bp) + OnCard (усе інше — лишається там, куди прийшло, і
-- витрачається з картки). План місяця стоїть на першому, стеля витрат — на
-- другому, і вони НЕ перетинаються: buildDebtExit бере IncomeUAH+ExtraUAH,
-- а не ExpenseUAH, саме тому.
--
-- Витрата, віднята з обох, забрала б удвічі більше, ніж коштує. Це не
-- гіпотеза: карткові розстрочки колись віднімались в обох, і 8 606,70
-- ₴/міс уронили план місяця з 26 902 до 18 296 (довід — при
-- MonthPlan.DebtDueUAH). Тому paid_from вибирає контур, і рядок тисне
-- рівно на один.
--
-- Відкинуто:
--   · КАСКАД (з'їдає спершу план, залишок — картку) — вимагав би в
--     buildDebtExit другого означення «скільки план не поглинув»;
--   · ДРУГИЙ ВІДСОТОК, як invest_bp — «розмір вирізки лишається за стелями
--     наповнення, і другий відсоток тут був би другим означенням того
--     самого числа» (0041).
--
-- # ДАТА, А НЕ МІСЯЦЬ
--
-- plan_receipts обрала місяць із прямо названої причини: «нічого не
-- прийшло» дня не має взагалі. У витрати навпаки — день є в самому
-- договорі, і його потребують двоє: фільтр місяця звірки картки (він міряє
-- платіжний день) і саме означення «прострочена» — 12-го числа витрата з
-- датою 20-го ще не прострочена, і місячний ключ цього сказати не може.
-- Місяць із дати виводиться; дата з місяця — ні.
--
-- # paid_date, А НЕ status
--
-- Ідіома тут уже є (goals.done_date, debts.closed_date), але в цій таблиці
-- вона ще й ЗМІСТОВНА: сплачена ДО дати звірки картки вже сидить у
-- виміряному мінусі, сплачена після — ні. status='paid' це знання втрачає,
-- а status і paid_date поруч були б двома джерелами одного стану, які
-- розійдуться (той самий довід, що при debts.exit_by у 0047).
--
-- ЧОГО ТУТ СВІДОМО НЕМАЄ:
--   · cancelled_date. Скасована планова витрата — не факт, який варто
--     зберігати: під нею немає журналу (на відміну від цілі з goal_ops), і
--     DELETE каже про неї все. Друга дата стану була б колонкою заради
--     одного випадку.
--   · cadence, growth_bp, until_date. Періодична витрата — це і є
--     plan_flows; другий спосіб описати щомісячний платіж породив би
--     питання «який із двох справжній».
--   · журналу ревізій. Минулі місяці з цієї таблиці не реконструюються
--     ніде: buildPlanHistory читає лише потоки. Дзеркало 0026 було б
--     механізмом без читача.
--
-- CHECK на paid_from — тому що цей набір читає АРИФМЕТИКА: описка 'wallet'
-- мовчки перекинула б гроші не в той контур, і помітили б це не одразу.
-- На amount CHECK-а немає навмисно: додатність перевіряє API, як і в
-- plan_flows, і третій спосіб робити те саме тут ні до чого.
CREATE TABLE plan_expenses (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    portfolio_id INTEGER NOT NULL DEFAULT 1 REFERENCES portfolios(id) ON DELETE CASCADE,
    name         TEXT    NOT NULL,
    amount       INTEGER NOT NULL,               -- мінорні, > 0; напрям у сутності, не в знаку
    currency     TEXT    NOT NULL DEFAULT 'UAH', -- своя, як у цілі: ціна речі названа у своїй валюті
    due_date     TEXT    NOT NULL,               -- 'YYYY-MM-DD', коли гроші мають піти
    paid_from    TEXT    NOT NULL DEFAULT 'card' -- 'card' — побут; 'plan' — портфельні гроші
                 CHECK (paid_from IN ('card','plan')),
    paid_date    TEXT    NOT NULL DEFAULT '',    -- '' = ще винна
    place        TEXT    NOT NULL DEFAULT '',
    note         TEXT    NOT NULL DEFAULT ''
) STRICT;

CREATE INDEX idx_plan_expenses_portfolio ON plan_expenses(portfolio_id);
CREATE INDEX idx_plan_expenses_due       ON plan_expenses(portfolio_id, due_date);
