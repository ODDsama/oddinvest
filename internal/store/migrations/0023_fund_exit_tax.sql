-- Податок при ДОСТРОКОВОМУ виході з фонду.
--
-- Друге число, а не уточнення першого. income_tax_bp (0022) — це податок
-- на дохід, коли фонд доживає до закриття й віддає його дивідендами:
-- 14% = 9% ПДФО + 5% ВЗ. Вийти раніше теж можна, але тоді це продаж
-- сертифікатів, і оподатковується різниця між купівлею й продажем за
-- іншою ставкою — для Inzhur MilTech це 23%.
--
-- Одним полем цього не сказати: події різні, ставки різні, і настає рівно
-- одна з двох. Модель накопичення веде фонд до закриття, тобто бачить
-- перше число; декумуляція питає «а якщо гроші потрібні зараз» і бачить
-- друге.
--
-- Нуль означає «не задано», і тоді податку при виході модель не малює.
-- Ставка не зашита в код з тієї самої причини, що й у 0022: вона залежить
-- від інструмента й від того, що саме сталося, а не від застосунку.
ALTER TABLE funds ADD COLUMN exit_tax_bp INTEGER NOT NULL DEFAULT 0;
