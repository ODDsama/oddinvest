-- Цілі накопичення: авто, будинок, ремонт.
--
-- ТРЕТЯ ПРИРОДА ГРОШЕЙ, і саме тому окрема сутність, а не рядок у сусідніх
-- таблицях.
--
-- Не `deposits`: там рух коштів НА РАХУНКАХ БРОКЕРІВ, тобто гроші, які
-- чекають на вкладення. Ці — навпаки, гроші, які вкладати не збираються.
-- Довід дослівно той самий, що привів до окремої таблиці резерв у 0020, і
-- наслідок хибного злиття той самий: помічник реінвесту порахував би
-- накопичення на авто купівельною спроможністю.
--
-- Але й не `reserve_ops`, попри однакову форму рядка. Резерв — це запас на
-- те, чого НЕ ПЛАНУЮТЬ: у нього немає ні суми, ні дати, а ціль виводиться
-- з місячних витрат («на скільки вистачить прожити»). Ціль накопичення —
-- протилежне за визначенням: у неї є названа сума, названа дата й намір
-- ВИТРАТИТИ. З цього виходять різні питання й різні відповіді: у резерву
-- питають «чи вистачить», у цілі — «чи встигну». Одна таблиця на дві
-- сутності означала б колонку `target_amount`, мертву в кожному рядку
-- резерву, і колонку `months`, мертву в кожному рядку цілі.
--
-- ЖУРНАЛ РУХІВ, А НЕ ПОТОЧНИЙ ЗАЛИШОК — так само, як у резерву: залишок
-- це Σ сум, а історія показує, як ціль набиралась, і не змушує гадати,
-- коли вона зрушила.
--
-- ПЕРЕМІЩЕННЯ ГАМАНЕЦЬ → ЦІЛЬ записується ДВОМА НОГАМИ (мінус у
-- `deposits`, плюс тут), бо окремої сутності переказу в застосунку немає.
-- Через це «внесено за місяць» рахується нетто по ВСІХ трьох журналах
-- разом — інакше відкладання на авто виглядало б як втрата капіталу,
-- псуючи місячний прогрес, фактичний темп і бенчмарк. Абзац перенесено з
-- 0020 навмисно: він однаково чинний і його однаково легко проґавити.
CREATE TABLE goals (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    name          TEXT    NOT NULL,
    -- Сума й валюта — У ВАЛЮТІ ЦІЛІ, а не в гривні. Авто коштує $20 000, і
    -- гривнева ціна цих самих $20 000 змінюється щодня; ціль, записана
    -- гривнею, тихо занижувалась би рівно на девальвацію, а прогрес до неї
    -- зростав би сам собою, без жодної відкладеної копійки.
    target_amount INTEGER NOT NULL,               -- мінорні, у валюті цілі
    currency      TEXT    NOT NULL DEFAULT 'UAH',
    -- Порожньо = ціль без дедлайну. Це не «дата ще не введена», а законний
    -- стан: «збираю на будинок, коли збереться — тоді й куплю». Темпу в
    -- такої цілі немає, і питання «чи встигаю» їй не ставлять.
    due_date      TEXT    NOT NULL DEFAULT '',
    -- Порядок наповнення, коли цілей кілька й на всіх не вистачає. Менше
    -- значення — раніше в черзі; рівні розводить due_date, потім id.
    priority      INTEGER NOT NULL DEFAULT 0,
    -- Місце зберігання — вільний текст, як у резерву й з того самого
    -- доводу: за ним нічого не рахується, це підпис для людини.
    place         TEXT    NOT NULL DEFAULT '',
    note          TEXT    NOT NULL DEFAULT '',
    -- Ціль закрита: річ куплена. Не видалення — журнал і є історія того,
    -- як на неї збирали, і стирати його разом із досягненням означало б
    -- карати за успіх.
    done_date     TEXT    NOT NULL DEFAULT ''
) STRICT;

CREATE TABLE goal_ops (
    id       INTEGER PRIMARY KEY AUTOINCREMENT,
    goal_id  INTEGER NOT NULL REFERENCES goals(id),
    date     TEXT    NOT NULL,
    -- + відклав / − узяв, мінорні. Валюта СВОЯ, а не ціль-ова: відкладати
    -- на доларову ціль можна й гривнею, і саме тоді курс стає видимим —
    -- зібране в гривні міряється в доларах за сьогоднішнім курсом, тож
    -- прогрес може поїхати назад без жодного зняття.
    amount   INTEGER NOT NULL,
    currency TEXT    NOT NULL DEFAULT 'UAH',
    place    TEXT    NOT NULL DEFAULT '',
    note     TEXT    NOT NULL DEFAULT ''
) STRICT;

CREATE INDEX idx_goal_ops_goal ON goal_ops(goal_id, date);
