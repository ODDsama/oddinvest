-- Дозвіл надходження: на що саме ці гроші можуть піти.
--
-- Доти джерело доходу вміло сказати про себе рівно одне число —
-- invest_bp, «яка частка доходить до портфеля». Куди саме вона доходить,
-- потік не казав нічого, і для подушки з цілями всі надходження були
-- однакові: дохід, який власник свідомо тримає лише на інвестиції,
-- подушка різала нарівні з тим, який справді можна класти під матрац.
--
-- ФОРМАТ: '' = без обмежень, інакше перелік кошиків через кому в сталому
-- порядку 'reserve,goals,invest,npf' — тому самому, у якому їх наповнює
-- розкладка. Значення розбирає domain.ParsePlanUses, і там же живуть
-- доводи, чому порожнє означає «будь-куди», а не «нікуди».
--
-- ЦЕ ДОЗВІЛ, А НЕ ПОДІЛ. Розмір вирізки лишається за стелями
-- reserve_fill_share_pct і goals_fill_share_pct: другий відсоток на
-- потоці був би другим означенням того самого числа.
ALTER TABLE plan_flows ADD COLUMN uses TEXT NOT NULL DEFAULT '';

