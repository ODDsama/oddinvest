-- Собівартість фондів у добовому знімку.
--
-- Знімок носив ВАРТІСТЬ фондів (funds_uah, 0012), але не те, за скільки
-- вони куплені. Через це на кривій неможливо було чесно показати прибуток:
-- invested_uah рахується лише по облігаціях (див. цикл по Positions у
-- internal/state), тож різниця між ним і капіталом складалась переважно з
-- вартості самих фондів, а читалась би як заробіток.
--
-- Тіло вкладів для тієї ж суми брати нема звідки й не треба: deposits_uah
-- (0016) — це вже внесені гроші, тобто водночас і вартість, і собівартість.
-- Бракувало саме фондів.
--
-- Старі рядки лишаються з нулем — і тут це особливо важливо: нуль означає
-- «тоді не рахували», а НЕ «купили задарма». Лінія собівартості мусить
-- починатись там, де зʼявилась колонка, інакше вона намалює прибуток
-- розміром у весь фонд у день, коли насправді нічого не сталося.
ALTER TABLE snapshots ADD COLUMN funds_cost_uah INTEGER NOT NULL DEFAULT 0;
