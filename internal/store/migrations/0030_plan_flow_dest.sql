-- Куди йде потік плану: у ліквідний портфель чи в пенсійний рахунок.
--
-- Доти витрата в плані означала рівно одне — гроші пішли й зникли. Для
-- квартплати це правда. Для внеску в НПФ хибно: гроші пішли з ліквідного,
-- але не зникли, а стали пенсійним капіталом, який компаундиться до
-- 50 років.
--
-- Без цієї колонки внесок доводилось заводити або витратою (і тоді
-- проєкція мовчки губила пенсійні гроші), або доходом зі знаком (і тоді
-- вони брались із нічого). Обидва варіанти дають правдоподібні числа й
-- обидва неправильні.
--
-- Чому колонка, а не власна таблиця npf_contributions. «1000 ₴/міс іде із
-- зарплати» — це рівно те, що plan_flows уже вміє сказати: сума,
-- періодичність, дата початку, індексація, журнал ревізій (0026) і журнал
-- фактичних надходжень (0027). Друга таблиця була б ДРУГИМ способом
-- задати ті самі числа, і на питання «який із них справжній» відповіді не
-- було б — та сама причина, через яку в застосунку немає ні пресетів
-- налаштувань, ні збереженого кошика.
--
-- Формат: '' = ліквідний портфель (поведінка, яку мали всі наявні рядки),
-- 'npf:<id>' = пенсійний рахунок. Рядком, а не FK на npf_accounts:
-- призначень із часом буде більше одного виду, і префікс лишає місце для
-- них, не плодячи по колонці на вид. Той самий синтетичний ключ, що вже
-- ходить у календарі (domain.NPFISINPrefix).
--
-- Знак при цьому НЕ змінюється: внесок лишається kind='expense', бо з
-- ліквідного боку він і є витратою. Призначення каже лише, що з цими
-- грошима сталося ПОТІМ, а не в який бік вони рухались.
ALTER TABLE plan_flows ADD COLUMN dest TEXT NOT NULL DEFAULT '';

-- Та сама колонка в журналі ревізій — і це не симетрія заради симетрії.
--
-- Журнал реконструює план на будь-яку дату в минулому: саме на ньому
-- стоїть картка «План проти факту». Колонка, якої в ревізіях немає,
-- відновлюється з ПОТОЧНОЇ таблиці — тобто минуле знову стає
-- переписуваним, рівно те, від чого 0026 і рятує. Перевів внесок на інший
-- рахунок — і вся історія заднім числом стала б такою, ніби він завжди
-- був там.
ALTER TABLE plan_flow_revisions ADD COLUMN dest TEXT NOT NULL DEFAULT '';
