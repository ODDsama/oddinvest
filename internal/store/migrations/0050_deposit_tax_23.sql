-- Податок на відсотки вкладу: 19.5% → 23%.
--
-- ЧОМУ ЦЕ ПОМИЛКА, А НЕ ЗМІНА ПОЛІТИКИ. З 01.12.2024 військовий збір для
-- фізосіб — 5%, а не 1.5%. Відсотки вкладу оподатковуються ПДФО 18% + ВЗ,
-- тобто 23%, а не 19.5%. Застосунок віз старе число з 0013 і сам собі
-- суперечив: funds.exit_tax_bp (0023) уже 2300, funds.income_tax_bp (0022)
-- уже 1400 = 9% + 5%. Обидва виведені з тієї самої ставки ВЗ, і збігтись
-- вони могли б лише за одного значення збору.
--
-- Ціна помилки не косметична. Занижений податок завищує NetRate, а через
-- неї — реальну дохідність, за якою «Що купити» РАНЖУЄ інструменти. Вклад
-- стояв у тому списку вище, ніж заслуговує, і саме проти ОВДП, чий купон
-- від податку звільнений узагалі.
--
-- ЧОМУ САМЕ `= 1950`, А НЕ ВСІ РЯДКИ. 1950 — старий дефолт, тобто «форма
-- підставила сама». Будь-яке інше число власник вписав руками, знаючи свій
-- договір, і затирати введене міграцією не можна: це рівно той випадок,
-- коли дані сильніші за налаштування (див. Replenishable у domain/deposit.go).
--
-- ЩО ЦЕ ЗАОКРУГЛЮЄ. Модель тримає ОДНУ ставку на вклад і застосовує її до
-- всіх відсотків за весь строк. Для вкладу, який платив ще до грудня 2024,
-- частина відсотків насправді оподаткована по 19.5%, і після міграції його
-- історичний податок буде трохи завищений. Розмін свідомий: майбутнє й
-- теперішнє важать більше за минуле, а альтернатива — сегментувати ставку
-- за датами — це другий стовпець і графік переходів заради вкладів, яких у
-- базі одиниці.
--
-- DEFAULT 1950 У СТОВПЦІ ЛИШАЄТЬСЯ, і це не недогляд. SQLite не вміє
-- змінювати дефолт без перебудови таблиці, а на term_deposits висить
-- зовнішній ключ із deposit_topups (0014). Дефолт при цьому мертвий: усі
-- INSERT називають tax_bp поіменно (store.go, backup.go), тож спрацювати
-- йому нема де. Живі дефолти сидять у Go — handlers_deposits.go і
-- defaultDepositTaxBP у state_plan_buys.go, — і вони змінені разом із цією
-- міграцією.
UPDATE term_deposits SET tax_bp = 2300 WHERE tax_bp = 1950;
