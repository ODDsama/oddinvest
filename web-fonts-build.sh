#!/usr/bin/env bash
# Збірка підмножин шрифтів для web/fonts. Запускається РАЗОВО, руками.
#
# Збірки в UI немає навмисно, і цей скрипт її не заводить: він не бере
# участі ні в `make ui`, ні в CI, ні в `go build`. Результат — два woff2 —
# лежить у репозиторії як звичайний файл, і саме він, а не цей скрипт,
# є джерелом істини. Скрипт відповідає лише на питання «звідки воно
# взялося і як повторити», яке інакше не має де бути записаним.
#
# Чому підмножина, а не файл як є: цілий Inter важить 856 КіБ, цілий
# Source Serif 4 — 1181 КіБ, і обидва їдуть у бінарник через //go:embed.
# Застосунок говорить українською й латиницею; решта — з десяток тисяч
# гліфів, які ніхто ніколи не побачить.
#
# Ліцензія — SIL OFL 1.1 в обох. Вона вимагає, щоб копія тексту їхала
# разом зі шрифтом, тож OFL-*.txt теж лягають у web/fonts і теж
# потрапляють у бінарник.
#
# Потрібні fontTools і brotli (без другого fontTools не вміє писати woff2).
# Системний pip на свіжих Debian/Ubuntu їх поставити не дасть — PEP 668, —
# тож нормальний шлях це окреме віртуальне середовище, а не
# --break-system-packages:
#
#   python3 -m venv /tmp/oi-fonts && /tmp/oi-fonts/bin/pip install fonttools brotli
#   PY=/tmp/oi-fonts/bin/python ./web-fonts-build.sh
set -euo pipefail

cd "$(dirname "$0")"
OUT="internal/api/web/fonts"
PY="${PY:-python3}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

if ! "$PY" -c 'import fontTools, brotli' 2>/dev/null; then
  echo "потрібні fontTools і brotli для $PY — див. коментар угорі файлу" >&2
  exit 1
fi

# Версія в імені файлу — не примха: /fonts/ віддається з
# `Cache-Control: immutable` (див. noCache у internal/api/server.go), тобто
# браузер має право не питати про цей файл рік. Оновлення шрифту — це
# НОВЕ ІМʼЯ, інакше половина користувачів лишиться зі старим назавжди.
VER="v1"

# Рівно ті гліфи, які застосунок справді вживає. Список не вигаданий:
# він знятий обходом web/ (див. нижче, чим саме), і перевіряти його треба
# так само, а не на око.
#
#   U+0000-00FF — латиниця, «», ×, ÷, °, ±, · і — важливо — U+00A0:
#                 саме нерозривним пробілом toLocaleString("uk-UA")
#                 розділяє розряди, тобто він стоїть у КОЖНОМУ числі
#                 застосунку. Пропустити його означало б прямокутник
#                 посеред кожної суми;
#   U+0400-045F,
#   U+0490-0491 — кирилиця разом із ґ (U+0490/0491 лежать поза основним
#                 блоком, і саме тому їх забувають);
#   U+2000-206F — загальна пунктуація: тире, лапки, багатокрапка, а також
#                 вузький нерозривний пробіл, яким деякі браузери
#                 розділяють розряди замість U+00A0;
#   далі поштучно — стрілки, математика й геометрія з розмітки:
#                 → ↻ − ∪ ≈ ≥ ▸ ○ ● ◦ ⚠ ✓ ✕ ⚙ ₴ € №
#
# ✅ (U+2705) у розмітці теж є, але це емодзі: його малює системний
# емодзі-шрифт, і в текстовій гарнітурі його немає ні в кого.
#
# Частини перелічених символів у самих гарнітурах НЕМАЄ, і підмножина їх
# додати не може: Inter не має ∪ ▸ ✕, Source Serif 4 — ще й ↻ ○ ● ◦ ⚠.
# Просити їх усе одно правильно (зайве ім'я в списку нічого не коштує), а
# малюються вони системним фолбеком погліфно — рівно так само, як досі
# малювались поверх system-ui. Тобто це не втрата, а те, що й було.
# Перевіряти треба саме по cmap шрифту, а не вимірюванням у браузері:
# фолбек підставляє власний гліф, і рядок виглядає правдоподібно доти,
# доки хтось не відкриє його на іншій машині.
UNICODES='U+0000-00FF,U+02BC,U+0400-045F,U+0490-0491,U+2000-206F,U+20AC,U+20B4,U+2116,U+2192,U+21BB,U+2212,U+222A,U+2248,U+2265,U+25B8,U+25CB,U+25CF,U+25E6,U+26A0,U+2699,U+2713,U+2715'

# ccmp/mark/mkmk потрібні кирилиці (акценти й йотація складаються з двох
# частин), locl — щоб українські форми не підмінялись російськими,
# tnum — те, заради чого все це й затівалось: справжні табличні цифри.
FEATURES='kern,liga,clig,calt,rlig,ccmp,locl,mark,mkmk,tnum'

fetch() {
  echo "  ← $2"
  curl -sSL --max-time 120 -o "$1" "$2"
}

build() {
  local name="$1" url="$2" out="$3" opsz="$4"
  fetch "$TMP/$name.ttf" "$url"

  # Спершу звузити ОСІ, і лише потім різати гліфи — порядок важливий, бо
  # вага варіативного шрифту переважно лежить не в контурах, а в дельтах.
  #
  # opsz прибирається зовсім. Оптичний розмір дає окремий шар дельт на
  # кожен гліф, а коштує тим, чого тут не видно: застосунок показує текст
  # у смузі 11-17px і одне число до 52px, тобто майже все живе на одному
  # кінці осі. Обидва шрифти з осями важили разом 256 КіБ — удвічі понад
  # стелю, і саме opsz була більшою половиною різниці.
  #
  # wght лишається віссю, але лише в тій смузі, яку застосунок уживає:
  # --oi-fw 400, --oi-fw-medium 500, --oi-fw-bold 600. Хвости до 200 і 900
  # не має чим викликати жодне правило в base.css.
  "$PY" -m fontTools.varLib.instancer -q \
    "$TMP/$name.ttf" "opsz=$opsz" 'wght=400:600' \
    -o "$TMP/$name-inst.ttf"

  # --no-hinting: інструкції TrueType важать помітно, а малює їх лише
  # застарілий растеризатор. DirectWrite і CoreText ведуть варіативний
  # шрифт власними алгоритмами й на інструкції не дивляться зовсім.
  "$PY" -m fontTools.subset "$TMP/$name-inst.ttf" \
    --output-file="$OUT/$out" \
    --flavor=woff2 \
    --layout-features="$FEATURES" \
    --unicodes="$UNICODES" \
    --no-hinting
  local src dst
  src=$(stat -c%s "$TMP/$name.ttf"); dst=$(stat -c%s "$OUT/$out")
  printf '  → %-44s %5s КіБ (з %s КіБ)\n' "$out" "$((dst / 1024))" "$((src / 1024))"
}

mkdir -p "$OUT"

echo 'Inter — текст, числа, таблиці:'
build inter \
  'https://raw.githubusercontent.com/google/fonts/main/ofl/inter/Inter%5Bopsz,wght%5D.ttf' \
  "inter-var.$VER.woff2" 16
fetch "$OUT/OFL-Inter.txt" \
  'https://raw.githubusercontent.com/google/fonts/main/ofl/inter/OFL.txt'

echo 'Source Serif 4 — проза «як це читати», дисплей:'
build source-serif-4 \
  'https://raw.githubusercontent.com/google/fonts/main/ofl/sourceserif4/SourceSerif4%5Bopsz,wght%5D.ttf' \
  "source-serif-4-var.$VER.woff2" 14
fetch "$OUT/OFL-SourceSerif4.txt" \
  'https://raw.githubusercontent.com/google/fonts/main/ofl/sourceserif4/OFL.txt'

echo
echo "разом у бінарнику: $(du -ck "$OUT"/*.woff2 | tail -1 | cut -f1) КіБ шрифтів"
echo 'стеля — 110 КіБ; більше означає, що серіф має скоротитись або зникнути'
